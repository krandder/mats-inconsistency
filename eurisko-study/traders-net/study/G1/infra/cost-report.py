#!/usr/bin/env python3
"""Regenerate study/G1/COST.md from GPU-LOG.md plus a live GCE listing (policy 15: a derived view).

Usage: cost-report.py [--no-live]    (--no-live skips the gcloud listing, e.g. in tests)
Per VM the cost is the COST-AUDIT value (GCE insert->delete receipts x ceiling rate) if present,
else the DELETE estimate (age x rate), else the full CREATE reserve. Rates are ceilings (on-demand
list price, $0.87/h for a g2-standard-8 L4); the Billing API is disabled, so no number is a real bill.
"""
import datetime, json, os, pathlib, re, subprocess, sys

INFRA = pathlib.Path(__file__).resolve().parent
G1 = pathlib.Path(os.environ.get("G1_ROOT", INFRA.parent))
LOG, OUT = G1 / "GPU-LOG.md", G1 / "COST.md"
BUDGET = float(os.environ.get("TN_BUDGET_USD", "45"))


def kv(line):
    return dict(x.split("=", 1) for x in line.split() if "=" in x)


def main():
    live = "--no-live" not in sys.argv
    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    vms = {}
    for line in (LOG.read_text().splitlines() if LOG.exists() else []):
        m = re.search(r" (PENDING-CREATE|CREATE-FAILED|CREATE|DELETE|COST-AUDIT|READY|RUN-END) ", line)
        if not m:
            continue
        f = kv(line); n = f.get("vm")
        if not n:
            continue
        v = vms.setdefault(n, dict(vm=n, ws="?", job="?", reserve=None, delete=None, audit=None, basis="", state="", created=line[2:22]))
        kind = m.group(1)
        if kind in ("PENDING-CREATE", "CREATE"):
            v["ws"], v["job"] = f.get("ws", v["ws"]), f.get("job", v["job"])
            v["reserve"] = float(f.get("reserve_usd", 0)); v["state"] = kind
        elif kind == "CREATE-FAILED":
            v["state"] = kind
        elif kind == "DELETE" and "cost_usd" in f:
            v["delete"] = float(f["cost_usd"]); v["state"] = "DELETED"
        elif kind == "COST-AUDIT":
            v["audit"] = float(f["cost_usd"]); v["basis"] = f.get("basis", ""); v["state"] = "AUDITED"
    for v in vms.values():
        if v["audit"] is not None:
            v["cost"], v["src"] = v["audit"], "audit"
        elif v["delete"] is not None:
            v["cost"], v["src"] = v["delete"], "delete-estimate"
        else:
            v["cost"], v["src"] = (v["reserve"] or 0.0), "reserve"
    total = sum(v["cost"] for v in vms.values())
    caps = dict(l.split("\t") for l in (INFRA / "caps.tsv").read_text().split("\n") if l.strip())
    byws = {}
    for v in vms.values():
        byws[v["ws"]] = byws.get(v["ws"], 0.0) + v["cost"]
    livetxt = "not checked (--no-live)"
    if live:
        try:
            out = subprocess.check_output(["gcloud", "compute", "instances", "list", "--project=GCP_PROJECT",
                                           "--filter=labels.traders-net:* OR name ~ ^tn-gpu-",
                                           "--format=value(name,zone.basename(),status)"], text=True, stderr=subprocess.DEVNULL)
            rows = [r for r in out.splitlines() if r.strip()]
            livetxt = f"{len(rows)} VM(s)" + ("" if not rows else ": " + "; ".join(r.replace("\t", " ") for r in rows))
        except Exception as e:  # listing failure is shown, not hidden
            livetxt = f"UNVERIFIED: gcloud listing failed ({e.__class__.__name__})"
    L = [
        "# COST: traders-net GPU ledger (generated; do not edit)",
        "",
        f"Generated by `infra/cost-report.py` from `GPU-LOG.md` at {now}. "
        "Check: `python3 infra/cost-report.py && head -20 COST.md`.",
        "",
        f"- **Total (ceiling): ${total:.2f} of ${BUDGET:.2f} cap; remaining ${BUDGET - total:.2f}.**",
        f"- Live traders-net VMs at {now}: {livetxt}.",
        "- Rate: $0.87 per g2-standard-8 (1x L4) hour, an UNVERIFIED ceiling (on-demand list price; "
        "Billing API disabled in GCP_PROJECT; spot is usually 60-70% lower). Admission reserves "
        "rate x max-run-duration and refuses any job that would push the total above the cap.",
        "",
        "## By workstream",
        "",
        "| ws | spent (ceiling) | cap |",
        "|---|---:|---:|",
    ]
    for ws in sorted(set(caps) | set(byws)):
        L.append(f"| {ws} | ${byws.get(ws, 0.0):.2f} | ${float(caps.get(ws, 0)):.2f} |")
    L += ["", "## By VM", "", "| created | vm | ws | job | cost | source | state |", "|---|---|---|---|---:|---|---|"]
    for v in sorted(vms.values(), key=lambda v: v["created"]):
        L.append(f"| {v['created']} | {v['vm']} | {v['ws']} | {v['job']} | ${v['cost']:.4f} | {v['src']}{' (' + v['basis'] + ')' if v['basis'] else ''} | {v['state']} |")
    if not vms:
        L.append("| - | none yet | | | $0 | | |")
    OUT.write_text("\n".join(L) + "\n")
    print(f"total={total:.4f} cap={BUDGET} vms={len(vms)} live={livetxt}")


if __name__ == "__main__":
    main()
