# ---------------- own placement enumeration (3 ships 4,3,2 on 6x6, distinct occupancy patterns, sorted by sorted cell list)
def my_placements():
    single = []
    for L in (4, 3, 2):
        opts = set()
        for r in range(6):
            for c in range(6):
                if c + L <= 6:
                    opts.add(frozenset(r * 6 + c + k for k in range(L)))
                if r + L <= 6:
                    opts.add(frozenset((r + k) * 6 + c for k in range(L)))
        single.append(list(opts))
    pats = set()
    for a, b, c in itertools.product(*single):
        if a & b or a & c or b & c:
            continue
        pats.add(frozenset(a | b | c))
    arr = np.zeros((len(pats), 36), dtype=bool)
    for i, cells in enumerate(sorted(pats, key=sorted)):
        arr[i, list(cells)] = True
    return arr

P = my_placements()
print("placements (own enumeration):", P.shape[0])

def my_boards2(stream, n, EPS=0.15, NOTE_REL=0.30):
    rng = np.random.default_rng([stream, 7702])
    occ = P[rng.integers(len(P), size=n)].copy()
    s = occ ^ (rng.random((n, 36)) < EPS)
    true_note = rng.random(n) < NOTE_REL
    sc = rng.random((n, 36))
    note = np.where(true_note, np.where(occ, sc, -1.0).argmax(1), np.where(~occ, sc, -1.0).argmax(1))
    anchors = rng.random((n, 36)).argsort(1)[:, :2]
    std6 = rng.random((n, 36)).argsort(1)[:, :6]
    return dict(occ=occ, s=s, note=note.astype(np.int64), anchors=anchors, std6=std6)

