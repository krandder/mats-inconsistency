def my_bayes(shown, s, note, EPS=0.15):
    """Exact posterior marginals given readings s on cells 'shown' (bool [n,36]) and the note. float64."""
    Pf = torch.as_tensor(P, dtype=torch.float64)
    llr = math.log((1 - EPS) / EPS)
    note_llr = math.log((0.30 / 9) / (0.70 / 27))
    out = []
    for a in range(0, s.shape[0], 100):
        sh = torch.as_tensor(shown[a:a + 100])
        sv = torch.as_tensor(s[a:a + 100])
        v = torch.where(sh, torch.where(sv, torch.full(sv.shape, llr, dtype=torch.float64),
                                        torch.full(sv.shape, -llr, dtype=torch.float64)), torch.zeros(sv.shape, dtype=torch.float64))
        nt = torch.as_tensor(note[a:a + 100])
        v[torch.arange(v.shape[0]), nt] += note_llr
        lw = v @ Pf.T
        out.append(torch.softmax(lw, 1) @ Pf)
    return torch.cat(out).numpy()

def bern_kl(p, q, eps=1e-6):
    q = np.clip(q, eps, 1 - eps)
    p = np.clip(p, 0, 1)
    with np.errstate(divide="ignore", invalid="ignore"):
        a = np.where(p > 0, p * (np.log(np.maximum(p, 1e-300)) - np.log(q)), 0.0)
        b = np.where(p < 1, (1 - p) * (np.log(np.maximum(1 - p, 1e-300)) - np.log1p(-q)), 0.0)
    return a + b

