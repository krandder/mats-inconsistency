"""report.py -- tables for NOTE.md from the registered outputs. -> out/report.md  (reads out/s_s*.json, out/p_w*_s1.json,
out/pscale.json; no computation beyond means, medians, ratios and the pre-registered bins)."""
import glob
import json
import os

import numpy as np

HERE = '/home/agent/workspaces/mats/work/deep-study/wf13/loop/'
L = []


def P(s=''):
    L.append(s)


def f(v, d=3):
    return 'n/a' if v is None or (isinstance(v, float) and np.isnan(v)) else ('%.' + str(d) + 'f') % v


# ------------------------------------------------------------------ Sudoku
S = {}
for fn in sorted(glob.glob(HERE + 'out/s_s[0-9].json')):
    r = json.load(open(fn))
    if 'arms' in r and 'final_mrvorder' in r['arms']:
        S[r['seed']] = r
P('# Report (generated by report.py)')
P()
for seed, r in S.items():
    A = r['arms']
    P('## Sudoku, seed %d (%d parameters; sets: %s)' % (seed, r['n_params'], json.dumps(r['sets'])))
    P()
    P('Loop log (training puzzles, budget %d openings): ' % r['cfg']['B_train']
      + '; '.join('round %d: closed %.2f, %.0f openings' % (x['round'], x['closed'], x['opened']) for x in r['loop'])
      + '. One-shot control: %d states.' % r['oneshot']['states'])
    P()
    P('| arm | rho | eps | hard: C | hard: median | hard: closed in cap | mixed: C | mixed: median | multi: closed | '
      'IS success per rollout (hard) | IS marg. err (multi) | one-pass solved (hard / mixed) | -log P(solution) hard | '
      'P(sol) < 1% (hard) | violations | wrong solutions | same set |')
    P('|' + '---|' * 17)
    for an, a in A.items():
        P('| %s | %.2f | %.2f | %s | %s | %.2f | %s | %s | %.2f | %.3f | %s | %.2f / %.2f | %s | %s | %d | %d | %.2f |' % (
            an, a['rho'], a['eps'], f(a['hard']['opened_censored_mean'], 0), f(a['hard']['opened_to_close_median'], 0),
            a['hard']['closed_within_cap'], f(a['mixed']['opened_censored_mean'], 0), f(a['mixed']['opened_to_close_median'], 0),
            a['multi']['closed_within_cap'], a['hard']['is_success_per_rollout'], f(a['multi']['is_err']),
            a['hard']['onepass_solved'], a['mixed']['onepass_solved'], f(a['hard']['neglog_p_solution'], 2),
            f(a['hard']['frac_p_solution_below_1pct'], 2), sum(a[s]['violations'] for s in ('hard', 'mixed', 'multi')),
            sum(a[s]['wrong_solutions'] for s in ('hard', 'mixed', 'multi')),
            np.mean([a[s]['same_set_as_exact'] for s in ('hard', 'mixed', 'multi')])))
    P()
    R = r['cfg']['R']
    for sn in ('hard', 'mixed'):
        c = [A['round%d' % k][sn]['opened_censored_mean'] for k in range(R + 1)]
        P('%s: C by round %s; one-shot %.0f; hand %.0f; random %.0f; ratio final/one-shot %.3f; final/hand %.2f; '
          'closed at marks %s (final): %s' % (sn, ' -> '.join('%.0f' % v for v in c), A['oneshot'][sn]['opened_censored_mean'],
                                              A['hand_mrv'][sn]['opened_censored_mean'], A['bad_random'][sn]['opened_censored_mean'],
                                              c[-1] / A['oneshot'][sn]['opened_censored_mean'], c[-1] / A['hand_mrv'][sn]['opened_censored_mean'],
                                              r['cfg']['marks'], ['%.2f' % v for v in A['round%d' % R][sn]['closed_at_marks']]))
    P()
if S:
    rat = [[r['arms']['round%d' % r['cfg']['R']][sn]['opened_censored_mean'] / r['arms']['oneshot'][sn]['opened_censored_mean']
            for sn in ('hard', 'mixed')] for r in S.values()]
    mx = max(max(v) for v in rat)
    P('**H3 bin**: ratios final/one-shot (hard, mixed) per seed: %s -> %s' % (
        [['%.3f' % v for v in x] for x in rat], 'major' if mx <= 0.5 else ('minor' if mx <= 0.8 else 'null')))
    P()

# ------------------------------------------------------------------ parity
PW = {}
for fn in sorted(glob.glob(HERE + 'out/p_w10[1-3]_s1.json')):
    r = json.load(open(fn))
    if 'baselines' in r:
        PW[r['world']] = r
h4, h5, h8 = [], [], []
for ws, r in PW.items():
    A, mk, km = r['arms'], r['cfg']['marks'], r['cfg']['kmarks']
    R = r['cfg']['R']
    i64, i256, i1k, i2k = mk.index(64), mk.index(256), mk.index(1024), mk.index(2048)
    P('## Parity world %d (%d parameters)' % (ws, r['n_params']))
    P()
    P('Loop log (budget %d openings + %d draws): ' % (r['cfg']['B_train'], r['cfg']['n_draw'])
      + '; '.join('round %d: audit width %.3f, unfound bound %.3f, closed %.1f' % (x['round'], x['w_aud'], x['unfound_ub'], x['n_closed'])
                  for x in r['loop']) + '.')
    b = r['baselines']
    P('Baselines, mean abs error against the exact posterior of the score: one pass of M %.4f; the prior %.4f; '
      '(the score against the true posterior %.4f).' % (b['onepass_M_abs'], b['prior_abs'], b['T_vs_truth_abs']))
    P()
    P('| arm | rho | eps | W_cert 64 / 256 / 1,024 / 2,048 | W_aud 64 / 256 / 1,024 / 2,048 | E_aud 64 / 256 / 1,024 | found share 64 / 256 / 1,024 | '
      'E_IS K = 4 / 16 / 64 / 256 | calls per rollout | one-pass err | KL(T, policy) | under-proposed 100x | viol. cert / Z | audit misses |')
    P('|' + '---|' * 14)
    for an, a in A.items():
        P('| %s | %.2f | %.2f | %s | %s | %s | %s | %s | %.1f | %.4f | %s | %s | %d / %d | %d |' % (
            an, a['rho'], a['eps'], ' / '.join(f(a['w_cert'][i]) for i in (i64, i256, i1k, i2k)),
            ' / '.join(f(a['w_aud'][i]) for i in (i64, i256, i1k, i2k)), ' / '.join(f(a['err_aud'][i], 4) for i in (i64, i256, i1k)),
            ' / '.join(f(a['found'][i]) for i in (i64, i256, i1k)), ' / '.join(f(a['is_err'][km.index(k)], 4) for k in (4, 16, 64, 256)),
            a['is_calls'][-1] / km[-1], a['onepass_abs'], f(a['kl_T_policy'], 2), f(a['frac_100x_under'], 3),
            a['viol_cert_total'], a['viol_Z_total'], a['miss_aud_total']))
    P()

    def need(a, key, thr):
        w = np.array(a[key])
        ok = w <= thr
        return float(np.median([mk[np.argmax(o)] if o.any() else 2 * mk[-1] for o in ok]))
    P('Openings needed for audit width <= 0.1 (median instance; 4,096 = not reached): '
      + '; '.join('%s %d' % (an, need(A[an], 'per_inst_w_aud', 0.1)) for an in A if an.startswith(('round', 'oneshot', 'hand', 'bad'))))
    P('Openings needed for certain width <= 0.1: '
      + '; '.join('%s %d' % (an, need(A[an], 'per_inst_w_cert', 0.1)) for an in A if an.startswith(('round', 'oneshot', 'hand', 'bad'))))
    sa = r['same_answers']
    P('Same answers across rounds 0..%d: certain intervals share a point in %.4f of (instance, assumption) pairs at 256 openings and '
      '%.4f at 2,048; audit intervals in %.4f and %.4f; audit points spread on average %.4f (max %.4f) at 256, %.5f (max %.4f) at 2,048.'
      % (R, sa['256']['cert_intervals_intersect'], sa['2048']['cert_intervals_intersect'], sa['256']['audit_intervals_intersect'],
         sa['2048']['audit_intervals_intersect'], sa['256']['mean_spread_audit_point'], sa['256']['max_spread_audit_point'],
         sa['2048']['mean_spread_audit_point'], sa['2048']['max_spread_audit_point']))
    P()
    fin, r0, os_ = A['round%d' % R], A['round0'], A['oneshot']
    k64 = km.index(64)
    h4.append((fin['w_aud'][i256] / r0['w_aud'][i256], fin['w_aud'][i256] / os_['w_aud'][i256]))
    h5.append((fin['is_err'][k64] / r0['is_err'][k64], fin['is_err'][k64] / os_['is_err'][k64]))
    h8.append(fin['err_aud'][i256] / b['onepass_M_abs'])
if PW:
    n4a = sum(a <= 0.5 and b <= 0.8 for a, b in h4)
    n4b = sum(a <= 0.8 for a, b in h4)
    P('**H4 bin** (W_aud at 256: final/round 0, final/one-shot per world): %s -> %s' % (
        [('%.2f' % a, '%.2f' % b) for a, b in h4], 'major' if n4a >= 2 else ('minor' if n4b >= 2 else 'null')))
    n5a = sum(a <= 0.25 and b <= 0.5 for a, b in h5)
    n5b = sum(a <= 0.5 and b <= 0.8 for a, b in h5)
    P('**H5 bin** (E_IS at K = 64: final/round 0, final/one-shot per world): %s -> %s' % (
        [('%.3f' % a, '%.3f' % b) for a, b in h5], 'major' if n5a >= 2 else ('minor' if n5b >= 2 else 'null')))
    P('**H8 bin** (E_aud(final, 256) / one pass of M, per world): %s -> %s' % (
        ['%.3f' % v for v in h8], 'major' if max(h8) <= 0.1 else ('minor' if max(h8) <= 0.5 else 'null')))
    P()

# ------------------------------------------------------------------ scale
if os.path.exists(HERE + 'out/pscale.json'):
    r = json.load(open(HERE + 'out/pscale.json'))
    P('## Scale: world 201, hidden assumptions 20 / 30 / 40 (medians over instances)')
    P()
    P('| hidden | arm | instances | ' + ' | '.join('%d openings: W_cert / W_aud 4k / W_aud 64k' % m for m in r['marks'])
      + ' | nested | viol. cert / Z | audit misses 4k / 64k | log10(UF / found) at the last mark |')
    P('|' + '---|' * (8 + len(r['marks'])))
    for hid, o in r['hidden'].items():
        for an, v in o.items():
            cells = []
            for a in range(len(r['marks'])):
                cells.append(' / '.join(f(float(np.median([inst[a][k] for inst in v]))) for k in ('w_cert', 'w_aud4k', 'w_aud64k')))
            last = [inst[-1] for inst in v]
            viol = '%d / %d' % (sum(d.get('viol_cert', 0) for i in v for d in i), sum(d.get('viol_Z', 0) for i in v for d in i)) if 'viol_cert' in last[0] else 'no exact answer'
            miss = '%d / %d' % (sum(d.get('miss4k', 0) for i in v for d in i), sum(d.get('miss64k', 0) for i in v for d in i)) if 'miss4k' in last[0] else 'no exact answer'
            lg = [d['log10_UF_over_found'] for d in last if d['log10_UF_over_found'] is not None]
            P('| %s | %s | %d | %s | %s | %s | %s | %s |' % (hid, an, len(v), ' | '.join(cells), all(d['nested'] for i in v for d in i), viol, miss,
                                                         ('%.1f (found something in %d of %d)' % (np.median(lg), len(lg), len(last))) if lg else 'nothing found'))
    P()
open(HERE + 'out/report.md', 'w').write('\n'.join(L) + '\n')
print('\n'.join(L)[:6000])
