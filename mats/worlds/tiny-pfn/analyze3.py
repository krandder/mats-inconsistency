"""Amendment 3: warm-started mixture head. usage: python analyze3.py runs > runs/summary_ws.md"""
import contextlib, io, json, math, os, sys
import numpy as np

with contextlib.redirect_stdout(io.StringIO()):
    import analyze2 as A2                      # loads test set, all runs and residual_map (its own output discarded)
runs, ms, T = A2.runs, A2.ms, A2.T

print('# Warm-started K=4 mixture head (Amendment 3; auto-generated by analyze3.py)\n')
print('Rule (pre-registered, all seeds counted): mean-over-seeds test NLL gap <= 0.02.\n')
print('| config | params | seed | source Gaussian gap (160k arm) | init val gap | converged | phase-1 steps | NLL gap | KL |')
print('|---|---|---|---|---|---|---|---|---|')
WS = ['w16_h2_L2_ds4_mix4_ws', 'w32_h2_L2_mix4_ws']
for c in WS:
    for e, p in sorted(runs.get(c, []), key=lambda x: x[0]['meta']['seed']):
        m = e['meta']; s = m['seed']
        src = [x for x, _ in runs[c.replace('_mix4_ws', '_long')] if x['meta']['seed'] == s][0]
        print(f"| {c} | {m['params']} | {s} | {src['best']['gap']:.4f} | {m.get('init_val_gap', float('nan')):+.4f} | "
              f"{m['converged']} | {m['phase1_steps'] // 1000}k | {e['best']['gap']:.4f} | {e['best']['kl']:.4f} |")
print('\n| config | params | NLL gap (5 seeds) | KL | seeds < 0.02 (gap) | seeds < 0.02 (KL) | qualifies | '
      'same config, Gaussian 160k | same config, cold mixture |')
print('|---|---|---|---|---|---|---|---|---|')
qual = []
for c in WS:
    R = runs.get(c, [])
    if not R: continue
    g = [e['best']['gap'] for e, _ in R]; k = [e['best']['kl'] for e, _ in R]
    base = c.replace('_mix4_ws', '')
    q = np.mean(g) <= 0.02
    if q: qual.append((R[0][0]['meta']['params'], c))
    print(f"| {c} | {R[0][0]['meta']['params']} | {ms(g)} | {ms(k)} | {sum(x < 0.02 for x in g)}/{len(g)} | "
          f"{sum(x < 0.02 for x in k)}/{len(k)} | {q} | {ms([e['best']['gap'] for e, _ in runs[base + '_long']])} | "
          f"{ms([e['best']['gap'] for e, _ in runs[base + '_mix4']])} |")
print('\nQualifying (smallest first): ' + (', '.join(c for _, c in sorted(qual)) if qual else 'none'))
if not any(c in runs for c in WS): sys.exit()
sel = sorted(qual)[0][1] if qual else min((c for c in WS if c in runs),
                                           key=lambda c: np.mean([e['best']['gap'] for e, _ in runs[c]]))
A2.residual_map(sel, runs[sel], f'Residual map of {sel} (all {len(runs[sel])} seeds)')
if qual and len(qual) > 1:
    other = sorted(qual)[1][1]
    A2.residual_map(other, runs[other], f'Residual map of {other} (all {len(runs[other])} seeds)')
