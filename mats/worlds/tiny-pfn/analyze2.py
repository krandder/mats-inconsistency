def ms(v, f='{:.4f}'):
    v = np.asarray(v, float)
    return f.format(v.mean()) + (' ± ' + f.format(v.std(ddof=1) / math.sqrt(len(v))) if len(v) > 1 else '')


def row(c):
    R = runs[c]; m = R[0][0]['meta']
    conv = sum(bool(e['meta']['converged']) for e, _ in R)
    steps = ','.join(str(e['meta']['phase1_steps'] // 1000) + 'k' for e, _ in R)
    return (f"| {c} | {m['params']} | {len(R)} | {conv}/{len(R)} | {steps} | {ms([e['best']['gap'] for e, _ in R])} | "
            f"{ms([e['best']['kl'] for e, _ in R])} | {ms([e['phase1']['gap'] for e, _ in R])} |")


