def residual_map(sel, R, title):
    KL = np.stack([p['kl'] for _, p in R]); km = KL.mean(0)
    mu = np.stack([p['mu'] for _, p in R]); ls = np.stack([p['logstd'] for _, p in R])
    mb, vb = T['mean_bayes'], T['var_bayes']
    mom = ((mb - mu) ** 2 / (2 * np.exp(2 * ls))).mean(0)                       # mean-mismatch diagnostic
    w, wl = T['w_bayes'], T['w_lab']
    H27 = -(w * np.log(np.maximum(w, 1e-300))).sum(1)
    coup = (w * (np.log(np.maximum(w, 1e-300)) - np.log(np.maximum(wl, 1e-300)))).sum(1)
    sp = T['src_post_lab']; Hsrc = -(sp * np.log(np.maximum(sp, 1e-300))).sum(2)
    ost = T['o'][:, :, W.QL]; spread = ost.max(1) - ost.min(1)
    logss = np.log(T['ss_resid']); fl = T['gauss_floor']
    mixvar = vb - (w * T['comp_vars'][None]).sum(1)
    # model's own multimodality: between-component variance of its mixture / its total variance
    cw = np.stack([np.exp(p['comp_logits'] - p['comp_logits'].max(-1, keepdims=True)) for _, p in R])
    cw /= cw.sum(-1, keepdims=True)
    cmu = np.stack([p['comp_mu'] for _, p in R]); cvar = np.exp(2 * np.stack([p['comp_logstd'] for _, p in R]))
    mm = (cw * cmu).sum(-1); mv = (cw * (cvar + cmu ** 2)).sum(-1) - mm ** 2
    mbetween = (mv - (cw * cvar).sum(-1)) / mv
    effk = np.exp(-(cw * np.log(np.maximum(cw, 1e-300))).sum(-1))
    STATS = {'entropy of 27-way Bayes posterior': H27, 'query coupling KL(w_Bayes‖w_lab)': coup,
             'max per-source reliability entropy (labelled)': Hsrc.max(1),
             'min log SS_resid over sources': logss.min(1), 'max log SS_resid over sources': logss.max(1),
             'spread of query readings': spread, 'Gaussian floor (Bayes non-Gaussianity)': fl,
             'between-component variance / Bayes var': mixvar / vb, 'Bayes predictive var': vb}
    print(f'\n### {title}\n')
    print(f'Mean KL {km.mean():.4f} (per seed: ' + ', '.join(f'{x:.4f}' for x in KL.mean(1)) + f'); mean-mismatch diagnostic '
          f'{mom.mean():.4f}. Seed-to-seed correlation of per-episode KL: '
          f'{np.mean([np.corrcoef(KL[i], KL[j])[0, 1] for i in range(len(KL)) for j in range(i + 1, len(KL))]):.2f}. '
          f'Effective number of model components (exp entropy of weights): {effk.mean():.2f}. Correlation of the model\'s '
          f'between-component variance fraction with Bayes\'s: {np.corrcoef(mbetween.mean(0), mixvar / vb)[0, 1]:.2f} '
          f'(means {mbetween.mean():.3f} vs {(mixvar / vb).mean():.3f}).\n')
    print('| statistic | Spearman ρ with KL |'); print('|---|---|')
    for nm, s in STATS.items(): print(f'| {nm} | {spearmanr(s, km)[0]:+.2f} |')
    for nm, s in STATS.items():
        qs = np.quantile(s, [0, .2, .4, .6, .8, 1]); b = np.clip(np.searchsorted(qs, s, side='right') - 1, 0, 4)
        print(f'\n**{nm}** (quintiles)\n\n| bin | range | mean KL | mean-mismatch diag. | Bayes floor (for reference) | share of total KL |')
        print('|---|---|---|---|---|---|')
        for i in range(5):
            sl = b == i
            print(f'| {i} | {qs[i]:.3g}–{qs[i + 1]:.3g} | {km[sl].mean():.4f} | {mom[sl].mean():.4f} | {fl[sl].mean():.4f} | '
                  f'{km[sl].sum() / km.sum():.2f} |')
    ms_lab = np.array([','.join(str(x) for x in sorted(W.VLEV[r])) for r in T['vidx']])
    gapn = np.stack([p['nll'] for _, p in R]).mean(0) - nb
    print('\n**true variance multiset**\n\n| variances | n | mean KL | mean-mismatch diag. | share of total KL | model NLL gap |')
    print('|---|---|---|---|---|---|')
    for lab in sorted(set(ms_lab)):
        sl = ms_lab == lab
        print(f'| {lab} | {sl.sum()} | {km[sl].mean():.4f} | {mom[sl].mean():.4f} | {km[sl].sum() / km.sum():.2f} | {gapn[sl].mean():+.4f} |')
    top = km >= np.quantile(km, 0.9)
    print(f'\nTop 10% of episodes by KL carry {km[top].sum() / km.sum():.2f} of the total. In them vs the rest: '
          f'coupling {coup[top].mean():.3f} vs {coup[~top].mean():.3f}; Bayes floor {fl[top].mean():.3f} vs {fl[~top].mean():.3f}; '
          f'spread {spread[top].mean():.2f} vs {spread[~top].mean():.2f}; H27 {H27[top].mean():.2f} vs {H27[~top].mean():.2f}.')
    mavg = mu.mean(0)
    print(f"\nSigned: slope of (model mean − Bayes mean) on (lab-only − Bayes) {np.polyfit(T['mean_lab'] - mb, mavg - mb, 1)[0]:.2f}, "
          f"on (query-only − Bayes) {np.polyfit(T['mean_qonly'] - mb, mavg - mb, 1)[0]:.2f}, on ((a) − Bayes) "
          f"{np.polyfit(T['mean_a'] - mb, mavg - mb, 1)[0]:.2f}; mean log(model sd / Bayes sd) {(ls.mean(0) - 0.5 * np.log(vb)).mean():+.4f}.")


