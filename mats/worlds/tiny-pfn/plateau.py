"""Plateau diagnostic (Amendment 3): did a run ever sit on the query-only plateau (validation gap in [0.14, 0.18] for
>= 10 consecutive evaluations, i.e. >= 10k steps), and when did it leave it? usage: python plateau.py runs"""
import glob, json, os, sys
from collections import defaultdict
import numpy as np

LO, HI, MINLEN = 0.14, 0.18, 10
root = sys.argv[1]


def plateau(curve, vb):
    steps = np.array([s for s, _ in curve]); gap = np.array([v for _, v in curve]) - vb
    inb = (gap >= LO) & (gap <= HI)
    stretches, i = [], 0
    while i < len(inb):
        if inb[i]:
            j = i
            while j + 1 < len(inb) and inb[j + 1]: j += 1
            if j - i + 1 >= MINLEN: stretches.append((i, j))
            i = j + 1
        else:
            i += 1
    if not stretches:
        return dict(ever=False, entry=None, escape=None, dwell=0, final_gap=float(gap[-1]))
    i0, jl = stretches[0][0], stretches[-1][1]
    after = np.flatnonzero(gap[jl + 1:] < LO)
    esc = int(steps[jl + 1 + after[0]]) if len(after) else None
    return dict(ever=True, entry=int(steps[i0]), escape=esc, dwell=int(sum(j - i + 1 for i, j in stretches)) * 1000,
                final_gap=float(gap[-1]))


R = defaultdict(list)
for f in sorted(glob.glob(os.path.join(root, 'w*_s*/meta.json'))):
    m = json.load(open(f))
    R[m['cfg']].append((m['seed'], m['depth'], plateau(m['curve'], m['val_bayes'])))

print('# Query-only plateau diagnostic (auto-generated by plateau.py)\n')
print(f'Plateau = validation gap to Bayes in [{LO}, {HI}] for >= {MINLEN} consecutive evaluations (>= {MINLEN}k steps). '
      'Escape = first evaluation after the last such stretch with gap < 0.14. Steps are evaluation steps (1000-step '
      'resolution). For 1-layer models the band contains their final capacity-limited level.\n')
print('| config | depth | runs | ever on plateau | escaped | never escaped | entry steps | escape steps | final val gaps |')
print('|---|---|---|---|---|---|---|---|---|')
esc_all, never_l2 = [], []
for c in sorted(R, key=lambda c: (R[c][0][1], c)):
    rr = sorted(R[c]); dep = rr[0][1]
    ev = [p for _, _, p in rr if p['ever']]
    esc = [p['escape'] for p in ev if p['escape'] is not None]
    nev = [s for s, _, p in rr if p['ever'] and p['escape'] is None]
    if dep >= 2:
        esc_all += [(c, s, p['entry'], p['escape']) for s, _, p in rr if p['ever'] and p['escape'] is not None]
        never_l2 += [(c, s) for s in nev]
    fg = ','.join('%.3f' % p['final_gap'] for _, _, p in rr)
    fmt = lambda xs: ','.join('-' if x is None else f'{x // 1000}k' for x in xs) if xs else '-'
    print(f"| {c} | {dep} | {len(rr)} | {len(ev)} | {len(esc)} | {len(nev)} | {fmt([p['entry'] for p in ev])} | "
          f"{fmt(esc)} | {fg} |")
print('\n## Depth >= 2 runs: escape-step distribution\n')
n2 = sum(len(v) for c, v in R.items() if v[0][1] >= 2)
ever2 = len(esc_all) + len(never_l2)
print(f'{ever2} of {n2} depth>=2 runs sat on the plateau; {len(esc_all)} escaped, {len(never_l2)} never did '
      f'({", ".join(f"{c} s{s}" for c, s in never_l2) if never_l2 else "none"}).')
if esc_all:
    e = np.array([x[3] for x in esc_all]); d = np.array([x[3] - x[2] for x in esc_all])
    print(f'Escape step: median {np.median(e) / 1000:.0f}k, quartiles {np.percentile(e, 25) / 1000:.0f}k-'
          f'{np.percentile(e, 75) / 1000:.0f}k, range {e.min() / 1000:.0f}k-{e.max() / 1000:.0f}k. Time on the plateau before '
          f'escaping (escape - entry): median {np.median(d) / 1000:.0f}k, range {d.min() / 1000:.0f}k-{d.max() / 1000:.0f}k.')
    print('\n| config | seed | entry | escape |'); print('|---|---|---|---|')
    for c, s, en, es in sorted(esc_all, key=lambda x: x[3]):
        print(f'| {c} | {s} | {en // 1000}k | {es // 1000}k |')
