"""Aggregate tiny-pfn runs: per-config tables, references, micro arms vs references, ds4 control, smallest good
config, and its residual map binned by Bayes sufficient statistics. usage: python analyze.py runs > runs/summary.md"""
import glob, json, math, os, sys
from collections import defaultdict
import numpy as np
from scipy.stats import spearmanr
import world as W

root = sys.argv[1]
TS = {16: np.load(os.path.join(root, 'testset.npz')), 4: np.load(os.path.join(root, 'testset_ds4.npz'))}
T = TS[16]
assert np.allclose(TS[4]['nll_bayes'], T['nll_bayes'])          # same episodes in both test sets
nb = T['nll_bayes']; n = len(nb)

runs = defaultdict(list)
for f in sorted(glob.glob(os.path.join(root, 'w*_s*/eval.json'))):
    e = json.load(open(f)); p = np.load(os.path.join(os.path.dirname(f), 'test_preds.npz'))
    runs[e['meta']['cfg']].append((e, dict(p)))

vt = W.vtype({'vidx': T['vidx']})
nrel = (T['vidx'] == 0).sum(1)
SPL = {'all': np.ones(n, bool)}
for i, nm in enumerate(W.VTYPE_NAMES): SPL[nm] = vt == i
for k in range(4): SPL[f'rel{k}'] = nrel == k


def ms(v, f='{:.4f}'):
    v = np.asarray(v, float)
    return f.format(v.mean()) + (' ± ' + f.format(v.std(ddof=1) / math.sqrt(len(v))) if len(v) > 1 else '')


def order(c):
    e = runs[c][0][0]['meta']
    return (e['ds'] != 4 or e['width'] > 8, e['params'], e['ds'], c)


cfgs = sorted(runs, key=order)
print('# tiny-pfn: results (auto-generated by analyze.py)\n')
print(f'Test set n = {n} (seed 20000). Gaps in nats vs exact Bayes, paired per episode; mean ± se over seeds.\n')
print('## References on the test set (NLL minus Bayes NLL)\n')
print('| split | n | Bayes NLL | (a) equal | (b) oracle | lab-only Bayes | query-only Bayes | Gaussian floor |')
print('|---|---|---|---|---|---|---|---|')
for s, sel in SPL.items():
    print(f"| {s} | {sel.sum()} | {nb[sel].mean():.4f} | " + ' | '.join(f"{(T['nll_' + k][sel] - nb[sel]).mean():+.4f}"
          for k in ('a', 'b', 'lab', 'qonly')) + f" | {T['gauss_floor'][sel].mean():.4f} |")

print('\n## Per config (best-validation checkpoint)\n')
print('| config | ds | params | runs | converged | phase-1 steps | NLL gap | KL(Bayes‖model) | KL mean part | '
      'KL scale part | gap before cooldown |')
print('|---|---|---|---|---|---|---|---|---|---|---|')
for c in cfgs:
    R = runs[c]; m = R[0][0]['meta']
    conv = sum(bool(e['meta']['converged']) for e, _ in R)
    steps = ','.join(str(e['meta']['phase1_steps'] // 1000) + 'k' for e, _ in R)
    print(f"| {c} | {m['ds']} | {m['params']} | {len(R)} | {conv}/{len(R)} | {steps} | "
          f"{ms([e['best']['gap'] for e, _ in R])} | {ms([e['best']['kl'] for e, _ in R])} | "
          f"{ms([e['best']['kl_mean'] for e, _ in R])} | {ms([e['best']['kl_scale'] for e, _ in R])} | "
          f"{ms([e['phase1']['gap'] for e, _ in R])} |")
unconv = [(c, e['meta']['seed']) for c in cfgs for e, _ in runs[c] if not e['meta']['converged']]
print(f'\nUnconverged runs (constant phase failed the rule at 80k): {unconv if unconv else "none"}\n')

print('## NLL gap by split (mean ± se over seeds)\n')
print('| config | ' + ' | '.join(SPL) + ' |'); print('|---' * (len(SPL) + 1) + '|')
for c in cfgs:
    print(f'| {c} | ' + ' | '.join(ms([(p['nll'][sel] - nb[sel]).mean() for _, p in runs[c]], '{:.3f}')
                                    for sel in SPL.values()) + ' |')

print('\n## Which reference is the model closest to? (mean squared distance of predictive means; mean over seeds)\n')
REFS = ('a', 'b', 'bayes', 'lab', 'qonly')
print('| config | ' + ' | '.join(f'to {r}' for r in REFS) + ' | closest |'); print('|---' * (len(REFS) + 2) + '|')
for c in cfgs:
    d = {r: np.mean([((p['mu'] - T['mean_' + r]) ** 2).mean() for _, p in runs[c]]) for r in REFS}
    print(f'| {c} | ' + ' | '.join(f'{d[r]:.4f}' for r in REFS) + f' | {min(d, key=d.get)} |')

print('\n## Micro arms vs references (test NLL; beats = mean-over-seeds NLL below the reference)\n')
print('| config | params | model NLL | (a) equal NLL | (b) oracle NLL | query-only Bayes NLL | beats (a) | beats (b) | '
      'seeds beating (a) | beats query-only |')
print('|---|---|---|---|---|---|---|---|---|---|')
for c in cfgs:
    m = runs[c][0][0]['meta']
    if not (m['ds'] == 4 and m['width'] <= 8): continue
    mn = [p['nll'].mean() for _, p in runs[c]]
    na, nbb, nq = T['nll_a'].mean(), T['nll_b'].mean(), T['nll_qonly'].mean()
    print(f"| {c} | {m['params']} | {ms(mn)} | {na:.4f} | {nbb:.4f} | {nq:.4f} | {np.mean(mn) < na} | "
          f"{np.mean(mn) < nbb} | {sum(x < na for x in mn)}/{len(mn)} | {np.mean(mn) < nq} |")

print('\n## R^4 vs R^16 identity vectors (same config)\n')
for c in cfgs:
    if c.endswith('_ds4') and c[:-4] in runs:
        a4 = [e['best']['gap'] for e, _ in runs[c]]; a16 = [e['best']['gap'] for e, _ in runs[c[:-4]]]
        print(f'- {c[:-4]}: R^16 gap {ms(a16)}, R^4 gap {ms(a4)}')

# smallest good config (main grid and controls; micro arms are included if they qualify)
good = [(runs[c][0][0]['meta']['params'], np.mean([e['best']['gap'] for e, _ in runs[c]]), c) for c in cfgs
        if np.mean([e['best']['gap'] for e, _ in runs[c]]) <= 0.02]
print('\n## Smallest config within 0.02 nats of Bayes\n')
if not good:
    print('None qualifies.'); sys.exit()
good.sort()
print(f'{good[0][2]}: params {good[0][0]}, mean gap {good[0][1]:.4f}. All qualifying (params, mean NLL gap, mean KL): ' +
      ', '.join(f"{c} ({p}, {g:.4f}, {np.mean([e['best']['kl'] for e, _ in runs[c]]):.4f})" for p, g, c in good))
sel = [good[0][2]]
g16 = [c for _, _, c in good if runs[c][0][0]['meta']['ds'] == 16]
if g16 and g16[0] not in sel:
    sel.append(g16[0]); print(f'Smallest qualifying with the pre-registered R^16 tokens: {g16[0]}.')


def residual_map(sel_c):
    KL = np.stack([p['kl'] for _, p in runs[sel_c]]); KLm = np.stack([p['kl_mean'] for _, p in runs[sel_c]])
    KLs = np.stack([p['kl_scale'] for _, p in runs[sel_c]])
    fl = T['gauss_floor']
    w, wl = T['w_bayes'], T['w_lab']
    H27 = -(w * np.log(np.maximum(w, 1e-300))).sum(1)
    coup = (w * (np.log(np.maximum(w, 1e-300)) - np.log(np.maximum(wl, 1e-300)))).sum(1)
    sp = T['src_post_lab']
    Hsrc = -(sp * np.log(np.maximum(sp, 1e-300))).sum(2)                   # (n, S) per-source reliability ambiguity
    ost = T['o'][:, :, W.QL]
    spread = ost.max(1) - ost.min(1)
    logss = np.log(T['ss_resid'])
    mb, vb = T['mean_bayes'], T['var_bayes']
    mixvar = vb - (w * T['comp_vars'][None]).sum(1)                       # between-component variance of the mixture
    STATS = {'entropy of 27-way Bayes posterior': H27, 'query coupling KL(w_Bayes‖w_lab)': coup,
             'max per-source reliability entropy (labelled)': Hsrc.max(1),
             'sum per-source reliability entropy (labelled)': Hsrc.sum(1),
             'min log SS_resid over sources': logss.min(1), 'max log SS_resid over sources': logss.max(1),
             'spread of query readings': spread, 'Gaussian floor KL(Bayes‖moment Gaussian)': fl,
             'between-component variance / Bayes var': mixvar / vb, 'Bayes predictive var': vb}
    km = KL.mean(0)
    print(f'\n### Residual map of {sel_c} (pooled over {len(KL)} seeds)\n')
    print(f'Mean KL {km.mean():.4f} = floor {fl.mean():.4f} + mean-mismatch {KLm.mean():.4f} + scale-mismatch '
          f'{KLs.mean():.4f}. Seed-to-seed correlation of per-episode excess (KL minus floor): ' +
          f"{np.mean([np.corrcoef(KL[i] - fl, KL[j] - fl)[0, 1] for i in range(len(KL)) for j in range(i + 1, len(KL))]):.2f}\n")
    print('| statistic | Spearman ρ with KL | ρ with KL minus floor |'); print('|---|---|---|')
    for nm, s in STATS.items():
        print(f'| {nm} | {spearmanr(s, km)[0]:+.2f} | {spearmanr(s, km - fl)[0]:+.2f} |')
    for nm, s in STATS.items():
        qs = np.quantile(s, [0, .2, .4, .6, .8, 1]); b = np.clip(np.searchsorted(qs, s, side='right') - 1, 0, 4)
        print(f'\n**{nm}** (quintiles)\n\n| bin | range | mean KL | floor | mean part | scale part | share of total KL |')
        print('|---|---|---|---|---|---|---|')
        for i in range(5):
            sl = b == i
            print(f'| {i} | {qs[i]:.3g}–{qs[i + 1]:.3g} | {km[sl].mean():.4f} | {fl[sl].mean():.4f} | {KLm.mean(0)[sl].mean():.4f} | '
                  f'{KLs.mean(0)[sl].mean():.4f} | {km[sl].sum() / km.sum():.2f} |')
    ms_lab = np.array([','.join(str(x) for x in sorted(W.VLEV[r])) for r in T['vidx']])
    print('\n**true variance multiset**\n\n| variances | n | mean KL | floor | mean part | scale part | share of total KL | '
          'model gap NLL |')
    print('|---|---|---|---|---|---|---|---|')
    gapn = np.stack([p['nll'] for _, p in runs[sel_c]]).mean(0) - nb
    for lab in sorted(set(ms_lab)):
        sl = ms_lab == lab
        print(f'| {lab} | {sl.sum()} | {km[sl].mean():.4f} | {fl[sl].mean():.4f} | {KLm.mean(0)[sl].mean():.4f} | '
              f'{KLs.mean(0)[sl].mean():.4f} | {km[sl].sum() / km.sum():.2f} | {gapn[sl].mean():+.4f} |')
    # top-decile concentration
    top = km >= np.quantile(km, 0.9)
    print(f'\nTop 10% of episodes by KL carry {km[top].sum() / km.sum():.2f} of the total KL. In them vs the rest: '
          f'H27 {H27[top].mean():.2f} vs {H27[~top].mean():.2f}; coupling {coup[top].mean():.3f} vs {coup[~top].mean():.3f}; '
          f'floor {fl[top].mean():.3f} vs {fl[~top].mean():.3f}; spread {spread[top].mean():.2f} vs {spread[~top].mean():.2f}.')
    # signed errors: does the model over- or under-weight the reliable source, and over/under-disperse?
    mu = np.stack([p['mu'] for _, p in runs[sel_c]]).mean(0); ls = np.stack([p['logstd'] for _, p in runs[sel_c]]).mean(0)
    print(f'\nSigned: mean log(model sd / Bayes sd) = {(ls - 0.5 * np.log(vb)).mean():+.4f}; '
          f'slope of (model mean − Bayes mean) on (lab-only mean − Bayes mean) = '
          f"{np.polyfit(T['mean_lab'] - mb, mu - mb, 1)[0]:.2f}; on (query-only mean − Bayes mean) = "
          f"{np.polyfit(T['mean_qonly'] - mb, mu - mb, 1)[0]:.2f}; on ((a) mean − Bayes mean) = "
          f"{np.polyfit(T['mean_a'] - mb, mu - mb, 1)[0]:.2f}.")

    print('\nPer-seed mean KL: ' + ', '.join(f'{x:.4f}' for x in KL.mean(1)))


for c in sel:
    residual_map(c)
