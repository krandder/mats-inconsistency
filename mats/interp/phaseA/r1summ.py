"""Summarise r1/*.json into r1/tables.md (round 1). usage: python r1summ.py"""
import json, math, os, glob
import numpy as np

D = '/home/agent/workspaces/mats/work/cm-interp/r1'
GROUPS = {'2L': [f'2L_s{s}' for s in range(5)], '3L': [f'3L_s{s}' for s in range(10, 15)], 'plat': ['plat_s3']}
R = {}
for g, ms in GROUPS.items():
    for m in ms:
        p = f'{D}/{m}.json'
        if os.path.exists(p):
            _r = json.load(open(p))
            if 'consistency_B' in _r:
                R[m] = _r
ONEPOOL = {'2L_s0', '2L_s2', '2L_s3'}
MIXER = {'2L_s0': 'head0', '2L_s2': 'head1', '2L_s3': 'head1'}          # step-1 table: own/other ratio ~1.2-1.4
out = []
P = out.append
f3 = lambda x: f'{x:.3f}'
f4 = lambda x: f'{x:.4f}'


def ms(vals):
    v = np.array([x for x in vals if x is not None and np.isfinite(x)], float)
    if len(v) == 0:
        return 'n/a'
    if len(v) == 1:
        return f'{v[0]:.4f}'
    return f'{v.mean():.4f} ± {v.std(ddof=1) / math.sqrt(len(v)):.4f}'


def sites(m):
    return list(R[m]['ratio_A'].keys())


def present(g):
    return [m for m in GROUPS[g] if m in R]


P('# Round 1 tables (generated by r1summ.py)\n')
P('Models present: ' + ', '.join(R.keys()) + '\n')
P('## Model KL (eval A, 48k draws) vs eval.json\n')
P('| model | KL_model (A) | KL (B) | eval.json KL |\n|---|---|---|---|')
for m, r in R.items():
    P(f"| {m} | {f4(r['kl_model_A'])} | {f4(r['kl_model_B'])} | {f4(r['eval_kl'])} |")

P('\n## V1: R_in at the embedding (max |real − R_in mean|, residual cov trace)\n')
P('| model | LAB | QQ | QT |\n|---|---|---|---|')
for m, r in R.items():
    P(f"| {m} | " + ' | '.join(f"{r['V1'][t]['max_abs_resid']:.1e}, {r['V1'][t]['trace_cov']:.1e}" for t in ('LAB', 'QQ', 'QT')) + ' |')

# ---------------------------------------------------------------- ladder
RUNGS = ['Rmarg', 'Rin', 'q0', 'q0U', 'q0noID']
for g in GROUPS:
    ms_ = present(g)
    if not ms_:
        continue
    P(f'\n## Ladder, direct Δ = L(q) − L(p) and Δ_rms (nats), eval A — {g} (mean ± se over {len(ms_)} seeds)\n')
    P('| site | ' + ' | '.join(f'Δ {r}' for r in RUNGS) + ' | Δ_rms q0 | Δ_rms q0U | Δ(q0)/KL |\n|' + '---|' * (len(RUNGS) + 4))
    for s in sites(ms_[0]):
        row = [ms([R[m]['direct_A'].get(f'{s}|{r}', {}).get('delta') for m in ms_]) if f'{s}|{r}' in R[ms_[0]]['direct_A'] else '–' for r in RUNGS]
        rq = ms([R[m]['direct_A'][f'{s}|q0']['rms'] for m in ms_]); ru = ms([R[m]['direct_A'][f'{s}|q0U']['rms'] for m in ms_])
        rel = ms([R[m]['direct_A'][f'{s}|q0']['delta'] / R[m]['kl_model_A'] for m in ms_])
        P(f'| {s} | ' + ' | '.join(row) + f' | {rq} | {ru} | {rel} |')

P('\n### q0 per seed: Δ ± se, Δ_rms [95% CI], Hill index\n')
for g in GROUPS:
    ms_ = present(g)
    if not ms_:
        continue
    P(f'\n{g}\n\n| site | ' + ' | '.join(ms_) + ' |\n|' + '---|' * (len(ms_) + 1))
    for s in sites(ms_[0]):
        cells = []
        for m in ms_:
            d = R[m]['direct_A'][f'{s}|q0']
            cells.append(f"{d['delta']:.4f}±{d['se']:.4f}; rms {d['rms']:.3f} [{d['rms_lo']:.3f},{d['rms_hi']:.3f}]; H {d['hill']:.1f}")
        P(f'| {s} | ' + ' | '.join(cells) + ' |')

# ---------------------------------------------------------------- ratio
P('\n## Output-space ratio for q0: L(0) − L(1) (bridge), Cov_q(G, ŵ), ESS, checks\n')
P('Cov_q(G,w) = E_p G − E_q G = −Δ if ŵ = w. "bridge/direct" = (L(0) − L(1)) / Δ_direct. SEs include classifier refit sd.\n')
for g in GROUPS:
    ms_ = present(g)
    if not ms_:
        continue
    P(f'\n{g} (mean ± se over seeds)\n')
    P('| site | AUC | direct Δ | L(0)−L(1) | bridge/direct | −Cov_q plain | −Cov_q SNIS | E_q[Gŵ] − E_pG | ESS_q frac | ESS_q per cell (of 8) | k̂_q | T1 L0/L1 pass | T2 pass | V5 pass |\n|' + '---|' * 15)
    for s in sites(ms_[0]):
        rr = [R[m]['ratio_A'][s] for m in ms_]
        Lp = [R[m]['direct_A'][f'{s}|q0']['Lp'] for m in ms_]
        P(f"| {s} | {ms([r['diag']['auc'] for r in rr])} | {ms([r['direct_delta'] for r in rr])} | {ms([r['gap'] for r in rr])} | "
          f"{ms([r['gap'] / r['direct_delta'] for r in rr])} | {ms([-r['cov_plain'] for r in rr])} | {ms([-r['cov_snis'] for r in rr])} | "
          f"{ms([r['ident'] - lp for r, lp in zip(rr, Lp)])} | {ms([r['ess_q_frac'] for r in rr])} | {ms([r['ess_q_cell'] for r in rr])} | "
          f"{ms([r['khat_q'] for r in rr])} | {sum(r['T1_L0'] for r in rr)}/{sum(r['T1_L1'] for r in rr)} of {len(rr)} | "
          f"{sum(r['T2'] for r in rr)}/{len(rr)} | {sum(r['V5'] for r in rr)}/{len(rr)} |")

P('\n### L(α) curves (bridge, per-cell normalised), seed mean; and Kelvin\'s q-side SNIS L_q(α) for comparison\n')
for g in GROUPS:
    ms_ = present(g)
    if not ms_:
        continue
    al = R[ms_[0]]['ratio_A'][sites(ms_[0])[0]]['alphas']
    P(f'\n{g}\n\n| site | ' + ' | '.join(f'α={a:.1f}' for a in al) + ' | direct L(q) | direct L(p) |\n|' + '---|' * (len(al) + 3))
    for s in sites(ms_[0]):
        Ls = np.mean([R[m]['ratio_A'][s]['L'] for m in ms_], 0)
        Lk = np.mean([R[m]['ratio_A'][s]['L_kelvin_q'] for m in ms_], 0)
        dq = np.mean([R[m]['direct_A'][f'{s}|q0']['Lq'] for m in ms_]); dp = np.mean([R[m]['direct_A'][f'{s}|q0']['Lp'] for m in ms_])
        P(f'| {s} bridge | ' + ' | '.join(f'{x:.4f}' for x in Ls) + f' | {dq:.4f} | {dp:.4f} |')
        P(f'| {s} Kelvin SNIS from q | ' + ' | '.join(f'{x:.4f}' for x in Lk) + ' | | |')

# ---------------------------------------------------------------- regions
P('\n## Where the q0 gap sits: share of Σ_c Δ(c) in the top quintile of episode statistics, and in the top decile of out-of-fold log ŵ_out\n')
P('(uniform = 0.20 per quintile, 0.10 per decile)\n')
for g in GROUPS:
    ms_ = present(g)
    if not ms_:
        continue
    P(f'\n{g}\n\n| site | between-comp var | query spread | coupling | 27-way entropy (bottom quintile) | top decile log ŵ_out |\n|---|---|---|---|---|---|')
    for s in sites(ms_[0]):
        rg = [R[m]['regions_A'][s] for m in ms_]
        P(f"| {s} | {ms([r['bcv'][4] for r in rg])} | {ms([r['spread'][4] for r in rg])} | {ms([r['coup'][4] for r in rg])} | "
          f"{ms([r['ent'][0] for r in rg])} | {ms([r['lw_out_decile_share'][9] for r in rg])} |")

# ---------------------------------------------------------------- localisation: components
P('\n## Subset localisation: components of the residual stream (q0-consistent stacked Gaussian)\n')
P('carried(C) = Δ_all − Δ_knock-in(C) (what keeping C real recovers); out(C) = Δ_knock-out(C) (structure in C not predictable from the rest + phi). '
  'Fractions of Δ_all of the stacked q. Heads are numbered as in the checkpoint; in 2L one-pool seeds the query-mixer head is marked *.\n')
for g in GROUPS:
    ms_ = present(g)
    if not ms_:
        continue
    cuts = [k for k in R[ms_[0]]['localisation_A'] if k.startswith('components_')]
    for ck in cuts:
        P(f'\n{g} {ck[11:]}\n\n| model | Δ_all | ' + ' | '.join(f'carried {c}' for c in ('prev', 'head0', 'head1', 'mlp')) + ' | ' +
          ' | '.join(f'out {c}' for c in ('prev', 'head0', 'head1', 'mlp')) + ' |\n|' + '---|' * 10)
        for m in ms_:
            o = R[m]['localisation_A'][ck]
            da = o['stack_all']['delta']
            car = [(da - o[f'{c}|knockin|ALL']['delta']) / da for c in ('prev', 'head0', 'head1', 'mlp')]
            ko = [o[f'{c}|knockout|ALL']['delta'] / da for c in ('prev', 'head0', 'head1', 'mlp')]
            nm = lambda c: c + ('*' if MIXER.get(m) == c else '')
            P(f'| {m} | {da:.4f} | ' + ' | '.join(f'{x:.2f}' for x in car) + ' | ' + ' | '.join(f'{x:.2f}' for x in ko) + ' |')
        # per type knockout
        if any('|knockout|QQ' in k for k in R[ms_[0]]['localisation_A'][ck]):
            P(f'\nper token type, knock-out Δ (nats), {g} {ck[11:]}, seed mean\n\n| component | LAB | QQ | QT |\n|---|---|---|---|')
            for c in ('prev', 'head0', 'head1', 'mlp'):
                P(f'| {c} | ' + ' | '.join(ms([R[m]['localisation_A'][ck][f'{c}|knockout|{t}']['delta'] for m in ms_]) for t in ('LAB', 'QQ', 'QT')) + ' |')

P('\n### Mixer vs pooling head at h1 (2L one-pool seeds): carried fraction, all tokens\n')
P('| model | mixer head | carried mixer | carried pooling head | out mixer (QQ) | out pooling (QQ) |\n|---|---|---|---|---|---|')
for m in sorted(ONEPOOL):
    if m not in R:
        continue
    o = R[m]['localisation_A']['components_h1']; da = o['stack_all']['delta']
    mx = MIXER[m]; pl = 'head0' if mx == 'head1' else 'head1'
    P(f"| {m} | {mx} | {(da - o[f'{mx}|knockin|ALL']['delta']) / da:.2f} | {(da - o[f'{pl}|knockin|ALL']['delta']) / da:.2f} | "
      f"{o[f'{mx}|knockout|QQ']['delta']:.4f} | {o[f'{pl}|knockout|QQ']['delta']:.4f} |")

# ---------------------------------------------------------------- localisation: subspaces
P('\n## Subset localisation: 4-d residual subspaces (fraction of the site\'s q0 Δ)\n')
P('Uout = output-ratio pull-back directions (G-relevant); Uh = h-space classifier Fisher directions; rand = random 4-d. '
  'knock-in = keep the 4-d subspace real, rest from q0 (small = the subspace carries the gap); knock-out = only the subspace from q0.\n')
for g in GROUPS:
    ms_ = present(g)
    if not ms_:
        continue
    keys = [k for k in R[ms_[0]]['localisation_A'] if k.startswith('subspace_')]
    P(f'\n{g} (seed mean ± se)\n\n| site | h-space AUC | knock-in Uout | knock-in Uh | knock-in rand | knock-out Uout | knock-out rand | mean cos(Uh, Uout) |\n|---|---|---|---|---|---|---|---|')
    for k in keys:
        s = k[9:]
        fr = lambda m, key: R[m]['localisation_A'][k][key]['delta'] / R[m]['direct_A'][f'{s}|q0']['delta']
        P(f"| {s} | {ms([R[m]['localisation_A'][k]['auc'] for m in ms_])} | {ms([fr(m, 'Uout4|knockin') for m in ms_])} | "
          f"{ms([fr(m, 'Uh4|knockin') for m in ms_])} | {ms([fr(m, 'rand4|knockin') for m in ms_])} | {ms([fr(m, 'Uout4|knockout') for m in ms_])} | "
          f"{ms([fr(m, 'rand4|knockout') for m in ms_])} | {ms([R[m]['localisation_A'][k]['cos_Uh_Uout'] for m in ms_])} |")

# ---------------------------------------------------------------- naming + fresh
P('\n## Refinement: naming (eval A) and acceptance on fresh B\n')
P('chosen = q1 candidate by the projected-log-density rule (Uout); best add-one = candidate with the smallest Δ_rms on B (attribution check).\n')
for g in GROUPS:
    ms_ = present(g)
    if not ms_:
        continue
    P(f'\n{g}\n\n| site | model | chosen (under Uh) | best add-one on B | Δ_rms q0 → q1 (B) | reduction | accepted | Δ q0 → q1 | DL q0 → q1 (bits) | BIC q0 → q1 | ε = 0.1 KL |\n|' + '---|' * 11)
    for m in ms_:
        r = R[m]
        for s, fb in r['fresh_B'].items():
            nm = r['naming_A'].get(s)
            types = [s] if nm else []
            if s.endswith('ALL'):
                cut = s.split('-')[0]
                ch = '+'.join(r['naming_A'][f'{cut}-{t}']['chosen'] for t in ('LAB', 'QQ', 'QT'))
                dl0 = sum(r['DL'][f'{cut}-{t}']['q0']['total'] for t in ('LAB', 'QQ', 'QT'))
                dl1 = sum(r['DL'][f'{cut}-{t}']['q1']['total'] for t in ('LAB', 'QQ', 'QT'))
                b0 = sum(r['DL'][f'{cut}-{t}']['q0']['bic'] for t in ('LAB', 'QQ', 'QT'))
                b1 = sum(r['DL'][f'{cut}-{t}']['q1']['bic'] for t in ('LAB', 'QQ', 'QT'))
                best = '–'
            else:
                ch = f"{nm['chosen']} ({nm['chosen_under_Uh']})"
                dl0, dl1 = r['DL'][s]['q0']['total'], r['DL'][s]['q1']['total']
                b0, b1 = r['DL'][s]['q0']['bic'], r['DL'][s]['q1']['bic']
                adds = {k[4:]: v['rms'] for k, v in fb.items() if k.startswith('add:')}
                best = min(adds, key=adds.get)
            red = 1 - fb['q1']['rms'] / fb['q0']['rms'] if fb['q0']['rms'] > 0 else float('nan')
            P(f"| {s} | {m} | {ch} | {best} | {fb['q0']['rms']:.4f} → {fb['q1']['rms']:.4f} | {red:.0%} | {'yes' if fb['accepted'] else 'no'} | "
              f"{fb['q0']['delta']:.4f} → {fb['q1']['delta']:.4f} | {dl0:.0f} → {dl1:.0f} | {b0:.0f} → {b1:.0f} | {0.1 * r['kl_model_B']:.4f} |")

