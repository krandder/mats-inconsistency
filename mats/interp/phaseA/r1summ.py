# ---------------------------------------------------------------- predictions
P_ = []
A = lambda m, s, r='q0': R[m]['direct_A'][f'{s}|{r}']
eps = lambda m: 0.1 * R[m]['kl_model_A']
g2, g3, gp = present('2L'), present('3L'), present('plat')
if g2 and g3:
    allsites = lambda m: [s for s in R[m]['ratio_A']]
    c1 = [all(A(m, s)['rms'] > eps(m) for s in allsites(m)) for m in g2 + g3]
    c2 = [A(m, 'h1-ALL')['delta'] > R[m]['kl_model_A'] for m in g2] + [A(m, 'h2-ALL')['delta'] > R[m]['kl_model_A'] for m in g3]
    P_.append(f"P1 q0 does not close: rms>eps at every site in {sum(c1)}/{len(c1)} nets; full-cut Δ > KL_model in {sum(c2)}/{len(c2)} -> "
              f"{'HOLDS' if sum(c1) >= 0.8 * len(c1) and sum(c2) >= 0.8 * len(c2) else 'FAILS'}")
    for m in gp:
        ok = []
        for s in ('h1-QQ', 'h1-ALL', 'h2-QT'):
            a0, aU = A(m, s), A(m, s, 'q0U')
            se = (aU['rms_hi'] - aU['rms_lo']) / 3.92
            ok.append(aU['rms'] <= 1.2 * a0['rms'] + 2 * se)
        closeU = A(m, 'h1-ALL', 'q0U')['rms'] <= eps(m)
        P_.append(f"P2 plateau {m}: rms(q0U) <= 1.2 rms(q0)+2SE at h1-QQ/h1-ALL/h2-QT: {ok}; rms(q0U) at h1-ALL {A(m, 'h1-ALL', 'q0U')['rms']:.4f} vs eps {eps(m):.4f} -> "
                  f"{'HOLDS' if all(ok) and closeU else 'FAILS'}")
    nb = [all(A(m, s, 'q0U')['rms'] >= 2 * A(m, s)['rms'] for s in ('h1-QQ', 'h1-ALL', 'h2-QT')) for m in g2]
    P_.append(f"P2 near-Bayes 2L: rms(q0U) >= 2 rms(q0) at all three sites in {sum(nb)}/{len(nb)} -> {'HOLDS' if sum(nb) >= 4 else 'FAILS'}; "
              f"per site ratios: " + '; '.join(f"{s} " + ','.join(f"{A(m, s, 'q0U')['rms'] / A(m, s)['rms']:.2f}" for m in g2) for s in ('h1-QQ', 'h1-ALL', 'h2-QT')))
    l2 = np.mean([A(m, 'h2-QT')['rms'] for m in g2]); l3 = np.mean([A(m, 'h3-QT')['rms'] for m in g3])
    f2 = np.mean([A(m, 'h1-ALL')['rms'] for m in g2]); f3 = np.mean([A(m, 'h2-ALL')['rms'] for m in g3])
    P_.append(f"P3 3L smaller residual: last QT 2L {l2:.4f} vs 3L {l3:.4f}; full cut 2L {f2:.4f} vs 3L {f3:.4f} -> {'HOLDS' if l3 < l2 and f3 < f2 else 'FAILS'}")
    one = [m for m in g2 if m in ONEPOOL]; two = [m for m in g2 if m not in ONEPOOL]
    if one and two:
        tw = np.mean([A(m, 'h1-QQ')['delta'] for m in two])
        okm = [A(m, 'h1-QQ')['delta'] >= 2 * tw for m in one]
        pick = [R[m]['naming_A']['h1-QQ']['chosen'] == 'cross' for m in one]
        P_.append(f"P4 motif: one-pool h1-QQ Δ {[round(A(m, 'h1-QQ')['delta'], 4) for m in one]} vs 2x two-pool mean {2 * tw:.4f}: {sum(okm)}/{len(okm)}; "
                  f"naming picks cross in {sum(pick)}/{len(pick)} -> {'HOLDS' if all(okm) and sum(pick) >= 2 else 'FAILS'}")
    lo = [(R[m]['ratio_A'][s]['gap'] / R[m]['ratio_A'][s]['direct_delta']) for m in g2 + g3 + gp for s in R[m]['ratio_A']
          if R[m]['ratio_A'][s]['diag']['auc'] < 0.6 and abs(R[m]['ratio_A'][s]['direct_delta']) > 2 * R[m]['ratio_A'][s]['direct_se']]
    P_.append(f"P5 attenuation where AUC<0.6 (and Δ significant): bridge/direct<1 at {sum(x < 1 for x in lo)}/{len(lo)} sites -> "
              f"{'HOLDS' if lo and sum(x < 1 for x in lo) >= 0.7 * len(lo) else ('NO SITES' if not lo else 'FAILS')}")
    hi_ = [(R[m]['ratio_A'][s]['gap'] / R[m]['ratio_A'][s]['direct_delta']) for m in g2 + g3 + gp for s in R[m]['ratio_A'] if R[m]['ratio_A'][s]['diag']['auc'] >= 0.9]
    P_.append(f"   (descriptive) bridge/direct where AUC>=0.9: median {np.median(hi_):.3f}, range {min(hi_):.3f}-{max(hi_):.3f}, n={len(hi_)}")
    idok = [A(m, 'h1-ALL', 'q0noID')['delta'] >= 2 * A(m, 'h1-ALL')['delta'] for m in g2]
    P_.append(f"P6 IDs: Δ(q0noID) >= 2Δ(q0) at h1-ALL in {sum(idok)}/{len(idok)} 2L seeds; ratios " +
              ','.join(f"{A(m, 'h1-ALL', 'q0noID')['delta'] / A(m, 'h1-ALL')['delta']:.2f}" for m in g2) + f" -> {'HOLDS' if sum(idok) >= 4 else 'FAILS'}")
    ti = max(c['tier_i_max_abs'] for m in R for c in R[m]['consistency_B'].values())
    fail2 = [not R[m]['consistency_B']['h1->h2']['pass_method'] for m in g2]
    P_.append(f"P7 tier i max {ti:.1e}; tier ii fails for 2L h1->h2 in {sum(fail2)}/{len(fail2)} -> {'HOLDS' if ti <= 1e-5 and sum(fail2) >= 4 else 'FAILS'}")
    acc = [R[m]['fresh_B']['h1-ALL']['accepted'] for m in g2]
    stillopen = [R[m]['fresh_B']['h1-ALL']['q1']['rms'] > 0.1 * R[m]['kl_model_B'] for m in g2]
    P_.append(f"P8 q1 accepted at 2L h1-ALL in {sum(acc)}/{len(acc)}; still > eps in {sum(stillopen)}/{len(stillopen)} -> {'HOLDS' if sum(acc) >= 3 and all(stillopen) else 'FAILS'}")
open(f'{D}/predictions.md', 'w').write('# Pre-registered predictions, evaluated\n\n' + '\n'.join('- ' + x for x in P_) + '\n')
print('\n'.join(P_))

# naming-rule validation: chosen vs best add-one on fresh B
agree = []; within = []
for m in R:
    for s, fb in R[m]['fresh_B'].items():
        if s.endswith('ALL'):
            continue
        adds = {k[4:]: v['rms'] for k, v in fb.items() if k.startswith('add:')}
        ch = R[m]['naming_A'][s]['chosen']; best = min(adds, key=adds.get)
        gain_best = fb['q0']['rms'] - adds[best]
        if gain_best > 0.1 * fb['q0']['rms']:
            agree.append(ch == best)
            within.append((fb['q0']['rms'] - adds[ch]) >= 0.8 * gain_best)
msg = (f"Naming rule vs best add-one on B (sites where the best add-one cuts rms by >10%): same candidate {sum(agree)}/{len(agree)}; "
       f"chosen achieves >= 80% of the best reduction {sum(within)}/{len(within)}")
open(f'{D}/predictions.md', 'a').write('- ' + msg + '\n')
print(msg)

