"""Score the pre-registered tests (PREREG.md) from the GPU job outputs.
python scratch/analyze.py RUNDIR  (RUNDIR contains r1/, r2/, r3/, r4/)  > results/tables.md"""
import glob, json, math, os, sys
import numpy as np

RD = sys.argv[1]
T3 = 3.182446          # t_{0.975, 3}
NETS = [113, 114, 115, 116]


def load(sub, n, L):
    out = {}
    for s in NETS:
        f = f'{RD}/{sub}/{"lin" if sub == "r4" else ("e2" if sub == "r2" else "e1")}_{n}_{L}_{s}.json'
        if os.path.exists(f):
            out[s] = (json.load(open(f)), np.load(f[:-5] + '.npz'))
    return out


def ci(vals):
    v = np.array([x for x in vals if x is not None and not math.isnan(x)])
    if len(v) == 0:
        return (math.nan, math.nan, math.nan, 0)
    m = v.mean()
    if len(v) < 2:
        return (m, math.nan, math.nan, len(v))
    h = (T3 if len(v) == 4 else 4.303 if len(v) == 3 else 12.706) * v.std(ddof=1) / math.sqrt(len(v))
    return (m, m - h, m + h, len(v))


def verdict(lo, hi, thr):
    if math.isnan(hi):
        return 'n/a'
    return 'PASS' if hi <= thr else ('FAIL' if lo > thr else 'inconclusive')


def rep_mean(d, cut, fam, L):
    """replicate-mean nMSE of family fam at cut, output layer L, for one net's e1 json."""
    vals = []
    for k, sc in d['runs'].items():
        r, c, f = k.split('/')
        if int(c) == cut and f == fam:
            vals.append(sc['nmse'][L - cut])
    return float(np.mean(vals)) if vals else None


def fmt(x):
    return '-' if x is None or (isinstance(x, float) and math.isnan(x)) else f'{x:.2e}'


print(f'# nongauss-family results (generated by scratch/analyze.py from {RD})\n')
# ------------------------------------------------------------------ R1: 256 x 64
r1 = load('r1', 256, 64)
fams = []
for s, (d, _) in r1.items():
    for k in d['runs']:
        f = k.split('/')[2]
        if f not in fams:
            fams.append(f)
print('## R1 single cuts, 256 x 64 (mean over nets of the replicate-mean nMSE; nets with data in brackets)\n')
for cut in (16, 32, 48):
    Ls = [x for x in (cut + 1, cut + 2, cut + 4, cut + 8, cut + 16, 64) if x <= 64]
    Ls = sorted(set(Ls))
    print(f'### cut {cut}\n')
    print('| family | ' + ' | '.join(f'L = {L}' for L in Ls) + ' | per-net at L = 64 |')
    print('|---' * (len(Ls) + 2) + '|')
    for f in fams:
        row = []
        for L in Ls:
            v = [rep_mean(d, cut, f, L) for s, (d, _) in r1.items()]
            v = [x for x in v if x is not None]
            row.append(f'{np.mean(v):.2e} [{len(v)}]' if v else '-')
        pn = [rep_mean(d, cut, f, 64) for s, (d, _) in r1.items()]
        print(f'| {f} | ' + ' | '.join(row) + ' | ' + ' '.join(fmt(x) for x in pn) + ' |')
    print()

# T0
print('## T0 reduction control: R_PEMP - R_EMP at L = 64 (per net; mean and 95% interval over nets; rule <= 2e-6)\n')
for cut in (32, 48):
    dv = [None if rep_mean(d, cut, 'PEMP', 64) is None else rep_mean(d, cut, 'PEMP', 64) - rep_mean(d, cut, 'EMP', 64)
          for s, (d, _) in r1.items()]
    m, lo, hi, k = ci(dv)
    print(f'- cut {cut}: per net {" ".join(fmt(x) for x in dv)}; mean {fmt(m)} [{fmt(lo)}, {fmt(hi)}] -> {verdict(lo, hi, 2e-6)}')
print()

# T1
print('## T1 single cut, 256 x 64 (rules: level R(32;64) <= 1e-5 and R(48;64) <= 1e-5; growth R(32;64) - R(32;40) '
      '<= 3e-6 and R(48;64) - R(48;56) <= 3e-6; mean over nets [95% interval])\n')
print('| family | R(32;64) | R(48;64) | R(32;64) - R(32;40) | R(48;64) - R(48;56) | verdicts (level32, level48, growth32, growth48) | T1 |')
print('|---|---|---|---|---|---|---|')
for f in fams:
    if f == 'EMP':
        pass
    stats = []
    vs = []
    for cut, Lm in ((32, 40), (48, 56)):
        a = [rep_mean(d, cut, f, 64) for s, (d, _) in r1.items()]
        b = [rep_mean(d, cut, f, Lm) for s, (d, _) in r1.items()]
        stats.append(ci(a))
        stats.append(ci([x - y if x is not None and y is not None else None for x, y in zip(a, b)]))
    lv32, gr32, lv48, gr48 = stats
    v = [verdict(lv32[1], lv32[2], 1e-5), verdict(lv48[1], lv48[2], 1e-5), verdict(gr32[1], gr32[2], 3e-6),
         verdict(gr48[1], gr48[2], 3e-6)]
    t1 = 'FAIL' if 'FAIL' in v else ('PASS' if all(x == 'PASS' for x in v) else 'inconclusive')
    cell = lambda s_: f'{fmt(s_[0])} [{fmt(s_[1])}, {fmt(s_[2])}]'
    print(f'| {f} | {cell(lv32)} | {cell(lv48)} | {cell(gr32)} | {cell(gr48)} | {", ".join(v)} | {t1} |')
print()

# T4 cosines (replicate 0)
print('## T4 coherence: cosine of the output error vectors (L = 64) from cuts 32 and 48, replicate 0, per net\n')
for f in fams:
    cs = []
    for s, (d, z) in r1.items():
        k1, k2 = f'0/32/{f}', f'0/48/{f}'
        if k1 in z.files and k2 in z.files:
            TM = z['TM'][63]
            e1 = z[k1][-1] - TM; e2 = z[k2][-1] - TM
            cs.append(float(e1 @ e2 / (np.linalg.norm(e1) * np.linalg.norm(e2))))
    if cs:
        print(f'- {f}: ' + ' '.join(f'{c:+.2f}' for c in cs))
print()

# error decomposition parallel / orthogonal to the truth mean (cut 32, L = 64, replicate 0)
print('## Error at L = 64 from cut 32 split along / orthogonal to the true mean vector (replicate 0, mean over nets)\n')
for f in fams:
    par, ort = [], []
    for s, (d, z) in r1.items():
        k = f'0/32/{f}'
        if k in z.files:
            TM = z['TM'][63]; tv = float(z['TV'][63].mean())
            e = z[k][-1] - TM; u = TM / np.linalg.norm(TM)
            p = float(e @ u); par.append(p * p / len(e) / tv); ort.append(float((e @ e - p * p) / len(e) / tv))
    if par:
        print(f'- {f}: along the mean {np.mean(par):.2e}, orthogonal {np.mean(ort):.2e} (raw, floors not subtracted)')
print()

# ------------------------------------------------------------------ R3: fixed L/n
print('## T2 fixed L/n = 1/4: R_F(L/2; L) and R_F(3L/4; L) (mean over nets), ratio 512 x 128 / 128 x 32 '
      '(geometric mean of per-net ratios)\n')
r3a = load('r3', 128, 32); r3c = load('r3', 512, 128)
sizes = [(128, 32, r3a), (256, 64, r1), (512, 128, r3c)]
print('| family | cut | 128 x 32 | 256 x 64 | 512 x 128 | ratio 512 / 128 | per-net ratios | verdict |')
print('|---|---|---|---|---|---|---|---|')
for f in ('EMP', 'PEMP', 'G', 'PG', 'PI', 'PB16', 'PB32', 'PC3I'):
    for frac in (0.5, 0.75):
        vals, pernet = [], {}
        for n, L, R in sizes:
            c = int(L * frac)
            v = {s: rep_mean(d, c, f, L) for s, (d, _) in R.items()}
            v = {s: x for s, x in v.items() if x is not None}
            vals.append(np.mean(list(v.values())) if v else math.nan)
            pernet[n] = v
        rat = [pernet[512][s] / pernet[128][s] for s in NETS if s in pernet[512] and s in pernet[128]
               and pernet[128][s] > 0 and pernet[512][s] > 0]
        g = math.exp(np.mean(np.log(rat))) if rat else math.nan
        ver = '' if math.isnan(g) else ('width-stable' if g <= 1 else ('width-growing' if g >= 2 else '-'))
        print(f'| {f} | {frac:g} L | ' + ' | '.join(fmt(x) for x in vals) + f' | {g:.2f} | ' +
              ' '.join(f'{x:.2f}' for x in rat) + f' | {ver} |')
print()

# ------------------------------------------------------------------ R2: composition
r2 = load('r2', 256, 64)
print('## T3 composition from layer 32 (256 x 64): chain nMSE C at L = 48 and 64 for NC = 2^20 and 2^21, and '
      'B = 2 C(2^21) - C(2^20)\n')
print('| chain | net | C48 (2^20) | C48 (2^21) | C64 (2^20) | C64 (2^21) | B48 | B64 |')
print('|---|---|---|---|---|---|---|---|')
Bs = {}
for s, (d, z) in r2.items():
    keys = sorted(set('/'.join(k.split('/')[1:]) for k in d['runs']))
    for kk in keys:
        a, b = d['runs'].get(f'20/{kk}'), d['runs'].get(f'21/{kk}')
        if a is None or b is None:
            continue
        c0 = d['c0']
        C = {(lnc, L): (a if lnc == 20 else b)['nmse'][L - c0] for lnc in (20, 21) for L in (48, 64)}
        B48 = 2 * C[(21, 48)] - C[(20, 48)]; B64 = 2 * C[(21, 64)] - C[(20, 64)]
        Bs.setdefault(kk, {})[s] = (B48, B64)
        print(f'| {kk} | {s} | {fmt(C[(20, 48)])} | {fmt(C[(21, 48)])} | {fmt(C[(20, 64)])} | {fmt(C[(21, 64)])} | '
              f'{fmt(B48)} | {fmt(B64)} |')
print()
for kk, v in Bs.items():
    if not kk.startswith('every'):
        continue
    ok = all(B64 <= 1e-5 and B64 - B48 <= 3e-6 for B48, B64 in v.values())
    bad = all(B64 >= 3 * B48 or B64 >= 1e-4 for B48, B64 in v.values())
    print(f'- {kk}: ' + ('bounded and useful' if ok else ('unbounded' if bad else 'inconclusive')))
print()
# two-cut interaction residual d = e_{32,48} - e_32 - e_48 (NC = 2^21), with e_32, e_48 from R1 replicate 0
print('## T4 two-cut interaction (NC = 2^21 chains vs R1 single cuts, L = 64): |e32|^2, |e48|^2, |e32,48|^2, |d|^2 '
      '(raw nMSE units, no floors subtracted)\n')
for s, (d, z) in r2.items():
    if s not in r1:
        continue
    z1 = r1[s][1]
    TM = z['TM'][63]; tv = float(z['TV'][63].mean()); n = len(TM)
    for f in ('G', 'PI', 'PB16'):
        k2 = f'21/two/{f}'
        if k2 not in z.files or f'0/32/{f}' not in z1.files:
            continue
        e32 = z1[f'0/32/{f}'][-1] - TM; e48 = z1[f'0/48/{f}'][-1] - TM; e2 = z[k2][-1] - TM
        dd = e2 - e32 - e48
        q = lambda e: float(e @ e) / n / tv
        print(f'- net {s} {f}: |e32|^2 {q(e32):.2e}, |e48|^2 {q(e48):.2e}, |e32,48|^2 {q(e2):.2e}, |d|^2 {q(dd):.2e}')
print()

# ------------------------------------------------------------------ R4: linearised composition
r4 = load('r4', 256, 64)
print('## R4 linearised composition: S_F = sum over cuts 32..63 of (e_F - e_EMP) at L = 64, as nMSE\n')
for s, (d, z) in r4.items():
    TM = z['TM'][63]; tv = float(z['TV'][63].mean()); n = len(TM)
    for f in ('G', 'PI', 'PB16'):
        S = np.zeros(n)
        ok = True
        for l in range(32, 64):
            if f'{l}/{f}' not in z.files or f'{l}/EMP' not in z.files:
                ok = False; break
            S += z[f'{l}/{f}'] - z[f'{l}/EMP']
        if ok:
            single = [d['runs'][f'{l}/{f}']['nmse'][0] for l in range(32, 64)]
            print(f'- net {s} {f}: |S|^2 = {float(S @ S) / n / tv:.2e}; sum of single-cut nMSE {sum(single):.2e}; '
                  f'largest single {max(single):.2e} (cut {32 + int(np.argmax(single))})')
