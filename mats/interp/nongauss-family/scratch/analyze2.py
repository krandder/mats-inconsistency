"""Score Amendments 1 and 2 (PREREG.md) from the second GPU job, with R1 (first job) for paired comparisons.
python scratch/analyze2.py RUNDIR2 RUNDIR1"""
import glob, json, math, os, sys
import numpy as np

R2, R1 = sys.argv[1], sys.argv[2]
NETS = [113, 114, 115, 116]
T3 = 3.182446


def fmt(x):
    return '-' if x is None or (isinstance(x, float) and math.isnan(x)) else f'{x:.2e}'


def ci(v):
    v = np.array([x for x in v if x is not None])
    if len(v) < 2:
        return (float(v.mean()) if len(v) else math.nan, math.nan, math.nan)
    t = {2: 12.706, 3: 4.303, 4: T3}[len(v)]
    h = t * v.std(ddof=1) / math.sqrt(len(v))
    return (v.mean(), v.mean() - h, v.mean() + h)


def verdict(lo, hi, thr):
    if math.isnan(hi):
        return 'n/a'
    return 'PASS' if hi <= thr else ('FAIL' if lo > thr else 'inconclusive')


def get(d, cut, fam, L, rep=None):
    vals = [sc['nmse'][L - cut] for k, sc in d['runs'].items()
            if int(k.split('/')[1]) == cut and k.split('/')[2] == fam and (rep is None or int(k.split('/')[0]) == rep)]
    return float(np.mean(vals)) if vals else None


a1 = {s: json.load(open(f)) for s in NETS for f in [f'{R2}/a1/e1_256_64_{s}.json'] if os.path.exists(f)}
r1 = {s: json.load(open(f)) for s in NETS for f in [f'{R1}/r1/e1_256_64_{s}.json'] if os.path.exists(f)}
print('# Amendments 1 and 2 (generated by scratch/analyze2.py)\n')
print('## A1 / T5c: single cuts at 256 x 64 (replicate 0 fit paths; PB16, PB32, PI, G from R1 replicate 0)\n')
fams = ['EMP', 'G', 'PI', 'PB16', 'PB32', 'PB64', 'PB128', 'PBA8', 'PBA16', 'PBS16', 'PBW8', 'PBW16', 'PBW32']
for cut in (32, 48):
    print(f'### cut {cut}\n')
    print('| family | R(c; c+1) | R(c; c+8) | R(c; 64) | growth R(c;64) - R(c;c+8) [95% interval] | level verdict | growth verdict | per-net R(c; 64) |')
    print('|---|---|---|---|---|---|---|---|')
    for f in fams:
        src = a1 if any(get(d, cut, f, 64) is not None for d in a1.values()) else r1
        rep = None if src is a1 else 0
        a = [get(src[s], cut, f, cut + 1, rep) for s in src]
        b = [get(src[s], cut, f, cut + 8, rep) for s in src]
        c = [get(src[s], cut, f, 64, rep) for s in src]
        if all(x is None for x in c):
            continue
        gr = ci([x - y for x, y in zip(c, b) if x is not None and y is not None])
        lv = ci(c)
        print(f'| {f} | {fmt(np.mean([x for x in a if x is not None]))} | {fmt(np.mean([x for x in b if x is not None]))} | '
              f'{fmt(lv[0])} [{fmt(lv[1])}, {fmt(lv[2])}] | {fmt(gr[0])} [{fmt(gr[1])}, {fmt(gr[2])}] | '
              f'{verdict(lv[1], lv[2], 1e-5)} | {verdict(gr[1], gr[2], 3e-6)} | ' + ' '.join(fmt(x) for x in c) + ' |')
    print()
# H1: PBA8 vs PB16 per net
print('## H1: ratio R_PB16 / R_PBA8 at L = 64 per net (>= 2 supports; <= 1.5 does not)\n')
for cut in (32, 48):
    rat = []
    for s in NETS:
        if s in a1 and s in r1:
            x = get(r1[s], cut, 'PB16', 64, 0); y = get(a1[s], cut, 'PBA8', 64)
            if x is not None and y is not None and y > 0:
                rat.append(x / y)
    print(f'- cut {cut}: ' + ' '.join(f'{x:.2f}' for x in rat))
print()
# H2: smallest k with R_PBk <= 3 R_EMP + 2e-6 (mean over nets)
print('## H2: smallest k (PB ladder) with mean R_PBk(c; 64) <= 3 x mean R_EMP(c; 64) + 2e-6\n')
for cut in (32, 48):
    emp = np.mean([get(a1[s], cut, 'EMP', 64) for s in a1])
    thr = 3 * emp + 2e-6                      # literal PREREG rule (mean EMP may be negative)
    found = None
    for k in (16, 32, 64, 128):
        src = r1 if k in (16, 32) else a1
        rep = 0 if src is r1 else None
        v = np.mean([get(src[s], cut, f'PB{k}', 64, rep) for s in src if get(src[s], cut, f'PB{k}', 64, rep) is not None])
        print(f'- cut {cut}: PB{k} {v:.2e} (threshold {thr:.2e})')
        if found is None and v <= thr:
            found = k
    print(f'  -> smallest k: {found}')
print()

# T5a
print('## T5a: spread-weighted downstream sensitivity S (radial direction removed); mean over nets\n')
print('| size | cut | Lo | S: k90 | S: k99 | S: PR | S top-1/4/16 share | PMP: k90 | PMP: k99 | state PR |')
print('|---|---|---|---|---|---|---|---|---|---|')
amp = {}
for f in sorted(glob.glob(f'{R2}/a2/amp_*.json')):
    for r in json.load(open(f)):
        amp.setdefault((r['n'], r['cut'], r['Lo']), []).append(r)
for (n, cut, Lo), rs in sorted(amp.items()):
    m = lambda key, sub: np.mean([r[sub][key] for r in rs])
    tops = '/'.join(f"{np.mean([r['S']['top'][str(t)] if str(t) in r['S']['top'] else r['S']['top'][t] for r in rs]):.2f}"
                    for t in (1, 4, 16))
    print(f"| {n} x {rs[0]['L']} | {cut} | {Lo} | {m('k90', 'S'):.1f} | {m('k99', 'S'):.1f} | {m('pr', 'S'):.1f} | {tops} | "
          f"{m('k90', 'PMP'):.1f} | {m('k99', 'PMP'):.1f} | {np.mean([r['C_pr'] for r in rs]):.1f} |")
print()
for frac, name in ((0.75, '3L/4'), (0.5, 'L/2')):
    vals = {}
    for (n, cut, Lo), rs in amp.items():
        L = rs[0]['L']
        if cut == int(L * frac) and Lo == L:
            vals[n] = np.mean([r['S']['k99'] for r in rs])
    if 128 in vals and 512 in vals:
        g = vals[512] / vals[128]
        v = 'few' if g <= 1.5 else ('about linear in n' if g >= 3 else 'sublinear')
        print(f'- T5a rule, cut {name}: k99(S) 128 / 256 / 512 = {vals.get(128, math.nan):.1f} / {vals.get(256, math.nan):.1f} / '
              f'{vals[512]:.1f}; ratio 512/128 = {g:.2f} -> {v}')
print()

# T5b
print("## T5b: finite-time Lyapunov spectra of single paths (mean over paths and nets)\n")
print("| size | cut | L' | L'/n | N_surv(e^-1) | N_surv(e^-2) | N_surv(e^-3) | 2n/L' | PR of s^2 | rank | gap/layer k=2 / 4 / 16 |")
print('|---|---|---|---|---|---|---|---|---|---|---|')
ly = {}
for f in sorted(glob.glob(f'{R2}/a2/lyap_*.json')) + sorted(glob.glob('runs/cpu_a2/lyap_*.json')):
    for r in json.load(open(f)):
        ly.setdefault((r['n'], r['cut'], r['Lp']), []).append(r)
for (n, cut, Lp), rs in sorted(ly.items()):
    ns = lambda t: np.mean([r['n_surv'][str(t)] for r in rs])
    gp = lambda k: np.mean([r['gap_per_layer'][k - 1] for r in rs])
    print(f"| {n} | {cut} | {Lp} | {Lp / n:.3f} | {ns(1):.1f} | {ns(2):.1f} | {ns(3):.1f} | {2 * n / Lp:.0f} | "
          f"{np.mean([r['pr'] for r in rs]):.2f} | {np.mean([r['rank'] for r in rs]):.0f} | {gp(2):+.3f} / {gp(4):+.3f} / {gp(16):+.3f} |")
print()
for ratio in (1 / 32, 1 / 16, 1 / 8):
    v = {n: np.mean([r['n_surv']['1'] for r in rs]) for (n, cut, Lp), rs in ly.items() if abs(Lp / n - ratio) < 1e-9}
    if 128 in v and 512 in v:
        print(f"- T5b rule, L'/n = {ratio:.4f}: N_surv(e^-1) 128 / 256 / 512 = {v[128]:.1f} / {v.get(256, math.nan):.1f} / "
              f"{v[512]:.1f}; ratio {v[512] / v[128]:.2f} -> {'O(1)' if v[512] / v[128] <= 1.5 else 'grows'}")
print()

