# ---------------------------------------------------------------- Amendment 3: needed joint block k* against width
if len(sys.argv) > 3:
    R3d = sys.argv[3]
    print('## Amendment 3 (H3): smallest PB block k with mean R_PBk(c; L) <= 3 x mean R_EMP(c; L) + 2e-6\n')
    print('| size | cut | EMP | ' + ' | '.join(f'PB{k}' for k in (8, 16, 32, 64, 128, 256)) + ' | k* |')
    print('|---|---|---|' + '---|' * 6 + '---|')
    kstar, kstar_c = {}, {}
    for n, L, cuts, src in ((128, 32, (16, 24), 'a3'), (256, 64, (32, 48), None), (512, 128, (64, 96), 'a3')):
        for cut in cuts:
            vals = {}
            if src is None:
                for k in (16, 32):
                    vals[k] = np.mean([get(r1[s], cut, f'PB{k}', L, 0) for s in r1])
                for k in (64, 128):
                    vals[k] = np.mean([get(a1[s], cut, f'PB{k}', L) for s in a1])
                emp = np.mean([get(a1[s], cut, 'EMP', L) for s in a1])
            else:
                D = {s: json.load(open(f)) for s in NETS for f in [f'{R3d}/{src}/e1_{n}_{L}_{s}.json'] if os.path.exists(f)}
                for k in (8, 16, 32, 64, 128, 256):
                    v = [get(D[s], cut, f'PB{k}', L) for s in D]
                    v = [x for x in v if x is not None]
                    if v:
                        vals[k] = np.mean(v)
                emp = np.mean([get(D[s], cut, 'EMP', L) for s in D])
            thr = 3 * emp + 2e-6                  # literal PREREG rule
            thr_c = 3 * max(emp, 0) + 2e-6        # clipped variant (used in the first draft; not pre-registered)
            ks = [k for k in sorted(vals) if vals[k] <= thr]
            ksc = [k for k in sorted(vals) if vals[k] <= thr_c]
            kstar[(n, round(cut / L, 2))] = ks[0] if ks else None
            kstar_c[(n, round(cut / L, 2))] = ksc[0] if ksc else None
            print(f'| {n} x {L} | {cut} | {emp:.1e} | ' + ' | '.join(fmt(vals.get(k)) for k in (8, 16, 32, 64, 128, 256)) +
                  f' | {ks[0] if ks else "not reached"} (threshold {thr:.1e}; clipped variant {ksc[0] if ksc else "not reached"}) |')
    print()
    ratios = []
    for frac in (0.5, 0.75):
        a, b = kstar.get((128, frac)), kstar.get((512, frac))
        if a and b:
            ratios.append(b / a)
        if a and b:
            r = b / a
            print(f'- cut {frac} L: k* 128 / 256 / 512 = {a} / {kstar.get((256, frac))} / {b}; ratio {r:.1f} -> '
                  + ('O(1)' if r <= 1.5 else ('about linear in n' if r >= 3 else 'sublinear')))
        else:
            print(f'- cut {frac} L: k* 128 / 256 / 512 = {a} / {kstar.get((256, frac))} / {b} (a value not reached)')
    if len(ratios) == 2:
        overall = 'O(1)' if all(r <= 1.5 for r in ratios) else ('about linear in n' if all(r >= 3 for r in ratios)
                                                                  else 'sublinear')
        print(f'- H3 overall (both relative cuts, literal rule): {overall}')
    print('- clipped-threshold variant (not pre-registered): ' + ', '.join(
        f'{k}: {v}' for k, v in sorted(kstar_c.items())))

# ---------------------------------------------------------------- Amendment 4: composition of large-block PB families
if len(sys.argv) > 4:
    R4d = sys.argv[4]
    print('\n## Amendment 4: composition (projection at every layer from l0; "two" = at l0 and 3L/4 only)\n')
    print('| size | net | chain | C(3L/4) 2^20 / 2^21 | C(L) 2^20 / 2^21 | B(3L/4) | B(L) |')
    print('|---|---|---|---|---|---|---|')
    verdicts = {}
    for n, L, c0, l3 in ((256, 64, 32, 48), (128, 32, 16, 24)):
        for s in NETS:
            f = f'{R4d}/a4/e2_{n}_{L}_{s}.json'
            if not os.path.exists(f):
                continue
            d = json.load(open(f))
            for kk in sorted(set('/'.join(k.split('/')[1:]) for k in d['runs'])):
                a, b = d['runs'].get(f'20/{kk}'), d['runs'].get(f'21/{kk}')
                if a is None or b is None:
                    continue
                C = lambda r, LL: r['nmse'][LL - c0]
                B3 = 2 * C(b, l3) - C(a, l3); BL = 2 * C(b, L) - C(a, L)
                verdicts.setdefault((n, kk), []).append((B3, BL))
                print(f'| {n} x {L} | {s} | {kk} | {C(a, l3):.1e} / {C(b, l3):.1e} | {C(a, L):.1e} / {C(b, L):.1e} | '
                      f'{B3:+.1e} | {BL:+.1e} |')
    print()
    for (n, kk), v in verdicts.items():
        if not kk.startswith('every'):
            continue
        ok = all(BL <= 1e-5 and BL - B3 <= 3e-6 for B3, BL in v)
        bad = all(BL >= 3 * B3 or BL >= 1e-4 for B3, BL in v)
        print(f'- {n}: {kk}: ' + ('bounded and useful' if ok else ('unbounded' if bad else 'inconclusive')))
