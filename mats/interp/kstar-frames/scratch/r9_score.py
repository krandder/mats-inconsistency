def theta_coh(th, y, level, nb=24):
    """State angle at which the binned median of y falls below level (log-interpolated); nan if never / always."""
    edges = np.logspace(-5, math.log10(math.pi), nb + 1)
    mids, med = [], []
    for a, b in zip(edges[:-1], edges[1:]):
        m = (th > a) & (th <= b)
        if m.sum() >= 8:
            mids.append(math.sqrt(a * b)); med.append(np.median(y[m]))
    mids, med = np.array(mids), np.array(med)
    below = np.where(med < level)[0]
    if len(below) == 0:
        return float('inf')
    j = below[0]
    if j == 0:
        return float(mids[0])
    x0, x1, y0, y1 = math.log(mids[j - 1]), math.log(mids[j]), med[j - 1], med[j]
    return float(math.exp(x0 + (level - y0) * (x1 - x0) / (y1 - y0)))


