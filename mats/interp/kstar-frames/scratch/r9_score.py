def layer_check(name, cond, label, cmin=2):
    """PREREG rule: path means, then net means; a cell is (n, L, c). Per-net counts are printed as a supplement."""
    viol, tot, pviol, ptot = [], 0, 0, 0
    for L in (32, 16):
        for n in WID:
            rows = [r for r in (jA(n, s, L) for s in SEEDS) if r]
            for c in range(cmin, L):
                vals = []
                for r in rows:
                    if L - c < 8 or name not in r['scores'] or str(c) not in r['scores'][name]:
                        continue
                    O, CS, T = r['scores'][name][str(c)]
                    if O is None or (isinstance(O, float) and math.isnan(O)):
                        continue
                    vals.append((O, CS, r['chance'][str(c)]))
                    ptot += 1
                    pviol += not cond(O, CS, r['chance'][str(c)])
                if not vals:
                    continue
                O, CS, ch = (float(np.mean([v[i] for v in vals])) for i in range(3))
                tot += 1
                if not cond(O, CS, ch):
                    viol.append((n, L, c, round(O, 3), round(CS, 3)))
    print(f"{label}: {verdict(not viol, tot)} ({len(viol)} of {tot} net-mean cells violate; per net {pviol} of {ptot}) "
          f"{viol[:8]}{' ...' if len(viol) > 8 else ''}")


