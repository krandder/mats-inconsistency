def logC_at(e, c, theta):
    """log C_c(theta), extrapolated below the smallest theta with >= 100 pairs using the local slope there."""
    d = e[str(c)]
    grid, C, slope, npairs = map(np.array, (d['grid'], d['C'], d['slope'], d['pairs_within']))
    j = int(np.argmax(npairs >= 100))
    if theta >= grid[j]:
        return float(np.interp(math.log(theta), np.log(grid), np.log(np.maximum(C, 1e-300)))), False
    # slope from the two grid points above the resolution limit (a secant, robust to the noisy gradient)
    sl = (math.log(C[j + 2]) - math.log(C[j])) / (math.log(grid[j + 2]) - math.log(grid[j]))
    return float(math.log(C[j]) + sl * (math.log(theta) - math.log(grid[j]))), True


