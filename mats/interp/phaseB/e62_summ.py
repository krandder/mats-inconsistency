"""E62 analysis (PREREG-B amendment 70): does given source membership also remove the code dependence and the run-to-run variation?
Inputs: results/e62/<arm>.npz (e62_run.py: own, ownf, fix), the E59 references results/e59/<arm>.npz (ctrl, uni, unif; e59_run.py),
the sign-family costs from the nets' registered evaluations (results/e60, results/e30, results/e37, results/e53: sign_pc, sign_kl)
and the types (middle-range rom sign) from the same files.
Statistics per arm (acquired nets), exactly as e59_summ.py: mean base KL; code share = sum code_pc / sum code_kl; sign share = sum
sign_pc / sum sign_kl; c_seed(K) = mean over the 5 subsets of the K-net ensemble's KL reduction / its members' mean KL; model-based
shared part = (K KL_ens - KL_members) / (K - 1), varying part = members' mean KL - shared part (E51's second-order model).
Intervals: 2,000 bootstrap resamples of nets for the shares (with multiplicities, numpy seed 620).
Predictions (registered in amendment 70):
  P234  code share(own) <= 0.5 x code share(ctrl) and code share(ownf) <= 0.5 x code share(ctrl);
  P235  c_seed(9)(own) <= c_seed(9)(ctrl) - 0.15 and c_seed(7)(ownf) <= c_seed(7)(ctrl) - 0.15;
  P236  c_seed(9)(fix) <= c_seed(9)(ctrl) - 0.15.
Also (descriptive): ctrl's code share by type (A, B), from E59's per-net values.
usage: python e62_summ.py -> results/e62.json, results/e62_tables.md   (E62_DIR overrides results/e62 for plumbing)
"""
import json, os
import numpy as np

rng = np.random.default_rng(620)
D62 = os.environ.get('E62_DIR', 'results/e62')
SRC = dict(ctrl=('results/e59/ctrl.npz', 'results/e37/e37_ctrl_s%d.npz'), uni=('results/e59/uni.npz', 'results/e53/e53_uni_s%d.npz'),
           unif=('results/e59/unif.npz', 'results/e53/e53_unif_s%d.npz'),
           own=(D62 + '/own.npz', 'results/e60/e60_own_s%d.npz'), ownf=(D62 + '/ownf.npz', 'results/e60/e60_ownf_s%d.npz'),
           fix=(D62 + '/fix.npz', 'results/e30/fix_s%d.npz'))
ARMS = ('ctrl', 'uni', 'unif', 'own', 'ownf', 'fix')


def share(num, den):
    num, den = np.asarray(num, float), np.asarray(den, float)
    pt = float(num.sum() / den.sum())
    bs = []
    for _ in range(2000):
        j = rng.integers(0, len(num), len(num)); bs.append(num[j].sum() / den[j].sum())
    return [pt, float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))]


def arm_stats(a):
    p, pat = SRC[a]
    if not os.path.exists(p):
        return None
    z = np.load(p)
    o = dict(n=int(len(z['seeds'])), seeds=[int(s) for s in z['seeds']], kl=float(z['kl'].mean()))
    if np.all(np.isfinite(z['code_pc'])):
        o['code_share'] = share(z['code_pc'], z['code_kl'])
    sp, sk, typ = [], [], []
    for s in z['seeds']:
        r = np.load(pat % s, allow_pickle=True)
        typ.append('A' if float(r['rom_middle']) < 0 else 'B')
        if 'sign_pc' in r.files:
            sp.append(float(r['sign_pc'])); sk.append(float(r['sign_kl']))
    o['types'] = typ
    if sp:
        o['sign_share'] = share(sp, sk)
    for k in (7, 9):
        if 'ens%d_kl' % k in z.files:
            mem = z['ens%d_member_kl' % k]; red = z['ens%d_pc' % k]; ens = mem - red
            o['c_seed%d' % k] = float(np.mean(red / mem)); o['ens%d' % k] = float(ens.mean()); o['members%d' % k] = float(mem.mean())
            o['shared%d' % k] = float(np.mean((k * ens - mem) / (k - 1))); o['varying%d' % k] = float(np.mean(mem - (k * ens - mem) / (k - 1)))
    if a == 'ctrl' and 'code_share' in o:
        for t in ('A', 'B'):
            j = [i for i, x in enumerate(typ) if x == t]
            if j:
                o['code_share_' + t] = share(z['code_pc'][j], z['code_kl'][j]) + [len(j)]
    return o


def main():
    res = dict(arms={}, predictions={})
    for a in ARMS:
        o = arm_stats(a)
        if o is not None:
            res['arms'][a] = o
    A = res['arms']; pr = res['predictions']
    if all(x in A and 'code_share' in A[x] for x in ('ctrl', 'own', 'ownf')):
        cc = A['ctrl']['code_share'][0]
        pr['P234'] = dict(ctrl=cc, own=A['own']['code_share'], ownf=A['ownf']['code_share'], bar=0.5 * cc,
                          holds=bool(A['own']['code_share'][0] <= 0.5 * cc and A['ownf']['code_share'][0] <= 0.5 * cc))
    if all(x in A for x in ('ctrl', 'own', 'ownf')) and 'c_seed9' in A['own'] and 'c_seed7' in A['ownf']:
        c9, c7 = A['ctrl']['c_seed9'], A['ctrl']['c_seed7']
        pr['P235'] = dict(ctrl9=c9, own9=A['own']['c_seed9'], ctrl7=c7, ownf7=A['ownf']['c_seed7'],
                          holds=bool(A['own']['c_seed9'] <= c9 - 0.15 and A['ownf']['c_seed7'] <= c7 - 0.15))
    if all(x in A for x in ('ctrl', 'fix')) and 'c_seed9' in A['fix']:
        c9 = A['ctrl']['c_seed9']
        pr['P236'] = dict(ctrl9=c9, fix9=A['fix']['c_seed9'], holds=bool(A['fix']['c_seed9'] <= c9 - 0.15))
    md = ['# E62 tables (generated by e62_summ.py)', '',
          '| arm | nets | A / B | mean KL | sign share [95% CI] | code share [95% CI] | c_seed(7) | c_seed(9) | shared(7) / varying(7) | shared(9) / varying(9) |',
          '|---' * 10 + '|']
    for a, o in A.items():
        f = lambda k: ('%.3f [%.3f, %.3f]' % tuple(o[k][:3])) if k in o else '-'
        g = lambda k: ('%.4f / %.4f' % (o['shared%d' % k], o['varying%d' % k])) if ('shared%d' % k) in o else '-'
        md.append('| %s | %d | %d / %d | %.4f | %s | %s | %s | %s | %s | %s |' % (
            a, o['n'], o['types'].count('A'), o['types'].count('B'), o['kl'], f('sign_share'), f('code_share'),
            '%.2f' % o['c_seed7'] if 'c_seed7' in o else '-', '%.2f' % o['c_seed9'] if 'c_seed9' in o else '-', g(7), g(9)))
    if 'ctrl' in A and 'code_share_A' in A['ctrl']:
        md += ['', 'ctrl code share by type (descriptive): A %s (%d nets), B %s (%d nets)' % (
            '%.3f [%.3f, %.3f]' % tuple(A['ctrl']['code_share_A'][:3]), A['ctrl']['code_share_A'][3],
            '%.3f [%.3f, %.3f]' % tuple(A['ctrl']['code_share_B'][:3]), A['ctrl']['code_share_B'][3])]
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    out = os.environ.get('E62_JSON', 'results/e62.json'); tab = os.environ.get('E62_TAB', 'results/e62_tables.md')
    json.dump(res, open(out, 'w'), indent=1, default=float)
    open(tab, 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
