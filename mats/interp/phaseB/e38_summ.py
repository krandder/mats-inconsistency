"""E38 analysis (PREREG-B amendment 46): does size close the gap between the signed and the sign-free formats?
Inputs: results/e38/<tag>.npz from e37_eval.py (tags e38_<cfg><fmt>_s<seed>, cfg in w64, w128, d3; fmt in ctrl, mag) and, for the
width-32 depth-2 reference, E37's pure arms results/e37/e37_ctrl_s*.npz and e37_mag_s*.npz (the same fixed 90,000-step schedule).
Per config c: r(c) = mean K_mag / mean K_ctrl over seeds acquired (gap < 0.10) in both arms of c (paired; E30's ratio of means),
the reduction rho(c) = 1 - r(c); 2,000 bootstrap resamples of seeds.
Predictions:
  P171  rho(w64) >= 0.3 and rho(w128) >= 0.3 (width does not close the gap);
  P172  rho(d3) <= 0.5 x rho(w32) (depth closes at least half of it; the per-token-transform-before-pooling account).
usage: python e38_summ.py -> results/e38.json, results/e38_tables.md
"""
import glob, json, os
import numpy as np

CFGS = ['w32', 'w64', 'w128', 'd3']
rng = np.random.default_rng(38)


def load():
    R = {}
    for f in sorted(glob.glob('results/e38/e38_*_s*.npz')):
        tag = os.path.basename(f)[4:-4]; cf, s = tag.rsplit('_s', 1)
        fm = 'ctrl' if cf.endswith('ctrl') else 'mag'; c = cf[:-len(fm)]
        R[(c, fm, int(s))] = {k: (v.item() if hasattr(v, 'item') else v) for k, v in dict(np.load(f)).items()}
    for fm in ('ctrl', 'mag'):
        for f in sorted(glob.glob('results/e37/e37_%s_s*.npz' % fm)):
            s = int(os.path.basename(f)[:-4].rsplit('_s', 1)[1])
            R[('w32', fm, s)] = {k: (v.item() if hasattr(v, 'item') else v) for k, v in dict(np.load(f)).items()}
    return R


def main():
    R = load()
    acq = {k: v['gap'] < 0.10 for k, v in R.items()}
    res = dict(per_net={'%s%s_s%d' % k: v for k, v in R.items()}, configs={})
    for c in CFGS:
        seeds = sorted({s for (cc, _, s) in R if cc == c})
        common = [s for s in seeds if all((c, fm, s) in R and acq[(c, fm, s)] for fm in ('ctrl', 'mag'))]
        o = dict(seeds=seeds, common=common)
        for fm in ('ctrl', 'mag'):
            acs = [s for s in seeds if (c, fm, s) in R and acq[(c, fm, s)]]
            q = dict(n=sum((c, fm, s) in R for s in seeds), n_acquired=len(acs))
            if acs:
                v = lambda k: [R[(c, fm, s)][k] for s in acs]
                q.update(K=float(np.mean(v('gap'))), K_median=float(np.median(v('gap'))), n_A=int(sum(x < 0 for x in v('rom_middle'))),
                         n_B=int(sum(x > 0 for x in v('rom_middle'))), rom_large=float(np.mean(v('rom_large'))),
                         lab=float(np.mean(v('lab_last'))), xq=float(np.mean(v('xq'))))
                have = [s for s in acs if 'sign_pc' in R[(c, fm, s)]]
                if have:
                    q['c_sign'] = float(sum(R[(c, fm, s)]['sign_pc'] for s in have) / sum(R[(c, fm, s)]['sign_kl'] for s in have))
            o[fm] = q
        if len(common) >= 3:
            f = lambda ss: 1 - np.mean([R[(c, 'mag', s)]['gap'] for s in ss]) / np.mean([R[(c, 'ctrl', s)]['gap'] for s in ss])
            bs = [f(list(rng.choice(common, len(common)))) for _ in range(2000)]
            o['rho'] = [float(f(common)), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))]
            o['per_seed_ratio'] = {s: R[(c, 'mag', s)]['gap'] / R[(c, 'ctrl', s)]['gap'] for s in common}
        res['configs'][c] = o
    rho = lambda c: (res['configs'].get(c) or {}).get('rho')
    pr = {}
    if rho('w64') and rho('w128'):
        pr['P171'] = dict(rho_w64=rho('w64'), rho_w128=rho('w128'), holds=bool(rho('w64')[0] >= 0.3 and rho('w128')[0] >= 0.3))
    if rho('d3') and rho('w32'):
        pr['P172'] = dict(rho_d3=rho('d3'), rho_w32=rho('w32'), holds=bool(rho('d3')[0] <= 0.5 * rho('w32')[0]))
    res['predictions'] = pr
    md = ['# E38 tables (generated by e38_summ.py)', '',
          '| config | format | nets | acquired | mean KL | median KL | A / B | rom large | lab (last block) | xq | sign red. / KL |',
          '|---' * 11 + '|']
    for c in CFGS:
        for fm in ('ctrl', 'mag'):
            q = res['configs'][c].get(fm, {})
            if not q.get('n_acquired'):
                md.append('| %s | %s | %d | 0 |' % (c, fm, q.get('n', 0))); continue
            md.append('| %s | %s | %d | %d | %.4f | %.4f | %d / %d | %.3f | %.3f | %.4f | %s |' % (
                c, fm, q['n'], q['n_acquired'], q['K'], q['K_median'], q['n_A'], q['n_B'], q['rom_large'], q['lab'], q['xq'],
                '%.3f' % q['c_sign'] if 'c_sign' in q else '-'))
    md += ['', '| config | paired seeds | reduction 1 - K_mag/K_ctrl [95% CI] |', '|---|---|---|']
    for c in CFGS:
        o = res['configs'][c]
        md.append('| %s | %d | %s |' % (c, len(o['common']), '%.2f [%.2f, %.2f]' % tuple(o['rho']) if o.get('rho') else '-'))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e38.json', 'w'), indent=1, default=float)
    open('results/e38_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1, default=float))


if __name__ == '__main__':
    main()
