"""E42 analysis (PREREG-B amendment 50): do E31's and E35's single-lineage dynamics generalise across lineages?
Inputs: results/e42/s<seed>_step<step>.npz (e42_run.py) and E37's final ctrl nets (results/e37/e37_ctrl_s<seed>.npz: acquisition,
gap < 0.10, and type, middle-range rom sign). Lineages: E37's acquired ctrl seeds except 5 and 6 (E16's replays reproduce them).
Per lineage: r_flip = median sign-flip cost over 20,000-30,000 steps / median over 10,000-15,000 (E31's windows); r_xq likewise.
Predictions:
  P179  median over A-type lineages of r_flip <= 0.5, and over B-type lineages >= 0.7 (E31's P154);
  P180  the same for r_xq (E31's P155);
  P181  in at least two thirds of B-type lineages, lab at 90,000 steps exceeds lab at 3,000 (E35's B pattern);
  P182  every B-type lineage among seeds 8-11 ends with lab >= 0.30 (above every A base in E34).
usage: python e42_summ.py -> results/e42.json, results/e42_tables.md
"""
import glob, json, os
import numpy as np

W1, W2 = (10000, 12000, 15000), (20000, 25000, 30000)


def main():
    T = {}
    for f in sorted(glob.glob('results/e42/s*_step*.npz')):
        z = dict(np.load(f)); T.setdefault(int(z['seed']), {})[int(z['step'])] = {k: float(v) for k, v in z.items()}
    lin = {}
    for s in sorted(T):
        if s in (5, 6):
            continue
        e = np.load('results/e37/e37_ctrl_s%d.npz' % s)
        if float(e['gap']) >= 0.10:
            continue
        lin[s] = 'B' if float(e['rom_middle']) > 0 else 'A'
    med = lambda s, k, W: float(np.median([T[s][st][k] for st in W if st in T[s]]))
    rows = {}
    for s, ty in lin.items():
        rows[s] = dict(type=ty, r_flip=med(s, 'flip_pc', W2) / med(s, 'flip_pc', W1), r_xq=med(s, 'xq', W2) / med(s, 'xq', W1),
                       lab3k=T[s].get(3000, {}).get('lab'), lab90k=T[s].get(90000, {}).get('lab'),
                       neg_over_flip_end=T[s][90000]['neg_pc'] / T[s][90000]['flip_pc'] if 90000 in T[s] else None)
    A = [s for s in rows if rows[s]['type'] == 'A']; B = [s for s in rows if rows[s]['type'] == 'B']
    m = lambda ss, k: float(np.median([rows[s][k] for s in ss])) if ss else None
    pr = {}
    if A and B:
        pr['P179'] = dict(A=m(A, 'r_flip'), B=m(B, 'r_flip'), nA=len(A), nB=len(B), holds=bool(m(A, 'r_flip') <= 0.5 and m(B, 'r_flip') >= 0.7))
        pr['P180'] = dict(A=m(A, 'r_xq'), B=m(B, 'r_xq'), nA=len(A), nB=len(B), holds=bool(m(A, 'r_xq') <= 0.5 and m(B, 'r_xq') >= 0.7))
    if B:
        up = [s for s in B if rows[s]['lab90k'] is not None and rows[s]['lab3k'] is not None and rows[s]['lab90k'] > rows[s]['lab3k']]
        pr['P181'] = dict(rising=len(up), of=len(B), holds=bool(len(up) >= 2 * len(B) / 3))
    B8 = [s for s in B if s >= 8]
    if B8:
        pr['P182'] = dict(lab90k={s: rows[s]['lab90k'] for s in B8}, holds=bool(all(rows[s]['lab90k'] >= 0.30 for s in B8)))
    traj = {s: {st: {k: T[s][st][k] for k in ('flip_pc', 'neg_pc', 'flip_kl', 'xq', 'lab', 'summ')} for st in sorted(T[s])} for s in T}
    res = dict(lineages=rows, predictions=pr, trajectories=traj)
    md = ['# E42 tables (generated by e42_summ.py)', '', '| seed | type | r_flip | r_xq | lab 3k | lab 90k | negation/flip at 90k |', '|---' * 7 + '|']
    for s, r in rows.items():
        md.append('| %d | %s | %.2f | %.2f | %s | %s | %s |' % (s, r['type'], r['r_flip'], r['r_xq'], '%.3f' % r['lab3k'] if r['lab3k'] is not None else '-',
                                                             '%.3f' % r['lab90k'] if r['lab90k'] is not None else '-',
                                                             '%.2f' % r['neg_over_flip_end'] if r['neg_over_flip_end'] else '-'))
    md += ['', '| seed | step | KL | flip cost | neg cost | xq | lab | summ |', '|---' * 8 + '|']
    for s in sorted(T):
        for st in sorted(T[s]):
            o = T[s][st]
            md.append('| %d | %d | %.4f | %.5f | %.5f | %.4f | %.3f | %.3f |' % (s, st, o['flip_kl'], o['flip_pc'], o['neg_pc'], o['xq'], o['lab'], o['summ']))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e42.json', 'w'), indent=1, default=float)
    open('results/e42_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1, default=float))


if __name__ == '__main__':
    main()
