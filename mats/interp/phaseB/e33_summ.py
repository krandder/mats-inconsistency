"""E33 analysis (PREREG-B amendment 41).
removed(arm) = (sum pc_none - sum pc_arm) / (sum pc_none - sum pc_all), pooled over a group's nets: the share of the negation
cost (KL reduction from geometric averaging over the 9 negation-family samples) that disappears when block 1's output at the arm's
tokens is replaced by its average over the negation orbit. The 'all' arm defines zero (its outputs are identical across the
orbit; any remaining cost is grid truncation). KL ratio(arm) = sum klbase_arm / sum klbase_none (base episode).
  P158  B bases: removed(summ) >= 0.5.
  P159  B bases: KL ratio(all) <= 0.9.
usage: python e33_summ.py -> results/e33.json, results/e33_tables.md
"""
import json, os
import numpy as np
import e26_summ as SM

ARMS = ['none', 'summ', 'lab', 'query', 'all']


def main():
    rows = json.load(open('results/e26_nets.json'))
    nets = {}
    for s in ('M', 'G'):
        for r in rows:
            if r['set'] == s:
                f = os.path.join('results/e33', s, r['tag'] + '.npz')
                if os.path.exists(f):
                    nets[r['tag']] = (s, {k: float(v) for k, v in np.load(f).items()})
    groups = dict(A=SM.A_BASES, B=SM.B_BASES, M=[t for t, (s, _) in nets.items() if s == 'M'],
                  G=[t for t, (s, _) in nets.items() if s == 'G'])
    res = dict(groups={}, per_net={t: dict(set=s, **o) for t, (s, o) in nets.items()})
    for g, tags in groups.items():
        L = [nets[t][1] for t in tags if t in nets]
        if not L:
            continue
        pc = {a: sum(x['pc_' + a] for x in L) for a in ARMS}
        kb = {a: sum(x['klbase_' + a] for x in L) for a in ARMS}
        o = dict(n=len(L), mean_pc={a: pc[a] / len(L) for a in ARMS},
                 removed={a: (pc['none'] - pc[a]) / (pc['none'] - pc['all']) for a in ARMS},
                 kl_ratio={a: kb[a] / kb['none'] for a in ARMS}, mean_kl_none=kb['none'] / len(L))
        res['groups'][g] = o
    pr = {}
    if 'B' in res['groups'] and res['groups']['B']['n'] == 6:
        b = res['groups']['B']
        pr['P158'] = dict(removed_summ=b['removed']['summ'], holds=bool(b['removed']['summ'] >= 0.5))
        pr['P159'] = dict(kl_ratio_all=b['kl_ratio']['all'], holds=bool(b['kl_ratio']['all'] <= 0.9))
    res['predictions'] = pr
    md = ['# E33 tables (generated by e33_summ.py)', '',
          '| group | nets | mean KL | negation cost (none) | removed: summary tokens | labelled tokens | query token | all | KL ratio: summ | lab | query | all |',
          '|---' * 12 + '|']
    for g, o in res['groups'].items():
        md.append('| %s | %d | %.4f | %.5f | %.2f | %.2f | %.2f | %.2f | %.3f | %.3f | %.3f | %.3f |' % (
            g, o['n'], o['mean_kl_none'], o['mean_pc']['none'], o['removed']['summ'], o['removed']['lab'], o['removed']['query'],
            o['removed']['all'], o['kl_ratio']['summ'], o['kl_ratio']['lab'], o['kl_ratio']['query'], o['kl_ratio']['all']))
    md += ['', '| net | set | ' + ' | '.join('pc %s' % a for a in ARMS) + ' | ' + ' | '.join('KL %s' % a for a in ARMS) + ' |', '|---' * (2 + 2 * len(ARMS)) + '|']
    for t, o in res['per_net'].items():
        md.append('| %s | %s | ' % (t, o['set']) + ' | '.join('%.5f' % o['pc_' + a] for a in ARMS) + ' | ' +
                  ' | '.join('%.4f' % o['klbase_' + a] for a in ARMS) + ' |')
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e33.json', 'w'), indent=1)
    open('results/e33_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1))


if __name__ == '__main__':
    main()
