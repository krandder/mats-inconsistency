"""E46 analysis (PREREG-B amendment 54): is the map from initial weights to solution type smooth? Perturbed initialisations.
Inputs: results/e46/e46_eps<E>_d<draw>_s<seed>.npz (e43_eval.py on the perturbed nets) and the parents
results/e43_parents/e37_ctrl_s<seed>.npz (E37's ctrl nets: type, KL, predictive mean).
Per perturbation size eps (pooled over the 2 draws): agreement A(eps) = share of acquired nets (gap < 0.10) with the parent's
type (middle-range rom sign); the similarity of each net's deviation from the Bayes mean to its parent's (4,000 test episodes); the
median |KL / parent KL - 1|. 2,000 bootstrap resamples of parents.
Predictions:
  P189  A(0.003) >= 0.9 (the type is locally stable in the initial weights);
  P190  A(0.3) <= 0.8 (a large perturbation acts like a new initialisation).
usage: python e46_summ.py -> results/e46.json, results/e46_tables.md
"""
import glob, json, os
import numpy as np

rng = np.random.default_rng(46)


def rd(f):
    return {k: (v.item() if np.ndim(v) == 0 else v) for k, v in dict(np.load(f)).items()}


def main():
    mb = np.load('/home/agent/workspaces/mats/work/tiny-pfn/runs/testset.npz')['mean_bayes'][:4000].astype(np.float64)
    par = {int(os.path.basename(f)[:-4].rsplit('_s', 1)[1]): rd(f) for f in glob.glob('results/e43_parents/e37_ctrl_s*.npz')}
    par = {s: o for s, o in par.items() if o['gap'] < 0.10}
    typ = lambda o: 'B' if o['rom_middle'] > 0 else 'A'
    corr = lambda u, v: float(np.corrcoef(u - mb, v - mb)[0, 1])
    rows = []
    for f in sorted(glob.glob('results/e46/e46_eps*_d*_s*.npz')):
        tag = os.path.basename(f)[4:-4]; e, d, s = tag.split('_'); e, d, s = float(e[3:]), int(d[1:]), int(s[1:])
        if s not in par:
            continue
        o = rd(f); p = par[s]
        rows.append(dict(eps=e, draw=d, seed=s, acquired=bool(o['gap'] < 0.10), type=typ(o), parent_type=typ(p), agree=typ(o) == typ(p),
                         gap=o['gap'], parent_gap=p['gap'], rho=corr(o['pm'], p['pm']), lab=o['lab_last'], xq=o['xq']))
    seeds = sorted(par); res = dict(rows=rows, eps={})
    for e in sorted({x['eps'] for x in rows}):
        R = [x for x in rows if x['eps'] == e and x['acquired']]
        # post-review correction (2026-10-30): the registered version turned the resampled parents into a set, which dropped
        # bootstrap multiplicities; rows of a parent drawn k times now count k times. Point estimates are unchanged.
        def ag(ss):
            v = [x['agree'] for s in ss for x in R if x['seed'] == s]
            return float(np.mean(v)) if v else np.nan
        bs = [ag(list(rng.choice(seeds, len(seeds)))) for _ in range(2000)]
        res['eps'][e] = dict(n=len(R), n_total=sum(x['eps'] == e for x in rows), agreement=[ag(seeds), float(np.nanpercentile(bs, 2.5)),
                             float(np.nanpercentile(bs, 97.5))], n_agree=int(sum(x['agree'] for x in R)),
                             rho_median=float(np.median([x['rho'] for x in R])),
                             kl_absdiff_median=float(np.median([abs(x['gap'] / x['parent_gap'] - 1) for x in R])))
    A = lambda e: (res['eps'].get(e) or {}).get('agreement')
    pr = {}
    if A(0.003):
        pr['P189'] = dict(A=A(0.003), holds=bool(A(0.003)[0] >= 0.9))
    if A(0.3):
        pr['P190'] = dict(A=A(0.3), holds=bool(A(0.3)[0] <= 0.8))
    res['predictions'] = pr
    md = ['# E46 tables (generated by e46_summ.py)', '', '| eps | acquired / total | agreement [95% CI] | median similarity to parent | median abs KL difference |',
          '|---' * 5 + '|']
    for e, o in res['eps'].items():
        md.append('| %g | %d / %d | %.2f [%.2f, %.2f] (%d) | %.2f | %.3f |' % (e, o['n'], o['n_total'], *o['agreement'], o['n_agree'], o['rho_median'], o['kl_absdiff_median']))
    md += ['', '| seed | parent | ' + ' | '.join('eps %g d%d' % (e, d) for e in sorted(res['eps']) for d in (0, 1)) + ' |',
           '|---' * (2 + 2 * len(res['eps'])) + '|']
    for s in seeds:
        cells = []
        for e in sorted(res['eps']):
            for d in (0, 1):
                x = [r for r in rows if r['seed'] == s and r['eps'] == e and r['draw'] == d]
                cells.append('-' if not x else '%s %.4f %.2f' % (x[0]['type'] if x[0]['acquired'] else 'x', x[0]['gap'], x[0]['rho']))
        md.append('| %d | %s %.4f | ' % (s, typ(par[s]), par[s]['gap']) + ' | '.join(cells) + ' |')
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e46.json', 'w'), indent=1, default=float)
    open('results/e46_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1, default=float)); print(json.dumps({e: (o['agreement'], o['n']) for e, o in res['eps'].items()}, default=float))


if __name__ == '__main__':
    main()
