"""E59 analysis (PREREG-B amendment 67): why are uniform-pool nets closer to Bayes?
Inputs: results/e59/<arm>.npz (e59_run.py: per-net base KL and identity-code family cost; K-net ensembles), the sign-family costs
from the nets' registered evaluations (results/e37, results/e53: sign_pc, sign_kl), the cap's constrained-Bayes KL curve
(results/e55_cbkl.json) and the nets' cap scales (results/e55_geom.json, E55's final run).
Statistics per arm (acquired nets): mean base KL; code share = sum code_pc / sum code_kl; sign share = sum sign_pc / sum sign_kl
(signed formats); c_seed(K) = mean over the 5 subsets of the K-net ensemble's KL reduction / its members' mean KL; model-based
shared part = (K KL_ens - KL_members) / (K - 1) with KL_ens = members' mean KL minus the reduction (E51's second-order model).
Intervals: 2,000 bootstrap resamples of nets for the shares (with multiplicities).
Predictions (registered in amendment 67):
  P227  code share(uni) <= 0.5 x code share(ctrl) and code share(unif) <= 0.5 x code share(ctrl);
  P228  c_seed(9) of uni and of unif each <= c_seed(9) of ctrl - 0.15.
usage: python e59_summ.py -> results/e59.json, results/e59_tables.md
"""
import json, os
import numpy as np

rng = np.random.default_rng(590)
ARMS = ('ctrl', 'uni', 'unif', 'unifnoln_mag', 'unifnoln_sq')
SUB = dict(ctrl=('e37', 'e37_ctrl_s%d'), uni=('e53', 'e53_uni_s%d'), unif=('e53', 'e53_unif_s%d'), unifnoln_mag=('e53', 'e53_unifnoln_mag_s%d'),
           unifnoln_sq=('e53', 'e53_unifnoln_sq_s%d'))


def share(num, den, idx=None):
    num, den = np.asarray(num), np.asarray(den)
    pt = float(num.sum() / den.sum())
    bs = []
    for _ in range(2000):
        j = rng.integers(0, len(num), len(num)); bs.append(num[j].sum() / den[j].sum())
    return [pt, float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))]


def main():
    geo = json.load(open('results/e55_geom.json')) if os.path.exists('results/e55_geom.json') else {}
    cbkl = json.load(open('results/e55_cbkl.json'))['kl']
    cg = np.array(sorted(float(c) for c in cbkl)); kg = np.array([cbkl['%.2f' % c][0] for c in cg])
    res = dict(arms={}, predictions={})
    for a in ARMS:
        p = 'results/e59/%s.npz' % a
        if not os.path.exists(p):
            continue
        z = np.load(p); sub, pat = SUB[a]
        o = dict(n=int(len(z['seeds'])), kl=float(z['kl'].mean()), code_share=share(z['code_pc'], z['code_kl']))
        sp, sk = [], []
        for s in z['seeds']:
            r = np.load('results/%s/%s.npz' % (sub, pat % s), allow_pickle=True)
            if 'sign_pc' in r.files:
                sp.append(float(r['sign_pc'])); sk.append(float(r['sign_kl']))
        if sp:
            o['sign_share'] = share(sp, sk)
        for k in (7, 9):
            if 'ens%d_kl' % k in z.files:
                mem = z['ens%d_member_kl' % k]; red = z['ens%d_pc' % k]; ens = mem - red
                o['c_seed%d' % k] = float(np.mean(red / mem)); o['ens%d' % k] = float(ens.mean()); o['members%d' % k] = float(mem.mean())
                o['shared%d' % k] = float(np.mean((k * ens - mem) / (k - 1))); o['varying%d' % k] = float(np.mean(mem - (k * ens - mem) / (k - 1)))
        cs = [geo[pat % s]['c'] for s in z['seeds'] if (pat % s) in geo]
        if cs and a in ('uni', 'unif'):
            o['c_median'] = float(np.median(cs)); o['cap_cost_cb'] = float(np.mean(np.interp(cs, cg, kg)))
        res['arms'][a] = o
    A = res['arms']; pr = res['predictions']
    if all(x in A for x in ('ctrl', 'uni', 'unif')):
        cc = A['ctrl']['code_share'][0]
        pr['P227'] = dict(ctrl=cc, uni=A['uni']['code_share'][0], unif=A['unif']['code_share'][0],
                          holds=bool(A['uni']['code_share'][0] <= 0.5 * cc and A['unif']['code_share'][0] <= 0.5 * cc))
        if all('c_seed9' in A[x] for x in ('ctrl', 'uni', 'unif')):
            c0 = A['ctrl']['c_seed9']
            pr['P228'] = dict(ctrl=c0, uni=A['uni']['c_seed9'], unif=A['unif']['c_seed9'],
                              holds=bool(A['uni']['c_seed9'] <= c0 - 0.15 and A['unif']['c_seed9'] <= c0 - 0.15))
    md = ['# E59 tables (generated by e59_summ.py)', '', '| arm | nets | mean KL | sign share [95% CI] | code share [95% CI] | c_seed(7) | c_seed(9) | shared(7) / varying(7) | median c | cap cost (CB) |',
          '|---' * 10 + '|']
    for a, o in A.items():
        f = lambda k: ('%.3f [%.3f, %.3f]' % tuple(o[k])) if k in o else '-'
        md.append('| %s | %d | %.4f | %s | %s | %s | %s | %s | %s | %s |' % (
            a, o['n'], o['kl'], f('sign_share'), f('code_share'), '%.2f' % o['c_seed7'] if 'c_seed7' in o else '-',
            '%.2f' % o['c_seed9'] if 'c_seed9' in o else '-', ('%.4f / %.4f' % (o['shared7'], o['varying7'])) if 'shared7' in o else '-',
            '%.2f' % o['c_median'] if 'c_median' in o else '-', '%.4f' % o['cap_cost_cb'] if 'cap_cost_cb' in o else '-'))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e59.json', 'w'), indent=1, default=float)
    open('results/e59_tables.md', 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
