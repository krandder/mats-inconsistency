"""E45 analysis (PREREG-B amendment 53): are single-pass LLM answers invariant to negating a source's past errors (Bayes is)?
Inputs: results/e45_items.json, results/e45_calls.jsonl (ok answers; for each (arm, pair, version, sample) the last ok record).
Per arm and pair: a_v = mean answer over samples for version v; shift D = a_neg - a_orig; X = 2 x (mean error of the negated source in
'orig') x (its Bayes weight in 'orig'). A bias correction that subtracts a weighted mean error from a source's reading gives D = c X
with c = 1 for a full correction.
  c          OLS slope of D on X without intercept (pairs with both versions answered);
  inv        invariance ratio = mean D^2 / s2, with s2 = the retest variance (mean over prompts with two samples of
             (a1 - a2)^2 / 2; then Var(D) = s2 under invariance, so inv ~ 1); arms with one sample have no inv;
  mad        mean |answer - Bayes mean| over all answers.
Pooled = mean over the three Claude arms of a framing. 2,000 bootstrap resamples of pairs (the same for every arm).
Predictions:
  P187  stated framing: the pooled slope c over the Claude arms has a 95% interval above 0;
  P188  unstated framing: the pooled slope c over the Claude arms is >= 0.5.
usage: python e45_summ.py -> results/e45.json, results/e45_tables.md
"""
import json
import numpy as np

CLAUDE = ('haiku45', 'sonnet46', 'opus48')
rng = np.random.default_rng(45)


def main():
    items = json.load(open('results/e45_items.json'))
    it = {(x['pair'], x['version']): x for x in items}
    pairs = sorted({x['pair'] for x in items})
    A = {}
    for l in open('results/e45_calls.jsonl'):
        r = json.loads(l)
        if r['ok'] and r['answer'] is not None:
            A[(r['arm'], r['pair'], r['version'], r['sample'])] = r['answer']
    arms = sorted({k[0] for k in A})

    def stats(arm, pp):
        D, X, rt, dev = [], [], [], []
        for p in pp:
            v = {}
            for ver in ('orig', 'neg'):
                a = [A[(arm, p, ver, s)] for s in (0, 1) if (arm, p, ver, s) in A]
                if a:
                    v[ver] = float(np.mean(a)); dev += [abs(x - it[(p, ver)]['bayes_mean']) for x in a]
                if len(a) == 2:
                    rt.append((a[0] - a[1]) ** 2 / 2)
            if len(v) == 2:
                o = it[(p, 'orig')]; D.append(v['neg'] - v['orig']); X.append(2 * o['mean_err'] * o['bayes_w'][o['src']])
        D, X = np.array(D), np.array(X)
        c = float((D * X).sum() / (X * X).sum()) if len(D) else np.nan
        s2 = float(np.mean(rt)) if rt else np.nan
        return dict(n=len(D), c=c, inv=float(np.mean(D ** 2) / s2) if rt and s2 > 0 else np.nan, s2=s2,
                    rms_shift=float(np.sqrt(np.mean(D ** 2))) if len(D) else np.nan, mad=float(np.mean(dev)) if dev else np.nan)

    boots = [list(rng.choice(pairs, len(pairs))) for _ in range(2000)]
    res = dict(arms={}, pooled={})
    for a in arms:
        o = stats(a, pairs); bs = [stats(a, b) for b in boots]
        for k in ('c', 'inv'):
            vals = [b[k] for b in bs if np.isfinite(b[k])]
            o[k + '_ci'] = [float(np.percentile(vals, 2.5)), float(np.percentile(vals, 97.5))] if vals else None
        res['arms'][a] = o
    for f in ('S', 'U'):
        cl = [f'{f}_{m}' for m in CLAUDE if f'{f}_{m}' in arms]
        if not cl:
            continue
        pt = float(np.mean([res['arms'][a]['c'] for a in cl]))
        bs = [float(np.mean([stats(a, b)['c'] for a in cl])) for b in boots]
        res['pooled'][f] = dict(arms=cl, c=pt, c_ci=[float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))])
    pr = {}
    if 'S' in res['pooled']:
        pr['P187'] = dict(pooled=res['pooled']['S'], holds=bool(res['pooled']['S']['c_ci'][0] > 0))
    if 'U' in res['pooled']:
        pr['P188'] = dict(pooled=res['pooled']['U'], holds=bool(res['pooled']['U']['c'] >= 0.5))
    res['predictions'] = pr
    md = ['# E45 tables (generated by e45_summ.py)', '', '| arm | pairs | slope c [95% CI] | invariance ratio [95% CI] | retest var | RMS shift | mean abs dev from Bayes |',
          '|---' * 7 + '|']
    f2 = lambda x: '-' if x is None or not np.isfinite(x) else '%.2f' % x
    for a, o in res['arms'].items():
        md.append('| %s | %d | %s [%s, %s] | %s %s | %s | %s | %s |' % (
            a, o['n'], f2(o['c']), *(f2(x) for x in (o['c_ci'] or [np.nan, np.nan])), f2(o['inv']),
            '[%s, %s]' % tuple(f2(x) for x in o['inv_ci']) if o['inv_ci'] else '', '%.4f' % o['s2'] if np.isfinite(o['s2']) else '-',
            f2(o['rms_shift']), f2(o['mad'])))
    md += ['', '## Pooled over the Claude arms', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in res['pooled'].items()]
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e45.json', 'w'), indent=1, default=float)
    open('results/e45_tables.md', 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
