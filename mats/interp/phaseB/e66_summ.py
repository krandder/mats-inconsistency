"""E66 analysis (PREREG-B amendment 74): removing the odd (signed-error) term from block 1's pooling-head logits of the summary rows.
Inputs: results/e66/{ctrl,fix,own}.json (e66_run.py). sign share = sign_pc / sign_kl (the KL reduction of geometric averaging over sign
flips as a share of the family KL); KL factor = KL(condition) / KL(base).
Predictions (registered in amendment 74):
  P256  ctrl and fix: zeroing one pooling head's odd term multiplies the KL by >= 3 in >= 80% of the (net, head) cases;
  P257  A nets of ctrl and fix (two pooling heads): zeroing one head's odd term at least doubles the sign share in >= 80% of the
        (net, head) cases, and zeroing both gives a smaller sign share than the mean of the two single-zero conditions in >= 75% of
        the A nets;
  P258  B nets of ctrl and fix (one pooling head): zeroing its odd term changes the sign share by less than a factor 2 (ratio in
        [0.5, 2]) in >= 75% of them;
  P259  own: the median KL factor of a single-head zeroing is below ctrl's median (membership frees the norm route).
Descriptive: rom_large and rom_middle for base and all-zeroed (or the single head's zeroing in B nets); per-net tables.
usage: python e66_summ.py -> results/e66.json, results/e66_tables.md   (E66_DIR overrides results/e66)
"""
import json, os
import numpy as np

D = os.environ.get('E66_DIR', 'results/e66')


def load(c):
    p = os.path.join(D, '%s.json' % c)
    return json.load(open(p)) if os.path.exists(p) else {}


def share(d):
    return d['sign_pc'] / d['sign_kl']


def main():
    R = {c: load(c) for c in ('ctrl', 'fix', 'own')}
    rows, pr = [], {}
    single = {c: [] for c in R}; Asing, Aboth, Bchg = [], [], []
    for c, r in R.items():
        for t, o in r.items():
            b = o['base']
            for h in o['pool_heads']:
                d = o['zero%d' % h]
                single[c].append(dict(net=t, head=h, type=o['type'], kl_factor=d['kl'] / b['kl'], share_ratio=share(d) / share(b)))
            if c in ('ctrl', 'fix') and o['type'] == 'A' and len(o['pool_heads']) == 2 and 'zeroall' in o:
                sh = [share(o['zero%d' % h]) for h in o['pool_heads']]
                Aboth.append(dict(net=t, both=share(o['zeroall']), single_mean=float(np.mean(sh)), holds=bool(share(o['zeroall']) < np.mean(sh))))
            if c in ('ctrl', 'fix') and o['type'] == 'B' and len(o['pool_heads']) == 1:
                ratio = share(o['zero%d' % o['pool_heads'][0]]) / share(b); Bchg.append(dict(net=t, ratio=ratio, holds=bool(0.5 <= ratio <= 2)))
            line = [c, t, o['type'], '%.4f' % b['kl'], '%.3f' % share(b), '%.3f' % b.get('rom_large', np.nan)]
            for name in ['zero%d' % h for h in o['pool_heads']] + (['zeroall'] if 'zeroall' in o else []):
                d = o[name]; line.append('%s: KL x%.1f, share %.3f%s' % (name, d['kl'] / b['kl'], share(d), (', rom %.3f' % d['rom_large']) if 'rom_large' in d else ''))
            rows.append(line)
    cf = [x for c in ('ctrl', 'fix') for x in single[c]]
    if cf:
        f = float(np.mean([x['kl_factor'] >= 3 for x in cf])); pr['P256'] = dict(frac=f, n=len(cf), holds=bool(f >= 0.8))
    As = [x for x in cf if x['type'] == 'A']
    if As and Aboth:
        f1 = float(np.mean([x['share_ratio'] >= 2 for x in As])); f2 = float(np.mean([x['holds'] for x in Aboth]))
        pr['P257'] = dict(single_frac=f1, n_single=len(As), both_frac=f2, n_nets=len(Aboth), holds=bool(f1 >= 0.8 and f2 >= 0.75))
    if Bchg:
        f = float(np.mean([x['holds'] for x in Bchg])); pr['P258'] = dict(frac=f, n=len(Bchg), ratios=[x['ratio'] for x in Bchg], holds=bool(f >= 0.75))
    if single['own'] and single['ctrl']:
        mo = float(np.median([x['kl_factor'] for x in single['own']])); mc = float(np.median([x['kl_factor'] for x in single['ctrl']]))
        pr['P259'] = dict(median_own=mo, median_ctrl=mc, holds=bool(mo < mc))
    desc = {}
    for c in R:
        for typ in ('A', 'B'):
            W = [x for x in single[c] if x['type'] == typ]
            if W:
                desc['%s_%s' % (c, typ)] = dict(n=len(W), kl_factor_median=float(np.median([x['kl_factor'] for x in W])),
                                                share_ratio_median=float(np.median([x['share_ratio'] for x in W])))
    md = ['# E66 tables (generated by e66_summ.py)', '', '| cohort | net | type | base KL | base sign share | base rom large | conditions |', '|---|---|---|---|---|---|---|']
    md += ['| %s | %s | %s | %s | %s | %s | %s |' % tuple(l[:6] + ['; '.join(l[6:])]) for l in rows]
    md += ['', '## Medians by cohort and type (single-head zeroing)', '', '```', json.dumps(desc, indent=1), '```', '', '## Predictions', ''] + \
          ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(dict(predictions=pr, single=single, A_both=Aboth, B=Bchg, desc=desc), open(os.environ.get('E66_JSON', 'results/e66.json'), 'w'), indent=1, default=float)
    open(os.environ.get('E66_TAB', 'results/e66_tables.md'), 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
