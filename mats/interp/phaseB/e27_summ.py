"""E27 analysis (PREREG-B amendment 35): which sign and assignment information the nets use.

Per net and family F: cost_F = mean pc_F x 9/8 (KL removed by averaging the net's log-density over the family's 9 samples, which
all have the same Bayes posterior), share_F = cost_F / mean KL, and T_F = mean 9-sample variance of the log-odds (six deltas).
Contrasts: agreement-breaking part of the sign effect = cost(flip_ind) - cost(flip_joint); of the assignment effect =
cost(perm_ind) - cost(perm_joint). Groups: A and B bases (E26), set M, set G. Pooled = sums over nets; intervals from 1,000
bootstrap resamples of the bases (the same for every net), conditional on the nets.
usage: python e27_summ.py -> results/e27.json, results/e27_tables.md
"""
import json, os
import numpy as np
import e26_summ as SM
import e27_data as E7

F = E7.FAMILIES


def per_net(set_name, tag):
    f = os.path.join('results/e27', set_name, tag + '.npz')
    if not os.path.exists(f):
        return None
    z = np.load(f); n = int(z['nb']); W = SM.boot_weights(n)
    cols = [z['kl_flip_ind']] + [z['pc_' + f] * 9 / 8 for f in F] + [z['t_' + f][:, :6].sum(1) for f in F]
    M = W @ np.stack(cols, 1)                                             # (B+1, 1 + 2 len(F))
    return dict(KL=M[:, 0], **{'cost_' + f: M[:, 1 + i] for i, f in enumerate(F)},
                **{'T_' + f: M[:, 1 + len(F) + i] for i, f in enumerate(F)}, xq=float(z['xq']) if 'xq' in z.files else None)


def group(nets):
    nets = [x for x in nets if x is not None]
    KL = sum(x['KL'] for x in nets)
    out = dict(n=len(nets), mean_KL=SM.ci(KL / len(nets)))
    for f in F:
        c = sum(x['cost_' + f] for x in nets)
        out['cost_' + f] = SM.ci(c / len(nets)); out['share_' + f] = SM.ci(c / KL)
    ci_, cj = sum(x['cost_flip_ind'] for x in nets), sum(x['cost_flip_joint'] for x in nets)
    pi_, pj = sum(x['cost_perm_ind'] for x in nets), sum(x['cost_perm_joint'] for x in nets)
    out['flip_joint_over_ind'] = SM.ci(cj / ci_); out['perm_joint_over_ind'] = SM.ci(pj / pi_)
    out['agreement_part_share_of_KL'] = SM.ci(((ci_ - cj) + (pi_ - pj)) / KL)
    return out


def main():
    rows = json.load(open('results/e26_nets.json'))
    nets = {}
    for s in ('M', 'G'):
        for r in rows:
            if r['set'] == s:
                x = per_net(s, r['tag'])
                if x is not None:
                    nets[(s, r['tag'])] = x
    res = dict(groups={}, per_net={})
    sets = dict(A=[nets.get(('M', t)) for t in SM.A_BASES], B=[nets.get(('M', t)) for t in SM.B_BASES],
                M=[v for (s, t), v in nets.items() if s == 'M'], G=[v for (s, t), v in nets.items() if s == 'G'])
    for g, lst in sets.items():
        if any(x is not None for x in lst):
            res['groups'][g] = group(lst)
    for (s, t), x in nets.items():
        res['per_net'][t] = dict(set=s, KL=float(x['KL'][0]), xq=x['xq'], **{'share_' + f: float(x['cost_' + f][0] / x['KL'][0]) for f in F})
    pr = {}
    if 'B' in res['groups']:
        b = res['groups']['B']
        testable_b = bool(b['share_perm_ind'][0] >= 0.05)
        pr['P142a'] = dict(flip_joint_over_ind=b['flip_joint_over_ind'], holds=bool(b['flip_joint_over_ind'][0] <= 0.5))
        pr['P142b'] = dict(perm_ind_share_of_KL=b['share_perm_ind'], perm_joint_over_ind=b['perm_joint_over_ind'], testable=testable_b,
                           holds=(bool(b['perm_joint_over_ind'][0] <= 0.5) if testable_b else None))
    if 'A' in res['groups'] and 'B' in res['groups'] and all(x is not None for x in sets['A'] + sets['B']):
        def mean_cost(lst, f):
            return sum(x['cost_' + f] for x in lst) / len(lst)
        d_ind = mean_cost(sets['B'], 'flip_ind') - mean_cost(sets['A'], 'flip_ind')
        d_joint = mean_cost(sets['B'], 'flip_joint') - mean_cost(sets['A'], 'flip_joint')
        p_ind = mean_cost(sets['B'], 'perm_ind') - mean_cost(sets['A'], 'perm_ind')
        p_joint = mean_cost(sets['B'], 'perm_joint') - mean_cost(sets['A'], 'perm_joint')
        agree = (d_ind - d_joint) + (p_ind - p_joint); total = d_ind + p_ind
        pr['P143'] = dict(B_minus_A_flip_ind=SM.ci(d_ind), B_minus_A_flip_joint=SM.ci(d_joint), B_minus_A_perm_ind=SM.ci(p_ind),
                          B_minus_A_perm_joint=SM.ci(p_joint), agreement_part_of_difference=SM.ci(agree / total),
                          holds=bool((agree / total)[0] >= 0.5))
    # descriptive: marker across the 48 nets
    tab = [(x['xq'], (x['cost_flip_ind'][0] - x['cost_flip_joint'][0] + x['cost_perm_ind'][0] - x['cost_perm_joint'][0]) / x['KL'][0])
           for x in nets.values() if x['xq'] is not None]
    if len(tab) > 5:
        t = np.array(tab); rk = np.argsort(np.argsort(t, 0), 0)
        res['xq_vs_agreement_share_spearman'] = dict(n=len(t), rho=float(np.corrcoef(rk.T)[0, 1]))
    res['predictions'] = pr
    md = ['# E27 tables (generated by e27_summ.py)', '', '| group | nets | mean KL | ' + ' | '.join('cost share %s' % f for f in F) +
          ' | flip joint/ind | perm joint/ind | agreement part / KL |', '|---' * (6 + len(F)) + '|']
    for g, o in res['groups'].items():
        md.append('| %s | %d | %.4f | ' % (g, o['n'], o['mean_KL'][0]) + ' | '.join('%.3f [%.3f, %.3f]' % tuple(o['share_' + f]) for f in F) +
                  ' | %.2f [%.2f, %.2f] | %.2f [%.2f, %.2f] | %.3f [%.3f, %.3f] |' % (*o['flip_joint_over_ind'], *o['perm_joint_over_ind'],
                                                                                    *o['agreement_part_share_of_KL']))
    md += ['', '| net | set | KL | xq | ' + ' | '.join('share %s' % f for f in F) + ' |', '|---' * (4 + len(F)) + '|']
    for t, o in res['per_net'].items():
        md.append('| %s | %s | %.4f | %s | ' % (t, o['set'], o['KL'], '%.3f' % o['xq'] if o['xq'] is not None else '-') +
                  ' | '.join('%.3f' % o['share_' + f] for f in F) + ' |')
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    if 'xq_vs_agreement_share_spearman' in res:
        md.append('- descriptive: Spearman(xq, agreement part / KL) = %.2f over %d nets' % (res['xq_vs_agreement_share_spearman']['rho'],
                                                                                          res['xq_vs_agreement_share_spearman']['n']))
    json.dump(res, open('results/e27.json', 'w'), indent=1, default=float)
    open('results/e27_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1, default=float))


if __name__ == '__main__':
    main()
