"""E73 analysis (PREREG-B amendment 81): how the departure's three parts form over training.
Input: results/e73_traj/<tag>.json (e73_traj.py, one file per lineage; keys '<tag>@<step>'). Primary lineages: E37's 11 acquired ctrl runs (final types from the
registered evaluations results/e37/e37_ctrl_s<seed>.npz: A s0, s1, s2, s6; B s4, s5, s7, s8, s9, s10, s11). Secondary (A-type tests only):
E69's 12 h4 and E70's 12 b1h4 lineages (all A). Checkpoints 2k, 3k, 5k, 10k, 15k, 20k, 40k, 90k.
Notation at a checkpoint: base = rom_large, detq, M3 (large); R = detq - M3; Qp = base - detq.
Predictions (registered):
  P292  A: M3(5k) - M3(90k) >= 0.6 x (base(5k) - base(90k)), with base(5k) > base(90k), in >= 3 of the 4 A lineages;
  P293  B: |M3(90k) - M3(5k)| <= 0.15 x M3(5k) in >= 75% of the B lineages with a pooling head (not forced) at 5k and at 90k;
  P294  B: R(90k) <= -0.10 and R(90k) <= R(5k) - 0.10 in >= 75% of the same B lineages;
  P295  all 11: Qp(90k) < Qp(5k) in >= 75%;
  P296  A: R > 0 at every checkpoint from 10k on, in >= 3 of the 4 A lineages.
Secondary: P292 and P296 on h4 and b1h4 (as fractions, >= 75%).
usage: python e73_summ.py -> results/e73.json, results/e73_tables.md
"""
import glob, json, os
import numpy as np

STEPS = [2000, 3000, 5000, 10000, 15000, 20000, 40000, 90000]


def series(d, tag):
    out = {}
    for st in STEPS:
        o = d.get('%s@%d' % (tag, st))
        if o:
            out[st] = dict(base=o['base']['large'], mid=o['base']['middle'], detq=o['detq']['large'], M3=o['M3']['large'], M3m=o['M3']['middle'],
                           M1=o['M1']['large'], gap=o['gap'], npool=len(o['pool']), forced=o['forced'], K=o['K'])
    return out


def p292(s):
    if 5000 not in s or 90000 not in s or s[5000]['base'] <= s[90000]['base']:
        return False
    return (s[5000]['M3'] - s[90000]['M3']) >= 0.6 * (s[5000]['base'] - s[90000]['base'])


def p296(s):
    return all(v['detq'] - v['M3'] > 0 for st, v in s.items() if st >= 10000) and any(st >= 10000 for st in s)


def main():
    d = {}
    for p in glob.glob('results/e73_traj/*.json'):                 # one file per lineage (e73_traj.py OUTJSON)
        d.update(json.load(open(p)))
    typ = {}
    for sd in range(12):
        f = 'results/e37/e37_ctrl_s%d.npz' % sd
        z = np.load(f, allow_pickle=True)
        if float(z['gap']) < 0.10:
            typ['e37_ctrl_s%d' % sd] = 'A' if float(z['rom_middle']) < 0 else 'B'
    S = {t: series(d, t) for t in typ}
    A = [t for t in typ if typ[t] == 'A']; B = [t for t in typ if typ[t] == 'B']
    Bp = [t for t in B if 5000 in S[t] and 90000 in S[t] and not S[t][5000]['forced'] and not S[t][90000]['forced']]
    pr = {}
    r = [p292(S[t]) for t in A]; pr['P292'] = dict(n=[int(sum(r)), len(r)], holds=bool(sum(r) >= 3))
    r = [abs(S[t][90000]['M3'] - S[t][5000]['M3']) <= 0.15 * S[t][5000]['M3'] for t in Bp]; pr['P293'] = dict(n=[int(sum(r)), len(r)], lineages=Bp, holds=bool(bool(r) and np.mean(r) >= 0.75))
    R = lambda t, st: S[t][st]['detq'] - S[t][st]['M3']
    r = [R(t, 90000) <= -0.10 and R(t, 90000) <= R(t, 5000) - 0.10 for t in Bp]; pr['P294'] = dict(n=[int(sum(r)), len(r)], holds=bool(bool(r) and np.mean(r) >= 0.75))
    Qp = lambda t, st: S[t][st]['base'] - S[t][st]['detq']
    allt = [t for t in typ if 5000 in S[t] and 90000 in S[t]]
    r = [Qp(t, 90000) < Qp(t, 5000) for t in allt]; pr['P295'] = dict(n=[int(sum(r)), len(r)], holds=bool(bool(r) and np.mean(r) >= 0.75))
    r = [p296(S[t]) for t in A]; pr['P296'] = dict(n=[int(sum(r)), len(r)], holds=bool(sum(r) >= 3))
    sec = {}
    for coh, pat in (('h4', 'e69_h4_s%d'), ('b1h4', 'e70_b1h4_s%d')):
        tags = [pat % sd for sd in range(12) if any(k.startswith(pat % sd + '@') for k in d)]
        if tags:
            Ss = {t: series(d, t) for t in tags}
            a = [p292(Ss[t]) for t in tags]; b = [p296(Ss[t]) for t in tags]
            sec[coh] = dict(P292=[int(sum(a)), len(a)], P296=[int(sum(b)), len(b)], holds=bool(np.mean(a) >= 0.75 and np.mean(b) >= 0.75))
            S.update(Ss); typ.update({t: 'A' for t in tags})
    md = ['# E73 tables (generated by e73_summ.py)', '',
          '| lineage | type | step | gap | pooling heads | base (large / middle) | detq | M3 (large / middle) | M1 | detq - M3 | base - detq |',
          '|---|---|---|---|---|---|---|---|---|---|---|']
    for t in sorted(S, key=lambda x: (x.split('_s')[0], typ[x], int(x.rsplit('_s', 1)[1]))):
        for st, v in sorted(S[t].items()):
            md.append('| %s | %s | %d | %.4f | %d%s | %.3f / %+.3f | %.3f | %.3f / %+.3f | %.3f | %+.3f | %+.3f |' % (
                t, typ[t], st, v['gap'], v['npool'], ' (forced)' if v['forced'] else '', v['base'], v['mid'], v['detq'], v['M3'], v['M3m'], v['M1'],
                v['detq'] - v['M3'], v['base'] - v['detq']))
    md += ['', '## Medians by type and step (primary lineages)', '', '| type | step | base | M3 | detq - M3 | base - detq |', '|---|---|---|---|---|---|']
    for ty, L in (('A', A), ('B', B)):
        for st in STEPS:
            v = [S[t][st] for t in L if st in S[t]]
            if v:
                md.append('| %s | %d | %.3f | %.3f | %+.3f | %+.3f |' % (ty, st, np.median([x['base'] for x in v]), np.median([x['M3'] for x in v]),
                                                                       np.median([x['detq'] - x['M3'] for x in v]), np.median([x['base'] - x['detq'] for x in v])))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()] + ['', '## Secondary (h4, b1h4)', ''] + \
          ['- %s: %s' % (k, json.dumps(v)) for k, v in sec.items()]
    json.dump(dict(predictions=pr, secondary=sec, types=typ), open('results/e73.json', 'w'), indent=1)
    open('results/e73_tables.md', 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md[-40:]))


if __name__ == '__main__':
    main()
