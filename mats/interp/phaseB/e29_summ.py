"""E29 analysis (PREREG-B amendment 37).
Negation shifts: dm_s = m(base) - m(base, source s negated); dm'_s = the same with source s's identity vector redrawn (one new
vector for both). If the odd shift is h(errors, ...) + g(errors, source ID) with g averaging to zero over IDs, then
phi = sum dm dm' / sum dm^2 estimates the share of its variance not tied to the source's identity vector.
Costs (uncorrected KL removed by averaging over 9 samples): source-ID family (all three source IDs redrawn) and question-ID
family (all five question IDs redrawn), as shares of the mean KL. Pooled = sums over nets; intervals from 1,000 bootstrap
resamples of the bases, conditional on the nets.
usage: python e29_summ.py -> results/e29.json, results/e29_tables.md
"""
import json, os
import numpy as np
import e26_summ as SM


def cols(z):
    m = z['m']
    dm = np.stack([m[:, 0] - m[:, 1 + s] for s in range(3)], 1); dm2 = np.stack([m[:, 4 + s] - m[:, 7 + s] for s in range(3)], 1)
    return np.stack([(dm * dm2).sum(1), (dm ** 2).sum(1), (dm2 ** 2).sum(1), z['pc_sid'], z['kl_sid'], z['pc_qid'], z['kl_qid']], 1)


def main():
    rows = json.load(open('results/e26_nets.json'))
    nets = {}
    for s in ('M', 'G'):
        for r in rows:
            if r['set'] == s:
                f = os.path.join('results/e29', s, r['tag'] + '.npz')
                if os.path.exists(f):
                    nets[r['tag']] = (s, np.load(f))
    groups = dict(A=SM.A_BASES, B=SM.B_BASES, M=[t for t, (s, _) in nets.items() if s == 'M'],
                  G=[t for t, (s, _) in nets.items() if s == 'G'])
    res = dict(groups={}, per_net={})
    for g, tags in groups.items():
        zs = [nets[t][1] for t in tags if t in nets]
        if not zs:
            continue
        n = int(zs[0]['nb']); W = SM.boot_weights(n)
        C = sum(W @ cols(z) for z in zs)
        res['groups'][g] = dict(n=len(zs), stable_fraction=SM.ci(C[:, 0] / C[:, 1]),
                                corr=SM.ci(C[:, 0] / np.sqrt(C[:, 1] * C[:, 2])),
                                sid_share=SM.ci(C[:, 3] / C[:, 4]), qid_share=SM.ci(C[:, 5] / C[:, 6]),
                                mean_KL=SM.ci(C[:, 4] / len(zs)), rms_dm=SM.ci(np.sqrt(C[:, 1] / (3 * len(zs)))))
    for t, (s, z) in nets.items():
        c = cols(z).sum(0)
        res['per_net'][t] = dict(set=s, stable_fraction=float(c[0] / c[1]), sid_share=float(c[3] / c[4]), qid_share=float(c[5] / c[6]),
                                 KL=float(z['kl_sid'].mean()), rms_dm=float(np.sqrt(c[1] / (3 * len(z['m'])))))
    pr = {}
    if 'A' in res['groups'] and 'B' in res['groups']:
        a, b = res['groups']['A'], res['groups']['B']
        pr['P147'] = dict(B_stable_fraction=b['stable_fraction'], holds=bool(b['stable_fraction'][0] <= 0.5))
        pr['P148'] = dict(B_sid_share=b['sid_share'], A_sid_share=a['sid_share'], holds=bool(b['sid_share'][0] >= 2 * a['sid_share'][0]))
        pr['P149'] = dict(A_qid_share=a['qid_share'], B_qid_share=b['qid_share'],
                          holds=bool(a['qid_share'][0] <= 0.05 and b['qid_share'][0] <= 0.05))
    res['predictions'] = pr
    md = ['# E29 tables (generated by e29_summ.py)', '',
          '| group | nets | mean KL | stable fraction of the odd shift | corr(dm, dm\') | RMS dm | source-ID cost / KL | question-ID cost / KL |',
          '|---' * 8 + '|']
    for g, o in res['groups'].items():
        md.append('| %s | %d | %.4f | %.2f [%.2f, %.2f] | %.2f | %.4f | %.3f [%.3f, %.3f] | %.3f [%.3f, %.3f] |' % (
            g, o['n'], o['mean_KL'][0], *o['stable_fraction'], o['corr'][0], o['rms_dm'][0], *o['sid_share'], *o['qid_share']))
    md += ['', '| net | set | KL | stable fraction | RMS dm | source-ID cost / KL | question-ID cost / KL |', '|---' * 7 + '|']
    for t, o in res['per_net'].items():
        md.append('| %s | %s | %.4f | %.2f | %.4f | %.3f | %.3f |' % (t, o['set'], o['KL'], o['stable_fraction'], o['rms_dm'], o['sid_share'], o['qid_share']))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e29.json', 'w'), indent=1, default=float)
    open('results/e29_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1, default=float))


if __name__ == '__main__':
    main()
