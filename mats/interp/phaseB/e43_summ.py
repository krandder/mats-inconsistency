"""E43 analysis (PREREG-B amendment 51): what fixes a seed's solution type, and when? Data-order branching and initialisation swaps.
Inputs: results/e43/e43_<arm>_s<seed>.npz (branch nets) and results/e43_parents/e37_ctrl_s<seed>.npz (parents), from e43_eval.py;
tiny-pfn's test set (Bayes predictive mean).
Arms: br0 (the parent's initialisation, a new episode stream from step 0), br2k, br3k, br5k, br10k, br20k (the parent's run up to
K steps, then a new stream), newinit (a new initialisation, the parent's stream). Seeds: parents acquired (gap < 0.10) with a type.
  agreement A(arm) = share of acquired branch nets whose type (middle-range rom sign) equals the parent's;
  similarity rho(arm, s) = correlation over 4,000 test episodes of (branch mean - Bayes mean) with (parent mean - Bayes mean);
  baseline: rho between parents of different seeds and the same type.
Intervals: 2,000 bootstrap resamples of seeds.
Predictions (selection at the reliability onset):
  P183  A(br5k) >= 0.9 and A(br10k) >= 0.9;
  P184  A(br0) <= 0.8 and A(newinit) <= 0.8.
usage: python e43_summ.py -> results/e43.json, results/e43_tables.md
"""
import glob, itertools, json, os
import numpy as np

ARMS = ['br0', 'br2k', 'br3k', 'br5k', 'br10k', 'br20k', 'newinit']
rng = np.random.default_rng(43)


def rd(f):
    return {k: (v.item() if np.ndim(v) == 0 else v) for k, v in dict(np.load(f)).items()}


def main():
    mb = np.load('/home/agent/workspaces/mats/work/tiny-pfn/runs/testset.npz')['mean_bayes'][:4000].astype(np.float64)
    par = {int(os.path.basename(f)[:-4].rsplit('_s', 1)[1]): rd(f) for f in sorted(glob.glob('results/e43_parents/e37_ctrl_s*.npz'))}
    par = {s: o for s, o in par.items() if o['gap'] < 0.10}
    typ = lambda o: 'B' if o['rom_middle'] > 0 else 'A'
    R = {}
    for f in sorted(glob.glob('results/e43/e43_*_s*.npz')):
        a, s = os.path.basename(f)[4:-4].rsplit('_s', 1); R[(a, int(s))] = rd(f)
    corr = lambda u, v: float(np.corrcoef(u - mb, v - mb)[0, 1])
    rows = {}
    for (a, s), o in R.items():
        if s not in par:
            continue
        p = par[s]
        rows[(a, s)] = dict(acquired=bool(o['gap'] < 0.10), type=typ(o), parent_type=typ(p), agree=typ(o) == typ(p),
                            gap=o['gap'], parent_gap=p['gap'], rho=corr(o['pm'], p['pm']), lab=o['lab_last'], parent_lab=p['lab_last'])
    res = dict(per_net={'%s_s%d' % k: v for k, v in rows.items()}, arms={})
    for a in ARMS:
        ss = sorted(s for (aa, s) in rows if aa == a and rows[(a, s)]['acquired'])
        if not ss:
            continue
        ag = lambda q: float(np.mean([rows[(a, s)]['agree'] for s in q]))
        bs = [ag(list(rng.choice(ss, len(ss)))) for _ in range(2000)]
        res['arms'][a] = dict(n=len(ss), agreement=[ag(ss), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))],
                              n_agree=int(sum(rows[(a, s)]['agree'] for s in ss)),
                              flips={'A->B': int(sum(rows[(a, s)]['parent_type'] == 'A' and not rows[(a, s)]['agree'] for s in ss)),
                                     'B->A': int(sum(rows[(a, s)]['parent_type'] == 'B' and not rows[(a, s)]['agree'] for s in ss))},
                              rho_median=float(np.median([rows[(a, s)]['rho'] for s in ss])),
                              kl_ratio_median=float(np.median([rows[(a, s)]['gap'] / rows[(a, s)]['parent_gap'] for s in ss])))
    base = [corr(par[s]['pm'], par[t]['pm']) for s, t in itertools.combinations(sorted(par), 2) if typ(par[s]) == typ(par[t])]
    res['baseline_rho_same_type'] = dict(median=float(np.median(base)) if base else None, n_pairs=len(base))
    pB = np.mean([typ(o) == 'B' for o in par.values()]) if par else np.nan
    res['chance_agreement'] = float(pB ** 2 + (1 - pB) ** 2)
    A = lambda a: (res['arms'].get(a) or {}).get('agreement')
    pr = {}
    if A('br5k') and A('br10k'):
        pr['P183'] = dict(br5k=A('br5k'), br10k=A('br10k'), holds=bool(A('br5k')[0] >= 0.9 and A('br10k')[0] >= 0.9))
    if A('br0') and A('newinit'):
        pr['P184'] = dict(br0=A('br0'), newinit=A('newinit'), holds=bool(A('br0')[0] <= 0.8 and A('newinit')[0] <= 0.8))
    res['predictions'] = pr
    md = ['# E43 tables (generated by e43_summ.py)', '',
          '| arm | acquired | agreement with parent type [95% CI] | A->B | B->A | median similarity to parent | median KL / parent KL |',
          '|---' * 7 + '|']
    for a, o in res['arms'].items():
        md.append('| %s | %d | %.2f [%.2f, %.2f] (%d of %d) | %d | %d | %.2f | %.2f |' % (
            a, o['n'], *o['agreement'], o['n_agree'], o['n'], o['flips']['A->B'], o['flips']['B->A'], o['rho_median'], o['kl_ratio_median']))
    md += ['', 'chance agreement (parent type frequencies): %.2f; baseline similarity between different parents of the same type: %s (%d pairs)'
           % (res['chance_agreement'], res['baseline_rho_same_type']['median'], res['baseline_rho_same_type']['n_pairs']), '',
           '| seed | parent | ' + ' | '.join(ARMS) + ' |', '|---' * (len(ARMS) + 2) + '|']
    for s in sorted(par):
        cells = []
        for a in ARMS:
            o = rows.get((a, s))
            cells.append('-' if o is None else '%s %.4f %.2f' % (o['type'] if o['acquired'] else 'x', o['gap'], o['rho']))
        md.append('| %d | %s %.4f | ' % (s, typ(par[s]), par[s]['gap']) + ' | '.join(cells) + ' |')
    md += ['', '(cells: type, test KL, similarity to the parent)', '', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e43.json', 'w'), indent=1, default=float)
    open('results/e43_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1, default=float)); print(json.dumps(res['arms'], default=float))


if __name__ == '__main__':
    main()
