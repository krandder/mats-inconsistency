"""E70 analysis (PREREG-B amendment 78): b1h4 (four heads in block 1 only) and ownmag (membership given, sign-free inputs).
Inputs: results/e70/e70_b1h4_s<seed>.npz (e48_eval_w1.py), results/e70/e70_ownmag_s<seed>.npz (e60_eval.py), results/e70_heads/<tag>.json
(e70_heads.py); comparisons results/e37/e37_ctrl_s<seed>.npz, results/e37/e37_mag_s<seed>.npz (GPU), results/e60/e60_own_s<seed>.npz (CPU).
Acquired: gap < 0.10. Bootstrap: 2,000 resamples of seeds (numpy seed 700).
Predictions (registered in amendment 78):
  P271  >= 75% of the acquired b1h4 nets are A-type;
  P272  >= 75% of them have >= 2 pooling heads and >= 1 consensus head in block 1;
  P273  the paired mean-KL ratios ownmag / own and ownmag / mag both have lower 95% limits >= 0.80;
  P274  mean rom_large of ownmag <= 0.03.
Also: the additive extrapolation KL_add = own + mag - ctrl per seed (seeds acquired in all four cells) with its interval, against
ownmag's mean; the multiplicative interaction mean(log ctrl - log own - log mag + log ownmag) with its interval.
usage: python e70_summ.py -> results/e70.json, results/e70_tables.md
"""
import glob, json, os
import numpy as np

rng = np.random.default_rng(700)


def ev(p):
    if not os.path.exists(p):
        return None
    z = np.load(p, allow_pickle=True)
    return {k: float(z[k]) for k in z.files if z[k].ndim == 0 and np.issubdtype(z[k].dtype, np.number)}


def boot(f, seeds):
    vals = []
    for _ in range(2000):
        j = list(rng.choice(seeds, len(seeds)))
        vals.append(f(j))
    return [float(f(seeds)), float(np.percentile(vals, 2.5)), float(np.percentile(vals, 97.5)), len(seeds)]


def main():
    C = {'b1h4': {s: ev('results/e70/e70_b1h4_s%d.npz' % s) for s in range(12)}, 'ownmag': {s: ev('results/e70/e70_ownmag_s%d.npz' % s) for s in range(12)},
         'ctrl': {s: ev('results/e37/e37_ctrl_s%d.npz' % s) for s in range(12)}, 'mag': {s: ev('results/e37/e37_mag_s%d.npz' % s) for s in range(12)},
         'own': {s: ev('results/e60/e60_own_s%d.npz' % s) for s in range(12)}}
    acq = {a: [s for s, r in d.items() if r is not None and r['gap'] < 0.10] for a, d in C.items()}
    heads = {int(o['tag'].rsplit('_s', 1)[1]): o for o in (json.load(open(p)) for p in glob.glob('results/e70_heads/*.json'))}
    res = dict(acquired=acq, predictions={}); pr = res['predictions']
    b = acq['b1h4']
    if b:
        nA = sum(C['b1h4'][s]['rom_middle'] < 0 for s in b)
        pr['P271'] = dict(A=int(nA), acquired=len(b), holds=bool(nA >= 0.75 * len(b)))
        both = [s for s in b if s in heads and heads[s]['n_pool'] >= 2 and heads[s]['n_consensus'] >= 1]
        pr['P272'] = dict(n=len(both), acquired=len(b), holds=bool(len(both) >= 0.75 * len(b)))
        res['b1h4'] = dict(kl=float(np.mean([C['b1h4'][s]['gap'] for s in b])), rom_large=float(np.mean([C['b1h4'][s]['rom_large'] for s in b])),
                           sign_share=float(sum(C['b1h4'][s]['sign_pc'] for s in b) / sum(C['b1h4'][s]['sign_kl'] for s in b)),
                           kl_ratio_ctrl=boot(lambda j: np.mean([C['b1h4'][s]['gap'] for s in j]) / np.mean([C['ctrl'][s]['gap'] for s in j]), [s for s in b if s in acq['ctrl']]))
    o = acq['ownmag']
    if o:
        g = lambda a, j: np.mean([C[a][s]['gap'] for s in j])
        so = [s for s in o if s in acq['own']]; sm = [s for s in o if s in acq['mag']]
        r_own = boot(lambda j: g('ownmag', j) / g('own', j), so); r_mag = boot(lambda j: g('ownmag', j) / g('mag', j), sm)
        verdict = 'redundant' if (r_own[1] >= 0.8 and r_mag[1] >= 0.8) else ('partly separate' if (r_own[2] < 0.8 or r_mag[2] < 0.8) else 'undecided')
        pr['P273'] = dict(ratio_own=r_own, ratio_mag=r_mag, verdict=verdict, holds=bool(verdict == 'redundant'))
        rl = float(np.mean([C['ownmag'][s]['rom_large'] for s in o])); pr['P274'] = dict(rom_large=rl, holds=bool(rl <= 0.03))
        s4 = [s for s in o if s in acq['own'] and s in acq['mag'] and s in acq['ctrl']]
        add = boot(lambda j: np.mean([C['own'][s]['gap'] + C['mag'][s]['gap'] - C['ctrl'][s]['gap'] for s in j]), s4)
        mult = boot(lambda j: np.mean([np.log(C['ctrl'][s]['gap']) - np.log(C['own'][s]['gap']) - np.log(C['mag'][s]['gap']) + np.log(C['ownmag'][s]['gap']) for s in j]), s4)
        om4 = float(np.mean([C['ownmag'][s]['gap'] for s in s4]))
        res['ownmag'] = dict(kl=float(np.mean([C['ownmag'][s]['gap'] for s in o])), rom_large=rl, rom_middle=float(np.mean([C['ownmag'][s]['rom_middle'] for s in o])),
                             additive_extrapolation=add, ownmag_on_same_seeds=om4, above_additive_upper=bool(om4 > add[2]), multiplicative_interaction=mult)
    md = ['# E70 tables (generated by e70_summ.py)', '', '| seed | b1h4: KL, type, rom | pooling / consensus heads | ownmag: KL, type, rom | own | mag | ctrl |', '|---|---|---|---|---|---|---|']
    t = lambda r: '-' if r is None else ('%.4f %s %.3f' % (r['gap'], 'stall' if r['gap'] >= 0.10 else ('A' if r['rom_middle'] < 0 else 'B'), r['rom_large']))
    for s in range(12):
        h = heads.get(s)
        md.append('| %d | %s | %s | %s | %s | %s | %s |' % (s, t(C['b1h4'][s]), ('%d / %d' % (h['n_pool'], h['n_consensus'])) if h else '-', t(C['ownmag'][s]), t(C['own'][s]), t(C['mag'][s]), t(C['ctrl'][s])))
    md += ['', '```', json.dumps({k: res[k] for k in ('b1h4', 'ownmag') if k in res}, indent=1), '```', '', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e70.json', 'w'), indent=1, default=float)
    open('results/e70_tables.md', 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
