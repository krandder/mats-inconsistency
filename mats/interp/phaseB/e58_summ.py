"""E58 analysis (PREREG-B amendment 66): does setting the LayerNorm cap scale by design (a frozen input embedding, everything else
trained) set the big-miss departure?
Arms (sep format, seeds 0-5; train_frz.py): unif (E53's uniform factorised pool) with the embedding frozen at c = 1, 2, 4; learned
pool (baseline architecture) frozen at c = 1, 4. Every other parameter starts as in E53's unif / E37's ctrl net of the seed.
Inputs: results/e58/<tag>.npz (e56_eval.py); the constrained-Bayes table results/e55_cbtable.json (grid points 1, 2 and 4); c of
each trained net re-measured by lngeom.py (must equal the design, the embedding being frozen).
Acquired: gap < 0.10. 2,000 bootstrap resamples of seeds, with multiplicities.
Predictions (registered in amendment 66):
  P225  uniform pool: at each designed c the mean rom_large and the mean rom_middle are each within 0.03 of constrained Bayes at
        that c (c = 1: 0.211 / 0.176; 2: 0.107 / 0.053; 4: 0.033 / 0.014), and the mean rom_large falls from c = 1 to 2 to 4;
  P226  learned pool: rom_large(c = 1) > rom_large(c = 4) in >= 5 of the 6 seeds (acquired in both arms), and the mean
        difference is >= 0.05.
usage: python e58_summ.py -> results/e58.json, results/e58_tables.md
"""
import glob, json, os, sys
import numpy as np
import torch

sys.path.insert(0, '/home/agent/workspaces/mats/work/tiny-pfn')
import e56_fmt as F  # noqa: E402
import lngeom as G  # noqa: E402

rng = np.random.default_rng(58)
NB = 2000
ARMS = ('unif_c1', 'unif_c2', 'unif_c4', 'lrn_c1', 'lrn_c4')
CDES = dict(unif_c1=1.0, unif_c2=2.0, unif_c4=4.0, lrn_c1=1.0, lrn_c4=4.0)


def main():
    tab = json.load(open('results/e55_cbtable.json'))['rom']
    z = np.load('results/e27_data.npz')
    Xs, _ = F.make_X(z['o'][:500, 0], z['y'][:500], z['semb'][:500], z['qemb'][:500], 'sep')
    R = {}
    for f in sorted(glob.glob('results/e58/e58_*.npz')):
        tag = os.path.basename(f)[:-4]; arm = tag[4:].rsplit('_s', 1)[0]; s = int(tag.rsplit('_s', 1)[1])
        r = {k: (v.item() if hasattr(v, 'item') else v) for k, v in dict(np.load(f, allow_pickle=True)).items()}
        sd = torch.load(os.path.join('runs/e58', tag, 'model.pt'), map_location='cpu')
        r['c'] = G.geom_wb(sd['inp.weight'].numpy(), sd['inp.bias'].numpy(), Xs)['c_median']
        R[(arm, s)] = r
    acq = {k: v['gap'] < 0.10 for k, v in R.items()}
    res = dict(arms={}, predictions={}, per_net={'%s_s%d' % k: {kk: vv for kk, vv in v.items() if not isinstance(vv, np.ndarray)} for k, v in R.items()})
    for a in ARMS:
        acs = [s for s in range(6) if (a, s) in R and acq[(a, s)]]
        cb = tab['%.2f' % CDES[a]]
        o = dict(n=sum((a, s) in R for s in range(6)), n_acquired=len(acs), c_design=CDES[a], cb_large=cb['large'], cb_middle=cb['middle'])
        if acs:
            v = lambda k: np.array([R[(a, s)][k] for s in acs])
            bs = [list(rng.choice(acs, len(acs))) for _ in range(NB)]
            o.update(c_measured=float(np.median(v('c'))), K=float(v('gap').mean()), rom_large=float(v('rom_large').mean()),
                     rom_middle=float(v('rom_middle').mean()),
                     rom_large_ci=[float(np.percentile([np.mean([R[(a, s)]['rom_large'] for s in q]) for q in bs], p)) for p in (2.5, 97.5)],
                     rom_middle_ci=[float(np.percentile([np.mean([R[(a, s)]['rom_middle'] for s in q]) for q in bs], p)) for p in (2.5, 97.5)],
                     n_A=int((v('rom_middle') < 0).sum()), lab=float(v('lab_last').mean()))
            if all('sign_pc' in R[(a, s)] for s in acs):
                o['c_sign'] = float(v('sign_pc').sum() / v('sign_kl').sum())
        res['arms'][a] = o
    pr = res['predictions']
    U = [res['arms'].get(a, {}) for a in ('unif_c1', 'unif_c2', 'unif_c4')]
    if all(u.get('n_acquired') for u in U):
        within = all(abs(u['rom_large'] - u['cb_large']) <= 0.03 and abs(u['rom_middle'] - u['cb_middle']) <= 0.03 for u in U)
        mono = U[0]['rom_large'] > U[1]['rom_large'] > U[2]['rom_large']
        pr['P225'] = dict(measured=[[u['rom_large'], u['rom_middle']] for u in U], cb=[[u['cb_large'], u['cb_middle']] for u in U],
                          within=bool(within), monotone=bool(mono), holds=bool(within and mono))
    ss = [s for s in range(6) if all((a, s) in R and acq[(a, s)] for a in ('lrn_c1', 'lrn_c4'))]
    if ss:
        d = [R[('lrn_c1', s)]['rom_large'] - R[('lrn_c4', s)]['rom_large'] for s in ss]
        pr['P226'] = dict(seeds=ss, diffs=d, n_positive=int(sum(x > 0 for x in d)), mean_diff=float(np.mean(d)),
                          holds=bool(sum(x > 0 for x in d) >= 5 and np.mean(d) >= 0.05))
    md = ['# E58 tables (generated by e58_summ.py)', '', '| arm | nets | acquired | designed c | measured c | mean KL | rom large [95% CI] | CB large | rom middle [95% CI] | CB middle | A / B | lab | sign share |',
          '|---' * 13 + '|']
    for a in ARMS:
        o = res['arms'][a]
        if not o.get('n_acquired'):
            md.append('| %s | %d | 0 |' % (a, o['n'])); continue
        md.append('| %s | %d | %d | %.1f | %.3f | %.4f | %.3f [%.3f, %.3f] | %.3f | %.3f [%.3f, %.3f] | %.3f | %d / %d | %.3f | %s |' % (
            a, o['n'], o['n_acquired'], o['c_design'], o['c_measured'], o['K'], o['rom_large'], *o['rom_large_ci'], o['cb_large'],
            o['rom_middle'], *o['rom_middle_ci'], o['cb_middle'], o['n_A'], o['n_acquired'] - o['n_A'], o['lab'],
            '%.3f' % o['c_sign'] if 'c_sign' in o else '-'))
    md += ['', '| seed | ' + ' | '.join(ARMS) + ' |', '|---' * (len(ARMS) + 1) + '|']
    for s in range(6):
        cell = lambda a: '-' if (a, s) not in R else '%.4f %.3f / %.3f%s' % (R[(a, s)]['gap'], R[(a, s)]['rom_large'], R[(a, s)]['rom_middle'], '' if acq[(a, s)] else ' stall')
        md.append('| %d | %s |' % (s, ' | '.join(cell(a) for a in ARMS)))
    md += ['', 'Cells: test KL, rom large / rom middle.', '', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e58.json', 'w'), indent=1, default=float)
    open('results/e58_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1, default=float))


if __name__ == '__main__':
    main()
