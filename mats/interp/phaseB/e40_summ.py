"""E40 analysis (PREREG-B amendment 48): the sign-invariance test in a second world (t2_world.py, in-context linear regression with
an unknown noise level). Inputs: results/e40/<tag>.npz from e40_eval.py, tags e40_d<D><fmt>_s<seed>.
Acquired: test gap < 0.5 x the level-blind reference's gap. Per D: K_fmt = mean gap over acquired nets; the paired reduction
rho = 1 - mean K_canon / mean K_ctrl over seeds acquired in both (E30's ratio of means); c_sign = the ctrl nets' pooled
sign-flip KL reduction / pooled family KL (uncorrected); c_neg likewise for the joint negation. 2,000 bootstrap resamples of seeds.
Predictions (D = 2):
  P174  c_sign >= 0.05 (the nets depend on the per-example signs, which Bayes ignores);
  P175  rho >= 1.5 x c_sign and rho >= 0.1 (building the invariance in gains more than its measured cost, as in E30).
usage: python e40_summ.py -> results/e40.json, results/e40_tables.md
"""
import glob, json, os
import numpy as np

rng = np.random.default_rng(40)


def main():
    R = {}
    for f in sorted(glob.glob('results/e40/e40_d*_s*.npz')):
        tag = os.path.basename(f)[4:-4]; cf, s = tag.rsplit('_s', 1)
        fm = 'ctrl' if cf.endswith('ctrl') else 'canon'; D = int(cf[1:-len(fm)])
        R[(D, fm, int(s))] = {k: (v.item() if hasattr(v, 'item') else v) for k, v in dict(np.load(f)).items()}
    acq = {k: v['gap'] < 0.5 * v['blind_gap'] for k, v in R.items()}
    res = dict(per_net={'d%d%s_s%d' % k: v for k, v in R.items()}, D={})
    for D in sorted({k[0] for k in R}):
        seeds = sorted({s for (dd, _, s) in R if dd == D})
        o = {}
        for fm in ('ctrl', 'canon'):
            acs = [s for s in seeds if (D, fm, s) in R and acq[(D, fm, s)]]
            q = dict(n=sum((D, fm, s) in R for s in seeds), n_acquired=len(acs))
            if acs:
                g = [R[(D, fm, s)]['gap'] for s in acs]
                q.update(K=float(np.mean(g)), K_median=float(np.median(g)),
                         K_by_level=[float(np.mean([R[(D, fm, s)]['gap_lev%d' % j] for s in acs])) for j in range(3)])
                for c in ('sign', 'neg'):
                    have = [s for s in acs if c + '_pc' in R[(D, fm, s)]]
                    if have:
                        q['c_' + c] = float(sum(R[(D, fm, s)][c + '_pc'] for s in have) / sum(R[(D, fm, s)][c + '_kl'] for s in have))
            o[fm] = q
        common = [s for s in seeds if all((D, fm, s) in R and acq[(D, fm, s)] for fm in ('ctrl', 'canon'))]
        o['common'] = common
        if len(common) >= 3:
            f = lambda ss: 1 - np.mean([R[(D, 'canon', s)]['gap'] for s in ss]) / np.mean([R[(D, 'ctrl', s)]['gap'] for s in ss])
            cs = lambda ss: sum(R[(D, 'ctrl', s)]['sign_pc'] for s in ss) / sum(R[(D, 'ctrl', s)]['sign_kl'] for s in ss)
            bs = [(f(x), cs(x)) for x in (list(rng.choice(common, len(common))) for _ in range(2000))]
            o['rho'] = [float(f(common)), float(np.percentile([b[0] for b in bs], 2.5)), float(np.percentile([b[0] for b in bs], 97.5))]
            o['c_sign_common'] = [float(cs(common)), float(np.percentile([b[1] for b in bs], 2.5)), float(np.percentile([b[1] for b in bs], 97.5))]
            o['rho_over_c_sign'] = float(f(common) / cs(common)) if cs(common) > 0 else None
            o['per_seed_ratio'] = {s: R[(D, 'canon', s)]['gap'] / R[(D, 'ctrl', s)]['gap'] for s in common}
        res['D'][D] = o
    pr = {}
    o = res['D'].get(2)
    if o and 'c_sign' in o.get('ctrl', {}):
        pr['P174'] = dict(c_sign=o['ctrl']['c_sign'], holds=bool(o['ctrl']['c_sign'] >= 0.05))
    if o and o.get('rho'):
        pr['P175'] = dict(rho=o['rho'], c_sign=o['c_sign_common'], holds=bool(o['rho'][0] >= 1.5 * o['c_sign_common'][0] and o['rho'][0] >= 0.1))
    res['predictions'] = pr
    md = ['# E40 tables (generated by e40_summ.py)', '',
          '| D | format | nets | acquired | mean KL | median KL | KL by level (0.1, 0.5, 2.0) | sign red. / KL | negation red. / KL |',
          '|---' * 9 + '|']
    for D, o in res['D'].items():
        for fm in ('ctrl', 'canon'):
            q = o.get(fm, {})
            if not q.get('n_acquired'):
                md.append('| %d | %s | %d | 0 |' % (D, fm, q.get('n', 0))); continue
            md.append('| %d | %s | %d | %d | %.4f | %.4f | %s | %s | %s |' % (
                D, fm, q['n'], q['n_acquired'], q['K'], q['K_median'], ', '.join('%.4f' % x for x in q['K_by_level']),
                '%.3f' % q['c_sign'] if 'c_sign' in q else '-', '%.3f' % q['c_neg'] if 'c_neg' in q else '-'))
    md += ['', '| D | paired seeds | reduction 1 - K_canon/K_ctrl [95% CI] | c_sign on those seeds [95% CI] | ratio |', '|---' * 5 + '|']
    for D, o in res['D'].items():
        md.append('| %d | %d | %s | %s | %s |' % (D, len(o['common']), '%.2f [%.2f, %.2f]' % tuple(o['rho']) if o.get('rho') else '-',
                                                 '%.3f [%.3f, %.3f]' % tuple(o['c_sign_common']) if o.get('c_sign_common') else '-',
                                                 '%.2f' % o['rho_over_c_sign'] if o.get('rho_over_c_sign') else '-'))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e40.json', 'w'), indent=1, default=float)
    open('results/e40_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1, default=float))


if __name__ == '__main__':
    main()
