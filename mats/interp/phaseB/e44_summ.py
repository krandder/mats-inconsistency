"""E44 analysis (PREREG-B amendment 52): which part of the initialisation carries the solution type?
Inputs: results/e44/e44_<group>_r<recipient>_d<donor>.npz (e43_eval.py on the hybrid nets) and the parents
results/e43_parents/e37_ctrl_s<seed>.npz (E37's ctrl nets: type, KL, predictive mean). tiny-pfn's test set for the Bayes mean.
Per hybrid (acquired, gap < 0.10): follows_donor = (type == the donor parent's type); similarity to the donor and to the recipient
parent (correlation over 4,000 test episodes of the deviations from the Bayes mean).
  T(G) = share of acquired hybrids of group G that follow the donor's type (both directions pooled; 12 hybrids per group);
  2,000 bootstrap resamples of the six pairs.
Predictions:
  P185  max over groups of T(G) >= 0.75 (one group carries most of the type);
  P186  that group is b2att (block 2's attention, where E34 found the A/B routing difference).
usage: python e44_summ.py -> results/e44.json, results/e44_tables.md
"""
import glob, json, os
import numpy as np

GROUPS = ['inp', 'b1att', 'b1mlp', 'b2att', 'b2mlp', 'head']
rng = np.random.default_rng(44)


def rd(f):
    return {k: (v.item() if np.ndim(v) == 0 else v) for k, v in dict(np.load(f)).items()}


def main():
    mb = np.load('/home/agent/workspaces/mats/work/tiny-pfn/runs/testset.npz')['mean_bayes'][:4000].astype(np.float64)
    par = {int(os.path.basename(f)[:-4].rsplit('_s', 1)[1]): rd(f) for f in glob.glob('results/e43_parents/e37_ctrl_s*.npz')}
    typ = lambda o: 'B' if o['rom_middle'] > 0 else 'A'
    corr = lambda u, v: float(np.corrcoef(u - mb, v - mb)[0, 1])
    rows = []
    for f in sorted(glob.glob('results/e44/e44_*_r*_d*.npz')):
        g, r, d = os.path.basename(f)[4:-4].rsplit('_', 2); r, d = int(r[1:]), int(d[1:]); o = rd(f)
        rows.append(dict(group=g, recipient=r, donor=d, pair=tuple(sorted((r, d))), acquired=bool(o['gap'] < 0.10), gap=o['gap'],
                         type=typ(o), donor_type=typ(par[d]), recipient_type=typ(par[r]),
                         follows_donor=typ(o) == typ(par[d]), rho_donor=corr(o['pm'], par[d]['pm']), rho_recipient=corr(o['pm'], par[r]['pm']),
                         lab=o['lab_last'], xq=o['xq']))
    pairs = sorted({x['pair'] for x in rows})
    res = dict(rows=rows, groups={})
    for g in GROUPS:
        R = [x for x in rows if x['group'] == g and x['acquired']]
        if not R:
            continue
        # post-review correction (2026-10-30): the registered version turned the resampled pairs into a set, which dropped
        # bootstrap multiplicities; rows of a pair drawn k times now count k times. Point estimates are unchanged.
        def T(pp):
            v = [x['follows_donor'] for p in pp for x in R if x['pair'] == p]
            return float(np.mean(v)) if v else np.nan
        bs = [T([pairs[i] for i in rng.integers(0, len(pairs), len(pairs))]) for _ in range(2000)]
        res['groups'][g] = dict(n=len(R), n_total=sum(x['group'] == g for x in rows), T=[T(pairs), float(np.nanpercentile(bs, 2.5)), float(np.nanpercentile(bs, 97.5))],
                                n_follow=int(sum(x['follows_donor'] for x in R)),
                                rho_donor=float(np.median([x['rho_donor'] for x in R])), rho_recipient=float(np.median([x['rho_recipient'] for x in R])),
                                A_to_B=dict(n=sum(x['donor_type'] == 'A' for x in R), follow=int(sum(x['follows_donor'] for x in R if x['donor_type'] == 'A'))),
                                B_to_A=dict(n=sum(x['donor_type'] == 'B' for x in R), follow=int(sum(x['follows_donor'] for x in R if x['donor_type'] == 'B'))))
    best = max(res['groups'], key=lambda g: res['groups'][g]['T'][0]) if res['groups'] else None
    pr = {}
    if best:
        pr['P185'] = dict(best_group=best, T=res['groups'][best]['T'], holds=bool(res['groups'][best]['T'][0] >= 0.75))
        pr['P186'] = dict(best_group=best, holds=bool(best == 'b2att'))
    res['predictions'] = pr
    md = ['# E44 tables (generated by e44_summ.py)', '',
          '| group | acquired / total | follows the donor type: T [95% CI] | A-donor hybrids become A | B-donor hybrids become B | median similarity to donor | to recipient |',
          '|---' * 7 + '|']
    for g, o in res['groups'].items():
        md.append('| %s | %d / %d | %.2f [%.2f, %.2f] (%d) | %d of %d | %d of %d | %.2f | %.2f |' % (
            g, o['n'], o['n_total'], *o['T'], o['n_follow'], o['A_to_B']['follow'], o['A_to_B']['n'], o['B_to_A']['follow'], o['B_to_A']['n'],
            o['rho_donor'], o['rho_recipient']))
    md += ['', '| group | recipient | donor | type (recipient, donor parents) | KL | similarity donor / recipient |', '|---' * 6 + '|']
    for x in rows:
        md.append('| %s | %d (%s) | %d (%s) | %s | %.4f | %.2f / %.2f |' % (x['group'], x['recipient'], x['recipient_type'], x['donor'], x['donor_type'],
                                                                     x['type'] if x['acquired'] else 'stalled', x['gap'], x['rho_donor'], x['rho_recipient']))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e44.json', 'w'), indent=1, default=float)
    open('results/e44_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1, default=float)); print(json.dumps({g: (o['T'], o['n']) for g, o in res['groups'].items()}, default=float))


if __name__ == '__main__':
    main()
