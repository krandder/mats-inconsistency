"""E63 analysis (PREREG-B amendment 71): block 1's summary heads in the standard nets: allocation (consensus against pooling heads),
the error dependence of the pooling heads' logits, leakage, the code-set normaliser and code idealisation at evaluation.
Inputs: results/e63/<cohort>.json (e63_run.py; cohorts ctrl, fix, own, ext, traj).
Predictions (registered in amendment 71):
  P237  E37's acquired ctrl nets and E30's fix nets: a consensus head (max_h C_h >= 0.5) in every B-type net and in no A-type net,
        with at most one exception among all these nets;
  P238  ext (E43, E44, E46 final acquired nets except the five explored): AUC(C_max, B > A) >= 0.90 (2,000 cluster-bootstrap
        resamples over parent seeds, E47's clusters, for the interval);
  P239  among the A-type nets of ctrl and fix with two pooling heads, the two heads' mean K_odd have opposite signs, with at most one
        exception;
  P240  (a) ctrl: every pooling head has mean L_own > 0 and mean dlogit(|r| = 3) < -1, with at most one exception over all pooling
        heads of the cohort; (b) the median over own nets' heads of L_own < 0.5 x the median over ctrl's pooling heads;
  P241  ctrl: KL(orthn) < KL(base) in >= 9 of the 11 nets and the mean of 1 - KL(orthn) / KL(base) >= 0.03; own: the mean of
        |1 - KL(orthn) / KL(base)| <= 0.02.
Descriptive: leakage and its Spearman with the largest code cosine; per-source A CV (ctrl, own, fix); eqn and orth; the consensus
marker over training (traj; median by final type and AUC by step); K_odd RMS by type; the consensus marker against rom.
usage: python e63_summ.py -> results/e63.json, results/e63_tables.md   (E63_DIR overrides results/e63)
"""
import json, os
import numpy as np

D = os.environ.get('E63_DIR', 'results/e63')
rng = np.random.default_rng(630)


def load(c):
    p = os.path.join(D, '%s.json' % c)
    return json.load(open(p)) if os.path.exists(p) else None


def auc(pos, neg):
    pos, neg = np.asarray(pos, float), np.asarray(neg, float)
    if not len(pos) or not len(neg):
        return np.nan
    return float(((pos[:, None] > neg[None]).sum() + 0.5 * (pos[:, None] == neg[None]).sum()) / (len(pos) * len(neg)))


def cluster_of(tag):
    if tag.startswith('e44_'):
        return int(tag.split('_r')[1].split('_')[0])
    return int(tag.split('@')[0].rsplit('_s', 1)[1])


def main():
    R = {c: load(c) for c in ('ctrl', 'fix', 'own', 'ext', 'traj')}
    res = dict(predictions={}, cohorts={})
    md = ['# E63 tables (generated by e63_summ.py)', '']
    pr = res['predictions']
    # per-net table for ctrl and fix
    for c in ('ctrl', 'fix'):
        if not R[c]:
            continue
        md += ['## %s' % c, '', '| net | type | KL (gap) | rom large | C_h | P_h | n pool | L_own (pool) | dlogit r=3 | K_odd mean | leak | A_src CV |',
               '|---' * 12 + '|']
        for t, o in R[c].items():
            f = lambda k, fmt='%.2f': ', '.join(fmt % x for x in o[k]) if k in o else '-'
            md.append('| %s | %s | %.4f | %.3f | %s | %s | %d | %s | %s | %s | %s | %.3f |' % (
                t, o['type'], o['gap'], o['rom_large'], f('C_h'), f('P_h'), o['n_pool'],
                ', '.join('%.1f' % o['L_own_h'][h] for h in o.get('pool_heads', [])), ', '.join('%.2f' % o['dlogit_r3_h'][h] for h in o.get('pool_heads', [])),
                ', '.join('%.2f' % o['Kodd_mean_h'][h] for h in o.get('pool_heads', [])), '%.4f' % o['leak_mean'] if 'leak_mean' in o else '-', o['A_src_cv']))
        md.append('')
    # P237
    if R['ctrl'] and R['fix']:
        nets = list(R['ctrl'].values()) + list(R['fix'].values())
        exc = [t for c in ('ctrl', 'fix') for t, o in R[c].items() if o['consensus'] != (o['type'] == 'B')]
        pr['P237'] = dict(n=len(nets), exceptions=exc, holds=bool(len(exc) <= 1))
        # P239
        pairs = [(t, o['Kodd_mean_h'][o['pool_heads'][0]], o['Kodd_mean_h'][o['pool_heads'][1]]) for c in ('ctrl', 'fix') for t, o in R[c].items()
                 if o['type'] == 'A' and o.get('n_pool') == 2]
        exc9 = [t for t, a, b in pairs if a * b >= 0]
        pr['P239'] = dict(n=len(pairs), exceptions=exc9, pairs=pairs, holds=bool(len(pairs) > 0 and len(exc9) <= 1))
    # P238
    if R['ext']:
        L = [(t, o['C_max'], o['type'] == 'B', cluster_of(t)) for t, o in R['ext'].items()]
        cl = sorted({x[3] for x in L})
        def stat(cs):
            sel = [x for c in cs for x in L if x[3] == c]
            return auc([x[1] for x in sel if x[2]], [x[1] for x in sel if not x[2]])
        pt = stat(cl); bs = [stat(list(rng.choice(cl, len(cl)))) for _ in range(2000)]; bs = [b for b in bs if np.isfinite(b)]
        ncons = dict(A=sum(1 for x in L if not x[2] and x[1] >= 0.5), A_n=sum(1 for x in L if not x[2]),
                     B=sum(1 for x in L if x[2] and x[1] >= 0.5), B_n=sum(1 for x in L if x[2]))
        pr['P238'] = dict(auc=[pt, float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))], n=len(L), clusters=len(cl), counts=ncons,
                          holds=bool(pt >= 0.90))
    # P240
    if R['ctrl']:
        heads = [(t, h, o['L_own_h'][h], o['dlogit_r3_h'][h]) for t, o in R['ctrl'].items() for h in o.get('pool_heads', [])]
        exc0 = [(t, h) for t, h, L_, d_ in heads if not (L_ > 0 and d_ < -1)]
        p = dict(n_heads=len(heads), exceptions=exc0, a_holds=bool(len(exc0) <= 1))
        if R['own']:
            own_L = [o['L_own_h'][h] for o in R['own'].values() for h in o.get('pool_heads', [])]
            mc = float(np.median([x[2] for x in heads])); mo = float(np.median(own_L))
            p.update(median_L_ctrl=mc, median_L_own=mo, b_holds=bool(mo < 0.5 * mc))
        p['holds'] = bool(p['a_holds'] and p.get('b_holds', False))
        pr['P240'] = p
    # P241
    if R['ctrl'] and R['own']:
        rc = np.array([o['kl_orthn'] / o['kl_base'] for o in R['ctrl'].values()]); ro = np.array([o['kl_orthn'] / o['kl_base'] for o in R['own'].values()])
        pr['P241'] = dict(ctrl_n_lower=int((rc < 1).sum()), ctrl_n=len(rc), ctrl_mean_reduction=float(np.mean(1 - rc)), own_mean_abs=float(np.mean(np.abs(1 - ro))),
                          holds=bool((rc < 1).sum() >= 9 and np.mean(1 - rc) >= 0.03 and np.mean(np.abs(1 - ro)) <= 0.02))
    # descriptive per cohort
    for c in ('ctrl', 'fix', 'own', 'ext'):
        if not R[c]:
            continue
        V = list(R[c].values()); o = dict(n=len(V))
        for typ in ('A', 'B'):
            W = [v for v in V if v['type'] == typ]
            if not W:
                continue
            d = dict(n=len(W), kl=float(np.mean([v['gap'] for v in W])), rom_large=float(np.mean([v['rom_large'] for v in W])),
                     A_src_cv=float(np.median([v['A_src_cv'] for v in W])))
            if 'C_max' in W[0]:
                d['consensus'] = int(sum(v['consensus'] for v in W)); d['n_pool'] = [int(sum(v['n_pool'] == k for v in W)) for k in (0, 1, 2)]
            # (post-registration fix, 04:15Z: nets without a pooling head carry no leakage or H3 fields; aggregate over the nets that do)
            Wl = [v for v in W if 'leak_mean' in v]
            if Wl:
                d['leak_n'] = len(Wl); d['leak_mean'] = float(np.mean([v['leak_mean'] for v in Wl])); d['leak_q99'] = float(np.mean([v['leak_q99'] for v in Wl]))
            Ws = [v for v in W if 'leak_spearman_maxcos' in v]
            if Ws:
                d['leak_spearman_pos'] = int(sum(v['leak_spearman_maxcos'] > 0 for v in Ws)); d['leak_spearman_n'] = len(Ws)
                d['leak_spearman_median'] = float(np.median([v['leak_spearman_maxcos'] for v in Ws]))
            Wk = [v for v in W if 'Kodd_rms_h' in v]
            if Wk:
                d['Kodd_rms_pool'] = float(np.mean([v['Kodd_rms_h'][h] for v in Wk for h in v.get('pool_heads', [])]))
                d['L_own_pool'] = float(np.median([v['L_own_h'][h] for v in Wk for h in v.get('pool_heads', [])]))
                d['dlogit_r3_pool'] = float(np.median([v['dlogit_r3_h'][h] for v in Wk for h in v.get('pool_heads', [])]))
            if all('kl_orthn' in v for v in W):
                for m in ('eqn', 'orth', 'orthn'):
                    d['kl_ratio_' + m] = float(np.mean([v['kl_' + m] / v['kl_base'] for v in W]))
            o[typ] = d
        res['cohorts'][c] = o
    if R['own']:
        V = list(R['own'].values())
        res['cohorts']['own']['all'] = dict(A_src_cv=float(np.median([v['A_src_cv'] for v in V])),
                                            L_own=float(np.median([v['L_own_h'][h] for v in V for h in v['pool_heads']])),
                                            Kodd_rms=float(np.mean([v['Kodd_rms_h'][h] for v in V for h in v['pool_heads']])),
                                            Kodd_pairs_opposite=int(sum(v['Kodd_mean_h'][0] * v['Kodd_mean_h'][1] < 0 for v in V)),
                                            kl_ratio_orthn=float(np.mean([v['kl_orthn'] / v['kl_base'] for v in V])))
    if R['traj']:
        steps = sorted({o['step'] for o in R['traj'].values()})
        tr = {}
        for st in steps:
            W = [o for o in R['traj'].values() if o['step'] == st]
            tr[st] = dict(auc=auc([o['C_max'] for o in W if o['type'] == 'B'], [o['C_max'] for o in W if o['type'] == 'A']),
                          C_med_A=float(np.median([o['C_max'] for o in W if o['type'] == 'A'])), C_med_B=float(np.median([o['C_max'] for o in W if o['type'] == 'B'])),
                          npool_med_A=float(np.median([o['n_pool'] for o in W if o['type'] == 'A'])), npool_med_B=float(np.median([o['n_pool'] for o in W if o['type'] == 'B'])))
        res['traj'] = tr
    md += ['## Cohorts by type (descriptive)', '', '```', json.dumps(res['cohorts'], indent=1), '```', '']
    if 'traj' in res:
        md += ['## Consensus marker over training (E37 ctrl runs; final type)', '', '| step | AUC(C_max, B > A) | median C_max A / B | median n_pool A / B |', '|---|---|---|---|']
        for st, v in res['traj'].items():
            md.append('| %d | %.2f | %.3f / %.3f | %.1f / %.1f |' % (st, v['auc'], v['C_med_A'], v['C_med_B'], v['npool_med_A'], v['npool_med_B']))
        md.append('')
    md += ['## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open(os.environ.get('E63_JSON', 'results/e63.json'), 'w'), indent=1, default=float)
    open(os.environ.get('E63_TAB', 'results/e63_tables.md'), 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
