"""E69 analysis (PREREG-B amendment 77): four block-1 heads (dh 8) against the 2-head ctrl nets, same initial values and episodes.
Inputs: results/e69/e69_h4_s<seed>.npz (e48_eval_w1.py: gap, rom_large, rom_middle, sign_pc, sign_kl, xq, lab_last), results/e69_heads/
<tag>.json (e69_heads.py); ctrl: results/e37/e37_ctrl_s<seed>.npz (GPU), E63's results/e63/ctrl.json. Acquired: gap < 0.10.
Predictions (registered in amendment 77):
  P267  >= 75% of the acquired h4 nets are A-type (middle-range rom < 0);
  P268  in >= 75% of the acquired h4 nets, block 1's summary rows have at least two pooling heads (P_h >= 0.5) and at least one
        consensus head (C_h >= 0.5);
  P269  the pooled sign share of the acquired h4 nets is <= 0.5 x ctrl's (E37's acquired ctrl nets: 0.200);
  P270  the paired mean KL ratio h4 / ctrl is <= 0.75 (seeds acquired in both; 2,000 bootstrap resamples of seeds).
usage: python e69_summ.py -> results/e69.json, results/e69_tables.md
"""
import glob, json, os
import numpy as np

rng = np.random.default_rng(690)


def ev(p):
    z = np.load(p, allow_pickle=True)
    return {k: float(z[k]) for k in z.files if z[k].ndim == 0 and np.issubdtype(z[k].dtype, np.number)}


def share(num, den):
    num, den = np.asarray(num, float), np.asarray(den, float)
    bs = []
    for _ in range(2000):
        j = rng.integers(0, len(num), len(num)); bs.append(num[j].sum() / den[j].sum())
    return [float(num.sum() / den.sum()), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))]


def main():
    h4 = {int(os.path.basename(p)[:-4].rsplit('_s', 1)[1]): ev(p) for p in glob.glob('results/e69/e69_h4_s*.npz')}
    ctrl = {s: ev('results/e37/e37_ctrl_s%d.npz' % s) for s in range(12)}
    heads = {int(o['tag'].rsplit('_s', 1)[1]): o for o in (json.load(open(p)) for p in glob.glob('results/e69_heads/*.json'))}
    acq = sorted(s for s, r in h4.items() if r['gap'] < 0.10)
    res = dict(n=len(h4), acquired=acq, predictions={}); pr = res['predictions']
    if acq:
        A = [s for s in acq if h4[s]['rom_middle'] < 0]
        pr['P267'] = dict(A=len(A), acquired=len(acq), holds=bool(len(A) >= 0.75 * len(acq)))
        both = [s for s in acq if s in heads and heads[s]['n_pool'] >= 2 and heads[s]['n_consensus'] >= 1]
        pr['P268'] = dict(n=len(both), acquired=len(acq), holds=bool(len(both) >= 0.75 * len(acq)))
        sh = share([h4[s]['sign_pc'] for s in acq], [h4[s]['sign_kl'] for s in acq])
        cacq = [s for s in range(12) if ctrl[s]['gap'] < 0.10]
        shc = share([ctrl[s]['sign_pc'] for s in cacq], [ctrl[s]['sign_kl'] for s in cacq])
        pr['P269'] = dict(h4=sh, ctrl=shc, holds=bool(sh[0] <= 0.5 * shc[0]))
        pair = [s for s in acq if ctrl[s]['gap'] < 0.10]
        x = np.array([h4[s]['gap'] for s in pair]); y = np.array([ctrl[s]['gap'] for s in pair]); bs = []
        for _ in range(2000):
            j = rng.integers(0, len(pair), len(pair)); bs.append(x[j].mean() / y[j].mean())
        r = [float(x.mean() / y.mean()), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5)), len(pair)]
        pr['P270'] = dict(ratio=r, holds=bool(r[0] <= 0.75))
        res.update(kl_h4=float(np.mean([h4[s]['gap'] for s in acq])), rom_large=float(np.mean([h4[s]['rom_large'] for s in acq])),
                   rom_middle=float(np.mean([h4[s]['rom_middle'] for s in acq])))
    md = ['# E69 tables (generated by e69_summ.py)', '', '| seed | h4: KL, type, rom large | pooling heads | consensus heads | opposite-sign pair | L_own (pool) | ctrl: KL, type, rom large |', '|---|---|---|---|---|---|---|']
    for s in range(12):
        r = h4.get(s); h = heads.get(s); c = ctrl[s]
        typ = lambda e: 'stall' if e['gap'] >= 0.10 else ('A' if e['rom_middle'] < 0 else 'B')
        md.append('| %d | %s | %s | %s | %s | %s | %.4f %s %.3f |' % (
            s, ('%.4f %s %.3f' % (r['gap'], typ(r), r['rom_large'])) if r else '-', h['n_pool'] if h else '-', h['n_consensus'] if h else '-',
            h['opposite_pair'] if h else '-', ', '.join('%.1f' % h['L_own_h'][i] for i in h['pool_heads']) if h else '-', c['gap'], typ(c), c['rom_large']))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e69.json', 'w'), indent=1, default=float)
    open('results/e69_tables.md', 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
