"""E74 analysis (PREREG-B amendment 82): does the cost of finding a source's tokens by content grow with the number of sources?
Inputs: results/e74/S6/<tag>.json (e74_eval.py on the S = 6 nets of runs/e74: ctrl_s<seed>, own_s<seed>) and results/e74/S3/<tag>.json
(the S = 3 references on the same construction: E37's ctrl nets e37_ctrl_s<seed>, E60's own nets e60_own_s<seed>). Acquired: gap < 0.10.
Bootstrap: 2,000 resamples of seeds (numpy seed 740).
Predictions (registered):
  P297  routing cost grows: over seeds acquired in all four cells, the ratio R6 / R3 of the paired-mean KL ratios R_S = mean KL(ctrl, S)
        / mean KL(own, S) has a lower 95% limit >= 1.0 and a point estimate >= 1.25;
  P298  the median norm-scaled own logit L_own of ctrl's pooling heads is larger at S = 6 than at S = 3 by >= 1 nat;
  P299  the pooling heads' mean mass on other sources' labelled tokens (leak) of ctrl at S = 6 is >= 1.5 x that at S = 3 (means over nets);
  P300  ctrl's mean rom_large at S = 6 >= ctrl's at S = 3 + 0.02;
  P301  own's mean |rom_large| at S = 6 <= 0.05.
Descriptive: per cell acquired counts, KL, rom (large, middle), type counts, pooling / consensus heads, opposite pairs, L_own, the norm
term at |r| = 3, leak; per-seed table.
usage: python e74_summ.py -> results/e74.json, results/e74_tables.md
"""
import glob, json, os
import numpy as np

rng = np.random.default_rng(740)


def load(pat):
    out = {}
    for p in glob.glob(pat):
        o = json.load(open(p)); out[int(o['seed'])] = o
    return out


def boot(f, seeds):
    if not seeds:
        return None
    vals = [f(list(rng.choice(seeds, len(seeds)))) for _ in range(2000)]
    return [float(f(seeds)), float(np.percentile(vals, 2.5)), float(np.percentile(vals, 97.5)), len(seeds)]


def main():
    C = {('ctrl', 6): load('results/e74/S6/ctrl_s*.json'), ('own', 6): load('results/e74/S6/own_s*.json'),
         ('ctrl', 3): load('results/e74/S3/e37_ctrl_s*.json'), ('own', 3): load('results/e74/S3/e60_own_s*.json')}
    acq = {k: [s for s, o in v.items() if o['gap'] < 0.10] for k, v in C.items()}
    res = dict(acquired={'%s_S%d' % k: v for k, v in acq.items()}, cells={}, predictions={}); pr = res['predictions']
    for (arm, S), d in C.items():
        a = acq[(arm, S)]
        if not a:
            continue
        x = dict(n=len(d), acquired=len(a), kl_mean=float(np.mean([d[s]['gap'] for s in a])), kl_median=float(np.median([d[s]['gap'] for s in a])),
                 rom_large=float(np.mean([d[s]['rom_large'] for s in a])), rom_middle=float(np.mean([d[s]['rom_middle'] for s in a])),
                 A=int(sum(d[s]['type'] == 'A' for s in a)))
        if arm == 'ctrl':
            pk = [d[s]['L_own_h'][h] for s in a for h in d[s]['pool_heads']]; dl = [d[s]['dlogit_r3_h'][h] for s in a for h in d[s]['pool_heads']]
            lk = [d[s]['leak_pool'] for s in a if d[s]['leak_pool'] is not None]
            x.update(L_own_pool_median=float(np.median(pk)) if pk else None, dlogit_r3_pool_median=float(np.median(dl)) if dl else None,
                     leak_pool_mean=float(np.mean(lk)) if lk else None, n_pool={s: d[s]['n_pool'] for s in a},
                     n_consensus={s: d[s]['n_consensus'] for s in a}, opposite_pair=int(sum(d[s]['opposite_pair'] for s in a)))
        res['cells']['%s_S%d' % (arm, S)] = x
    cl = res['cells']
    s4 = [s for s in range(12) if all(s in acq[k] for k in C)]
    if s4:
        g = lambda arm, S, j: np.mean([C[(arm, S)][s]['gap'] for s in j])
        r = boot(lambda j: (g('ctrl', 6, j) / g('own', 6, j)) / (g('ctrl', 3, j) / g('own', 3, j)), s4)
        res['R6'] = boot(lambda j: g('ctrl', 6, j) / g('own', 6, j), s4); res['R3'] = boot(lambda j: g('ctrl', 3, j) / g('own', 3, j), s4)
        pr['P297'] = dict(ratio=r, holds=bool(r[1] >= 1.0 and r[0] >= 1.25))
    if 'ctrl_S6' in cl and 'ctrl_S3' in cl:
        a, b = cl['ctrl_S6'], cl['ctrl_S3']
        if a['L_own_pool_median'] is not None and b['L_own_pool_median'] is not None:
            pr['P298'] = dict(S6=a['L_own_pool_median'], S3=b['L_own_pool_median'], holds=bool(a['L_own_pool_median'] >= b['L_own_pool_median'] + 1.0))
        if a['leak_pool_mean'] is not None and b['leak_pool_mean'] is not None:
            pr['P299'] = dict(S6=a['leak_pool_mean'], S3=b['leak_pool_mean'], holds=bool(a['leak_pool_mean'] >= 1.5 * b['leak_pool_mean']))
        pr['P300'] = dict(S6=a['rom_large'], S3=b['rom_large'], holds=bool(a['rom_large'] >= b['rom_large'] + 0.02))
    if 'own_S6' in cl:
        v = float(np.mean([abs(C[('own', 6)][s]['rom_large']) for s in acq[('own', 6)]])); pr['P301'] = dict(mean_abs=v, holds=bool(v <= 0.05))
    md = ['# E74 tables (generated by e74_summ.py)', '', '| seed | ctrl S=6: KL, type, rom_large, pool / cons | own S=6: KL, type, rom_large | ctrl S=3 | own S=3 |', '|---|---|---|---|---|']
    t = lambda o: '-' if o is None else '%.4f %s %.3f%s' % (o['gap'], 'stall' if o['gap'] >= 0.10 else o['type'], o['rom_large'],
                                                          (' %d / %d' % (o['n_pool'], o['n_consensus'])) if 'n_pool' in o else '')
    for s in range(12):
        md.append('| %d | %s | %s | %s | %s |' % (s, t(C[('ctrl', 6)].get(s)), t(C[('own', 6)].get(s)), t(C[('ctrl', 3)].get(s)), t(C[('own', 3)].get(s))))
    md += ['', '```', json.dumps({k: v for k, v in res.items() if k != 'predictions'}, indent=1, default=float), '```', '', '## Predictions', ''] + \
          ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e74.json', 'w'), indent=1, default=float)
    open('results/e74_tables.md', 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
