"""E50 analysis (PREREG-B amendment 58): does block 1's pre-attention LayerNorm cause the big-miss departure and the r^2
format's deficit? World 1; the no-block-1-LayerNorm variant (pfn_noln.py) in the ctrl, mag and sq formats, against the same
formats with the LayerNorm (E37's ctrl and mag nets, E48's sq nets: same seeds, the same initialisation of every remaining
parameter, the same episodes and schedule).
Inputs: results/e50/e50_<fmt>_s<seed>.npz (e50_eval.py); results/e37/e37_{ctrl,mag}_s<seed>.npz; results/e48w1/e48_w1sq_s<seed>.npz.
Acquired: gap < 0.10. r(a/b) = mean K_a / mean K_b over seeds acquired in both; rom(a) = mean large-range rom over the seeds
acquired in both arms of a comparison; c_sign pooled over acquired nets. 2,000 bootstrap resamples of seeds, with multiplicities.
Predictions (registered in amendment 58):
  P201  rom_large(sq without LN) <= 0.5 x rom_large(sq with LN), paired seeds;
  P202  r(sq without LN / mag without LN) <= 0.8;
  P203  rom_large(ctrl without LN) <= 0.5 x rom_large(ctrl with LN), paired seeds.
usage: python e50_summ.py -> results/e50.json, results/e50_tables.md
"""
import glob, json, os
import numpy as np

rng = np.random.default_rng(50)
NB = 2000


def rd(f):
    return {k: (v.item() if hasattr(v, 'item') else v) for k, v in dict(np.load(f)).items()}


def seed_of(f):
    return int(os.path.basename(f)[:-4].rsplit('_s', 1)[1])


def main():
    R = {}
    for a, pat in (('ctrl_noln', 'results/e50/e50_ctrl_s*.npz'), ('mag_noln', 'results/e50/e50_mag_s*.npz'), ('sq_noln', 'results/e50/e50_sq_s*.npz'),
                   ('ctrl', 'results/e37/e37_ctrl_s*.npz'), ('mag', 'results/e37/e37_mag_s*.npz'), ('sq', 'results/e48w1/e48_w1sq_s*.npz')):
        for f in sorted(glob.glob(pat)):
            R[(a, seed_of(f))] = rd(f)
    seeds = sorted({s for (a, s) in R if a.endswith('_noln')})
    acq = {k: v['gap'] < 0.10 for k, v in R.items()}
    arms = ('ctrl', 'ctrl_noln', 'mag', 'mag_noln', 'sq', 'sq_noln')
    res = dict(per_net={'%s_s%d' % k: v for k, v in R.items() if k[1] in seeds}, arms={}, ratios={}, rom={}, predictions={})
    for a in arms:
        acs = [s for s in seeds if (a, s) in R and acq[(a, s)]]
        o = dict(n=sum((a, s) in R for s in seeds), n_acquired=len(acs), acquired=acs)
        if acs:
            v = lambda k: [R[(a, s)][k] for s in acs]
            o.update(K=float(np.mean(v('gap'))), K_median=float(np.median(v('gap'))), rom_large=float(np.mean(v('rom_large'))),
                     rom_middle=float(np.mean(v('rom_middle'))), n_A=int(sum(x < 0 for x in v('rom_middle'))),
                     n_B=int(sum(x > 0 for x in v('rom_middle'))), lab=float(np.mean(v('lab_last'))), xq=float(np.mean(v('xq'))))
            have = [s for s in acs if 'sign_pc' in R[(a, s)]]
            if have:
                o['c_sign'] = float(sum(R[(a, s)]['sign_pc'] for s in have) / sum(R[(a, s)]['sign_kl'] for s in have))
        res['arms'][a] = o
    both = lambda a, b: [s for s in seeds if all((x, s) in R and acq[(x, s)] for x in (a, b))]
    for a, b in (('sq_noln', 'mag_noln'), ('sq_noln', 'sq'), ('mag_noln', 'mag'), ('ctrl_noln', 'ctrl'), ('sq_noln', 'mag'), ('mag_noln', 'ctrl_noln')):
        ss = both(a, b)
        if len(ss) >= 3:
            f = lambda q: np.mean([R[(a, s)]['gap'] for s in q]) / np.mean([R[(b, s)]['gap'] for s in q])
            bs = [f(list(rng.choice(ss, len(ss)))) for _ in range(NB)]
            res['ratios']['%s/%s' % (a, b)] = [float(f(ss)), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5)), len(ss)]
    for a, b in (('sq_noln', 'sq'), ('ctrl_noln', 'ctrl'), ('mag_noln', 'mag'), ('sq_noln', 'mag_noln')):
        ss = both(a, b)
        if len(ss) >= 3:
            f = lambda q: (np.mean([R[(a, s)]['rom_large'] for s in q]), np.mean([R[(b, s)]['rom_large'] for s in q]))
            bs = [f(list(rng.choice(ss, len(ss)))) for _ in range(NB)]
            ra, rb = f(ss)
            d = [x[0] - 0.5 * x[1] for x in bs]
            res['rom']['%s/%s' % (a, b)] = dict(a=float(ra), b=float(rb), seeds=ss, a_minus_half_b_ci=[float(np.percentile(d, 2.5)), float(np.percentile(d, 97.5))])
    pr = res['predictions']
    q = res['rom'].get('sq_noln/sq')
    if q:
        pr['P201'] = dict(rom_sq_noln=q['a'], rom_sq=q['b'], ci=q['a_minus_half_b_ci'], n=len(q['seeds']), holds=bool(q['a'] <= 0.5 * q['b']))
    r = res['ratios'].get('sq_noln/mag_noln')
    if r:
        pr['P202'] = dict(sq_noln_over_mag_noln=r, holds=bool(r[0] <= 0.8))
    q = res['rom'].get('ctrl_noln/ctrl')
    if q:
        pr['P203'] = dict(rom_ctrl_noln=q['a'], rom_ctrl=q['b'], ci=q['a_minus_half_b_ci'], n=len(q['seeds']), holds=bool(q['a'] <= 0.5 * q['b']))
    md = ['# E50 tables (generated by e50_summ.py)', '', '| arm | nets | acquired | mean KL | median KL | A / B | rom large | rom middle | lab | xq | sign share |',
          '|---' * 11 + '|']
    for a in arms:
        o = res['arms'][a]
        if not o.get('n_acquired'):
            md.append('| %s | %d | 0 |' % (a, o['n'])); continue
        md.append('| %s | %d | %d | %.4f | %.4f | %d / %d | %.3f | %.3f | %.3f | %.4f | %s |' % (
            a, o['n'], o['n_acquired'], o['K'], o['K_median'], o['n_A'], o['n_B'], o['rom_large'], o['rom_middle'], o['lab'], o['xq'],
            '%.3f' % o['c_sign'] if 'c_sign' in o else '-'))
    md += ['', '| ratio of means (paired seeds) | value [95% CI] (seeds) |', '|---|---|']
    md += ['| %s | %.2f [%.2f, %.2f] (%d) |' % ((k,) + tuple(v)) for k, v in res['ratios'].items()]
    md += ['', '| large-range rom, paired seeds | a | b | a - 0.5 b [95% CI] | seeds |', '|---|---|---|---|---|']
    md += ['| %s | %.3f | %.3f | [%.3f, %.3f] | %d |' % (k, v['a'], v['b'], v['a_minus_half_b_ci'][0], v['a_minus_half_b_ci'][1], len(v['seeds']))
           for k, v in res['rom'].items()]
    md += ['', '| seed | ' + ' | '.join(arms) + ' |', '|---' * (len(arms) + 1) + '|']
    for s in seeds:
        cell = lambda a: '-' if (a, s) not in R else '%.4f %s' % (R[(a, s)]['gap'], ('B' if R[(a, s)]['rom_middle'] > 0 else 'A') if acq[(a, s)] else 'stall')
        md.append('| %d | %s |' % (s, ' | '.join(cell(a) for a in arms)))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e50.json', 'w'), indent=1, default=float)
    open('results/e50_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1, default=float))


if __name__ == '__main__':
    main()
