"""E31 analysis (PREREG-B amendment 39): when do the two lineages lose their sign dependence and their cross-source attention?
Window medians over checkpoints: W1 = 10,000-15,000 steps, W2 = 20,000-30,000 steps (inclusive).
  P154  A lineage (s6): median sign-flip cost (nats, uncorrected) in W2 <= 0.5 x its median in W1; B lineage (s5): >= 0.7 x.
  P155  A lineage: median xq in W2 <= 0.5 x its median in W1; B lineage: >= 0.7 x.
Descriptive: full trajectories of KL, sign-flip and negation costs, their shares of KL, the odd share (negation / flips), xq.
usage: python e31_summ.py -> results/e31.json, results/e31_tables.md, results/e31_dyn.png
"""
import glob, json, os
import numpy as np


def load(seed):
    T = []
    for f in sorted(glob.glob(f'results/e31/s{seed}_step*.npz')):
        z = np.load(f); T.append({k: float(z[k]) for k in z.files})
    return sorted(T, key=lambda r: r['step'])


def wmed(T, key, lo, hi):
    v = [r[key] for r in T if lo <= r['step'] <= hi]
    return float(np.median(v)) if v else None


def main():
    res = {}
    for s, lab in ((5, 'B'), (6, 'A')):
        T = load(s)
        res[lab] = dict(seed=s, n=len(T), traj=T,
                        W1=dict(flip=wmed(T, 'pc_flip_ind', 10000, 15000), xq=wmed(T, 'xq', 10000, 15000)),
                        W2=dict(flip=wmed(T, 'pc_flip_ind', 20000, 30000), xq=wmed(T, 'xq', 20000, 30000)))
        for k in ('flip', 'xq'):
            w1, w2 = res[lab]['W1'][k], res[lab]['W2'][k]
            res[lab]['ratio_' + k] = (w2 / w1) if (w1 and w2 is not None) else None
    pr = {}
    if res['A']['ratio_flip'] is not None and res['B']['ratio_flip'] is not None:
        pr['P154'] = dict(A_ratio=res['A']['ratio_flip'], B_ratio=res['B']['ratio_flip'],
                          holds=bool(res['A']['ratio_flip'] <= 0.5 and res['B']['ratio_flip'] >= 0.7))
        pr['P155'] = dict(A_ratio=res['A']['ratio_xq'], B_ratio=res['B']['ratio_xq'],
                          holds=bool(res['A']['ratio_xq'] <= 0.5 and res['B']['ratio_xq'] >= 0.7))
    res['predictions'] = pr
    md = ['# E31 tables (generated by e31_summ.py)', '', '| lineage | step | KL | sign-flip cost | negation cost | flip / KL | odd share | xq |', '|---' * 8 + '|']
    for lab in ('B', 'A'):
        for r in res[lab]['traj']:
            if r['step'] in (1000, 2000, 2500, 2750, 3000, 4000, 5000, 7500, 10000, 12000, 15000, 17000, 18000, 19000, 20000, 21000,
                             22000, 25000, 30000, 35000, 40000, 50000, 60000, 70000, 80000, 89000, 90000):
                md.append('| %s | %d | %.4f | %.5f | %.5f | %.3f | %.2f | %.4f |' % (lab, r['step'], r['kl_flip_ind'], r['pc_flip_ind'],
                          r['pc_negate_ind'], r['pc_flip_ind'] / r['kl_flip_ind'], r['pc_negate_ind'] / max(r['pc_flip_ind'], 1e-12), r['xq']))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e31.json', 'w'), indent=1)
    open('results/e31_tables.md', 'w').write('\n'.join(md) + '\n')
    try:
        import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
        fig, ax = plt.subplots(1, 3, figsize=(15, 4))
        for lab in ('B', 'A'):
            T = res[lab]['traj']; st = [r['step'] for r in T]
            ax[0].plot(st, [r['pc_flip_ind'] for r in T], label=f'{lab} sign-flip cost'); ax[0].plot(st, [r['pc_negate_ind'] for r in T], '--', label=f'{lab} negation cost')
            ax[1].plot(st, [r['pc_flip_ind'] / r['kl_flip_ind'] for r in T], label=f'{lab} flip / KL')
            ax[2].plot(st, [r['xq'] for r in T], label=f'{lab} xq')
        for a in ax:
            a.set_xscale('symlog', linthresh=1000); a.legend(fontsize=7)
        ax[0].set_yscale('log'); ax[0].set_title('costs (nats)'); ax[1].set_title('sign-flip cost / KL'); ax[2].set_title('block-1 cross-source same-question attention')
        fig.tight_layout(); fig.savefig('results/e31_dyn.png', dpi=110)
    except Exception as ex:
        print('plot failed', ex)
    print(json.dumps(pr, indent=1))


if __name__ == '__main__':
    main()
