"""E61 analysis (PREREG-B amendment 69): do the uniform pool's advantage and the constrained-Bayes prediction hold at larger sizes?
Arms (GPU, ctrl format, fixed 90,000-step schedule; pfn_uni's unif variant): width 128 depth 2 and width 32 depth 3, seeds 0-9,
every parameter starting as in E38's ctrl net of the same seed and size, with its episodes. Comparisons: E38's ctrl nets (same seeds,
sizes, device); E53's unif nets at width 32 (CPU) for reference.
Inputs: results/e61/<tag>.npz (e53_eval.py), results/e38/; c of each unif net by lngeom.py (as e55_run.py); the constrained-Bayes
table results/e55_cbtable.json. Acquired: gap < 0.10. 2,000 bootstrap resamples of seeds, with multiplicities.
Predictions (registered in amendment 69):
  P232  mean KL(unif) / mean KL(ctrl) <= 0.6 on paired seeds, at width 128 and at depth 3;
  P233  at width 128 and at depth 3, the unif nets' mean rom_large and rom_middle are each within 0.03 of the mean constrained-
        Bayes value at their c.
usage: python e61_summ.py -> results/e61.json, results/e61_tables.md
"""
import glob, json, os, sys
import numpy as np
import torch

sys.path.insert(0, '/home/agent/workspaces/mats/work/tiny-pfn')
import e48_fmt as F  # noqa: E402
import lngeom as G  # noqa: E402

rng = np.random.default_rng(61)
NB = 2000
CONF = dict(w128=('e61_unifw128_s%d', 'e38_w128ctrl_s%d'), d3=('e61_unifd3_s%d', 'e38_d3ctrl_s%d'))


def rd(f):
    return {k: (v.item() if hasattr(v, 'item') else v) for k, v in dict(np.load(f, allow_pickle=True)).items()}


def ci(x):
    return [float(np.percentile(x, 2.5)), float(np.percentile(x, 97.5))]


def main():
    tab = json.load(open('results/e55_cbtable.json')); grid = np.array(tab['grid'])
    TL = np.array([tab['rom']['%.2f' % c]['large'] for c in grid]); TM = np.array([tab['rom']['%.2f' % c]['middle'] for c in grid])
    z = np.load('results/e27_data.npz')
    X, _ = F.make_X(z['o'][:500, 0], z['y'][:500], z['semb'][:500], z['qemb'][:500], 'ctrl')
    res = dict(configs={}, predictions={}, per_net={})
    for cf, (up, cp) in CONF.items():
        U, C = {}, {}
        for s in range(10):
            fu = 'results/e61/%s.npz' % (up % s); fc = 'results/e38/%s.npz' % (cp % s)
            if os.path.exists(fu):
                r = rd(fu); sd = torch.load('runs/e61/%s/model.pt' % (up % s), map_location='cpu')
                g = G.geom_wb(sd['inp.weight'].numpy(), sd['inp.bias'].numpy(), X)
                r.update(c=g['c_median'], A_cv=g['A_cv'], rho=g['rho_abs_median'], cb_large=float(np.interp(g['c_median'], grid, TL)),
                         cb_middle=float(np.interp(g['c_median'], grid, TM)))
                U[s] = r; res['per_net'][up % s] = {k: v for k, v in r.items() if not isinstance(v, np.ndarray)}
            if os.path.exists(fc):
                C[s] = rd(fc)
        au = [s for s in U if U[s]['gap'] < 0.10]; ac = [s for s in C if C[s]['gap'] < 0.10]
        both = sorted(set(au) & set(ac))
        o = dict(n_unif=len(U), acquired_unif=len(au), n_ctrl=len(C), acquired_ctrl=len(ac), paired=both)
        if au:
            v = lambda k: np.array([U[s][k] for s in au])
            o.update(K_unif=float(v('gap').mean()), rom_large=float(v('rom_large').mean()), rom_middle=float(v('rom_middle').mean()),
                     cb_large=float(v('cb_large').mean()), cb_middle=float(v('cb_middle').mean()), c_median=float(np.median(v('c'))),
                     c_range=[float(v('c').min()), float(v('c').max())], A_cv=float(np.median(v('A_cv'))), rho=float(np.median(v('rho'))))
            if all('sign_pc' in U[s] for s in au):
                o['c_sign_unif'] = float(v('sign_pc').sum() / v('sign_kl').sum())
        if ac:
            o['K_ctrl'] = float(np.mean([C[s]['gap'] for s in ac])); o['rom_large_ctrl'] = float(np.mean([C[s]['rom_large'] for s in ac]))
        if len(both) >= 3:
            f = lambda q: np.mean([U[s]['gap'] for s in q]) / np.mean([C[s]['gap'] for s in q])
            o['ratio'] = [float(f(both))] + ci([f(list(rng.choice(both, len(both)))) for _ in range(NB)]) + [len(both)]
        res['configs'][cf] = o
    W, D = res['configs'].get('w128', {}), res['configs'].get('d3', {})
    if 'ratio' in W and 'ratio' in D:
        res['predictions']['P232'] = dict(w128=W['ratio'], d3=D['ratio'], holds=bool(W['ratio'][0] <= 0.6 and D['ratio'][0] <= 0.6))
    if 'rom_large' in W and 'rom_large' in D:
        ok = all(abs(x['rom_large'] - x['cb_large']) <= 0.03 and abs(x['rom_middle'] - x['cb_middle']) <= 0.03 for x in (W, D))
        res['predictions']['P233'] = dict(w128=[W['rom_large'], W['cb_large'], W['rom_middle'], W['cb_middle']],
                                          d3=[D['rom_large'], D['cb_large'], D['rom_middle'], D['cb_middle']], holds=bool(ok))
    md = ['# E61 tables (generated by e61_summ.py)', '', '| size | unif acquired | ctrl acquired | KL unif / ctrl | ratio [95% CI] (paired) | median c [range] | rom large: unif / CB at c / ctrl | rom middle: unif / CB at c | sign share unif |',
          '|---' * 9 + '|']
    for cf, o in res['configs'].items():
        if 'K_unif' not in o:
            md.append('| %s | %d | %d |' % (cf, o['acquired_unif'], o['acquired_ctrl'])); continue
        md.append('| %s | %d / %d | %d / %d | %.4f / %.4f | %s | %.2f [%.2f, %.2f] | %.3f / %.3f / %.3f | %.3f / %.3f | %s |' % (
            cf, o['acquired_unif'], o['n_unif'], o['acquired_ctrl'], o['n_ctrl'], o['K_unif'], o.get('K_ctrl', float('nan')),
            ('%.2f [%.2f, %.2f] (%d)' % tuple(o['ratio'])) if 'ratio' in o else '-', o['c_median'], *o['c_range'], o['rom_large'], o['cb_large'],
            o.get('rom_large_ctrl', float('nan')), o['rom_middle'], o['cb_middle'], '%.3f' % o['c_sign_unif'] if 'c_sign_unif' in o else '-'))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in res['predictions'].items()]
    json.dump(res, open('results/e61.json', 'w'), indent=1, default=float)
    open('results/e61_tables.md', 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
