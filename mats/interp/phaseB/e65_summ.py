"""E65 analysis (PREREG-B amendment 73): E63's head allocation and routing-logit measures across sizes (E38's ctrl nets at width 64,
width 128 and depth 3) and in the sign-free format (E37's and E38's mag nets).
Inputs: results/e65/<cohort>.json (e65_run.py); E63's ctrl cohort results/e63/ctrl.json (width 32, for P250).
Predictions (registered in amendment 73):
  P247  in each of w64ctrl, w128ctrl and d3ctrl: A-type if and only if two block-1 summary pooling heads, at most one exception per
        cohort;
  P248  every pooling head of the three ctrl cohorts has mean L_own > 0 and mean dlogit(|r| = 3) < -1, at most 10% exceptions over
        their pooling heads;
  P249  in each of w32mag, w64mag, w128mag and d3mag: A-type if and only if two pooling heads, at most one exception per cohort; and
        the mean K_lin (the coefficient of |r|) is > 0 in >= 80% of the four cohorts' pooling heads;
  P250  the median dlogit over w128ctrl's pooling heads is greater (less negative) than the median over E63's width-32 ctrl pooling
        heads.
Descriptive: per cohort and type: counts, KL, rom, consensus heads, pooling-head counts, L_own, dlogit, K RMS and K sign pairing.
usage: python e65_summ.py -> results/e65.json, results/e65_tables.md   (E65_DIR overrides results/e65)
"""
import json, os
import numpy as np

D = os.environ.get('E65_DIR', 'results/e65')
CTRL = ('w64ctrl', 'w128ctrl', 'd3ctrl'); MAG = ('w32mag', 'w64mag', 'w128mag', 'd3mag')


def load(c):
    p = os.path.join(D, '%s.json' % c)
    return json.load(open(p)) if os.path.exists(p) else None


def main():
    R = {c: load(c) for c in CTRL + MAG}
    res = dict(cohorts={}, predictions={}); pr = res['predictions']
    for c, r in R.items():
        if not r:
            continue
        o = dict(n=len(r), exceptions_A_iff_two=[t for t, v in r.items() if (v['n_pool'] == 2) != (v['type'] == 'A')])
        for typ in ('A', 'B'):
            W = [v for v in r.values() if v['type'] == typ]
            if not W:
                continue
            ph = [(v, h) for v in W for h in v['pool_heads']]
            d = dict(n=len(W), kl=float(np.mean([v['gap'] for v in W])), rom_large=float(np.mean([v['rom_large'] for v in W])),
                     consensus=int(sum(v['consensus'] for v in W)), n_pool=[int(sum(v['n_pool'] == k for v in W)) for k in (0, 1, 2)])
            if ph:
                d['L_own_median'] = float(np.median([v['L_own_h'][h] for v, h in ph])); d['dlogit_median'] = float(np.median([v['dlogit_r3_h'][h] for v, h in ph]))
                d['K_rms'] = float(np.mean([v['K_rms_h'][h] for v, h in ph])); d['K_pos_frac'] = float(np.mean([v['K_mean_h'][h] > 0 for v, h in ph]))
                pairs = [v for v in W if v['n_pool'] == 2]
                d['K_pairs_opposite'] = [int(sum(v['K_mean_h'][v['pool_heads'][0]] * v['K_mean_h'][v['pool_heads'][1]] < 0 for v in pairs)), len(pairs)]
            o[typ] = d
        res['cohorts'][c] = o
    if all(R[c] for c in CTRL):
        exc = {c: res['cohorts'][c]['exceptions_A_iff_two'] for c in CTRL}
        pr['P247'] = dict(exceptions=exc, holds=bool(all(len(x) <= 1 for x in exc.values())))
        heads = [(c, t, h, v['L_own_h'][h], v['dlogit_r3_h'][h]) for c in CTRL for t, v in R[c].items() for h in v['pool_heads']]
        bad = [x[:3] for x in heads if not (x[3] > 0 and x[4] < -1)]
        pr['P248'] = dict(n_heads=len(heads), exceptions=bad, holds=bool(len(bad) <= 0.10 * len(heads)))
    if all(R[c] for c in MAG):
        exc = {c: res['cohorts'][c]['exceptions_A_iff_two'] for c in MAG}
        kh = [v['K_mean_h'][h] for c in MAG for v in R[c].values() for h in v['pool_heads']]
        fpos = float(np.mean([k > 0 for k in kh])) if kh else float('nan')
        pr['P249'] = dict(exceptions=exc, K_lin_pos_frac=fpos, n_heads=len(kh), holds=bool(all(len(x) <= 1 for x in exc.values()) and fpos >= 0.8))
    if R['w128ctrl']:
        e63 = json.load(open('results/e63/ctrl.json'))
        m32 = float(np.median([v['dlogit_r3_h'][h] for v in e63.values() for h in v.get('pool_heads', [])]))
        m128 = float(np.median([v['dlogit_r3_h'][h] for v in R['w128ctrl'].values() for h in v['pool_heads']]))
        pr['P250'] = dict(median_w32=m32, median_w128=m128, holds=bool(m128 > m32))
    md = ['# E65 tables (generated by e65_summ.py)', '', '| cohort, type | nets | KL | rom large | consensus | pooling heads 0/1/2 | L_own | dlogit | K RMS | K > 0 | K pairs opposite |',
          '|---' * 11 + '|']
    for c, o in res['cohorts'].items():
        for typ in ('A', 'B'):
            if typ not in o:
                continue
            d = o[typ]
            md.append('| %s %s | %d | %.4f | %.3f | %d | %s | %s | %s | %s | %s | %s |' % (
                c, typ, d['n'], d['kl'], d['rom_large'], d['consensus'], '/'.join(str(x) for x in d['n_pool']),
                '%.1f' % d['L_own_median'] if 'L_own_median' in d else '-', '%.2f' % d['dlogit_median'] if 'dlogit_median' in d else '-',
                '%.2f' % d['K_rms'] if 'K_rms' in d else '-', '%.2f' % d['K_pos_frac'] if 'K_pos_frac' in d else '-',
                '%d of %d' % tuple(d['K_pairs_opposite']) if 'K_pairs_opposite' in d else '-'))
        md.append('| %s exceptions to "A iff two pooling heads" | %s |' % (c, ', '.join(o['exceptions_A_iff_two']) or 'none'))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open(os.environ.get('E65_JSON', 'results/e65.json'), 'w'), indent=1, default=float)
    open(os.environ.get('E65_TAB', 'results/e65_tables.md'), 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
