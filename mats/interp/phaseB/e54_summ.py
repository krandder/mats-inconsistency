"""E54 analysis (PREREG-B amendment 62): does world 2 show the big-miss fingerprint?
Inputs: results/e54/<tag>.npz (e54_run.py) and the pairs results/e54_pairs_d1.npz, results/e54_pairs_d2.npz (e54_data.py).
Arms: ctrl, canon (E40), prod, sgnprod (E48), pre (E49, ctrl format), at D = 1 and D = 2 (12 nets each; every net acquired).
Per net, over the pairs (both versions have the same sufficient statistics, so Bayes's change is 0):
  dls  = mean (log-sd_big - log-sd_spread) of the predictive (moments): < 0 means narrower when the residual is concentrated;
  lam  = the coefficient on d in the least-squares fit of (mean_big - mean_spread) on [d, Bayes mean, 1], with d = x*.(w_hat_{-j}
         - w_hat) on the big version (the shift that leaving out the outlier would cause): > 0 means the mean moves as if the
         outlier were discounted;
  dkl  = mean (KL_big - KL_spread);
  u    = (descriptive) the fraction of RSS the net behaves as if it ignored: with b the slope of the mean log-sd of the spread
         versions on log f (f = 0.6, 0.8, 1; RSS x f^2), u = 1 - exp(2 dls / b).
Arm statistics: means over nets; intervals from 2,000 bootstrap resamples of nets (with multiplicities); counts of nets.
Predictions (registered in amendment 62):
  P212  ctrl at D = 1 and at D = 2: mean dls < 0 and dls < 0 in >= 10 of 12 nets;
  P213  ctrl at D = 1 and at D = 2: mean lam > 0 and lam > 0 in >= 10 of 12 nets;
  P214  mean dls < 0 in >= 8 of the 10 arms.
usage: python e54_summ.py [RESDIR PAIRS_PREFIX] -> results/e54.json, results/e54_tables.md
"""
import glob, json, os, sys
import numpy as np

rng = np.random.default_rng(54)
NB = 2000
RES = sys.argv[1] if len(sys.argv) > 2 else 'results/e54'
PAIRS = sys.argv[2] if len(sys.argv) > 2 else 'results/e54_pairs_d%d.npz'
ARMS = [(f, D) for D in (1, 2) for f in ('ctrl', 'canon', 'prod', 'sgnprod', 'pre')]


def arm_of(z):
    return ('pre' if str(z['variant']) == 'pre' else str(z['fmt'])), int(z['D'])


def per_net(z, P):
    dls = z['ls_big'] - z['ls_spr']
    mB = (P['bayes_wt'] * P['bayes_mu']).sum(1)
    A = np.c_[P['dshift'], mB, np.ones(len(mB))]
    coef = np.linalg.lstsq(A, z['m_big'] - z['m_spr'], rcond=None)[0]
    lf = np.log([0.6, 0.8, 1.0]); lsm = np.array([z['ls_f60'].mean(), z['ls_f80'].mean(), z['ls_spr'].mean()])
    b = np.polyfit(lf, lsm, 1)[0]
    o = dict(dls=float(dls.mean()), lam=float(coef[0]), kappa=float(coef[1]), dkl=float((z['kl_big'] - z['kl_spr']).mean()),
             kl_spr=float(z['kl_spr'].mean()), kl_big=float(z['kl_big'].mean()), b=float(b),
             u=float(1 - np.exp(2 * dls.mean() / b)) if b > 0 else float('nan'), frac_neg=float((dls < 0).mean()))
    for j in range(3):
        s = P['li'] == j
        o['dls_lev%d' % j] = float(dls[s].mean())
    return o


def boot(xs):
    xs = np.asarray(xs)
    b = [xs[rng.integers(0, len(xs), len(xs))].mean() for _ in range(NB)]
    return [float(xs.mean()), float(np.percentile(b, 2.5)), float(np.percentile(b, 97.5))]


def main():
    P = {D: np.load(PAIRS % D) for D in (1, 2)}
    R = {}
    for f in sorted(glob.glob(os.path.join(RES, '*.npz'))):
        z = np.load(f, allow_pickle=True); a = arm_of(z)
        R.setdefault(a, {})[int(z['seed'])] = per_net(z, P[a[1]])
    res = dict(arms={}, predictions={}, per_net={'%s_d%d_s%d' % (a[0], a[1], s): v for a, d in R.items() for s, v in d.items()})
    for a in ARMS:
        if a not in R:
            continue
        nets = list(R[a].values())
        o = dict(n=len(nets))
        for k in ('dls', 'lam', 'kappa', 'dkl', 'u', 'kl_spr', 'kl_big', 'b', 'dls_lev0', 'dls_lev1', 'dls_lev2'):
            o[k] = boot([x[k] for x in nets])
        o['n_dls_neg'] = int(sum(x['dls'] < 0 for x in nets)); o['n_lam_pos'] = int(sum(x['lam'] > 0 for x in nets))
        res['arms']['%s_d%d' % a] = o
    pr = res['predictions']
    c = [res['arms'].get('ctrl_d%d' % D) for D in (1, 2)]
    if all(c):
        pr['P212'] = dict(d1=[c[0]['dls'], c[0]['n_dls_neg']], d2=[c[1]['dls'], c[1]['n_dls_neg']],
                          holds=bool(all(x['dls'][0] < 0 and x['n_dls_neg'] >= 10 for x in c)))
        pr['P213'] = dict(d1=[c[0]['lam'], c[0]['n_lam_pos']], d2=[c[1]['lam'], c[1]['n_lam_pos']],
                          holds=bool(all(x['lam'][0] > 0 and x['n_lam_pos'] >= 10 for x in c)))
    if len(res['arms']) == 10:
        neg = [k for k, v in res['arms'].items() if v['dls'][0] < 0]
        pr['P214'] = dict(arms_negative=neg, n=len(neg), holds=bool(len(neg) >= 8))
    md = ['# E54 tables (generated by e54_summ.py)', '',
          '| arm | nets | dls [95% CI] | nets dls < 0 | lam [95% CI] | nets lam > 0 | u (RSS share ignored) | dKL | KL spread | dls by level 0.1 / 0.5 / 2.0 |',
          '|---' * 10 + '|']
    for k, o in res['arms'].items():
        md.append('| %s | %d | %.4f [%.4f, %.4f] | %d | %.3f [%.3f, %.3f] | %d | %.3f | %.4f | %.4f | %.4f / %.4f / %.4f |' % (
            k, o['n'], *o['dls'], o['n_dls_neg'], *o['lam'], o['n_lam_pos'], o['u'][0], o['dkl'][0], o['kl_spr'][0],
            o['dls_lev0'][0], o['dls_lev1'][0], o['dls_lev2'][0]))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    out = 'results' if RES == 'results/e54' else os.path.dirname(RES.rstrip('/'))
    os.makedirs(out, exist_ok=True)
    json.dump(res, open(os.path.join(out, 'e54.json'), 'w'), indent=1, default=float)
    open(os.path.join(out, 'e54_tables.md'), 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1, default=float))


if __name__ == '__main__':
    main()
