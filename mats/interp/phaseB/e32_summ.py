"""E32 analysis (PREREG-B amendment 40).
Per group (A bases, B bases, all 15 mixture-head nets, 33 Gaussian-head nets): pooled sign-flip cost, negation cost and base KL,
unpatched and patched (sums over nets); ratios patched / unpatched; per-net counts.
  P156  B bases: pooled sign-flip cost patched <= 0.5 x unpatched.
  P157  B bases: patched base KL < unpatched base KL in >= 4 of the 6 nets.
usage: python e32_summ.py -> results/e32.json, results/e32_tables.md
"""
import json, os
import numpy as np
import e26_summ as SM


def main():
    rows = json.load(open('results/e26_nets.json'))
    nets = {}
    for s in ('M', 'G'):
        for r in rows:
            if r['set'] == s:
                f = os.path.join('results/e32', s, r['tag'] + '.npz')
                if os.path.exists(f):
                    nets[r['tag']] = (s, {k: float(v) for k, v in np.load(f).items()})
    groups = dict(A=SM.A_BASES, B=SM.B_BASES, M=[t for t, (s, _) in nets.items() if s == 'M'],
                  G=[t for t, (s, _) in nets.items() if s == 'G'])
    res = dict(groups={}, per_net={t: dict(set=s, **o) for t, (s, o) in nets.items()})
    for g, tags in groups.items():
        L = [nets[t][1] for t in tags if t in nets]
        if not L:
            continue
        o = dict(n=len(L))
        for key in ('pc_flip_ind', 'pc_negate_ind', 'kl_base', 'kl_flip_ind'):
            u = sum(x[key + '_u'] for x in L); p = sum(x[key + '_p'] for x in L)
            o[key] = dict(unpatched=u / len(L), patched=p / len(L), ratio=p / u)
        o['flip_share_u'] = sum(x['pc_flip_ind_u'] for x in L) / sum(x['kl_flip_ind_u'] for x in L)
        o['flip_share_p'] = sum(x['pc_flip_ind_p'] for x in L) / sum(x['kl_flip_ind_p'] for x in L)
        o['n_kl_down'] = int(sum(x['kl_base_p'] < x['kl_base_u'] for x in L))
        o['n_flip_halved'] = int(sum(x['pc_flip_ind_p'] <= 0.5 * x['pc_flip_ind_u'] for x in L))
        o['xq'] = float(np.mean([x['xq_u'] for x in L]))
        res['groups'][g] = o
    pr = {}
    if 'B' in res['groups'] and res['groups']['B']['n'] == 6:
        b = res['groups']['B']
        pr['P156'] = dict(ratio=b['pc_flip_ind']['ratio'], holds=bool(b['pc_flip_ind']['ratio'] <= 0.5))
        pr['P157'] = dict(n_kl_down=b['n_kl_down'], kl_ratio=b['kl_base']['ratio'], holds=bool(b['n_kl_down'] >= 4))
    res['predictions'] = pr
    md = ['# E32 tables (generated by e32_summ.py)', '',
          '| group | nets | xq | sign-flip cost u -> p (ratio) | negation cost u -> p (ratio) | base KL u -> p (ratio) | flip share of KL u -> p | KL down | flip halved |',
          '|---' * 9 + '|']
    for g, o in res['groups'].items():
        f = o['pc_flip_ind']; n_ = o['pc_negate_ind']; k = o['kl_base']
        md.append('| %s | %d | %.3f | %.5f -> %.5f (%.2f) | %.5f -> %.5f (%.2f) | %.4f -> %.4f (%.2f) | %.3f -> %.3f | %d | %d |' % (
            g, o['n'], o['xq'], f['unpatched'], f['patched'], f['ratio'], n_['unpatched'], n_['patched'], n_['ratio'],
            k['unpatched'], k['patched'], k['ratio'], o['flip_share_u'], o['flip_share_p'], o['n_kl_down'], o['n_flip_halved']))
    md += ['', '| net | set | xq | flip u | flip p | KL u | KL p |', '|---' * 7 + '|']
    for t, o in res['per_net'].items():
        md.append('| %s | %s | %.3f | %.5f | %.5f | %.4f | %.4f |' % (t, o['set'], o['xq_u'], o['pc_flip_ind_u'], o['pc_flip_ind_p'],
                                                                   o['kl_base_u'], o['kl_base_p']))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e32.json', 'w'), indent=1)
    open('results/e32_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1))


if __name__ == '__main__':
    main()
