"""E52 analysis (PREREG-B amendment 60). Inputs: results/e52/<config>.npz from e52_run.py (w32, w64, w128, d3).
Per configuration and format (ctrl, mag), over the acquired nets on E27's first 3,000 bases:
  K1    = the nets' mean single-net KL; K9 = the mean over the 5 subsets of the 9-net ensemble's KL (members' mean KL minus the
          ensemble's reduction); c_seed = the mean over subsets of the ensemble's reduction / its members' mean KL;
  rho_g = the mean pairwise correlation across nets of their deviations from the Bayes mean (base predictive means).
Descriptive, model-based: K_shared = (9 K9 - K1) / 8 and K_specific = K1 - K_shared, as e51_post.py (members' and ensembles'
KLs of the same subsets).
Predictions (registered in amendment 60):
  P206  c_seed(width 128) <= c_seed(width 32) - 0.10, for ctrl and for mag (wider nets vary less between trainings);
  P207  K9(ctrl, width 128) >= 0.6 x K9(ctrl, width 32) (the part shared across trainings persists with width).
usage: python e52_summ.py -> results/e52.json, results/e52_tables.md
"""
import json, os
import numpy as np


def pair_corr(A):
    Z = A - A.mean(1, keepdims=True)
    Z = Z / np.linalg.norm(Z, axis=1, keepdims=True)
    C = Z @ Z.T
    iu = np.triu_indices(len(A), 1)
    return float(C[iu].mean())


def main():
    res = {}
    for cf in ('w32', 'w64', 'w128', 'd3'):
        p = 'results/e52/%s.npz' % cf
        if not os.path.exists(p):
            continue
        z = np.load(p); o = {}
        for arm in ('ctrl', 'mag'):
            sk, sp = z['%s_seed_kl' % arm], z['%s_seed_pc' % arm]
            k9 = float((sk - sp).mean()); k1m = float(sk.mean())
            ks = (9 * k9 - k1m) / 8
            o[arm] = dict(n=int(len(z['%s_kl' % arm])), K1=float(z['%s_kl' % arm].mean()), K1_subsets=k1m, K9=k9,
                          c_seed=float((sp / sk).mean()), c_seed_range=[float((sp / sk).min()), float((sp / sk).max())],
                          rho_g=pair_corr(z['%s_M' % arm] - z['bayes_mean'][None]), K_shared=ks, K_specific=k1m - ks)
        res[cf] = o
    pr = {}
    if 'w32' in res and 'w128' in res:
        a, b = res['w32'], res['w128']
        pr['P206'] = dict(c_seed_w32=[a['ctrl']['c_seed'], a['mag']['c_seed']], c_seed_w128=[b['ctrl']['c_seed'], b['mag']['c_seed']],
                          holds=bool(b['ctrl']['c_seed'] <= a['ctrl']['c_seed'] - 0.10 and b['mag']['c_seed'] <= a['mag']['c_seed'] - 0.10))
        pr['P207'] = dict(K9_ctrl_w32=a['ctrl']['K9'], K9_ctrl_w128=b['ctrl']['K9'], ratio=b['ctrl']['K9'] / a['ctrl']['K9'],
                          holds=bool(b['ctrl']['K9'] >= 0.6 * a['ctrl']['K9']))
    res['predictions'] = pr
    md = ['# E52 tables (generated by e52_summ.py)', '',
          '| config | format | nets | single-net KL | 9-net ensemble KL | c_seed [subset range] | rho_g | shared (model) | specific (model) |',
          '|---' * 9 + '|']
    for cf, o in res.items():
        if cf == 'predictions':
            continue
        for arm, q in o.items():
            md.append('| %s | %s | %d | %.4f | %.4f | %.3f [%.3f, %.3f] | %.3f | %.4f | %.4f |' % (
                cf, arm, q['n'], q['K1'], q['K9'], q['c_seed'], q['c_seed_range'][0], q['c_seed_range'][1], q['rho_g'], q['K_shared'],
                q['K_specific']))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e52.json', 'w'), indent=1, default=float)
    open('results/e52_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1, default=float))


if __name__ == '__main__':
    main()
