"""E41 analysis (PREREG-B amendment 49): the sign format in E20's single-source pooling toy (toy_fmt.py).
Inputs: results/e41/<arm>_s<seed>.json. K = the toy's KL to the exact posterior over the three levels (final format).
  c_sign  = the ctrl toys' pooled sign-flip KL reduction / pooled family KL (uncorrected); c_neg likewise for the negation;
  rho     = 1 - mean K_mag / mean K_ctrl over seeds (paired ratio of means);
  R(a)    = sum_s (K_ctrl,s - K_a,s) / sum_s (K_ctrl,s - K_mag,s) (E37's rescue fraction).
2,000 bootstrap resamples of seeds.
Predictions:
  P176  c_sign >= 0.05;
  P177  rho >= 1.5 x c_sign;
  P178  R(c2m2k) >= 0.8, R(c2m12k) <= 0.5 and R(mag18) >= 0.8.
usage: python e41_summ.py -> results/e41.json, results/e41_tables.md
"""
import glob, json, os
import numpy as np

ARMS = ['ctrl', 'mag', 'c2m2k', 'c2m12k', 'mag18', 'm2c12k']
rng = np.random.default_rng(41)


def main():
    R = {}
    for f in sorted(glob.glob('results/e41/*_s*.json')):
        d = json.load(open(f)); R[(d['arm'], d['seed'])] = d
    seeds = sorted({s for (a, s) in R if a == 'ctrl'})
    have = lambda arms: [s for s in seeds if all((a, s) in R for a in arms)]

    def boot(stat, arms):
        ss = have(arms)
        if len(ss) < 3:
            return None
        bs = [stat(list(rng.choice(ss, len(ss)))) for _ in range(2000)]
        return [float(stat(ss)), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))]

    K = lambda a, ss: np.mean([R[(a, s)]['kl'] for s in ss])
    cs = lambda ss, c='sign': sum(R[('ctrl', s)][c + '_pc'] for s in ss) / sum(R[('ctrl', s)][c + '_kl'] for s in ss)
    Rf = lambda a: (lambda ss: sum(R[('ctrl', s)]['kl'] - R[(a, s)]['kl'] for s in ss) / sum(R[('ctrl', s)]['kl'] - R[('mag', s)]['kl'] for s in ss))
    res = dict(per_net={'%s_s%d' % k: {kk: v for kk, v in d.items() if kk != 'curve'} for k, d in R.items()}, arms={})
    for a in ARMS:
        ss = [s for s in seeds if (a, s) in R]
        if ss:
            res['arms'][a] = dict(n=len(ss), K=float(K(a, ss)), K_median=float(np.median([R[(a, s)]['kl'] for s in ss])),
                                  K_min=float(min(R[(a, s)]['kl'] for s in ss)), K_max=float(max(R[(a, s)]['kl'] for s in ss)))
    c_sign = boot(cs, ['ctrl']); c_neg = boot(lambda ss: cs(ss, 'neg'), ['ctrl'])
    rho = boot(lambda ss: 1 - K('mag', ss) / K('ctrl', ss), ['ctrl', 'mag'])
    Rv = {a: boot(Rf(a), ['ctrl', 'mag', a]) for a in ARMS[2:]}
    res.update(c_sign=c_sign, c_neg=c_neg, rho=rho, R=Rv)
    pr = {}
    if c_sign:
        pr['P176'] = dict(c_sign=c_sign, holds=bool(c_sign[0] >= 0.05))
    if rho and c_sign:
        pr['P177'] = dict(rho=rho, c_sign=c_sign, holds=bool(rho[0] >= 1.5 * c_sign[0]))
    if all(Rv.get(a) for a in ('c2m2k', 'c2m12k', 'mag18')):
        pr['P178'] = dict(R_c2m2k=Rv['c2m2k'], R_c2m12k=Rv['c2m12k'], R_mag18=Rv['mag18'],
                          holds=bool(Rv['c2m2k'][0] >= 0.8 and Rv['c2m12k'][0] <= 0.5 and Rv['mag18'][0] >= 0.8))
    res['predictions'] = pr
    md = ['# E41 tables (generated by e41_summ.py)', '', '| arm | toys | mean KL | median | min | max | R [95% CI] |', '|---' * 7 + '|']
    for a, o in res['arms'].items():
        md.append('| %s | %d | %.4f | %.4f | %.4f | %.4f | %s |' % (a, o['n'], o['K'], o['K_median'], o['K_min'], o['K_max'],
                                                               '%.2f [%.2f, %.2f]' % tuple(Rv[a]) if Rv.get(a) else '-'))
    md += ['', 'c_sign %s; c_neg %s; rho %s' % (c_sign, c_neg, rho), '', '| seed | ' + ' | '.join(ARMS) + ' |', '|---' * (len(ARMS) + 1) + '|']
    for s in seeds:
        md.append('| %d | ' % s + ' | '.join('%.4f' % R[(a, s)]['kl'] if (a, s) in R else '-' for a in ARMS) + ' |')
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e41.json', 'w'), indent=1, default=float)
    open('results/e41_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1, default=float)); print('R', json.dumps(Rv)); print('arms', json.dumps(res['arms']))


if __name__ == '__main__':
    main()
