"""E47 analysis (PREREG-B amendment 55): when does a net's final A/B type become visible in training?
Inputs: results/e47/<tag>.npz (e47_run.py) and each run's final evaluation (results/e37, e43, e44 or e46: gap, rom_middle).
Lineages: acquired runs (final gap < 0.10) trained in ctrl throughout; an E43 brK run is left out at steps <= K, where its
checkpoint duplicates its parent's (the parent is included). Clusters for the bootstrap: the parent seed (E37 ctrl seed,
E43 parent seed, E44 recipient seed, E46 parent seed).
For each step (0, 2,000, 3,000, 5,000, 10,000) and marker (lab, xq, the sign-flip cost share sign_pc / sign_kl, KL):
  AUC = P(marker of a final-B lineage > marker of a final-A lineage) (ties count half); 2,000 cluster-bootstrap resamples.
Predictions:
  P191  AUC(lab at 3,000 steps) >= 0.75;
  P192  at step 0, every marker's |AUC - 0.5| <= 0.15.
usage: python e47_summ.py -> results/e47.json, results/e47_tables.md
"""
import glob, json, os
import numpy as np

MARKERS = ['lab', 'xq', 'sign_share', 'kl']
STEPS = [0, 2000, 3000, 5000, 10000]
rng = np.random.default_rng(47)


def final_and_cluster(tag):
    if tag.startswith('e37_ctrl_s'):
        return 'results/e37/%s.npz' % tag, int(tag.rsplit('_s', 1)[1])
    if tag.startswith('e43_'):
        return 'results/e43/%s.npz' % tag, int(tag.rsplit('_s', 1)[1])
    if tag.startswith('e44_'):
        return 'results/e44/%s.npz' % tag, int(tag.split('_r')[1].split('_')[0])
    if tag.startswith('e46_'):
        return 'results/e46/%s.npz' % tag, int(tag.rsplit('_s', 1)[1])
    return None, None


def auc(pos, neg):
    pos, neg = np.asarray(pos), np.asarray(neg)
    if not len(pos) or not len(neg):
        return np.nan
    return float(((pos[:, None] > neg[None]).sum() + 0.5 * (pos[:, None] == neg[None]).sum()) / (len(pos) * len(neg)))


def main():
    L = []
    for f in sorted(glob.glob('results/e47/*.npz')):
        tag = os.path.basename(f)[:-4]; fp, cl = final_and_cluster(tag)
        if fp is None or not os.path.exists(fp):
            continue
        fz = np.load(fp)
        if float(fz['gap']) >= 0.10:
            continue
        z = np.load(f); m = {}
        # post-review correction (2026-10-30): br0 shares its parent's initialisation, so its step-0 checkpoint duplicates the
        # parent's and is now left out too (the registered rule, brK out at steps <= K, with K = 0).
        arm = tag.split('_')[1]
        kb = (0 if arm == 'br0' else int(arm[2:-1]) * 1000) if tag.startswith('e43_br') else -1
        for i, st in enumerate(z['step']):
            if int(st) <= kb:                                   # brK equals its parent (included) up to step K: skip duplicates
                continue
            m[int(st)] = dict(lab=float(z['lab'][i]), xq=float(z['xq'][i]), kl=float(z['kl'][i]),
                              sign_share=float(z['sign_pc'][i] / z['sign_kl'][i]) if z['sign_kl'][i] > 0 else np.nan)
        L.append(dict(tag=tag, cluster=cl, B=bool(float(fz['rom_middle']) > 0), m=m))
    clusters = sorted({x['cluster'] for x in L})
    res = dict(n=len(L), n_B=sum(x['B'] for x in L), clusters=clusters, auc={})
    for st in STEPS:
        for mk in MARKERS:
            def stat(cs):
                sel = [x for c in cs for x in L if x['cluster'] == c and st in x['m'] and np.isfinite(x['m'][st][mk])]
                return auc([x['m'][st][mk] for x in sel if x['B']], [x['m'][st][mk] for x in sel if not x['B']])
            pt = stat(clusters)
            bs = [stat(list(rng.choice(clusters, len(clusters)))) for _ in range(2000)]
            bs = [b for b in bs if np.isfinite(b)]
            res['auc']['%s@%d' % (mk, st)] = [pt, float(np.percentile(bs, 2.5)) if bs else np.nan, float(np.percentile(bs, 97.5)) if bs else np.nan]
    pr = {}
    a = res['auc'].get('lab@3000')
    if a:
        pr['P191'] = dict(auc=a, holds=bool(a[0] >= 0.75))
    a0 = {mk: res['auc']['%s@0' % mk][0] for mk in MARKERS}
    pr['P192'] = dict(auc_at_0=a0, holds=bool(all(abs(v - 0.5) <= 0.15 for v in a0.values() if np.isfinite(v))))
    res['predictions'] = pr
    md = ['# E47 tables (generated by e47_summ.py)', '', 'lineages: %d (%d B), clusters: %d' % (res['n'], res['n_B'], len(clusters)), '',
          '| step | ' + ' | '.join('AUC %s [95%% CI]' % mk for mk in MARKERS) + ' |', '|---' * (len(MARKERS) + 1) + '|']
    for st in STEPS:
        md.append('| %d | ' % st + ' | '.join('%.2f [%.2f, %.2f]' % tuple(res['auc']['%s@%d' % (mk, st)]) for mk in MARKERS) + ' |')
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e47.json', 'w'), indent=1, default=float)
    open('results/e47_tables.md', 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
