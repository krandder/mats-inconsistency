"""E76 analysis (PREREG-B amendment 84): does a fresh reader on a frozen block 1 reproduce the departure and its parts, and does more
reader training lower the KL? Inputs: results/e76/<tag>.json (e76_eval.py) for the sources (E37 ctrl s0, s1, s2, s6 = A; s4, s5, s7, s9,
s10, s11 = B) and their readers fresh_s<seed>, continue_s<seed> (runs/e76); M3 of each source from results/e72/ctrl_s<seed>.json.
Notation: rom = rom_large; Qt = rom - detq (the query term); D = detq.
Predictions (registered):
  P307  fresh: |rom(fresh) - rom(src)| <= 0.02 in >= 75% of the 10 sources;
  P308  fresh: |D(fresh) - D(src)| <= 0.02 and |Qt(fresh) - Qt(src)| <= 0.015 in >= 75%;
  P309  fresh: gap(fresh) / gap(src) within [0.85, 1.15] in >= 75%;
  P310  continue: gap(continue) <= 0.95 x gap(src) and |rom(continue) - rom(src)| <= 0.02 in >= 75%.
usage: python e76_summ.py -> results/e76.json, results/e76_tables.md
"""
import json, os
import numpy as np

SRC = {0: 'A', 1: 'A', 2: 'A', 6: 'A', 4: 'B', 5: 'B', 7: 'B', 9: 'B', 10: 'B', 11: 'B'}


def ld(t):
    p = 'results/e76/%s.json' % t
    return json.load(open(p)) if os.path.exists(p) else None


def main():
    rows, f307, f308, f309, f310 = [], [], [], [], []
    for s, ty in SRC.items():
        src, fr, co = ld('e37_ctrl_s%d' % s), ld('fresh_s%d' % s), ld('continue_s%d' % s)
        m3 = json.load(open('results/e72/ctrl_s%d.json' % s))['M3']['large']
        if not (src and fr and co):
            continue
        Q = lambda o: o['rom_large'] - o['detq_large']
        f307.append(abs(fr['rom_large'] - src['rom_large']) <= 0.02)
        f308.append(abs(fr['detq_large'] - src['detq_large']) <= 0.02 and abs(Q(fr) - Q(src)) <= 0.015)
        f309.append(0.85 <= fr['gap'] / src['gap'] <= 1.15)
        f310.append(co['gap'] <= 0.95 * src['gap'] and abs(co['rom_large'] - src['rom_large']) <= 0.02)
        for nm, o in (('source', src), ('fresh', fr), ('continue', co)):
            rows.append('| s%d | %s | %s | %.4f | %.3f / %+.3f | %.3f | %+.3f | %+.3f |' % (s, ty, nm, o['gap'], o['rom_large'], o['rom_middle'], o['detq_large'],
                                                                                o['detq_large'] - m3, Q(o)))
    fr_ = lambda xs: [int(sum(xs)), len(xs)]
    hb = lambda xs: bool(bool(xs) and np.mean(xs) >= 0.75)                      # JSON fix (ninth agent): a numpy bool; tests unchanged
    pr = dict(P307=dict(n=fr_(f307), holds=hb(f307)), P308=dict(n=fr_(f308), holds=hb(f308)),
              P309=dict(n=fr_(f309), holds=hb(f309)), P310=dict(n=fr_(f310), holds=hb(f310)))
    md = ['# E76 tables (generated by e76_summ.py)', '', '| source | type | net | gap | rom (large / middle) | detq | detq - M3 | rom - detq |',
          '|---|---|---|---|---|---|---|---|'] + rows + ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(dict(predictions=pr), open('results/e76.json', 'w'), indent=1)
    open('results/e76_tables.md', 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
