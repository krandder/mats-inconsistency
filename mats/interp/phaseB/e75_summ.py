"""E75 analysis (PREREG-B amendment 83): the reading's path through its own pool.
Input: results/e75/<cohort>_s<seed>.json (e75_run.py). Registered cohorts: ctrl, fix, h4, b1h4, mag, w64ctrl, w128ctrl, w64mag, w128mag;
descriptive: d3ctrl, d3mag; secondary (same tests, reported separately): E71's h2w8, h3w16, h4w16. Acquired: gap < 0.10 (registered).
Sets: A = A-type nets with >= 2 pooling heads; Bp = B-type nets with >= 1 pooling head; Bc = B-type nets with >= 1 consensus head.
Ratios use the recomputed base gap.
Predictions (registered):
  P302  Bp: gap(shuf_pool) / gap(base) >= 1.5 in >= 75%;
  P303  A: gap(shuf_pool) / gap(base) <= 1.15 in >= 75%;
  P304  Bc: gap(shuf_cons) / gap(base) <= 1.10 in >= 75%;
  P305  A: rom_large(shuf_pool) - rom_large(base) >= 0.02 in >= 75%;
  P306  corr(K, o*) <= -0.20 for >= 75% of Bp nets' pooling heads, and |corr(K, o*)| <= 0.15 for >= 75% of A nets' pooling heads.
usage: python e75_summ.py -> results/e75.json, results/e75_tables.md
"""
import glob, json
import numpy as np

REG = ('ctrl', 'fix', 'h4', 'b1h4', 'mag', 'w64ctrl', 'w128ctrl', 'w64mag', 'w128mag')
DESC = ('d3ctrl', 'd3mag'); SEC = ('h2w8', 'h3w16', 'h4w16')


def frac(xs):
    return [int(sum(xs)), len(xs), float(np.mean(xs)) if xs else None]


def tests(nets):
    A = [o for o in nets if o['type'] == 'A' and len(o['pool']) >= 2]
    Bp = [o for o in nets if o['type'] == 'B' and len(o['pool']) >= 1]
    Bc = [o for o in nets if o['type'] == 'B' and len(o['cons']) >= 1 and 'shuf_cons' in o]
    r = lambda o, m: o[m]['gap'] / o['base']['gap']
    pr = {}
    f = frac([r(o, 'shuf_pool') >= 1.5 for o in Bp]); pr['P302'] = dict(n=f, holds=bool(Bp) and f[2] >= 0.75)
    f = frac([r(o, 'shuf_pool') <= 1.15 for o in A]); pr['P303'] = dict(n=f, holds=bool(A) and f[2] >= 0.75)
    f = frac([r(o, 'shuf_cons') <= 1.10 for o in Bc]); pr['P304'] = dict(n=f, holds=bool(Bc) and f[2] >= 0.75)
    f = frac([o['shuf_pool']['large'] - o['base']['large'] >= 0.02 for o in A]); pr['P305'] = dict(n=f, holds=bool(A) and f[2] >= 0.75)
    fb = frac([v <= -0.20 for o in Bp for v in o['corr_K_ostar'].values()]); fa = frac([abs(v) <= 0.15 for o in A for v in o['corr_K_ostar'].values()])
    pr['P306'] = dict(B=fb, A=fa, holds=bool(Bp and A) and fb[2] >= 0.75 and fa[2] >= 0.75)
    return pr


def main():
    D = {}
    for p in glob.glob('results/e75/*.json'):
        o = json.load(open(p))
        if o['net_gap'] < 0.10:
            D.setdefault(o['tag'].rsplit('_s', 1)[0], []).append(o)
    res = dict(predictions=tests([o for c in REG for o in D.get(c, [])]),
               secondary=tests([o for c in SEC for o in D.get(c, [])]) if any(c in D for c in SEC) else None)
    md = ['# E75 tables (generated by e75_summ.py)', '', '| cohort | type | nets | base KL | shuf_pool KL ratio (median [range]) | shuf_cons KL ratio | rom_large base / shuf_pool | corr(K, o*) of pooling heads (median) |',
          '|---|---|---|---|---|---|---|---|']
    for c in REG + DESC + SEC:
        for t in ('A', 'B'):
            L = [o for o in D.get(c, []) if o['type'] == t]
            if not L:
                continue
            rp = [o['shuf_pool']['gap'] / o['base']['gap'] for o in L if 'shuf_pool' in o]
            rc = [o['shuf_cons']['gap'] / o['base']['gap'] for o in L if 'shuf_cons' in o]
            rl = [(o['base']['large'], o['shuf_pool']['large']) for o in L if 'shuf_pool' in o]
            ck = [v for o in L for v in o['corr_K_ostar'].values()]
            md.append('| %s | %s | %d | %.4f | %s | %s | %s | %s |' % (
                c, t, len(L), np.mean([o['base']['gap'] for o in L]),
                ('%.2f [%.2f, %.2f]' % (np.median(rp), min(rp), max(rp))) if rp else '-', ('%.2f' % np.median(rc)) if rc else '-',
                ('%.3f / %.3f' % (np.mean([a for a, b in rl]), np.mean([b for a, b in rl]))) if rl else '-', ('%+.2f' % np.median(ck)) if ck else '-'))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in res['predictions'].items()]
    if res['secondary']:
        md += ['', '## Secondary (E71 arms)', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in res['secondary'].items()]
    json.dump(res, open('results/e75.json', 'w'), indent=1, default=float)
    open('results/e75_tables.md', 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
