"""E34 analysis (PREREG-B amendment 42).
Pooled over a group's nets: share_path = sum dm_path dm_full / sum dm_full^2 (share of the single-source negation shift that the
query's block-2 read of the labelled tokens reproduces alone), share_rev (share removed when only that path is restored to the base),
cost_path = negation cost with only that path seeing the signs / full negation cost, cost_rev = all-but-path cost / full cost,
KL of the hybrid families / full, and the marker masses.
  P160  B bases: share_path >= 0.5 and cost_path >= 0.5.
  P161  A bases: share_path <= 0.3, and below the B bases' share.
usage: python e34_summ.py -> results/e34.json, results/e34_tables.md
"""
import json, os
import numpy as np
import e26_summ as SM


def main():
    rows = json.load(open('results/e26_nets.json'))
    nets = {}
    for s in ('M', 'G'):
        for r in rows:
            if r['set'] == s:
                f = os.path.join('results/e34', s, r['tag'] + '.npz')
                if os.path.exists(f):
                    nets[r['tag']] = (s, {k: float(v) for k, v in np.load(f).items()})
    groups = dict(A=SM.A_BASES, B=SM.B_BASES, M=[t for t, (s, _) in nets.items() if s == 'M'],
                  G=[t for t, (s, _) in nets.items() if s == 'G'])
    res = dict(groups={}, per_net={})
    for t, (s, o) in nets.items():
        res['per_net'][t] = dict(set=s, share_path=o['dm_path_full'] / o['dm_full2'], share_rev=o['dm_rev_full'] / o['dm_full2'],
                                 cost_path=o['pc_path'] / o['pc_full'], cost_rev=o['pc_rev'] / o['pc_full'],
                                 kl_path=o['kl_path'] / o['kl_full'], kl_rev=o['kl_rev'] / o['kl_full'], m_lab=o['m_lab'], m_summ=o['m_summ'],
                                 mass=o['mass'])
    for g, tags in groups.items():
        L = [nets[t][1] for t in tags if t in nets]
        if not L:
            continue
        S = lambda k: sum(x[k] for x in L)
        res['groups'][g] = dict(n=len(L), share_path=S('dm_path_full') / S('dm_full2'), share_rev=S('dm_rev_full') / S('dm_full2'),
                                cost_path=S('pc_path') / S('pc_full'), cost_rev=S('pc_rev') / S('pc_full'),
                                kl_path=S('kl_path') / S('kl_full'), kl_rev=S('kl_rev') / S('kl_full'),
                                m_lab=float(np.mean([x['m_lab'] for x in L])), m_summ=float(np.mean([x['m_summ'] for x in L])),
                                cost_full=S('pc_full') / len(L), mass_min=min(x['mass'] for x in L))
    pr = {}
    if 'A' in res['groups'] and 'B' in res['groups']:
        a, b = res['groups']['A'], res['groups']['B']
        pr['P160'] = dict(share_path=b['share_path'], cost_path=b['cost_path'], holds=bool(b['share_path'] >= 0.5 and b['cost_path'] >= 0.5))
        pr['P161'] = dict(share_path_A=a['share_path'], share_path_B=b['share_path'], holds=bool(a['share_path'] <= 0.3 and a['share_path'] < b['share_path']))
    res['predictions'] = pr
    md = ['# E34 tables (generated by e34_summ.py)', '',
          '| group | nets | full negation cost | dm share: path | dm share: rev | cost: path-only / full | cost: all-but-path / full | KL path / full | KL rev / full | block-2 query attention: labelled | summary |',
          '|---' * 11 + '|']
    for g, o in res['groups'].items():
        md.append('| %s | %d | %.5f | %.2f | %.2f | %.2f | %.2f | %.3f | %.3f | %.3f | %.3f |' % (
            g, o['n'], o['cost_full'], o['share_path'], o['share_rev'], o['cost_path'], o['cost_rev'], o['kl_path'], o['kl_rev'], o['m_lab'], o['m_summ']))
    md += ['', '| net | set | dm share path | dm share rev | cost path | cost rev | attention labelled | summary |', '|---' * 8 + '|']
    for t, o in res['per_net'].items():
        md.append('| %s | %s | %.2f | %.2f | %.2f | %.2f | %.3f | %.3f |' % (t, o['set'], o['share_path'], o['share_rev'], o['cost_path'], o['cost_rev'],
                                                                        o['m_lab'], o['m_summ']))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e34.json', 'w'), indent=1)
    open('results/e34_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1))


if __name__ == '__main__':
    main()
