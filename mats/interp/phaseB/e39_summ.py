"""E39 analysis (PREREG-B amendment 47): signs plus a magnitude feature, paired at initialisation with ctrl and mag.
Inputs: results/e39/e39_sgp_s<seed>.npz from e37_eval.py and E37's pure arms results/e37/e37_{ctrl,mag}_s<seed>.npz (same seeds,
initialisation of every shared parameter, episode stream and fixed 90,000-step schedule); E30's unpaired sgnmag nets for comparison.
r = mean K_sgp / mean K_mag over seeds acquired (gap < 0.10) in both (paired ratio of means; 2,000 bootstrap resamples of seeds);
c_sign(arm) = pooled sign-flip KL reduction / pooled family KL (uncorrected, E27's data, flip_ind).
Prediction:
  P173  r <= 1.1 and c_sign(sgp) <= 0.25 x c_sign(ctrl)   (E30's P151, now paired at initialisation).
usage: python e39_summ.py -> results/e39.json, results/e39_tables.md
"""
import glob, json, os
import numpy as np

rng = np.random.default_rng(39)


def rd(f):
    return {k: (v.item() if hasattr(v, 'item') else v) for k, v in dict(np.load(f)).items()}


def main():
    R = {}
    for f in sorted(glob.glob('results/e39/e39_sgp_s*.npz')):
        R[('sgp', int(os.path.basename(f)[:-4].rsplit('_s', 1)[1]))] = rd(f)
    for a in ('ctrl', 'mag'):
        for f in sorted(glob.glob('results/e37/e37_%s_s*.npz' % a)):
            R[(a, int(os.path.basename(f)[:-4].rsplit('_s', 1)[1]))] = rd(f)
    for f in sorted(glob.glob('results/e30/sgnmag_s*.npz')):
        R[('sgnmag_e30', int(os.path.basename(f)[:-4].rsplit('_s', 1)[1]))] = rd(f)
    acq = {k: v['gap'] < 0.10 for k, v in R.items()}
    seeds = sorted({s for (a, s) in R if a == 'sgp'})
    res = dict(per_net={'%s_s%d' % k: v for k, v in R.items()}, arms={})
    for a in ('ctrl', 'mag', 'sgp', 'sgnmag_e30'):
        acs = [s for s in seeds if (a, s) in R and acq[(a, s)]]
        o = dict(n=sum((a, s) in R for s in seeds), n_acquired=len(acs))
        if acs:
            v = lambda k: [R[(a, s)][k] for s in acs]
            o.update(K=float(np.mean(v('gap'))), K_median=float(np.median(v('gap'))), n_A=int(sum(x < 0 for x in v('rom_middle'))),
                     n_B=int(sum(x > 0 for x in v('rom_middle'))), rom_large=float(np.mean(v('rom_large'))))
            if all('lab_last' in R[(a, s)] for s in acs):
                o.update(lab=float(np.mean(v('lab_last'))), xq=float(np.mean(v('xq'))))
            have = [s for s in acs if 'sign_pc' in R[(a, s)]]
            if have:
                o['c_sign'] = float(sum(R[(a, s)]['sign_pc'] for s in have) / sum(R[(a, s)]['sign_kl'] for s in have))
        res['arms'][a] = o
    common = [s for s in seeds if all((a, s) in R and acq[(a, s)] for a in ('mag', 'sgp'))]
    pr = {}
    if len(common) >= 3:
        f = lambda ss: np.mean([R[('sgp', s)]['gap'] for s in ss]) / np.mean([R[('mag', s)]['gap'] for s in ss])
        bs = [f(list(rng.choice(common, len(common)))) for _ in range(2000)]
        r = [float(f(common)), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))]
        cs, cc = res['arms']['sgp'].get('c_sign'), res['arms']['ctrl'].get('c_sign')
        pr['P173'] = dict(K_sgp_over_K_mag=r, n_seeds=len(common), c_sign_sgp=cs, c_sign_ctrl=cc,
                          holds=bool(r[0] <= 1.1 and cs is not None and cc is not None and cs <= 0.25 * cc))
    res['predictions'] = pr
    md = ['# E39 tables (generated by e39_summ.py)', '',
          '| arm | nets | acquired | mean KL | median KL | A / B | rom large | lab (last block) | xq | sign red. / KL |', '|---' * 10 + '|']
    for a, o in res['arms'].items():
        if not o.get('n_acquired'):
            md.append('| %s | %d | 0 |' % (a, o['n'])); continue
        md.append('| %s | %d | %d | %.4f | %.4f | %d / %d | %.3f | %s | %s | %s |' % (
            a, o['n'], o['n_acquired'], o['K'], o['K_median'], o['n_A'], o['n_B'], o['rom_large'],
            '%.3f' % o['lab'] if 'lab' in o else '-', '%.4f' % o['xq'] if 'xq' in o else '-', '%.3f' % o['c_sign'] if 'c_sign' in o else '-'))
    md += ['', '| seed | ctrl | mag | sgp | sgnmag (E30, unpaired) |', '|---|---|---|---|---|']
    for s in seeds:
        cell = lambda a: '-' if (a, s) not in R else '%.4f %s' % (R[(a, s)]['gap'], 'B' if R[(a, s)]['rom_middle'] > 0 else 'A')
        md.append('| %d | %s | %s | %s | %s |' % (s, cell('ctrl'), cell('mag'), cell('sgp'), cell('sgnmag_e30')))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e39.json', 'w'), indent=1, default=float)
    open('results/e39_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1, default=float))


if __name__ == '__main__':
    main()
