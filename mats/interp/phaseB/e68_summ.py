"""E68 analysis (PREREG-B amendment 76): how the A allocation forms over training, over E47's lineages (results/e68/<tag>.json).
Lineages, final types, acquisition and clusters as E47 (e47_summ.final_and_cluster; an E43 brK lineage is used only at steps > K,
where it differs from its parent); the five nets explored in amendment 71 are excluded. Pooling head: P_h >= 0.5.
Predictions (registered in amendment 76):
  P264  among the final-A lineages that have two pooling heads at some checkpoint, the two heads' mean signed coefficients K have
        opposite signs at the first such checkpoint in >= 80% of them;
  P265  that first two-pooling-head checkpoint is at 5,000-20,000 steps in >= 70% of the final-A lineages;
  P266  in >= 80% of the final-B lineages, no checkpoint from 5,000 steps on has two pooling heads.
Descriptive: the distribution of the first two-pooling-head step; at that step and at the end, the pair's |K| ratio; whether the first
pooling head's K sign is stable from its first pooling checkpoint to the end; L_own of pooling heads over training by final type.
usage: python e68_summ.py -> results/e68.json, results/e68_tables.md   (E68_DIR overrides results/e68)
"""
import glob, json, os
import numpy as np

import e47_summ as E47

D = os.environ.get('E68_DIR', 'results/e68')
STEPS = [0, 2000, 3000, 5000, 10000, 20000, 40000, 60000, 80000, 90000]


def main():
    L = []
    for f in sorted(glob.glob(os.path.join(D, '*.json'))):
        tag = os.path.basename(f)[:-5]; fp, cl = E47.final_and_cluster(tag)
        if fp is None or not os.path.exists(fp):
            continue
        fz = np.load(fp)
        if float(fz['gap']) >= 0.10:
            continue
        arm = tag.split('_')[1]
        kb = (0 if arm == 'br0' else int(arm[2:-1]) * 1000) if tag.startswith('e43_br') else -1
        tr = {int(k): v for k, v in json.load(open(f)).items() if int(k) > kb}
        L.append(dict(tag=tag, cluster=cl, B=bool(float(fz['rom_middle']) > 0), tr=tr))
    res = dict(n=len(L), n_B=sum(x['B'] for x in L), predictions={}); pr = res['predictions']
    first, opp, ratio_first, ratio_end, stable = [], [], [], [], []
    for x in L:
        if x['B']:
            continue
        st2 = [st for st in sorted(x['tr']) if sum(p >= 0.5 for p in x['tr'][st]['P_h']) == 2]
        if not st2:
            continue
        s0 = st2[0]; o = x['tr'][s0]; first.append(s0)
        opp.append(bool(o['K_h'][0] * o['K_h'][1] < 0))
        ratio_first.append(float(min(abs(o['K_h'][0]), abs(o['K_h'][1])) / max(abs(o['K_h'][0]), abs(o['K_h'][1]))))
        e = x['tr'][max(x['tr'])]; ratio_end.append(float(min(abs(e['K_h'][0]), abs(e['K_h'][1])) / max(abs(e['K_h'][0]), abs(e['K_h'][1]))))
    nA = sum(not x['B'] for x in L)
    if opp:
        pr['P264'] = dict(frac=float(np.mean(opp)), n=len(opp), n_A=nA, holds=bool(np.mean(opp) >= 0.8))
        win = [5000 <= s <= 20000 for s in first]
        pr['P265'] = dict(frac=float(sum(win) / nA), n_with_pair=len(first), n_A=nA, steps=sorted(first), holds=bool(sum(win) / nA >= 0.7))
    Bs = [x for x in L if x['B']]
    if Bs:
        never = [all(sum(p >= 0.5 for p in x['tr'][st]['P_h']) < 2 for st in x['tr'] if st >= 5000) for x in Bs]
        pr['P266'] = dict(frac=float(np.mean(never)), n_B=len(Bs), holds=bool(np.mean(never) >= 0.8))
    for x in L:                                                  # first pooling head's K sign stability
        pools = [(st, [h for h, p in enumerate(x['tr'][st]['P_h']) if p >= 0.5]) for st in sorted(x['tr'])]
        pools = [(st, hs) for st, hs in pools if hs]
        if not pools:
            continue
        st0, hs0 = pools[0]; h0 = hs0[0]; k0 = np.sign(x['tr'][st0]['K_h'][h0]); ke = np.sign(x['tr'][max(x['tr'])]['K_h'][h0])
        stable.append(bool(k0 == ke))
    traj = {}
    for typ, sel in (('A', [x for x in L if not x['B']]), ('B', Bs)):
        t = {}
        for st in STEPS:
            vals = [x['tr'][st] for x in sel if st in x['tr']]
            if not vals:
                continue
            npool = [sum(p >= 0.5 for p in v['P_h']) for v in vals]
            Lp = [v['L_own_h'][h] for v in vals for h, p in enumerate(v['P_h']) if p >= 0.5]
            t[st] = dict(n=len(vals), npool_mean=float(np.mean(npool)), frac_two=float(np.mean([k == 2 for k in npool])),
                         L_own_pool_median=float(np.median(Lp)) if Lp else None, C_max_median=float(np.median([max(v['C_h']) for v in vals])))
        traj[typ] = t
    res.update(first_two_pool_steps={str(s): int(sum(f == s for f in first)) for s in STEPS}, pair_K_ratio_first=float(np.median(ratio_first)) if ratio_first else None,
               pair_K_ratio_end=float(np.median(ratio_end)) if ratio_end else None, first_head_K_sign_stable=float(np.mean(stable)) if stable else None, traj=traj)
    md = ['# E68 tables (generated by e68_summ.py)', '', 'lineages %d (%d B)' % (res['n'], res['n_B']), '',
          '| step | A: lineages | A: mean pooling heads | A: two pooling heads | A: L_own (pool) | A: C_max | B: lineages | B: mean pooling heads | B: two pooling heads | B: L_own (pool) | B: C_max |',
          '|---' * 11 + '|']
    for st in STEPS:
        a = traj.get('A', {}).get(st); b = traj.get('B', {}).get(st)
        f = lambda d: ('%d | %.2f | %.2f | %s | %.2f' % (d['n'], d['npool_mean'], d['frac_two'], '%.1f' % d['L_own_pool_median'] if d['L_own_pool_median'] is not None else '-', d['C_max_median'])) if d else '- | - | - | - | -'
        md.append('| %d | %s | %s |' % (st, f(a), f(b)))
    md += ['', 'first two-pooling-head step (A lineages): %s' % json.dumps(res['first_two_pool_steps']),
           'pair |K| ratio (min / max) at that step: %s; at the end: %s' % (res['pair_K_ratio_first'], res['pair_K_ratio_end']),
           'first pooling head keeps its K sign to the end: %s' % res['first_head_K_sign_stable'], '', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open(os.environ.get('E68_JSON', 'results/e68.json'), 'w'), indent=1, default=float)
    open(os.environ.get('E68_TAB', 'results/e68_tables.md'), 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
