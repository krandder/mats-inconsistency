"""E67 analysis (PREREG-B amendment 75): the head-level account in world 2, where nothing has to be routed.
Inputs: results/e67/<cohort>.json (e67_run.py); E63's world-1 ctrl pooling heads (results/e63/ctrl.json) for comparison.
Predictions (registered in amendment 75):
  P260  over the query token's block-1 heads of all registered nets (ctrl, canon, sgnprod; D = 1, 2), the median |L| is < 3 (world 1's
        routing heads: median 16.8);
  P261  the norm term at a large example (|y| = 3, x = 0) is > -1 in >= 80% of those heads;
  P262  ctrl nets: removing one head's signed terms from the query row multiplies the KL by >= 2 in >= 75% of the (net, head) cases;
  P263  the median single-head KL factor of the sgnprod nets is below the ctrl nets'.
usage: python e67_summ.py -> results/e67.json, results/e67_tables.md   (E67_DIR overrides results/e67)
"""
import json, os
import numpy as np

D = os.environ.get('E67_DIR', 'results/e67')
COH = ('d1ctrl', 'd2ctrl', 'd1canon', 'd2canon', 'd1sgnprod', 'd2sgnprod')


def main():
    R = {c: json.load(open(os.path.join(D, '%s.json' % c))) for c in COH if os.path.exists(os.path.join(D, '%s.json' % c))}
    res = dict(cohorts={}, predictions={}); pr = res['predictions']
    heads = [(c, t, h, o) for c, r in R.items() for t, o in r.items() for h in range(len(o['L']))]
    if heads:
        absL = [abs(o['L'][h]) for c, t, h, o in heads]; dl = [o['dlogit_y3'][h] for c, t, h, o in heads]
        e63 = json.load(open('results/e63/ctrl.json')); w1 = float(np.median([o['L_own_h'][h] for o in e63.values() for h in o.get('pool_heads', [])]))
        pr['P260'] = dict(median_absL=float(np.median(absL)), n_heads=len(absL), world1_median=w1, holds=bool(np.median(absL) < 3))
        f = float(np.mean([x > -1 for x in dl])); pr['P261'] = dict(frac=f, n_heads=len(dl), holds=bool(f >= 0.8))
    fac = lambda o, h: o['kl']['zero%d' % h] / o['kl']['base']
    ctrl = [fac(o, h) for c, t, h, o in heads if c.endswith('ctrl')]
    sgp = [fac(o, h) for c, t, h, o in heads if c.endswith('sgnprod')]
    if ctrl:
        f = float(np.mean([x >= 2 for x in ctrl])); pr['P262'] = dict(frac=f, n=len(ctrl), median=float(np.median(ctrl)), holds=bool(f >= 0.75))
    if ctrl and sgp:
        pr['P263'] = dict(median_sgnprod=float(np.median(sgp)), median_ctrl=float(np.median(ctrl)), holds=bool(np.median(sgp) < np.median(ctrl)))
    md = ['# E67 tables (generated by e67_summ.py)', '', '| cohort | nets | KL | query mass on examples | L (median |L|) | norm term at y = 3 | K_y RMS | K_x RMS | K_y signs opposite across heads | KL factor: one head (median) / both |',
          '|---' * 10 + '|']
    for c, r in R.items():
        V = list(r.values())
        if not V:
            continue
        hL = [abs(x) for o in V for x in o['L']]
        opp = sum(o['K_y'][0] * o['K_y'][1] < 0 for o in V)
        one = [o['kl']['zero%d' % h] / o['kl']['base'] for o in V for h in range(len(o['L']))]; both = [o['kl']['zeroall'] / o['kl']['base'] for o in V]
        d = dict(n=len(V), kl=float(np.mean([o['gap'] for o in V])), q_on_examples=float(np.mean([x for o in V for x in o['q_on_examples']])),
                 median_absL=float(np.median(hL)), dlogit_y3=float(np.median([x for o in V for x in o['dlogit_y3']])),
                 K_y_rms=float(np.mean([x for o in V for x in o['K_y_rms']])), K_x_rms=float(np.mean([x for o in V for x in o['K_x_rms']])),
                 K_y_opposite=int(opp), kl_factor_one=float(np.median(one)), kl_factor_both=float(np.median(both)))
        res['cohorts'][c] = d
        md.append('| %s | %d | %.4f | %.2f | %.2f | %.2f | %.2f | %.2f | %d of %d | %.1f / %.1f |' % (c, d['n'], d['kl'], d['q_on_examples'], d['median_absL'], d['dlogit_y3'],
                                                                                              d['K_y_rms'], d['K_x_rms'], opp, len(V), d['kl_factor_one'], d['kl_factor_both']))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open(os.environ.get('E67_JSON', 'results/e67.json'), 'w'), indent=1, default=float)
    open(os.environ.get('E67_TAB', 'results/e67_tables.md'), 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
