"""E60 analysis (PREREG-B amendment 68): is the uniform-pool nets' advantage (E53) given source membership or fixed weights?
Arms (CPU, ctrl format, fixed 90,000-step schedule, same initialisation and episodes per seed): own (summary rows restricted to the
source's own labelled tokens, weights learned; seeds 0-11), ownf (own plus the query barred from labelled tokens; seeds 0-7),
ctrl_cpu (the baseline on CPU; seeds 0, 1, 4, 7: a device check against E37's GPU-trained ctrl nets). Comparisons: E53's uni and
unif (CPU; same allowed sets, weights fixed at 1/4), E37's ctrl.
Inputs: results/e60/<tag>.npz (e60_eval.py), results/e53/, results/e37/. Acquired: gap < 0.10. Paired seeds acquired in both.
2,000 bootstrap resamples of seeds, with multiplicities.
Predictions (registered in amendment 68; the learned within-source weighting, not membership, makes the cost):
  P229  KL: mean K(own) / mean K(uni) >= 2, paired seeds;
  P230  sign share (pooled sign_pc / sign_kl over acquired nets): own >= 0.10;
  P231  departure: mean rom_large(own) - mean rom_large(uni) <= -0.02, paired seeds.
usage: python e60_summ.py -> results/e60.json, results/e60_tables.md
"""
import glob, json, os
import numpy as np

rng = np.random.default_rng(60)
NB = 2000


def rd(f):
    return {k: (v.item() if hasattr(v, 'item') else v) for k, v in dict(np.load(f, allow_pickle=True)).items()}


def seed_of(f):
    return int(os.path.basename(f)[:-4].rsplit('_s', 1)[1])


def ci(x):
    return [float(np.percentile(x, 2.5)), float(np.percentile(x, 97.5))]


def main():
    R = {}
    for a, pat in (('own', 'results/e60/e60_own_s*.npz'), ('ownf', 'results/e60/e60_ownf_s*.npz'), ('ctrl_cpu', 'results/e60/e60_ctrlcpu_s*.npz'),
                   ('uni', 'results/e53/e53_uni_s*.npz'), ('unif', 'results/e53/e53_unif_s*.npz'), ('ctrl', 'results/e37/e37_ctrl_s*.npz')):
        for f in sorted(glob.glob(pat)):
            R[(a, seed_of(f))] = rd(f)
    acq = {k: v['gap'] < 0.10 for k, v in R.items()}
    arms = ('ctrl', 'ctrl_cpu', 'own', 'uni', 'ownf', 'unif')
    res = dict(arms={}, ratios={}, rom={}, predictions={}, per_net={'%s_s%d' % k: v for k, v in R.items() if k[0] in ('own', 'ownf', 'ctrl_cpu')})
    for a in arms:
        acs = [s for s in range(12) if (a, s) in R and acq[(a, s)]]
        o = dict(n=sum((a, s) in R for s in range(12)), n_acquired=len(acs))
        if acs:
            v = lambda k: np.array([R[(a, s)][k] for s in acs])
            o.update(K=float(v('gap').mean()), K_median=float(np.median(v('gap'))), rom_large=float(v('rom_large').mean()),
                     rom_middle=float(v('rom_middle').mean()), n_A=int((v('rom_middle') < 0).sum()), lab=float(v('lab_last').mean()),
                     xq=float(v('xq').mean()), K_sd=float(v('gap').std()), rom_large_sd=float(v('rom_large').std()))
            have = [s for s in acs if 'sign_pc' in R[(a, s)]]
            if have:
                sp = np.array([R[(a, s)]['sign_pc'] for s in have]); sk = np.array([R[(a, s)]['sign_kl'] for s in have])
                bs = []
                for _ in range(NB):
                    j = rng.integers(0, len(have), len(have)); bs.append(sp[j].sum() / sk[j].sum())
                o['c_sign'] = float(sp.sum() / sk.sum()); o['c_sign_ci'] = ci(bs)
        res['arms'][a] = o
    both = lambda a, b: [s for s in range(12) if all((x, s) in R and acq[(x, s)] for x in (a, b))]
    for a, b in (('own', 'uni'), ('own', 'ctrl'), ('ownf', 'unif'), ('ownf', 'own'), ('ctrl_cpu', 'ctrl'), ('own', 'ctrl_cpu')):
        ss = both(a, b)
        if len(ss) >= 2:
            f = lambda q: np.mean([R[(a, s)]['gap'] for s in q]) / np.mean([R[(b, s)]['gap'] for s in q])
            g = lambda q: np.mean([R[(a, s)]['rom_large'] - R[(b, s)]['rom_large'] for s in q])
            bs = [list(rng.choice(ss, len(ss))) for _ in range(NB)]
            res['ratios']['%s/%s' % (a, b)] = [float(f(ss))] + ci([f(q) for q in bs]) + [len(ss)]
            res['rom']['%s-%s' % (a, b)] = [float(g(ss))] + ci([g(q) for q in bs]) + [len(ss)]
    pr = res['predictions']
    r = res['ratios'].get('own/uni')
    if r:
        pr['P229'] = dict(ratio=r, holds=bool(r[0] >= 2))
    o = res['arms'].get('own', {})
    if 'c_sign' in o:
        pr['P230'] = dict(c_sign=o['c_sign'], ci=o['c_sign_ci'], holds=bool(o['c_sign'] >= 0.10))
    d = res['rom'].get('own-uni')
    if d:
        pr['P231'] = dict(diff=d, holds=bool(d[0] <= -0.02))
    md = ['# E60 tables (generated by e60_summ.py)', '', '| arm | nets | acquired | mean KL (sd) | median KL | A / B | rom large (sd) | rom middle | lab | xq | sign share [95% CI] |',
          '|---' * 11 + '|']
    for a in arms:
        o = res['arms'][a]
        if not o.get('n_acquired'):
            md.append('| %s | %d | 0 |' % (a, o['n'])); continue
        md.append('| %s | %d | %d | %.4f (%.4f) | %.4f | %d / %d | %.3f (%.3f) | %.3f | %.3f | %.4f | %s |' % (
            a, o['n'], o['n_acquired'], o['K'], o['K_sd'], o['K_median'], o['n_A'], o['n_acquired'] - o['n_A'], o['rom_large'], o['rom_large_sd'],
            o['rom_middle'], o['lab'], o['xq'], ('%.3f [%.3f, %.3f]' % (o['c_sign'], *o['c_sign_ci'])) if 'c_sign' in o else '-'))
    md += ['', '| pair | KL ratio [95% CI] (seeds) | rom large difference [95% CI] |', '|---|---|---|']
    md += ['| %s | %.2f [%.2f, %.2f] (%d) | %+.3f [%+.3f, %+.3f] |' % (k, *v, *res['rom'][k.replace('/', '-')][:3]) for k, v in res['ratios'].items()]
    md += ['', '| seed | ' + ' | '.join(arms) + ' |', '|---' * (len(arms) + 1) + '|']
    for s in range(12):
        cell = lambda a: '-' if (a, s) not in R else '%.4f %s %.3f' % (R[(a, s)]['gap'], ('B' if R[(a, s)]['rom_middle'] > 0 else 'A') if acq[(a, s)] else 'stall', R[(a, s)]['rom_large'])
        md.append('| %d | %s |' % (s, ' | '.join(cell(a) for a in arms)))
    md += ['', 'Cells: test KL, type (or stall), large-range rom.', '', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in pr.items()]
    json.dump(res, open('results/e60.json', 'w'), indent=1, default=float)
    open('results/e60_tables.md', 'w').write('\n'.join(md) + '\n')
    print(json.dumps(pr, indent=1, default=float))


if __name__ == '__main__':
    main()
