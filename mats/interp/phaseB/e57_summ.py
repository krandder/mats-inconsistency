"""E57 analysis (PREREG-B amendment 65): when does the LayerNorm cap scale c separate the eventual A and B types?
Lineages, final types, clusters and the duplicate rule exactly as E47 (e47_summ.py: acquired runs, final gap < 0.10, type B if the
final middle-range rom > 0; an E43 brK run is left out at steps <= K, br0 included from step 1 on; clusters = parent seed).
AUC_c(step) = P(c of a final-A lineage > c of a final-B lineage) (ties half); 2,000 cluster-bootstrap resamples (numpy seed 57).
Also: the same AUC without E37's lineages (their c at 6,000 and 90,000 steps was seen before registration), and E47's marker AUCs
at 5,000 and 10,000 steps for comparison (results/e47.json).
Predictions (registered in amendment 65):
  P222  AUC_c at step 0 within [0.4, 0.6];
  P223  AUC_c at 10,000 steps < 0.75;
  P224  AUC_c at 40,000 steps >= 0.80.
usage: python e57_summ.py -> results/e57.json, results/e57_tables.md
"""
import json, os
import numpy as np
import e47_summ as E47

STEPS = [0, 2000, 3000, 5000, 10000, 20000, 40000, 60000, 80000, 90000]
rng = np.random.default_rng(57)


def lineages(cdat, drop_e37=False):
    L = []
    for tag, m in cdat.items():
        if drop_e37 and tag.startswith('e37_'):
            continue
        fp, cl = E47.final_and_cluster(tag)
        if fp is None or not os.path.exists(fp):
            continue
        fz = np.load(fp)
        if float(fz['gap']) >= 0.10:
            continue
        arm = tag.split('_')[1]
        kb = (0 if arm == 'br0' else int(arm[2:-1]) * 1000) if tag.startswith('e43_br') else -1
        L.append(dict(tag=tag, cluster=cl, B=bool(float(fz['rom_middle']) > 0), c={int(s): v for s, v in m.items() if int(s) > kb}))
    return L


def auc_table(L):
    clusters = sorted({x['cluster'] for x in L}); out = {}
    for st in STEPS:
        def stat(cs):
            sel = [x for c in cs for x in L if x['cluster'] == c and st in x['c']]
            return E47.auc([x['c'][st] for x in sel if not x['B']], [x['c'][st] for x in sel if x['B']])
        pt = stat(clusters)
        bs = [b for b in (stat(list(rng.choice(clusters, len(clusters)))) for _ in range(2000)) if np.isfinite(b)]
        n = sum(st in x['c'] for x in L)
        out[st] = [pt, float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5)), n]
    return out


def main():
    cdat = json.load(open('results/e57_c.json'))
    L = lineages(cdat); L2 = lineages(cdat, drop_e37=True)
    res = dict(n=len(L), n_B=sum(x['B'] for x in L), auc=auc_table(L), auc_without_e37=auc_table(L2),
               median_c={st: dict(A=float(np.median([x['c'][st] for x in L if not x['B'] and st in x['c']])),
                                  B=float(np.median([x['c'][st] for x in L if x['B'] and st in x['c']]))) for st in STEPS})
    e47 = json.load(open('results/e47.json'))['auc'] if os.path.exists('results/e47.json') else {}
    a = res['auc']
    res['predictions'] = dict(P222=dict(auc=a[0], holds=bool(0.4 <= a[0][0] <= 0.6)), P223=dict(auc=a[10000], holds=bool(a[10000][0] < 0.75)),
                              P224=dict(auc=a[40000], holds=bool(a[40000][0] >= 0.80)))
    md = ['# E57 tables (generated by e57_summ.py)', '', 'lineages: %d (%d B)' % (res['n'], res['n_B']), '',
          '| step | AUC_c (A > B) [95% CI] (n) | without E37 | median c A / B | E47 markers (B > A): xq, sign share, lab |', '|---|---|---|---|---|']
    for st in STEPS:
        e = ', '.join('%.2f' % e47['%s@%d' % (mk, st)][0] for mk in ('xq', 'sign_share', 'lab')) if '%s@%d' % ('xq', st) in e47 else '-'
        md.append('| %d | %.2f [%.2f, %.2f] (%d) | %.2f [%.2f, %.2f] | %.2f / %.2f | %s |' % (st, *a[st], *res['auc_without_e37'][st][:3],
                  res['median_c'][st]['A'], res['median_c'][st]['B'], e))
    md += ['', '## Predictions', ''] + ['- %s: %s' % (k, json.dumps(v)) for k, v in res['predictions'].items()]
    json.dump(res, open('results/e57.json', 'w'), indent=1, default=float)
    open('results/e57_tables.md', 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
