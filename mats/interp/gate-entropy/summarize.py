"""Tables from results/*.json (gate-entropy). usage: python summarize.py [TAG ...] > results/tables.md"""
import json, sys, os, glob, math

HERE = os.path.dirname(os.path.abspath(__file__))


def f(x, nd=1):
    if x is None: return '-'
    if isinstance(x, float) and math.isnan(x): return 'nan'
    return f'{x:.{nd}f}'


def bracket(p):
    if p is None: return '-', '-'
    lo = p['plugin']
    if not p['H2_zero']: lo = max(lo, p['H2'])
    up = p['upper']
    point = '-'
    if up - lo < 1.0:
        point = f(p['mm'], 2)
    lo_s = f(lo)
    if p['H2_zero']:
        lo_s += f' (H2>{p["H2"]:.0f}*)'
    return f'{lo_s} - {f(up)}', point


def table(tag):
    r = json.load(open(os.path.join(HERE, 'results', tag + '.json')))
    kind = r['kind']
    out = [f'### {tag}: {r["name"]} ({kind})', '']
    a = r.get('answer_ho_set', {})
    out.append('answer (held-out): ' + ', '.join(f'{k}={v:.4g}' if isinstance(v, float) else f'{k}={v}' for k, v in a.items()) +
               f'; C_l = (d/2)log2(1+1/sigma^2) = {f(r.get("capacity_bits"), 0)} bits; sizes {r["sizes"]}')
    out.append('')
    eps_cols = ['H_merged_eps0.01'] + (['H_merged_eps0.002'] if kind == 'rnn' else ['H_merged_bias0.0001', 'H_merged_bias1e-05'] if kind in ('arc', 'tanh') else [])
    hdr = ['layer', 'm', 'H(G) bracket', 'H(G) pt', 'H(G|X)', 'C_cov', 'D(1%)', 'D(0.1%)', 'H(G_R) bracket (1%)', 'k var99', 'k agree99',
           'log2 cells(k agree99)'] + [c.replace('H_merged_', 'E3 ') for c in eps_cols] + ['E3 last (leaves, H, change)']
    out.append('| ' + ' | '.join(hdr) + ' |'); out.append('|' + '---|' * len(hdr))
    for l, L in sorted(r['layers'].items(), key=lambda kv: int(kv[0])):
        b1, p1 = bracket(L['E1'])
        e2 = L['E2'].get('tau0.01', {}); e2b = L['E2'].get('tau0.001', {})
        b2, _ = bracket(e2.get('panel')) if e2.get('D') else ('-', '-')
        sub = e2.get('subspace', {}) if e2.get('D') else {}
        cond = L.get('cond')
        e3 = L['E3']; last = e3['path'][-1]
        row = [l, L['m'], b1, p1, (f(cond['plugin_mean'], 2) + '-' + f(cond['indep_mean'], 2)) if cond else '-', f(L.get('cap_cov_bits'), 0),
               e2.get('D', 0), e2b.get('D', 0), b2, sub.get('k_var99', '-'), sub.get('k_agree0.99', '-'),
               f(sub.get('log2cells_k_agree0.99'))]
        row += [f(e3.get(c), 2) if e3.get(c) is not None else 'not reached' for c in eps_cols]
        row += [f'{last["leaves"]}, {last["H_leaves"]:.1f}, {100 * last["change_rate"]:.2f}%']
        out.append('| ' + ' | '.join(str(x) for x in row) + ' |')
    out.append('')
    return '\n'.join(out)


if __name__ == '__main__':
    tags = sys.argv[1:] or sorted(os.path.basename(p)[:-5] for p in glob.glob(os.path.join(HERE, 'results', '*.json'))
                                  if not os.path.basename(p).startswith(('smoke', 'exact')))
    print('# Gate-entropy tables (generated by summarize.py)\n')
    print('Brackets: lower = max(plug-in, Renyi-2 from collisions); * = zero collisions, approximate bound log2(pairs/3); '
          'upper = min(sum of unit entropies, FVSBN/MADE held-out cross-entropy + 2 SE). Point (Miller-Madow) only if the '
          'bracket is < 1 bit wide. H(G|X): mean per-input plug-in - per-unit sum, over noise draws. E3: merged entropy '
          '(bits) at the first verified checkpoint meeting the tolerance.\n')
    for t in tags:
        try:
            print(table(t))
        except Exception as e:
            print(f'### {t}: unreadable ({e})\n')
