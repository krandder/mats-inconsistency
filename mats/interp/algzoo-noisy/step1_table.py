"""Collect Step-1 results (test-time noise on ARC's weights; FT and FS runs) into results/step1.md and results/step1.json."""
import json, glob, os, math
import numpy as np

H = os.path.dirname(os.path.abspath(__file__))
base = json.load(open(os.path.join(H, 'results/arc_baseline.json')))
rows = []
for f in sorted(glob.glob(os.path.join(H, 'runs/*.json'))):
    j = json.load(open(f)); e = j.get('eval')
    if not e: continue
    name = os.path.basename(f)[:-5]
    if name.startswith('test'): continue
    rows.append(dict(name=name, mode=j['mode'], d=j['d'], n=j['n'], seed=j['seed'], sigma=j['sigma'], steps=j['n_steps'],
                     L_var=e['L_var'], L_orig=e['L_orig'], dL=e['dL'], dL_ci=e['dL_ci95'], gap=e['rel_gap'],
                     A_var=e['A_var'], A_orig=e['A_orig'], dA=e['dA'], dA_se=e['dA_se'], meets=e['meets'],
                     L_marg=(j['marginal'] or {}).get('L_marg'), A_marg=(j['marginal'] or {}).get('A_marg')))
out = ['# Step 1 table (generated by step1_table.py)', '',
       'Test-time noise on ARC\'s original weights (single-draw accuracy, 2^22 sequences):', '',
       '| model | seed | noiseless | sigma 0.01 | 0.03 | 0.1 |', '|---|---|---|---|---|---|']
for k, v in base.items():
    d, n, s = k.split('_')
    out.append(f"| M_{{{d},{n}}} | {s} | {v['noiseless']['acc']:.4f} | {v['test_noise_0.01']['acc']:.4f} | {v['test_noise_0.03']['acc']:.4f} | {v['test_noise_0.1']['acc']:.4f} |")
out += ['', 'Noise-trained variants (noise on at test, one draw; paired with the original on 2^22 sequences):', '',
        '| run | mode | steps | sigma | loss var / orig | rel. gap | dL 95% CI | acc var / orig | dA (SE) | meets | loss (16-draw marginal) |',
        '|---|---|---|---|---|---|---|---|---|---|---|']
for r in sorted(rows, key=lambda r: (r['d'], r['n'], str(r['seed']), r['mode'], r['sigma'], r['steps'])):
    out.append(f"| {r['name']} | {r['mode']} | {r['steps']} | {r['sigma']} | {r['L_var']:.4f} / {r['L_orig']:.4f} | {100 * r['gap']:+.1f}% | "
               f"[{r['dL_ci'][0]:+.4f}, {r['dL_ci'][1]:+.4f}] | {r['A_var']:.4f} / {r['A_orig']:.4f} | {100 * r['dA']:+.2f} ({100 * r['dA_se']:.2f}) pp | "
               f"{'yes' if r['meets'] else 'no'} | {r['L_marg']:.4f} |" if r['L_marg'] is not None else
               f"| {r['name']} | {r['mode']} | {r['steps']} | {r['sigma']} | {r['L_var']:.4f} / {r['L_orig']:.4f} | {100 * r['gap']:+.1f}% | "
               f"[{r['dL_ci'][0]:+.4f}, {r['dL_ci'][1]:+.4f}] | {r['A_var']:.4f} / {r['A_orig']:.4f} | {100 * r['dA']:+.2f} ({100 * r['dA_se']:.2f}) pp | "
               f"{'yes' if r['meets'] else 'no'} | - |")
# ARC seed spread (noiseless)
out += ['', 'ARC 5-seed spread, noiseless accuracy:', '']
for dn in ('2_2', '4_3', '16_10'):
    accs = [base[f'{dn}_{s}']['noiseless']['acc'] for s in range(5)]
    out.append(f"- M_{{{dn.replace('_', ',')}}}: min {min(accs):.4f}, max {max(accs):.4f}, SD {np.std(accs):.4f}")
open(os.path.join(H, 'results/step1.md'), 'w').write('\n'.join(out) + '\n')
json.dump(rows, open(os.path.join(H, 'results/step1.json'), 'w'), indent=1)
print('\n'.join(out))
