def list_envs(include_heldout=True):
    """Every registered environment: [{name, family, heldout, kind}], in registry order (E*, then open Z*,
    then held-out Z*). Held-out structures are for confirmatory generalization-across-structure rounds only:
    do not tune on them; make_env refuses them without allow_heldout=True."""
    from .envs import PRESETS
    out = []
    for name in list(PRESETS) + [z for z in ZOO if z not in HELDOUT] + list(HELDOUT):
        held = name in HELDOUT
        if held and not include_heldout:
            continue
        env = PRESETS[name]() if name in PRESETS else ZOO[name]()
        out.append({"name": name, "family": FAMILIES[name], "heldout": held, "kind": env.kind})
    return out


