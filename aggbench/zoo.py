"""Structure zoo (added 2026-10-21; Kelvin: "it needs to converge near the full best bayes for all kinds of
information structures we can think of").

Every zoo environment is a finite world. A latent world state w takes |W| values with prior pi(w); the
target is Y = h(w) in {0, 1}; agent i observes one symbol o_i from a finite alphabet, and the agents are
conditionally independent GIVEN w (all dependence between agents goes through w). The observations are
generated by a physical simulator (continuous noise, then binned; Bernoulli draws; ...) and the tables
lik[i, w, o] = P(o_i = o | w) are computed in closed form from the same parameters. So every ceiling is a
finite sum:

    local_i   = log-odds of Y given o_i                   (what agent i reports)
    bayes     = log-odds of Y given o_1..o_N              (sum over w of pi(w) prod_i lik[i, w, o_i])
    oracle    = log-odds of Y given the N REPORTS          (merge the symbols with the same report into
                and the true structure                     one symbol, then the same sum)

Checks: verify.brute_force_tabular recomputes all three with plain Python loops; tests/aggbench/test_zoo.py
checks every table against Monte Carlo draws of the physical simulator, the calibration of `bayes` on
simulated draws, closed forms where they exist, and a full joint enumeration for the binary-alphabet envs.

Families (README "Structure zoo"):
  Z1 common-cause         shared latent parents of subsets of agents (hierarchical), plus direct observers
  Z2 nonlinear            linear, thresholded and magnitude-only (|theta|) readings of a latent theta
  Z3 heavy-tail           contaminated-Gaussian (outlier) readings of a shared latent theta
  Z4 hypothesis-samples   some agents report a SAMPLE from a model's posterior (mixture semantics),
                          others independent evidence
  Z5 multi-question       agents read different sub-questions of a joint of 3 binaries; target f(A, B, C)
  Z6 complementary-xor    target is the parity of bits; every agent reads one bit: alone uninformative
  Z7 context-reliability  an agent's reliability depends on a latent regime; some agents see regime cues
  Z9 k-parity             Y = XOR of k bits (k = 4; 3, 6 by override) read by many traders with redundancy and
                          distractors; no single reading and (k >= 3) no pair of readings informs Y
  Z8 hidden-provenance    E2 with private read noise and shared strength levels: overlap is not identifiable
                          from content or own models (also Z1-blind, Z4-blind: parents / models without
                          fingerprinting parameters). Z8 is linear-Gaussian, not tabular (closed forms).

Held-out structures (`HELDOUT`) are reserved for confirmatory generalization-across-structure rounds:
make_env refuses them without allow_heldout=True.
"""
from dataclasses import dataclass, asdict
import math

import numpy as np

from .envs import _Env

try:  # exact normal CDF; math.erfc fallback keeps the harness numpy-only
    from scipy.special import ndtr as _ndtr
except ImportError:  # pragma: no cover
    _erfc = np.frompyfunc(math.erfc, 1, 1)

    def _ndtr(z):
        return 0.5 * _erfc(-np.asarray(z, float) / math.sqrt(2)).astype(float)


def binned_normal(mean, sd, edges):
    """P(x in bin | mean, sd) for x ~ N(mean, sd^2); bins (-inf, e0), [e0, e1), ..., [e_last, inf).
    mean (...,) -> (..., len(edges) + 1). Upper-tail bins use survival functions for relative precision."""
    mean = np.asarray(mean, float)[..., None]
    z = (np.concatenate([[-np.inf], edges, [np.inf]]) - mean) / np.asarray(sd, float)[..., None]
    lo, hi = z[..., :-1], z[..., 1:]
    with np.errstate(invalid="ignore"):
        p = np.where(lo > 0, _ndtr(-lo) - _ndtr(-hi), _ndtr(hi) - _ndtr(lo))
    return np.clip(p, 0.0, 1.0)


def bin_of(x, edges):
    """Symbol of a continuous reading: 0 for x < e0, ..., len(edges) for x >= e_last."""
    return np.searchsorted(edges, x, side="right")


def bin_values(edges):
    """Representative value of each bin: its centre; the tail bins sit half a bin width outside."""
    w = edges[1] - edges[0]
    return np.concatenate([[edges[0] - w / 2], (edges[1:] + edges[:-1]) / 2, [edges[-1] + w / 2]])


def _lse(a, axis=-1):
    with np.errstate(invalid="ignore"):
        return np.logaddexp.reduce(a, axis=axis)


def _log(x):
    with np.errstate(divide="ignore"):
        return np.log(x)


def local_table(prior_w, target, lik):
    """g[i, o] = log-odds of Y given agent i's symbol o alone (NaN for symbols impossible under every w)."""
    lj = _log(prior_w)[None, :, None] + _log(lik)
    with np.errstate(invalid="ignore"):
        return _lse(lj[:, target == 1], 1) - _lse(lj[:, target == 0], 1)


def posterior_logit(prior_w, target, lik_obs):
    """Log-odds of Y given per-agent likelihood columns lik_obs (N, W) = P(o_i | w)."""
    s = _log(prior_w) + _log(lik_obs).sum(0)
    return float(_lse(s[target == 1]) - _lse(s[target == 0]))


def report_classes(g_i, o, rtol=1e-9):
    """Symbols whose report equals the report of symbol o (the report cannot tell them apart)."""
    with np.errstate(invalid="ignore"):
        return np.abs(g_i - g_i[o]) <= rtol * (1 + abs(g_i[o]))


def tabular_ceilings(prior_w, target, lik, sym):
    """(local reports (N,), bayes logit, reports-ceiling logit) for one episode."""
    N = lik.shape[0]
    g = local_table(prior_w, target, lik)
    report = g[np.arange(N), sym]
    bayes = posterior_logit(prior_w, target, lik[np.arange(N), :, sym])
    merged = np.stack([lik[i][:, report_classes(g[i], sym[i])].sum(-1) for i in range(N)])
    return report, bayes, posterior_logit(prior_w, target, merged)


def _onehot(idx, n):
    out = np.zeros((len(idx), n))
    ok = idx >= 0
    out[np.flatnonzero(ok), idx[ok]] = 1.0
    return out


def _flip(bits, rng, p):
    return np.abs(bits - (rng.random(bits.shape) < p))


def _jit(x, rng, s):
    """Multiplicative jitter for positive key entries."""
    return x * np.exp(s * rng.standard_normal(np.shape(x)))


class TabularEnv(_Env):
    """Base class of the zoo. Subclasses define Config, structure(rng), tables(struct), simulate(struct, rng, n),
    make_keys(struct, rng) and optionally key_slot_blocks (alignment slots, see envs.alignment_transforms)."""
    kind = "bernoulli"
    family = "?"
    Config = None
    key_slot_blocks = ()   # ((start, n_slots, width), ...) blocks of the key indexed by a source identity

    def __init__(self, name, **overrides):
        self.name = name
        self.config = self.Config(**overrides)
        self.check_config()

    def check_config(self):
        pass

    def prior_logit(self):
        return 0.0

    def public(self):
        c = self.config
        return {"prior_logit": self.prior_logit(), "n_agents": c.n_agents}

    def episode(self, seed):
        rng = np.random.default_rng(seed)
        struct = self.structure(rng)
        prior_w, target, lik, values = self.tables(struct)
        w, sym = (v[0] for v in self.simulate(struct, rng, 1))
        N = lik.shape[0]
        report, bayes, ceiling = tabular_ceilings(prior_w, target, lik, sym)
        key_full, key_noisy = self.make_keys(struct, rng)
        out = {
            "truth": np.int64(target[w]), "obs": values[np.arange(N), sym],
            "local.logit": report, "report.logit": report.copy(), "bayes.logit": np.float64(bayes),
            "key.none": np.zeros((N, 0)), "key.noisy": key_noisy, "key.full": key_full,
            "oracle.w": np.int64(w), "oracle.sym": sym, "oracle.report_logit": np.float64(ceiling),
        }
        out.update({f"oracle.{k}": v for k, v in struct.items()})
        return out

    def tables_for(self, batch, e):
        """Tables of episode e of a batch of this env (rebuilt from the structure stored in batch.oracle)."""
        return self.tables({k: v[e] for k, v in batch.oracle.items()})


# ----------------------------------------------------------------------------- Z1 common cause

@dataclass
class CommonCauseConfig:
    n_agents: int = 6
    n_groups: int = 3                 # shared parents Z_g; P(Z_g = Y) = rho_g
    direct_prob: float = 0.2          # probability that an agent observes Y directly (no shared parent)
    rho_range: tuple = (0.6, 0.95)
    rho_levels: tuple = ()            # if set, rho_g is drawn from these values (shared parents not fingerprinted)
    strength_range: tuple = (0.5, 2.0)  # reading x_i ~ N(s_i (2 u_i - 1), 1), u_i = the agent's parent bit
    obs_edges: tuple = (-5.0, 5.0, 41)  # reading bins: linspace(*obs_edges) plus two tail bins
    prior: float = 0.5
    key_noise: float = 0.15


class CommonCauseEnv(TabularEnv):
    """Z1. Y -> Z_g (g < G) -> agents of group g; some agents hang directly off Y. Agents of one group are
    correlated through their shared parent, not through shared noise: however many of them agree, they
    cannot push the posterior past what Z_g says about Y."""
    family = "common-cause"
    Config = CommonCauseConfig

    @property
    def key_slot_blocks(self):
        return ((0, self.config.n_groups, 1),)

    def check_config(self):
        c = self.config
        if c.n_groups < 1 or not 0 <= c.direct_prob <= 1 or not 0 < c.prior < 1:
            raise ValueError("need n_groups >= 1, 0 <= direct_prob <= 1, 0 < prior < 1")

    def prior_logit(self):
        return float(np.log(self.config.prior / (1 - self.config.prior)))

    def edges(self):
        return np.linspace(*self.config.obs_edges[:2], int(self.config.obs_edges[2]))

    def structure(self, rng):
        c = self.config
        group = rng.integers(0, c.n_groups, c.n_agents)
        group[rng.random(c.n_agents) < c.direct_prob] = -1
        rho = (rng.choice(np.asarray(c.rho_levels, float), c.n_groups) if c.rho_levels
               else rng.uniform(*c.rho_range, c.n_groups))
        return {"group": group, "rho": rho, "s": rng.uniform(*c.strength_range, c.n_agents)}

    def tables(self, st):
        c = self.config
        G, N = c.n_groups, c.n_agents
        w = np.arange(2 ** (G + 1))
        y = w & 1
        z = (w[:, None] >> (np.arange(G) + 1)) & 1                     # (W, G)
        prior_w = np.where(y == 1, c.prior, 1 - c.prior) * np.prod(
            np.where(z == y[:, None], st["rho"], 1 - st["rho"]), axis=1)
        parent = np.where(st["group"][:, None] < 0, y[None], z[:, np.maximum(st["group"], 0)].T)  # (N, W)
        edges = self.edges()
        lik = binned_normal(st["s"][:, None] * (2 * parent - 1), np.ones((N, 1)), edges)
        values = np.broadcast_to(bin_values(edges)[None, :, None], (N, len(edges) + 1, 1))
        return prior_w, y, lik, values

    def simulate(self, st, rng, n):
        c = self.config
        G = c.n_groups
        y = (rng.random(n) < c.prior).astype(np.int64)
        z = np.where(rng.random((n, G)) < st["rho"], y[:, None], 1 - y[:, None])
        parent = np.where(st["group"] < 0, y[:, None], z[:, np.maximum(st["group"], 0)])
        x = st["s"] * (2 * parent - 1) + rng.standard_normal((n, c.n_agents))
        w = y + (z << (np.arange(G) + 1)).sum(1)
        return w, bin_of(x, self.edges())

    def make_keys(self, st, rng):
        c = self.config
        g = st["group"]
        direct = (g < 0).astype(float)
        rho_parent = np.where(g < 0, 1.0, st["rho"][np.maximum(g, 0)])
        full = np.concatenate([_onehot(g, c.n_groups), np.stack([direct, rho_parent, st["s"]], 1)], 1)
        noisy = np.concatenate([_flip(_onehot(g, c.n_groups), rng, c.key_noise),
                                np.stack([_flip(direct, rng, c.key_noise),
                                          np.clip(_jit(rho_parent, rng, c.key_noise), 0, 1),
                                          _jit(st["s"], rng, c.key_noise)], 1)], 1)
        return full, noisy


# ----------------------------------------------------------------------------- Z2 / Z3 grid latent

def theta_grid(n_half, step):
    """Grid symmetric about 0 that excludes 0 (so Y = 1[theta > 0] has no tie), with N(0, 1) prior weights."""
    pos = (np.arange(n_half) + 0.5) * step
    grid = np.concatenate([-pos[::-1], pos])
    p = np.exp(-grid ** 2 / 2)
    return grid, p / p.sum()


@dataclass
class NonlinearConfig:
    n_agents: int = 6
    type_probs: tuple = (0.3, 0.3, 0.4)   # linear, threshold, magnitude
    grid: tuple = (20, 0.15)              # theta grid: n_half points per side, spacing
    noise_range: tuple = (0.2, 1.0)       # reading noise sd, log-uniform
    slope_range: tuple = (0.5, 1.5)       # |a| of linear readings (sign random)
    threshold_range: tuple = (-1.5, 1.5)  # c of threshold readings
    obs_edges: tuple = (-4.0, 4.0, 33)
    key_noise: float = 0.15


TYPES_Z2 = ("linear", "threshold", "magnitude")


class NonlinearEnv(TabularEnv):
    """Z2. theta on a grid with a discretized N(0, 1) prior; Y = 1[theta > 0]. Readings:
    linear     x = a theta + sd eps (binned)
    threshold  o = 1[theta + sd eps > c]
    magnitude  x = |theta| + sd eps (binned): its report is exactly the prior (it says nothing about the sign),
               but it sharpens what the linear and threshold readings say about the sign."""
    family = "nonlinear"
    Config = NonlinearConfig

    def edges(self):
        return np.linspace(*self.config.obs_edges[:2], int(self.config.obs_edges[2]))

    def structure(self, rng):
        c = self.config
        N = c.n_agents
        return {"type": rng.choice(3, N, p=np.asarray(c.type_probs) / np.sum(c.type_probs)),
                "sd": np.exp(rng.uniform(*np.log(c.noise_range), N)),
                "a": rng.uniform(*c.slope_range, N) * rng.choice([-1.0, 1.0], N),
                "c": rng.uniform(*c.threshold_range, N)}

    def tables(self, st):
        c = self.config
        theta, prior_w = theta_grid(*c.grid)
        edges = self.edges()
        O = len(edges) + 1
        N = c.n_agents
        lik = np.zeros((N, len(theta), O))
        values = np.full((N, O, 1), np.nan)
        for i in range(N):
            t, sd = st["type"][i], st["sd"][i]
            if t == 1:
                p1 = _ndtr((theta - st["c"][i]) / sd)
                lik[i, :, 0], lik[i, :, 1] = 1 - p1, p1
                values[i, :2, 0] = (0.0, 1.0)
            else:
                mean = st["a"][i] * theta if t == 0 else np.abs(theta)
                lik[i] = binned_normal(mean, np.full(len(theta), sd), edges)
                values[i, :, 0] = bin_values(edges)
        return prior_w, (theta > 0).astype(np.int64), lik, values

    def simulate(self, st, rng, n):
        c = self.config
        theta, prior_w = theta_grid(*c.grid)
        w = rng.choice(len(theta), n, p=prior_w)
        th = theta[w][:, None]
        eps = st["sd"] * rng.standard_normal((n, c.n_agents))
        x = np.where(st["type"] == 0, st["a"] * th, np.abs(th)) + eps
        sym = np.where(st["type"] == 1, (th + eps > st["c"]).astype(np.int64), bin_of(x, self.edges()))
        return w, sym

    def make_keys(self, st, rng):
        c = self.config
        t = st["type"]
        a = np.where(t == 0, st["a"], 0.0)
        cc = np.where(t == 1, st["c"], 0.0)
        full = np.concatenate([_onehot(t, 3), np.stack([a, st["sd"], cc], 1)], 1)
        noisy = np.concatenate([_flip(_onehot(t, 3), rng, c.key_noise),
                                np.stack([_jit(a, rng, c.key_noise), _jit(st["sd"], rng, c.key_noise),
                                          cc + c.key_noise * rng.standard_normal(len(t)) * (t == 1)], 1)], 1)
        return full, noisy


@dataclass
class HeavyTailConfig:
    n_agents: int = 6
    grid: tuple = (20, 0.15)
    noise_range: tuple = (0.3, 1.0)       # sd of the clean component, log-uniform
    outlier_range: tuple = (0.0, 0.3)     # p_i: probability that a reading is an outlier
    outlier_scale: float = 10.0           # outlier component: N(theta, (outlier_scale * sd)^2)
    obs_edges: tuple = (-8.0, 8.0, 65)
    key_noise: float = 0.15


class HeavyTailEnv(TabularEnv):
    """Z3. theta on a grid, Y = 1[theta > 0]; every agent reads x_i = theta + noise with a contaminated
    Gaussian noise (1 - p_i) N(0, sd_i^2) + p_i N(0, (k sd_i)^2): heavy tails, outliers. Agents are
    conditionally independent given theta, not given Y, and one wild reading can dominate a naive pool."""
    family = "heavy-tail"
    Config = HeavyTailConfig

    def edges(self):
        return np.linspace(*self.config.obs_edges[:2], int(self.config.obs_edges[2]))

    def structure(self, rng):
        c = self.config
        return {"sd": np.exp(rng.uniform(*np.log(c.noise_range), c.n_agents)),
                "p_out": rng.uniform(*c.outlier_range, c.n_agents)}

    def tables(self, st):
        c = self.config
        theta, prior_w = theta_grid(*c.grid)
        edges = self.edges()
        N, J = c.n_agents, len(theta)
        sd, p = st["sd"][:, None], st["p_out"][:, None, None]
        clean = binned_normal(np.broadcast_to(theta, (N, J)), np.broadcast_to(sd, (N, J)), edges)
        wide = binned_normal(np.broadcast_to(theta, (N, J)), np.broadcast_to(c.outlier_scale * sd, (N, J)), edges)
        lik = (1 - p) * clean + p * wide
        values = np.broadcast_to(bin_values(edges)[None, :, None], (N, len(edges) + 1, 1))
        return prior_w, (theta > 0).astype(np.int64), lik, values

    def simulate(self, st, rng, n):
        c = self.config
        theta, prior_w = theta_grid(*c.grid)
        w = rng.choice(len(theta), n, p=prior_w)
        out = rng.random((n, c.n_agents)) < st["p_out"]
        sd = st["sd"] * np.where(out, c.outlier_scale, 1.0)
        return w, bin_of(theta[w][:, None] + sd * rng.standard_normal((n, c.n_agents)), self.edges())

    def make_keys(self, st, rng):
        c = self.config
        full = np.stack([st["sd"], st["p_out"]], 1)
        noisy = np.stack([_jit(st["sd"], rng, c.key_noise),
                          np.clip(st["p_out"] + c.key_noise * 0.3 * rng.standard_normal(c.n_agents), 0, 1)], 1)
        return full, noisy


# ----------------------------------------------------------------------------- Z4 hypothesis samples

@dataclass
class HypothesisConfig:
    n_agents: int = 8
    n_models: int = 2                  # models m with private evidence D_m ~ binned N(+-mu_m, 1)
    hypothesis_prob: float = 0.6       # probability that an agent is a hypothesis sampler
    model_strength: tuple = (0.5, 1.5)  # mu_m
    model_strength_levels: tuple = ()  # if set, mu_m is drawn from these values (models not fingerprinted)
    evidence_strength: tuple = (0.2, 1.0)  # s_i of evidence agents
    obs_edges: tuple = (-3.0, 3.0, 13)
    prior: float = 0.5
    key_noise: float = 0.15


class HypothesisEnv(TabularEnv):
    """Z4. Two kinds of sources. A hypothesis agent attached to model m reports a SAMPLE h ~ Bernoulli(q_m),
    where q_m = P(Y = 1 | D_m) is model m's posterior given its private evidence D_m (a sampled world, i.e.
    mixture semantics: many samples of one model estimate q_m, they do not add up evidence). An evidence
    agent reads its own independent evidence x_i ~ N(s_i (2Y - 1), 1) (binned). World w = (Y, D_1..D_M)."""
    family = "hypothesis-samples"
    Config = HypothesisConfig

    @property
    def key_slot_blocks(self):
        return ((1, self.config.n_models, 1),)

    def prior_logit(self):
        return float(np.log(self.config.prior / (1 - self.config.prior)))

    def edges(self):
        return np.linspace(*self.config.obs_edges[:2], int(self.config.obs_edges[2]))

    def structure(self, rng):
        c = self.config
        hyp = rng.random(c.n_agents) < c.hypothesis_prob
        mu = (rng.choice(np.asarray(c.model_strength_levels, float), c.n_models) if c.model_strength_levels
              else rng.uniform(*c.model_strength, c.n_models))
        return {"model": np.where(hyp, rng.integers(0, c.n_models, c.n_agents), -1),
                "mu": mu,
                "s": np.where(hyp, 0.0, rng.uniform(*c.evidence_strength, c.n_agents))}

    def _model_tables(self, st):
        """P(D_m = d | Y) (M, 2, B) and q_m(d) = P(Y = 1 | D_m = d) (M, B)."""
        c = self.config
        e = self.edges()
        pd = np.stack([binned_normal(np.array([-mu, mu]), np.ones(2), e) for mu in st["mu"]])
        q = c.prior * pd[:, 1] / (c.prior * pd[:, 1] + (1 - c.prior) * pd[:, 0])
        return pd, q

    def tables(self, st):
        c = self.config
        M, N = c.n_models, c.n_agents
        e = self.edges()
        B = len(e) + 1
        pd, q = self._model_tables(st)
        w = np.arange(2 * B ** M)
        y = w % 2
        d = (w[:, None] // (2 * B ** np.arange(M))) % B           # (W, M)
        prior_w = np.where(y == 1, c.prior, 1 - c.prior) * np.prod(pd[np.arange(M), y[:, None], d], axis=1)
        lik = np.zeros((N, len(w), B))
        values = np.full((N, B, 1), np.nan)
        for i in range(N):
            m = st["model"][i]
            if m >= 0:
                qi = q[m, d[:, m]]
                lik[i, :, 0], lik[i, :, 1] = 1 - qi, qi
                values[i, :2, 0] = (0.0, 1.0)
            else:
                lik[i] = binned_normal(st["s"][i] * (2 * y - 1), np.ones(len(w)), e)
                values[i, :, 0] = bin_values(e)
        return prior_w, y, lik, values

    def simulate(self, st, rng, n):
        c = self.config
        M, N = c.n_models, c.n_agents
        e = self.edges()
        B = len(e) + 1
        _, q = self._model_tables(st)
        y = (rng.random(n) < c.prior).astype(np.int64)
        d = bin_of(st["mu"] * (2 * y[:, None] - 1) + rng.standard_normal((n, M)), e)   # (n, M)
        qd = q[np.arange(M), d]                                                        # (n, M)
        h = (rng.random((n, N)) < qd[:, np.maximum(st["model"], 0)]).astype(np.int64)
        x = bin_of(st["s"] * (2 * y[:, None] - 1) + rng.standard_normal((n, N)), e)
        sym = np.where(st["model"] >= 0, h, x)
        return y + 2 * (d * B ** np.arange(M)).sum(1), sym

    def make_keys(self, st, rng):
        c = self.config
        m = st["model"]
        hyp = (m >= 0).astype(float)
        mu_m = np.where(m >= 0, st["mu"][np.maximum(m, 0)], 0.0)
        full = np.concatenate([hyp[:, None], _onehot(m, c.n_models), np.stack([mu_m, st["s"]], 1)], 1)
        noisy = np.concatenate([_flip(hyp, rng, c.key_noise)[:, None], _flip(_onehot(m, c.n_models), rng, c.key_noise),
                                np.stack([_jit(mu_m, rng, c.key_noise), _jit(st["s"], rng, c.key_noise)], 1)], 1)
        return full, noisy


# ----------------------------------------------------------------------------- Z5 multi-question

TARGETS_Z5 = {
    "and_or": lambda a, b, c: a & (b | c),
    "majority": lambda a, b, c: (a + b + c >= 2).astype(np.int64),
    "parity": lambda a, b, c: a ^ b ^ c,
}
TARGET_MARGINAL_Z5 = {"and_or": 3 / 8, "majority": 0.5, "parity": 0.5}  # E over episodes: each cell 1/8


@dataclass
class MultiQuestionConfig:
    n_agents: int = 6
    target: str = "and_or"         # T = f(A, B, C), see TARGETS_Z5
    field_scale: float = 0.5       # joint P(A, B, C) ~ exp(h . s + sum_{j<k} J_jk s_j s_k), s = 2 bit - 1
    coupling_scale: float = 1.0    # h ~ N(0, field^2), J ~ N(0, coupling^2), redrawn every episode
    accuracy_range: tuple = (0.6, 0.95)
    key_noise: float = 0.15


class MultiQuestionEnv(TabularEnv):
    """Z5. A joint of three binary sub-questions (A, B, C), redrawn each episode and known to the agents (it is
    in their keys); the target is T = f(A, B, C). Agent i reads one sub-question v_i with accuracy q_i. Its
    report is P(T | its reading); the aggregate must recombine sub-question evidence through the joint."""
    family = "multi-question"
    Config = MultiQuestionConfig

    def check_config(self):
        if self.config.target not in TARGETS_Z5:
            raise ValueError(f"target must be one of {list(TARGETS_Z5)}")

    def prior_logit(self):
        p = TARGET_MARGINAL_Z5[self.config.target]
        return float(np.log(p / (1 - p)))

    def structure(self, rng):
        c = self.config
        N = c.n_agents
        return {"field": c.field_scale * rng.standard_normal(3),
                "coupling": c.coupling_scale * rng.standard_normal(3),   # J_ab, J_ac, J_bc
                "var": rng.integers(0, 3, N), "acc": rng.uniform(*c.accuracy_range, N)}

    @staticmethod
    def bits():
        w = np.arange(8)
        return (w >> 0) & 1, (w >> 1) & 1, (w >> 2) & 1

    def joint(self, st):
        a, b, cc = self.bits()
        s = 2 * np.stack([a, b, cc], 1) - 1
        h, J = st["field"], st["coupling"]
        logp = s @ h + J[0] * s[:, 0] * s[:, 1] + J[1] * s[:, 0] * s[:, 2] + J[2] * s[:, 1] * s[:, 2]
        p = np.exp(logp - logp.max())
        return p / p.sum()

    def tables(self, st):
        bits = np.stack(self.bits(), 1)                        # (8, 3)
        target = TARGETS_Z5[self.config.target](*self.bits()).astype(np.int64)
        read = bits[:, st["var"]].T                            # (N, 8) the bit agent i reads
        acc = st["acc"][:, None]
        lik = np.stack([np.where(read == 0, acc, 1 - acc), np.where(read == 1, acc, 1 - acc)], -1)
        values = np.broadcast_to(np.array([0.0, 1.0])[None, :, None], (len(acc), 2, 1))
        return self.joint(st), target, lik, values

    def simulate(self, st, rng, n):
        w = rng.choice(8, n, p=self.joint(st))
        bits = np.stack(self.bits(), 1)[w]                     # (n, 3)
        read = bits[:, st["var"]]
        correct = rng.random(read.shape) < st["acc"]
        return w, np.where(correct, read, 1 - read)

    def make_keys(self, st, rng):
        c = self.config
        N = c.n_agents
        lj = np.log(self.joint(st))
        lj = np.broadcast_to(lj - lj.mean(), (N, 8))
        full = np.concatenate([_onehot(st["var"], 3), st["acc"][:, None], lj], 1)
        noisy = np.concatenate([_flip(_onehot(st["var"], 3), rng, c.key_noise),
                                np.clip(st["acc"] + 0.3 * c.key_noise * rng.standard_normal(N), 0.5, 1)[:, None],
                                lj + c.key_noise * rng.standard_normal((N, 8))], 1)
        return full, noisy


# ----------------------------------------------------------------------------- Z6 complementary (XOR)

@dataclass
class ParityConfig:
    n_agents: int = 6
    n_bits: int = 2                    # Y = B_1 xor ... xor B_n, bits iid uniform
    accuracy_range: tuple = (0.65, 0.95)
    key_noise: float = 0.15


class ParityEnv(TabularEnv):
    """Z6. Complementary information: Y is the parity of n_bits uniform bits; agent i reads one bit with
    accuracy q_i. Every single reading is independent of Y, so every report equals the prior exactly; only
    readings of all the bits taken together say anything. A scalar-report aggregator cannot beat the prior
    (the reports ceiling is the prior); the information is in the per-agent observations and keys."""
    family = "complementary-xor"
    Config = ParityConfig

    def check_config(self):
        if not 1 <= self.config.n_bits <= 6:
            raise ValueError("need 1 <= n_bits <= 6")

    def structure(self, rng):
        c = self.config
        return {"var": rng.integers(0, c.n_bits, c.n_agents), "acc": rng.uniform(*c.accuracy_range, c.n_agents)}

    def tables(self, st):
        nb = self.config.n_bits
        w = np.arange(2 ** nb)
        bits = (w[:, None] >> np.arange(nb)) & 1
        read = bits[:, st["var"]].T
        acc = st["acc"][:, None]
        lik = np.stack([np.where(read == 0, acc, 1 - acc), np.where(read == 1, acc, 1 - acc)], -1)
        values = np.broadcast_to(np.array([0.0, 1.0])[None, :, None], (len(acc), 2, 1))
        return np.full(len(w), 1.0 / len(w)), bits.sum(1) % 2, lik, values

    def simulate(self, st, rng, n):
        nb = self.config.n_bits
        bits = (rng.random((n, nb)) < 0.5).astype(np.int64)
        read = bits[:, st["var"]]
        correct = rng.random(read.shape) < st["acc"]
        return (bits << np.arange(nb)).sum(1), np.where(correct, read, 1 - read)

    def make_keys(self, st, rng):
        c = self.config
        full = np.concatenate([_onehot(st["var"], c.n_bits), st["acc"][:, None]], 1)
        noisy = np.concatenate([_flip(_onehot(st["var"], c.n_bits), rng, c.key_noise),
                                np.clip(st["acc"] + 0.3 * c.key_noise * rng.standard_normal(c.n_agents), 0.5, 1)[:, None]], 1)
        return full, noisy


# ----------------------------------------------------------------------------- Z7 context-dependent reliability

@dataclass
class ContextConfig:
    n_agents: int = 6
    n_regimes: int = 3                 # latent regime C, uniform, independent of Y
    strength_range: tuple = (-0.5, 2.0)  # s_i[c]: reading x ~ N(s_i[C] (2Y - 1), 1); negative = misleading
    cue_prob: float = 0.5              # probability that an agent also reads a regime cue
    cue_accuracy: tuple = (0.5, 0.9)   # P(cue = C)
    obs_edges: tuple = (-4.0, 4.0, 17)
    prior: float = 0.5
    key_noise: float = 0.15


class ContextEnv(TabularEnv):
    """Z7. Reliability depends on context: agent i's reading strength s_i[C] depends on a latent regime C, so an
    agent is good in some regimes and useless or misleading in others. Some agents also read a noisy regime cue.
    Observation = (binned reading, cue in {0..R-1} or -1 for none). World w = (Y, C)."""
    family = "context-reliability"
    Config = ContextConfig

    def check_config(self):
        if self.config.n_regimes < 2:
            raise ValueError("need n_regimes >= 2")

    def prior_logit(self):
        return float(np.log(self.config.prior / (1 - self.config.prior)))

    def edges(self):
        return np.linspace(*self.config.obs_edges[:2], int(self.config.obs_edges[2]))

    def structure(self, rng):
        c = self.config
        N, R = c.n_agents, c.n_regimes
        return {"s": rng.uniform(*c.strength_range, (N, R)), "cue": rng.random(N) < c.cue_prob,
                "cue_acc": rng.uniform(*c.cue_accuracy, N)}

    def tables(self, st):
        c = self.config
        N, R = c.n_agents, c.n_regimes
        e = self.edges()
        B = len(e) + 1
        w = np.arange(2 * R)
        y, reg = w % 2, w // 2
        prior_w = np.where(y == 1, c.prior, 1 - c.prior) / R
        read = binned_normal(st["s"][:, reg] * (2 * y - 1), np.ones((N, len(w))), e)       # (N, W, B)
        pc = np.where(reg[None, :, None] == np.arange(R), st["cue_acc"][:, None, None],
                      (1 - st["cue_acc"][:, None, None]) / (R - 1))                       # (N, W, R)
        cue = np.where(st["cue"][:, None, None], np.concatenate([pc, np.zeros((N, len(w), 1))], -1),
                       np.concatenate([np.zeros((N, len(w), R)), np.ones((N, len(w), 1))], -1))  # (N, W, R + 1)
        lik = (read[..., :, None] * cue[..., None, :]).reshape(N, len(w), B * (R + 1))
        rv = np.repeat(bin_values(e), R + 1)
        cv = np.tile(np.concatenate([np.arange(R), [-1]]), B).astype(float)
        values = np.broadcast_to(np.stack([rv, cv], -1)[None], (N, B * (R + 1), 2))
        return prior_w, y, lik, values

    def simulate(self, st, rng, n):
        c = self.config
        N, R = c.n_agents, c.n_regimes
        y = (rng.random(n) < c.prior).astype(np.int64)
        reg = rng.integers(0, R, n)
        x = st["s"][:, reg].T * (2 * y[:, None] - 1) + rng.standard_normal((n, N))
        wrong = (reg[:, None] + rng.integers(1, R, (n, N))) % R
        cue = np.where(rng.random((n, N)) < st["cue_acc"], reg[:, None], wrong)
        cue = np.where(st["cue"], cue, R)
        return y + 2 * reg, bin_of(x, self.edges()) * (R + 1) + cue

    def make_keys(self, st, rng):
        c = self.config
        N = c.n_agents
        has = st["cue"].astype(float)
        acc = np.where(st["cue"], st["cue_acc"], 0.0)
        full = np.concatenate([st["s"], np.stack([has, acc], 1)], 1)
        noisy = np.concatenate([st["s"] + c.key_noise * rng.standard_normal(st["s"].shape),
                                np.stack([_flip(has, rng, c.key_noise), _jit(acc, rng, c.key_noise)], 1)], 1)
        return full, noisy


# ----------------------------------------------------------------------------- Z9 k-bit parity

@dataclass
class KParityConfig:
    n_bits: int = 4                     # k: Y = XOR of the k parity bits (override 3, 4, 6, ...)
    n_distractor_bits: int = 2          # extra uniform bits that are not in the parity
    readers_per_bit: int = 3            # each parity bit is read by this many agents; None: the "hard-noise" scheme
    n_distractor_agents: int = 2        # agents reading a distractor bit (readers_per_bit scheme)
    accuracy_range: tuple = (0.85, 0.97)
    n_agents: int = None                # readers_per_bit scheme: k * readers_per_bit + n_distractor_agents
    distractor_prob: float = 0.2        # hard-noise scheme: an agent beyond the first k reads a distractor bit
    key_noise: float = 0.15
    readers_random: bool = False        # (2026-10-22) each of the k * readers_per_bit parity readers picks its bit
    #                                     uniformly per episode, so readers per bit vary: removes the count leak of
    #                                     the fixed scheme (the number of 1-readings informs Y when every bit has
    #                                     exactly readers_per_bit readers; learnability review B2)
    readers_alpha: float = 0.0          # (2026-10-22) readers_random only: > 0 draws per-episode bit weights from
    #                                     Dirichlet(alpha), so readers per bit are uneven; with readers_per_bit=6 and
    #                                     alpha=1 the count code keeps 0.010 of 0.270 nats (leak-reduced benchmark)
    bit_prob: float = 0.5               # (2026-10-22) P(bit = 1) for every bit; != 0.5 gives single readings a
    #                                     correlation (1 - 2p)^(k-1) with Y (biased-bit curriculum, review step 5)

    def __post_init__(self):
        if self.n_agents is None:
            self.n_agents = (self.n_bits * self.readers_per_bit + self.n_distractor_agents
                             if self.readers_per_bit else 12)


class KParityEnv(TabularEnv):
    """Z9. k-bit parity spread across traders. Y = b_1 xor ... xor b_k (uniform bits); the world also has
    n_distractor_bits irrelevant bits. Default: every parity bit is read by readers_per_bit = 3 agents with accuracy
    in [0.85, 0.97], plus 2 agents reading distractor bits (prior-to-Bayes gap >= 0.3 nats for k = 3, 4, 6).
    "Z9-hard" (readers_per_bit=None, the first version): 12 agents, the first k read one parity bit each, every other
    one reads a random parity bit or, with probability distractor_prob, a distractor bit; accuracy in [0.65, 0.95]. For k >= 2 every single reading is independent of Y (all reports equal the
    prior, so the reports ceiling is the prior), and for k >= 3 so is every PAIR of readings: only combining
    readings of all k bits informs Y (multi-hop combination). Exact Bayes: with p_j = P(b_j = 1 | readings of
    bit j), P(Y = 1) = (1 - prod_j (1 - 2 p_j)) / 2. Own model / key: one-hot of the bit read (parity bits first,
    then distractor bits) and the accuracy."""
    family = "k-parity"
    Config = KParityConfig

    def check_config(self):
        c = self.config
        if not 1 <= c.n_bits or c.n_bits + c.n_distractor_bits > 10 or c.n_agents < c.n_bits:
            raise ValueError("need 1 <= n_bits, n_bits + n_distractor_bits <= 10, n_agents >= n_bits")
        if c.readers_per_bit and c.n_agents != c.n_bits * c.readers_per_bit + c.n_distractor_agents:
            raise ValueError("with readers_per_bit, n_agents = n_bits * readers_per_bit + n_distractor_agents")
        if c.readers_per_bit and c.n_distractor_agents and not c.n_distractor_bits:
            raise ValueError("distractor agents need n_distractor_bits >= 1")
        if not 0 < c.bit_prob < 1:
            raise ValueError("bit_prob must be in (0, 1)")
        if c.readers_random and not c.readers_per_bit:
            raise ValueError("readers_random needs the readers_per_bit scheme")

    def prior_logit(self):
        """P(Y = 1) = (1 - (1 - 2 q)^k) / 2 for bits with P(1) = q (0 at q = 0.5)."""
        q, k = self.config.bit_prob, self.config.n_bits
        if q == 0.5:
            return 0.0
        p1 = (1 - (1 - 2 * q) ** k) / 2
        return float(np.log(p1 / (1 - p1)))

    def n_vars(self):
        return self.config.n_bits + self.config.n_distractor_bits

    def structure(self, rng):
        c = self.config
        if c.readers_per_bit and c.readers_random:
            par = (rng.choice(c.n_bits, c.n_bits * c.readers_per_bit, p=rng.dirichlet(np.full(c.n_bits, c.readers_alpha)))
                   if c.readers_alpha > 0 else rng.integers(0, c.n_bits, c.n_bits * c.readers_per_bit))
            var = np.concatenate([par,
                                  c.n_bits + rng.integers(0, max(c.n_distractor_bits, 1), c.n_distractor_agents)])
        elif c.readers_per_bit:
            var = np.concatenate([np.repeat(np.arange(c.n_bits), c.readers_per_bit),
                                  c.n_bits + rng.integers(0, max(c.n_distractor_bits, 1), c.n_distractor_agents)])
        else:   # hard-noise scheme: the first k agents cover the bits, the rest read random bits or distractors
            var = np.concatenate([np.arange(c.n_bits), rng.integers(0, c.n_bits, c.n_agents - c.n_bits)])
            distract = np.r_[np.zeros(c.n_bits, bool), rng.random(c.n_agents - c.n_bits) < c.distractor_prob]
            if c.n_distractor_bits:
                var = np.where(distract, c.n_bits + rng.integers(0, c.n_distractor_bits, c.n_agents), var)
        perm = rng.permutation(c.n_agents)
        return {"var": var[perm], "acc": rng.uniform(*c.accuracy_range, c.n_agents)}

    def tables(self, st):
        nv, k = self.n_vars(), self.config.n_bits
        w = np.arange(2 ** nv)
        bits = (w[:, None] >> np.arange(nv)) & 1
        read = bits[:, st["var"]].T
        acc = st["acc"][:, None]
        lik = np.stack([np.where(read == 0, acc, 1 - acc), np.where(read == 1, acc, 1 - acc)], -1)
        values = np.broadcast_to(np.array([0.0, 1.0])[None, :, None], (len(acc), 2, 1))
        q = self.config.bit_prob
        prior_w = (np.full(len(w), 1.0 / len(w)) if q == 0.5
                   else np.prod(np.where(bits == 1, q, 1 - q), axis=1))
        return prior_w, bits[:, :k].sum(1) % 2, lik, values

    def simulate(self, st, rng, n):
        nv = self.n_vars()
        bits = (rng.random((n, nv)) < self.config.bit_prob).astype(np.int64)
        read = bits[:, st["var"]]
        correct = rng.random(read.shape) < st["acc"]
        return (bits << np.arange(nv)).sum(1), np.where(correct, read, 1 - read)

    def make_keys(self, st, rng):
        c = self.config
        nv = self.n_vars()
        full = np.concatenate([_onehot(st["var"], nv), st["acc"][:, None]], 1)
        noisy = np.concatenate([_flip(_onehot(st["var"], nv), rng, c.key_noise),
                                np.clip(st["acc"] + 0.3 * c.key_noise * rng.standard_normal(c.n_agents), 0.5, 1)[:, None]], 1)
        return full, noisy


# ----------------------------------------------------------------------------- Z8 hidden provenance

@dataclass
class PrivateReadConfig:
    n_agents: int = 5
    n_pieces: int = 12
    pieces_per_agent: tuple = (2, 6)
    strength_levels: tuple = (0.2, 0.4, 0.6)  # mu_k drawn from these: strengths do not fingerprint a piece
    read_noise: float = 0.5           # tau: agent i reads piece k as r_ik = x_k + tau eps_ik (private noise)
    prior: float = 0.5
    key_noise: float = 0.15


class PrivateReadEnv(_Env):
    """Z8. E2's evidence pool, but provenance is hidden in the content and in the agents' own models: agent i
    reads each of its pieces through private noise, r_ik = x_k + tau eps_ik, and piece strengths take a few
    shared values. Two agents that read the same piece see different numbers and the same kind of likelihood
    as agents reading different pieces, so at provenance `none` overlap must be inferred, not looked up.
    Everything is linear-Gaussian given Y, so all ceilings are closed forms:
      local  l0 + sum_{k in C_i} 2 mu_k r_ik / (1 + tau^2)
      bayes  l0 + sum_k 2 mu_k (sum_{i reads k} r_ik) / (n_k + tau^2)   (n_k readers of piece k)
      oracle exact posterior given the N reports and the true structure (Gaussian given Y).
    Keys: coverage bits, coverage x mu (the agent's own model) and the piece identity of each read coordinate
    (provenance: at `full` it tells the aggregator exactly which agents share which pieces, also in unaligned mode,
    where it moves with the coordinate; `noisy` replaces an identity by a random one with probability 0.15; `none`
    hides it). obs (N, K) readings, NaN = piece not read."""
    kind = "bernoulli"
    family = "hidden-provenance"
    key_slot_blocks = ()

    @property
    def provenance_blocks(self):
        """The piece-identity block of the key: provenance, never part of the own model."""
        K = self.config.n_pieces
        return ((2 * K, K, 1),)

    def __init__(self, name="Z8", **overrides):
        self.name = name
        self.config = c = PrivateReadConfig(**overrides)
        lo, hi = c.pieces_per_agent
        if not 1 <= lo <= hi <= c.n_pieces or c.read_noise <= 0 or not 0 < c.prior < 1:
            raise ValueError("need 1 <= pieces_per_agent <= n_pieces, read_noise > 0, 0 < prior < 1")
        self.logit0 = float(np.log(c.prior / (1 - c.prior)))

    def public(self):
        c = self.config
        return {"prior_logit": self.logit0, "n_agents": c.n_agents, "n_pieces": c.n_pieces}

    def weights(self, cov, mu):
        """Report weights w_ik = 2 mu_k / (1 + tau^2) on agent i's readings."""
        return cov * (2 * mu / (1 + self.config.read_noise ** 2))

    def report_ceiling(self, report, cov, mu):
        """Exact log-odds of Y given the reports: report - l0 = Wt (+-mu + z) + tau sum_k w_ik eps_ik with
        Wt = cov * w, z ~ N(0, I); so given Y it is N(+-Wt mu, Wt Wt^T + tau^2 diag(sum_k w_ik^2))."""
        Wt = self.weights(cov, mu)
        S = Wt @ Wt.T + self.config.read_noise ** 2 * np.diag((Wt ** 2).sum(1))
        return self.logit0 + 2 * (Wt @ mu) @ np.linalg.pinv(S, rcond=1e-10, hermitian=True) @ (report - self.logit0)

    def episode(self, seed):
        c = self.config
        rng = np.random.default_rng(seed)
        K, N, tau = c.n_pieces, c.n_agents, c.read_noise
        mu = rng.choice(np.asarray(c.strength_levels, float), K)
        y = int(rng.random() < c.prior)
        x = (2 * y - 1) * mu + rng.standard_normal(K)
        cov = np.zeros((N, K), dtype=bool)
        for i in range(N):
            cov[i, rng.choice(K, rng.integers(c.pieces_per_agent[0], c.pieces_per_agent[1] + 1), replace=False)] = True
        reads = np.where(cov, x + tau * rng.standard_normal((N, K)), np.nan)
        local = self.logit0 + np.nansum(self.weights(cov, mu) * np.nan_to_num(reads), 1)
        n_k = cov.sum(0)
        bayes = self.logit0 + np.sum(np.where(n_k > 0, 2 * mu * np.nansum(np.where(cov, reads, 0), 0)
                                              / (n_k + tau ** 2), 0.0))
        ids = cov * (np.arange(K) + 1) / K                     # provenance: the true identity of each read piece
        key_full = np.concatenate([cov.astype(float), cov * mu, ids], 1)
        ncov = cov ^ (rng.random(cov.shape) < c.key_noise)
        wrong = rng.random(cov.shape) < c.key_noise
        nids = np.where(wrong, cov * (rng.integers(0, K, cov.shape) + 1) / K, ids)
        key_noisy = np.concatenate([ncov.astype(float), ncov * _jit(mu, rng, c.key_noise), nids], 1)
        return {
            "truth": np.int64(y), "obs": reads, "local.logit": local, "report.logit": local.copy(),
            "bayes.logit": np.float64(bayes),
            "key.none": np.zeros((N, 0)), "key.noisy": key_noisy, "key.full": key_full,
            "oracle.cov": cov, "oracle.mu": mu, "oracle.x": x,
            "oracle.report_logit": np.float64(self.report_ceiling(local, cov, mu)),
        }


# ----------------------------------------------------------------------------- floor without provenance

def none_floor_logit(env, batch):
    """Exact log-odds of Y given what agents can send at provenance `none`: their observations and own models,
    with the source identities (Z1 parent group, Z4 model) marginalized under the environment's prior. Only the
    blind variants need it (Z1 rho_levels, Z4 model_strength_levels); elsewhere in the tabular zoo the own models
    identify the sources exactly (continuous rho / mu are fingerprints) and the answer is `bayes`. Returns None for
    other environments (unknown). Assignments of agents to sources are independent and uniform given the source
    parameters R, so for each R the sum over assignments factorizes per agent:
        P(Y, obs) = sum_R P(R) sum_w pi_R(w) prod_i (1/S) sum_{sources j with R_j = own_i} P(o_i | w, j)."""
    if isinstance(env, CommonCauseEnv):
        levels, n_src = env.config.rho_levels, env.config.n_groups
    elif isinstance(env, HypothesisEnv):
        levels, n_src = env.config.model_strength_levels, env.config.n_models
    elif hasattr(env, "tables"):
        return batch.bayes["logit"].copy()
    else:
        return None
    if not levels:
        return batch.bayes["logit"].copy()
    import itertools
    out = np.empty(len(batch))
    for e in range(len(batch)):
        st = {k: v[e] for k, v in batch.oracle.items()}
        src = st["group"] if isinstance(env, CommonCauseEnv) else st["model"]
        own_param = st["rho"] if isinstance(env, CommonCauseEnv) else st["mu"]
        own = np.where(src >= 0, own_param[np.maximum(src, 0)], np.nan)     # what each agent knows of its source
        joint = np.zeros(2)
        for R in itertools.product(levels, repeat=n_src):
            R = np.asarray(R, float)
            cols = []
            for j in range(n_src):                     # tables as if every source-attached agent hung off source j
                stj = dict(st, **({"rho": R} if isinstance(env, CommonCauseEnv) else {"mu": R}))
                key = "group" if isinstance(env, CommonCauseEnv) else "model"
                stj[key] = np.where(src >= 0, j, src)
                prior_w, target, lik, _ = env.tables(stj)
                cols.append(lik[np.arange(len(src)), :, st["sym"]])        # (N, W)
            cols = np.stack(cols)                                           # (S, N, W)
            ok = np.isclose(R[:, None], own[None, :])                       # (S, N): source j consistent with agent i
            Lbar = np.where(src[:, None] >= 0, (cols * ok[:, :, None]).sum(0) / n_src, cols[0])
            joint += np.bincount(target, weights=prior_w * np.prod(Lbar, 0), minlength=2)
        out[e] = np.log(joint[1]) - np.log(joint[0])
    return out


