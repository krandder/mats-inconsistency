"""Write tables.md from the per-cell result JSONs (numbers copied from JSON, not typed by hand).

Usage: python make_tables.py DIR   (DIR holds json/*.json written by l6_attention.py)
"""
import json
import sys
from pathlib import Path

NS = (2, 4, 8, 16, 32)
OVS = ("low", "mid", "high")
ARMS = ("softmax", "softmax_T", "softmax_gain", "sigmoid", "linear", "clearing_learned")
REFS = ("clearing_exact", "oracle_clearing", "extremized_log_pool", "log_pool", "sum_logodds")
OVDESC = {"E2": {"low": "K = 16N pieces", "mid": "K = 4N", "high": "K = max(N, 6)"},
          "E1": {"low": "factor_scale 0 (independent noise)", "mid": "factor_scale 1", "high": "factor_scale 3"}}


def fmt(m, p=3):
    return f"{m['mean']:.{p}f} [{m['ci_low']:.{p}f}, {m['ci_high']:.{p}f}]"


def main(d):
    d = Path(d)
    res = {p.stem: json.loads(p.read_text()) for p in sorted((d / "json").glob("*.json"))}
    any_r = next(iter(res.values()))
    seeds = any_r["extra"]["seeds"]
    lines = [f"# L6 tables (EXPLORATORY)\n",
             f"Generated by make_tables.py from json/*.json. Harness commit {any_r['harness']['git_commit'][:10]}, "
             f"dirty={any_r['harness']['git_dirty']}, track {any_r['track']}. Mean regret to Bayes (nats/episode) on "
             f"{any_r['splits']['eval']['n']} dev episodes per cell, 95% bootstrap CI over episodes. Learned arms: "
             f"mean over seeds {seeds} of the per-episode regret.\n"]
    for env in ("E2", "E1"):
        cells = {(n, ov): res.get(f"{env}-N{n}-{ov}") for n in NS for ov in OVS}
        if not any(cells.values()):
            continue
        for ov in OVS:
            lines.append(f"\n## {env}, overlap {ov} ({OVDESC[env][ov]}): regret\n")
            lines.append("| arm | " + " | ".join(f"N={n}" for n in NS) + " |")
            lines.append("|---|" + "---|" * len(NS))
            for arm in ARMS:
                row = [fmt(cells[(n, ov)]["extra"]["seed_mean_regret"][arm]) for n in NS]
                lines.append(f"| {arm} | " + " | ".join(row) + " |")
            for ref in REFS:
                row = [fmt(cells[(n, ov)]["methods"][ref]["regret"]) for n in NS]
                lines.append(f"| *{ref}* | " + " | ".join(row) + " |")
            row = [f"{cells[(n, ov)]['methods']['bayes']['logloss']['mean']:.3f}" for n in NS]
            lines.append("| *Bayes log loss* | " + " | ".join(row) + " |")
            lines.append(f"\n{env}, overlap {ov}: total weight on the reports (mean [CI]; seed {seeds[0]}). "
                         "Bayes: E2 sum of exact clearing weights, E1 tr(P_bayes - I)/tr(mean_i P_i - I).\n")
            lines.append("| arm | " + " | ".join(f"N={n}" for n in NS) + " |")
            lines.append("|---|" + "---|" * len(NS))
            for arm in ("bayes",) + tuple(f"{a}:s{seeds[0]}" for a in ARMS):
                row = [fmt(cells[(n, ov)]["extra"]["total_weight"][arm], 2) for n in NS]
                lines.append(f"| {arm} | " + " | ".join(row) + " |")
        lines.append(f"\n## {env} controls (seed {seeds[0]}): mean regret over the 15 cells, and in how many cells the "
                     "trained arm's regret is below both controls' (CIs not used)\n")
        lines.append("| arm | trained | untrained init | random network | cells trained < both controls |")
        lines.append("|---|---|---|---|---|")
        for arm in ARMS:
            b = f"{arm}:s{seeds[0]}"
            tr = [c["methods"][b]["regret"]["mean"] for c in cells.values()]
            un = [c["methods"][f"{b}:control:untrained_init"]["regret"]["mean"] for c in cells.values()]
            rn = [c["methods"][f"{b}:control:random_network"]["regret"]["mean"] for c in cells.values()]
            wins = sum(t < min(u, r) for t, u, r in zip(tr, un, rn))
            mean = lambda x: sum(x) / len(x)
            lines.append(f"| {arm} | {mean(tr):.3f} | {mean(un):.3f} | {mean(rn):.3f} | {wins}/{len(tr)} |")
        lines.append(f"\n## {env}: best learned arm per cell (lowest seed-mean regret)\n")
        lines.append("| overlap | " + " | ".join(f"N={n}" for n in NS) + " |")
        lines.append("|---|" + "---|" * len(NS))
        for ov in OVS:
            row = [min(ARMS, key=lambda a: cells[(n, ov)]["extra"]["seed_mean_regret"][a]["mean"]) for n in NS]
            lines.append(f"| {ov} | " + " | ".join(row) + " |")
    (d / "tables.md").write_text("\n".join(lines) + "\n")
    compact(d, res, seeds)
    print((d / "tables.md").read_text())


COLS = (("low", 2), ("low", 8), ("low", 32), ("mid", 32), ("high", 8), ("high", 32))


def compact(d, res, seeds):
    """compact.md: a few cells per env for the README (regret with CI, then total weight)."""
    out = []
    for env in ("E2", "E1"):
        if f"{env}-N2-low" not in res:
            continue
        head = "| arm | " + " | ".join(f"{ov} N={n}" for ov, n in COLS) + " |"
        out += [f"\n**{env}: regret to Bayes, nats/episode, mean [95% CI] (learned arms: mean of seeds {seeds})**\n",
                head, "|---|" + "---|" * len(COLS)]
        for arm in ARMS:
            out.append(f"| {arm} | " + " | ".join(fmt(res[f"{env}-N{n}-{ov}"]["extra"]["seed_mean_regret"][arm])
                                               for ov, n in COLS) + " |")
        for ref in REFS:
            out.append(f"| *{ref}* | " + " | ".join(fmt(res[f"{env}-N{n}-{ov}"]["methods"][ref]["regret"])
                                                 for ov, n in COLS) + " |")
        out += [f"\n**{env}: total weight on the reports, mean (seed {seeds[0]}; controls of the sigmoid arm included)**\n",
                head, "|---|" + "---|" * len(COLS)]
        rows = ("bayes",) + tuple(f"{a}:s{seeds[0]}" for a in ARMS) + (
            f"sigmoid:s{seeds[0]}:control:untrained_init", f"sigmoid:s{seeds[0]}:control:random_network")
        for arm in rows:
            out.append(f"| {arm} | " + " | ".join(f"{res[f'{env}-N{n}-{ov}']['extra']['total_weight'][arm]['mean']:.2f}"
                                               for ov, n in COLS) + " |")
    (d / "compact.md").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
