# Teacher 4: DisjunctiveBPTeacher (Counterfactual Disjunctive Bayes + Normal Equations)
# ==============================================================================


class DisjunctiveBPTeacher(BaseClassicalSearchTeacher):
    """Teacher 4: Multi-Witness Counterfactual Disjunctive Belief Propagation (`Disjunctive-BP`).

    Performs bottom-up disjunctive Bayes marginalization over case-split subtrees combined with
    Gershgorin preconditioned normal-equation clearing (`TwoStageTreeClearer`), steering search
    toward partially explored counterfactual splits.
    """

    teacher_name = "Disjunctive-BP"

    def compute_targets_from_bank(
        self,
        tree_bank: TreePagedKVBank,
        batch: Optional[EnvBatch] = None,
    ) -> SearchTreeTrace:
        b = tree_bank.num_active
        N = tree_bank.batch_size
        device = tree_bank.logits_bank.device
        dtype = tree_bank.logits_bank.dtype

        node_feats = extract_local_node_features(tree_bank)
        topo = extract_tree_topology(tree_bank)

        m_ql = tree_bank.m_ql_bank[:, :b]                                   # [N, b]
        beta = tree_bank.beta_trust_bank[:, :b]                             # [N, b]
        prec = (m_ql * beta).clamp(min=0.05)                                # [N, b]
        anc_f = topo["anc_mask"].to(dtype)                                  # [N, b, b]

        # Subtree effective precision mass N^{BP}(j) = sum_{k in Desc(j)} m_ql(C_k) beta_trust(C_k)
        target_N = torch.bmm(anc_f, prec.unsqueeze(-1)).squeeze(-1).clamp(min=0.1)

        # Subtree marginal Value of Information and disjunctive split coverage
        mvoi = self.r12_puct.compute_marginal_voi(tree_bank)                # [N, b]
        desc_mvoi = torch.bmm(anc_f, (prec * tree_bank.leaf_value_bank[:, :b]).unsqueeze(-1)).squeeze(-1)
        target_Q = (desc_mvoi / target_N + 0.35 * torch.tanh(mvoi)).clamp(-1.0, 1.0)

        # Prioritize nodes with 1 explored child (open counterfactual sibling split!) or high MVoI
        n_exp = tree_bank.n_exp[:, :b].to(dtype)
        open_counterfactual_bonus = (n_exp == 1.0).to(dtype) * 0.75
        raw_select = target_Q + 1.2 * mvoi / (1.0 + 0.5 * n_exp) + open_counterfactual_bonus

        expandable = topo["expandable_mask"]
        is_root = torch.arange(b, device=device).unsqueeze(0) == 0
        safe_exp = expandable | ((~expandable.any(dim=-1, keepdim=True)) & is_root)
        target_node_select = raw_select.masked_fill(~safe_exp, -1e9)

        j_star = target_node_select.argmax(dim=-1)
        target_action_prior = self.compute_default_action_prior(tree_bank, j_star)

        root_logits = tree_bank.logits_bank[:, 0]
        ell_bp, _, _ = self.tree_clearer.clear_tree_at_step(
            tree_bank=tree_bank,
            ell_prev=root_logits,
            h_cons_prev=tree_bank.edge_delta_amp_bank[:, 0],
        )
        target_root_belief = F.softmax(ell_bp, dim=-1)

        return SearchTreeTrace(
            node_features=node_feats,
            tree_topology=topo,
            target_subtree_N=target_N,
            target_subtree_Q=target_Q,
            target_node_select=target_node_select,
            target_action_prior=target_action_prior,
            target_root_belief=target_root_belief,
            teacher_name=self.teacher_name,
            tree_bank=tree_bank,
            extra_targets={
                "target_log_N": torch.log(target_N.clamp(min=1e-2)),
                "mvoi": mvoi,
            },
        )


