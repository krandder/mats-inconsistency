# Teacher 5: CFRRegretMatchingTeacher (Imperfect-Info Infoset CFR+ & Regret Matching)
# ==============================================================================


class CFRRegretMatchingTeacher(BaseClassicalSearchTeacher):
    """Teacher 5: Imperfect-Information Counterfactual Regret Minimization (`CFR-Infoset-RegretMatching`).

    Solves Expressivity Barrier 3 (`Proposal-Poker`, `Micro-Stratego`, `Galanis-Market`, `ShipHunt`):
    1. Pools counterfactual subtree values across Infoset Equivalence classes `M_infoset(j, k)`
       weighted by path reach probabilities `pi_{-i}(j) = exp(path_log_reach(j))`:
         `v_CF(I(j)) = sum_{k in I(j)} pi_{-i}(k) Q(k) / sum_{k in I(j)} pi_{-i}(k)`
    2. Computes instantaneous positive counterfactual regrets `R^+(j) = ReLU(v_CF(j) - v_CF(pa(j)))`
       and Regret-Matching mixed strategy `sigma_RM(j) proportional to ReLU(R^+(j))`.
    """

    teacher_name = "CFR-Infoset-RegretMatching"

    def compute_targets_from_bank(
        self,
        tree_bank: TreePagedKVBank,
        batch: Optional[EnvBatch] = None,
    ) -> SearchTreeTrace:
        b = tree_bank.num_active
        N = tree_bank.batch_size
        V = tree_bank.num_vars
        K = tree_bank.num_vals
        device = tree_bank.logits_bank.device
        dtype = tree_bank.logits_bank.dtype
        b_arange = torch.arange(N, device=device)

        node_feats = extract_local_node_features(tree_bank)
        topo = extract_tree_topology(tree_bank)

        anc_f = topo["anc_mask"].to(dtype)                                  # [N, b, b]
        infoset_f = topo["infoset_mask"].to(dtype)                          # [N, b, b]
        reach = torch.exp(topo["path_log_reach"].clamp(min=-12.0, max=0.0))  # [N, b]

        # Subtree reach-weighted visit mass and raw subtree value
        sub_reach = torch.bmm(anc_f, reach.unsqueeze(-1)).squeeze(-1).clamp(min=1e-4)
        sub_val_raw = torch.bmm(
            anc_f, (reach * tree_bank.leaf_value_bank[:, :b]).unsqueeze(-1)
        ).squeeze(-1) / sub_reach

        # Pool counterfactual values across infoset-equivalent nodes k in I(j)
        info_reach_sum = torch.bmm(infoset_f, reach.unsqueeze(-1)).squeeze(-1).clamp(min=1e-4)
        v_cf = torch.bmm(infoset_f, (reach * sub_val_raw).unsqueeze(-1)).squeeze(-1) / info_reach_sum  # [N, b]

        pa_idx = topo["parent_idx"]
        v_cf_pa = v_cf.gather(1, pa_idx)
        inst_regret = F.relu(v_cf - v_cf_pa + 0.15 * node_feats[:, :, 9])   # [N, b] positive regret R^+(j)

        # Sibling Regret-Matching normalization: sigma(j) = R^+(j) / (sum_{s in Sib(j) U {j}} R^+(s) + eps)
        sib_or_self = (topo["sibling_mask"] | topo["self_mask"]).to(dtype)
        sib_regret_sum = torch.bmm(sib_or_self, inst_regret.unsqueeze(-1)).squeeze(-1)
        sigma_rm = torch.where(
            sib_regret_sum > 1e-5,
            inst_regret / (sib_regret_sum + self.eps),
            1.0 / sib_or_self.sum(dim=-1).clamp(min=1.0),
        )                                                                   # [N, b]

        target_N = torch.bmm(infoset_f, anc_f.sum(dim=-1, keepdim=True)).squeeze(-1).clamp(min=1.0)
        target_Q = v_cf.clamp(-1.0, 1.0)

        raw_select = 1.5 * sigma_rm + 0.8 * inst_regret + 0.4 * v_cf
        expandable = topo["expandable_mask"]
        is_root = torch.arange(b, device=device).unsqueeze(0) == 0
        safe_exp = expandable | ((~expandable.any(dim=-1, keepdim=True)) & is_root)
        target_node_select = raw_select.masked_fill(~safe_exp, -1e9)

        j_star = target_node_select.argmax(dim=-1)
        # Regret-matching action prior at j_star (proportional to ReLU advantage over mean logit)
        node_logits = tree_bank.logits_bank[b_arange, j_star]               # [N, V, K]
        open_mask = tree_bank.get_open_var_val_mask(j_star)
        any_open = open_mask.any(dim=(-1, -2), keepdim=True)
        safe_open = open_mask | (~any_open)
        mean_l = node_logits.mean(dim=-1, keepdim=True)
        pos_regret_vk = F.relu(node_logits - mean_l + 0.25) * safe_open.to(dtype)
        reg_sum = pos_regret_vk.sum(dim=(-1, -2), keepdim=True)
        unif_open = safe_open.to(dtype) / safe_open.to(dtype).sum(dim=(-1, -2), keepdim=True).clamp(min=1.0)
        target_action_prior = torch.where(reg_sum > 1e-6, pos_regret_vk / (reg_sum + self.eps), unif_open)

        root_logits = tree_bank.logits_bank[:, 0]
        ell_cfr, _, _ = self.tree_clearer.clear_tree_at_step(
            tree_bank=tree_bank,
            ell_prev=root_logits,
            h_cons_prev=tree_bank.edge_delta_amp_bank[:, 0],
        )
        target_root_belief = F.softmax(ell_cfr, dim=-1)

        return SearchTreeTrace(
            node_features=node_feats,
            tree_topology=topo,
            target_subtree_N=target_N,
            target_subtree_Q=target_Q,
            target_node_select=target_node_select,
            target_action_prior=target_action_prior,
            target_root_belief=target_root_belief,
            teacher_name=self.teacher_name,
            tree_bank=tree_bank,
            extra_targets={
                "target_log_N": torch.log(target_N.clamp(min=1.0)),
                "regret_matching_sigma": sigma_rm,
                "positive_regret": inst_regret,
            },
        )


