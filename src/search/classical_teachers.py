"""Classical Search Teachers for Supervised Algorithm Imitation (`R13`) & Expressivity Benchmarks.

Implements exact, ground-truth classical search teachers generating step-by-step search tree traces
`(node_features, tree_topology, target_subtree_N, target_subtree_Q, target_node_select, target_action_prior, target_root_belief)`
across all unified environments (`hex_5x5`, `connect4_6x7`, `sudoku_6x6`, `equiv_sat`, `shiphunt_6x6`, `micro_stratego_4x4`):

1. `MCTSPUCTTeacher` (`"MCTS-PUCT"`):
   - Full bottom-up backpropagation of leaf rollout values `v(C_k)` and visit counts `+1` to ALL ancestors
     `j in Anc(k)`: `N(j) = sum_{k in Desc(j)} 1`, `Q(j) = (1 / N(j)) sum_{k in Desc(j)} v(C_k)`.
   - Top-down UCT/PUCT selection from root `0` to an expandable node.
2. `MCGSTranspositionTeacher` (`"MCGS-Transposition-DAG"`):
   - Monte-Carlo Graph Search (KataGo / Zobrist transposition DAG) sharing descendant visits and values
     across commuted move sequences via `R^{DAG} = AncMask * E_trans * AncMask`.
3. `MinimaxAlphaBetaTeacher` / `MinimaxAlphaBetaPNSTeacher` (`"Minimax-AlphaBeta-PNS"`):
   - Non-commutative alternating `max / min` ply value backup from leaves to ancestors across arbitrary depth `d`,
     coupled with Proof-Number Search (`PNS`) `OR / AND` proof/disproof numbers and Alpha-Beta window `[alpha(j), beta(j)]`
     principal-variation selection.
4. `CDCLBackjumpTeacher` (`"CDCL-Global-Nogood"`):
   - Unit-propagation (MRV / minimum entropy variable ordering) + conflict-clause nogood detection +
     non-chronological 1-UIP backjump to the highest asserting ancestor `j* in Anc(b)` +
     Global Conflict-Clause / Nogood Broadcast across disjoint cousin subtrees.
5. `DisjunctiveBPTeacher` (`"Disjunctive-BP"`):
   - Multi-witness counterfactual disjunctive Bayes marginalization over case-split subtrees +
     Gershgorin preconditioned normal-equation clearing (`TwoStageTreeClearer`).
6. `CFRRegretMatchingTeacher` (`"CFR-Infoset-RegretMatching"`):
   - Imperfect-information Counterfactual Regret Minimization (`CFR+`) pooling counterfactual values across
     Infoset Equivalence classes `M_infoset(j, k)` weighted by path reach `pi_{-i}(j)` and outputting
     Regret-Matching mixed strategies `sigma(I, a) proportional to ReLU(R(I, a))`.
7. `GumbelSequentialHalvingTeacher` (`"Gumbel-Sequential-Halving"`):
   - Gumbel MuZero Sequential Halving (`SH`) with completed Q-values `sigma(Q_hat)`, sibling rank
     `rank_sib(j)`, and halving-round elimination of the bottom half of sibling candidates.
8. `HeuristicGLCPopTeacher` (`"Heuristic-GLC-PUCT"`):
   - The R12 hand-crafted `ResolvableInconsistencyTreePUCT` formula (`Teacher 5` baseline).
"""

