@torch.no_grad()
def build_controlled_depth_tree_bank(
    world_model: GLCAOMWorldModel,
    batch: EnvBatch,
    target_depth: int = 8,
    num_branches: int = 2,
    include_transpositions: bool = True,
    include_conflicts: bool = True,
    seed: int = 0,
) -> TreePagedKVBank:
    """Build a rich, multi-branch search tree of exact depth `target_depth` (`d in {2, 4, 8, 16}`)
    inside `TreePagedKVBank` for controlled depth-scaling and expressivity evaluation (`R13`).

    Constructs `num_branches` competing subtrees under root `0`, where each subtree reaches depth
    `target_depth` with distinct leaf values, plus optional commuted transposition nodes (`MCGS`)
    and conflict leaves (`CDCL`) so all 6+1 teachers have non-trivial, distinct targets at any `d`.
    """
    gen = torch.Generator(device=batch.device)
    gen.manual_seed(int(seed) + 100 * int(target_depth))

    N = batch.batch_size
    V = batch.num_vars
    K = batch.domain_size
    device = batch.device
    dtype = batch.obs_features.dtype

    root_out = world_model(batch)
    root_logits = root_out["var_logits"]
    root_h = root_out["h_var"]
    root_kv = root_out["kv_cache"]
    root_h_cons = root_out["h_cons"]
    root_beta = root_out["beta_trust"]
    root_plan = root_out["p0_prospectus"]

    extra_nodes = 4 if (include_transpositions or include_conflicts) else 2
    max_steps = num_branches * (target_depth + 1) + extra_nodes

    tree_bank = TreePagedKVBank.initialize_from_root(
        root_clamped_mask=batch.obs_mask,
        root_clamped_tokens=batch.obs_tokens,
        root_kv=root_kv,
        root_h=root_h,
        root_logits=root_logits,
        root_h_cons=root_h_cons,
        root_beta=root_beta,
        root_plan=root_plan,
        max_steps=max_steps,
    )

    b_arange = torch.arange(N, device=device)
    branch_tips: List[torch.Tensor] = []

    for br in range(num_branches):
        cur_parent = torch.zeros(N, dtype=torch.long, device=device)
        branch_payoff = (torch.rand((N,), generator=gen, device=device, dtype=dtype) * 1.8 - 0.9).clamp(-0.95, 0.95)
        deep_start = max(target_depth // 2 + 1, 2) if target_depth >= 4 else target_depth
        for d_step in range(1, target_depth + 1):
            v_idx = torch.full((N,), (br * target_depth + d_step - 1) % V, dtype=torch.long, device=device)
            z_idx = torch.full((N,), (br + d_step - 1) % K, dtype=torch.long, device=device)

            # Vary leaf values and step probabilities systematically across branches & instances
            rand_v = torch.rand((N,), generator=gen, device=device, dtype=dtype) * 1.6 - 0.8
            if d_step >= deep_start:
                leaf_val = (0.85 * branch_payoff + 0.15 * rand_v).clamp(-0.95, 0.95)
            else:
                leaf_val = (0.08 * rand_v).clamp(-0.95, 0.95)
            step_prob = torch.rand((N,), generator=gen, device=device, dtype=dtype) * 0.6 + 0.25
            m_ql = torch.ones((N,), device=device, dtype=dtype) * (0.75 + 0.20 * torch.sigmoid(leaf_val))
            valid = torch.ones((N,), device=device, dtype=torch.bool)

            # Inject a conflict leaf on branch 1 if include_conflicts is True
            if include_conflicts and br == num_branches - 1 and d_step == target_depth:
                m_ql = torch.full((N,), 0.05, device=device, dtype=dtype)
                valid = torch.zeros((N,), device=device, dtype=torch.bool)
                leaf_val = torch.full((N,), -0.90, device=device, dtype=dtype)

            pa_logits = tree_bank.logits_bank[b_arange, cur_parent]
            delta_shift = torch.randn(pa_logits.shape, generator=gen, device=device, dtype=dtype) * 0.35
            new_logits = pa_logits + delta_shift

            node_id = tree_bank.append_node(
                selected_parent=cur_parent,
                var_idx=v_idx,
                val_idx=z_idx,
                new_kv=root_kv,
                new_h=root_h,
                new_logits=new_logits,
                new_m_ql=m_ql,
                new_beta_trust=root_beta,
                new_valid=valid,
                active_plan=root_plan,
                aux_emitter=world_model.aux_emitter,
                step_prob=step_prob,
                q_tree_val=leaf_val,
            )
            cur_parent = torch.full((N,), node_id, dtype=torch.long, device=device)
        branch_tips.append(cur_parent)

    # Append extra siblings at the deepest ply (depth == target_depth) so alternating Minimax/PNS
    # at depth target_depth requires non-trivial max/min choices at the bottom-most ply!
    for br in range(num_branches):
        tip_node = branch_tips[br]
        tip_parent = tree_bank.parent_idx[b_arange, tip_node]
        v_sib = torch.full((N,), (br * target_depth + target_depth) % V, dtype=torch.long, device=device)
        z_sib = torch.full((N,), (br + 1) % K, dtype=torch.long, device=device)
        sib_val = torch.rand((N,), generator=gen, device=device, dtype=dtype) * 1.8 - 0.9
        sib_prob = torch.rand((N,), generator=gen, device=device, dtype=dtype) * 0.5 + 0.3
        tree_bank.append_node(
            selected_parent=tip_parent,
            var_idx=v_sib,
            val_idx=z_sib,
            new_kv=root_kv,
            new_h=root_h,
            new_logits=root_logits,
            new_m_ql=torch.full((N,), 0.85, device=device, dtype=dtype),
            new_beta_trust=root_beta,
            new_valid=torch.ones((N,), device=device, dtype=torch.bool),
            active_plan=root_plan,
            aux_emitter=world_model.aux_emitter,
            step_prob=sib_prob,
            q_tree_val=sib_val,
        )

    # Optional commuted transposition pair: root -> (v1, z1) -> (v0, z0) matching branch 0's (v0, z0) -> (v1, z1)
    if include_transpositions and target_depth >= 2 and V >= 2:
        v0 = torch.zeros(N, dtype=torch.long, device=device)
        z0 = torch.zeros(N, dtype=torch.long, device=device)
        v1 = torch.ones(N, dtype=torch.long, device=device)
        z1 = torch.ones(N, dtype=torch.long, device=device) % K

        n_t1 = tree_bank.append_node(
            selected_parent=torch.zeros(N, dtype=torch.long, device=device),
            var_idx=v1,
            val_idx=z1,
            new_kv=root_kv,
            new_h=root_h,
            new_logits=root_logits,
            new_m_ql=torch.full((N,), 0.90, device=device, dtype=dtype),
            new_beta_trust=root_beta,
            new_valid=torch.ones((N,), device=device, dtype=torch.bool),
            active_plan=root_plan,
            aux_emitter=world_model.aux_emitter,
            step_prob=torch.full((N,), 0.5, device=device, dtype=dtype),
            q_tree_val=torch.full((N,), 0.4, device=device, dtype=dtype),
        )
        tree_bank.append_node(
            selected_parent=torch.full((N,), n_t1, dtype=torch.long, device=device),
            var_idx=v0,
            val_idx=z0,
            new_kv=root_kv,
            new_h=root_h,
            new_logits=root_logits,
            new_m_ql=torch.full((N,), 0.92, device=device, dtype=dtype),
            new_beta_trust=root_beta,
            new_valid=torch.ones((N,), device=device, dtype=torch.bool),
            active_plan=root_plan,
            aux_emitter=world_model.aux_emitter,
            step_prob=torch.full((N,), 0.5, device=device, dtype=dtype),
            q_tree_val=torch.full((N,), 0.75, device=device, dtype=dtype),
        )

    return tree_bank


def make_classical_teacher(
    name: str,
    world_model: GLCAOMWorldModel,
    **kwargs: Any,
) -> BaseClassicalSearchTeacher:
    """Instantiate any of the Classical Search Teachers by name."""
    key = name.strip().lower().replace("_", "-")
    if key in ("mcts", "mcts-puct", "mctspuctteacher"):
        return MCTSPUCTTeacher(world_model, **kwargs)
    if key in ("mcgs", "mcgs-transposition-dag", "mcgstranspositionteacher"):
        return MCGSTranspositionTeacher(world_model, **kwargs)
    if key in ("minimax", "minimax-alphabeta", "minimax-alphabeta-pns", "minimaxalphabetateacher"):
        return MinimaxAlphaBetaTeacher(world_model, **kwargs)
