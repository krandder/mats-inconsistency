@dataclass
class SearchTreeTrace:
    """Step-by-step and final search tree trace generated by a Classical Search Teacher.

    Supports both 7-tuple unpacking:
      `node_features, tree_topology, target_subtree_N, target_subtree_Q, target_node_select, target_action_prior, target_root_belief = trace`
    and attribute / dictionary key access (`trace.target_subtree_Q` or `trace["target_subtree_Q"]`).
    """

    node_features: torch.Tensor               # [N, b, D_local] strictly node-local features
    tree_topology: Dict[str, torch.Tensor]    # anc_mask, rel_depth, parent_idx, depth, child_mask, sibling_mask, etc.
    target_subtree_N: torch.Tensor            # [N, b] exact backed-up subtree count / mass N(j)
    target_subtree_Q: torch.Tensor            # [N, b] exact backed-up subtree value Q(j)
    target_node_select: torch.Tensor          # [N, b] teacher node selection logits / scores s_select(j)
    target_action_prior: torch.Tensor         # [N, V, K] teacher next-step variable-value prior probabilities
    target_root_belief: torch.Tensor          # [N, V, K] teacher cleared root belief probabilities mu_b(V)

    teacher_name: str = "MCTS-PUCT"
    tree_bank: Optional[TreePagedKVBank] = None
    step_traces: List[Dict[str, Any]] = field(default_factory=list)
    query_probs: Optional[torch.Tensor] = None
    action_probs: Optional[torch.Tensor] = None
    selected_nodes: Optional[torch.Tensor] = None
    extra_targets: Dict[str, torch.Tensor] = field(default_factory=dict)

    def __iter__(self) -> Iterator[Any]:
        yield self.node_features
        yield self.tree_topology
        yield self.target_subtree_N
        yield self.target_subtree_Q
        yield self.target_node_select
        yield self.target_action_prior
        yield self.target_root_belief

    def __len__(self) -> int:
        return 7

    def __getitem__(self, key: Union[int, str]) -> Any:
        if isinstance(key, int):
            items = (
                self.node_features,
                self.tree_topology,
                self.target_subtree_N,
                self.target_subtree_Q,
                self.target_node_select,
                self.target_action_prior,
                self.target_root_belief,
            )
            return items[key]
        if key in self.extra_targets:
            return self.extra_targets[key]
        return getattr(self, key)

    def keys(self) -> List[str]:
        base = [
            "node_features",
            "tree_topology",
            "target_subtree_N",
            "target_subtree_Q",
            "target_node_select",
            "target_action_prior",
            "target_root_belief",
            "teacher_name",
            "tree_bank",
            "step_traces",
            "query_probs",
            "action_probs",
            "selected_nodes",
        ]
        return base + list(self.extra_targets.keys())


def extract_local_node_features(
    tree_bank: TreePagedKVBank,
    eps: float = 1e-6,
) -> torch.Tensor:
    """Extract strictly node-local features `[N, b, 16]` for nodes `0 .. b-1`.

    IMPORTANT: Does NOT include transitive descendant counts `N(j)` or backed-up descendant value sums,
    ensuring that `flat_token` and `parent_1hop` ablations must rely on their attention masks to aggregate
    descendant information across the tree.
    """
    b = tree_bank.num_active
    N = tree_bank.batch_size
    V = tree_bank.num_vars
    K = tree_bank.num_vals
    device = tree_bank.logits_bank.device
    dtype = tree_bank.logits_bank.dtype

    leaf_val = tree_bank.leaf_value_bank[:, :b]                             # [N, b]
    m_ql = tree_bank.m_ql_bank[:, :b]                                       # [N, b]
    beta_trust = tree_bank.beta_trust_bank[:, :b]                           # [N, b]
    has_parent = (tree_bank.depth[:, :b] > 0).to(dtype)                     # [N, b] 1-hop local indicator
    ply_parity = torch.where((tree_bank.depth[:, :b] % 2) == 0, 1.0, -1.0).to(dtype)  # [N, b]

    is_root = torch.zeros((N, b), dtype=dtype, device=device)
    is_root[:, 0] = 1.0

    # Immediate children expanded from j (local 1-hop degree, NOT transitive subtree count)
    n_exp_norm = torch.log1p(tree_bank.n_exp[:, :b].to(dtype))              # [N, b]
    step_prob = tree_bank.step_prob_bank[:, :b]                             # [N, b]

    logits = tree_bank.logits_bank[:, :b]                                   # [N, b, V, K]
    probs = F.softmax(logits, dim=-1)
    ent = -torch.sum(probs * torch.log(probs.clamp_min(1e-7)), dim=-1)      # [N, b, V]

    clamped = tree_bank.clamped_mask[:, :b]                                 # [N, b, V]
    used = tree_bank.used_children[:, :b]                                   # [N, b, V, K]
    var_open = ((~clamped.unsqueeze(-1)) & (~used)).any(dim=-1)             # [N, b, V]
    open_f = var_open.to(dtype)
    open_cnt = open_f.sum(dim=-1).clamp(min=1.0)                            # [N, b]

    open_ent_mean = (ent * open_f).sum(dim=-1) / open_cnt                   # [N, b]
    open_ent_max = torch.where(var_open, ent, torch.zeros_like(ent)).max(dim=-1).values  # [N, b]
    max_possible_ent = math.log(float(max(K, 2)))
    stiff = (max_possible_ent - ent).clamp(min=0.0)
    open_stiff_max = torch.where(var_open, stiff, torch.zeros_like(stiff)).max(dim=-1).values  # [N, b]

    open_var = ((ent - open_ent_mean.unsqueeze(-1)) ** 2 * open_f).sum(dim=-1) / open_cnt
    open_ent_std = torch.sqrt(open_var.clamp(min=0.0))                      # [N, b]
    conflict_flag = ((~tree_bank.is_valid[:, :b]) | (m_ql < 0.20)).to(dtype)  # [N, b]
    expandable_flag = tree_bank.get_expandable_node_mask().to(dtype)        # [N, b]

    edge_delta = tree_bank.edge_delta_var_bank[:, :b].reshape(N, b, -1)
    edge_delta_norm = torch.norm(edge_delta, p=2.0, dim=-1) / math.sqrt(float(max(V * K, 1)))  # [N, b]

    plan_align = torch.sum(
        tree_bank.plan_bank[:, :b] * tree_bank.edge_keys_bank[:, :b], dim=-1
    )                                                                       # [N, b]

    feats = torch.stack(
        [
            leaf_val,
            m_ql,
            beta_trust,
            has_parent,
            ply_parity,
            is_root,
            n_exp_norm,
            step_prob,
            open_ent_mean,
            open_ent_max,
            open_stiff_max,
            open_ent_std,
            conflict_flag,
            expandable_flag,
            edge_delta_norm,
            plan_align,
        ],
        dim=-1,
    )
    return feats


def extract_tree_topology(tree_bank: TreePagedKVBank) -> Dict[str, torch.Tensor]:
    """Extract the full relational topology dictionary for active nodes `0 .. b-1`."""
    b = tree_bank.num_active
    rel = tree_bank.get_relational_masks()
    rel["parent_idx"] = tree_bank.parent_idx[:, :b].clone()
    rel["depth"] = tree_bank.depth[:, :b].clone()
    rel["tree_mask"] = tree_bank.tree_mask[:, :b, :b].clone()
    rel["expandable_mask"] = tree_bank.get_expandable_node_mask().clone()
    rel["step_var"] = tree_bank.step_var[:, :b].clone()
    rel["step_val"] = tree_bank.step_val[:, :b].clone()
    rel["is_valid"] = tree_bank.is_valid[:, :b].clone()
    rel["path_log_reach"] = tree_bank.path_log_reach[:, :b].clone()
    return rel


class BaseClassicalSearchTeacher(nn.Module):
    """Abstract base class for the Classical Search Teachers (`chi = (1, 1)`)."""

    teacher_name: str = "BaseTeacher"

    def __init__(
        self,
        world_model: GLCAOMWorldModel,
        c_puct: float = 1.5,
        tau_rel: float = 0.25,
        tau_mql: float = 0.05,
        eps: float = 1e-6,
    ):
        super().__init__()
        self.world_model = world_model
        self.cfg = world_model.cfg
        self.lir_mask = LIRMask.policy_search()
        self.c_puct = float(c_puct)
        self.tau_rel = float(tau_rel)
        self.tau_mql = float(tau_mql)
        self.eps = float(eps)

        self.plan_head = MoPSFractalPlanHead(self.cfg)
        self.tree_clearer = TwoStageTreeClearer(
            self.cfg,
            tau_rel=tau_rel,
            tau_mql=tau_mql,
        )
        self.r12_puct = ResolvableInconsistencyTreePUCT(c_puct=c_puct, eps=eps)
        self.to(next(world_model.parameters()).device)

    def compute_intrinsic_leaf_value(
        self,
        batch: EnvBatch,
        child_batch: EnvBatch,
        child_logits: torch.Tensor,
        m_ql_child: torch.Tensor,
        chk_valid: torch.Tensor,
        depth: torch.Tensor,
        step_var: torch.Tensor,
        step_val: torch.Tensor,
    ) -> torch.Tensor:
        """Compute purely observable intrinsic leaf evaluation `v(C_k) in [-1, 1]` without any oracle access."""
        N, V, K = child_logits.shape
        dtype = child_logits.dtype
        device = child_logits.device
        b_arange = torch.arange(N, device=device)

        probs = F.softmax(child_logits, dim=-1)
        ent = -torch.sum(probs * torch.log(probs.clamp_min(1e-7)), dim=-1)  # [N, V]
        max_ent = math.log(float(max(K, 2)))
        conf_gain = (max_ent - ent.mean(dim=-1)) / max_ent                   # [N] in [0, 1]

        d_f = depth.to(dtype)
        progress = d_f / (d_f + 4.0)
        valid_f = chk_valid.to(dtype)
        # Base epistemic consistency value: positive when consistent, negative on conflict
        v_epistemic = m_ql_child * (0.45 * conf_gain + 0.35 * progress + 0.20 * valid_f) - 0.65 * (
            1.0 - m_ql_child
        )

        # Incorporate observable tactical utility signal when present (Hex, Connect4, MicroStratego, ShipHunt)
        if batch.utility_vector is not None:
            u_vec = batch.utility_vector.to(dtype)
            n_act = u_vec.shape[1]
            v_clamped = step_var.clamp(0, n_act - 1)
            raw_u = u_vec[b_arange, v_clamped]
            valid_u = torch.where(raw_u > -100.0, torch.tanh(raw_u), torch.zeros_like(raw_u))
            uspec = batch.header[:, 5]
            flip = (
                (uspec == int(UtilitySpec.PLAYER_1_WIN))
                | (uspec == int(UtilitySpec.SECTOR_SE_PREF))
                | (uspec == int(UtilitySpec.BIAS_PRO_REJECT))
            )
            valid_u = torch.where(flip, -valid_u, valid_u)
            v_total = 0.65 * v_epistemic + 0.35 * valid_u
        else:
            v_total = v_epistemic

        return v_total.clamp(-1.0, 1.0)

    def compute_default_action_prior(
        self,
        tree_bank: TreePagedKVBank,
        selected_node: torch.Tensor,
    ) -> torch.Tensor:
        """Compute `[N, V, K]` variable-value expansion distribution at `selected_node`."""
        N = tree_bank.batch_size
        V = tree_bank.num_vars
        K = tree_bank.num_vals
        device = tree_bank.logits_bank.device
        dtype = tree_bank.logits_bank.dtype
        b_arange = torch.arange(N, device=device)

        node_logits = tree_bank.logits_bank[b_arange, selected_node]        # [N, V, K]
        open_mask = tree_bank.get_open_var_val_mask(selected_node)          # [N, V, K] bool
        active_plan = tree_bank.plan_bank[b_arange, selected_node]          # [N, D_amp]

        probs = F.softmax(node_logits, dim=-1)
        ent = -torch.sum(probs * torch.log(probs.clamp_min(1e-7)), dim=-1)  # [N, V]
        plan_v = active_plan[:, : self.cfg.d_v].view(
            N, self.cfg.num_vars, self.cfg.num_vals
        )[:, :V, :K].norm(p=2, dim=-1)
        stiffness = math.log(float(max(K, 2))) - ent
        var_score = (2.0 * plan_v + 1.5 * stiffness).unsqueeze(-1)          # [N, V, 1]

        joint_logits = node_logits + var_score
        any_open = open_mask.any(dim=(-1, -2), keepdim=True)
        safe_open = open_mask | (~any_open)
        masked_logits = joint_logits.masked_fill(~safe_open, -1e9)
        flat_probs = F.softmax(masked_logits.reshape(N, V * K), dim=-1).view(N, V, K)
        return flat_probs

    def compute_targets_from_bank(
        self,
        tree_bank: TreePagedKVBank,
        batch: Optional[EnvBatch] = None,
    ) -> SearchTreeTrace:
        """Compute teacher supervision targets on the current `tree_bank` state."""
        raise NotImplementedError

    @torch.no_grad()
    def generate_trace(
        self,
        env: UnifiedGameEnv,
        batch: EnvBatch,
        budget: int = 8,
        force_min_depth: Optional[int] = None,
        record_step_traces: bool = True,
    ) -> SearchTreeTrace:
        """Run a full `budget`-step search with this Classical Teacher and return its `SearchTreeTrace`."""
        N = batch.batch_size
        V = batch.num_vars
        K = batch.domain_size
        device = batch.device
        b_arange = torch.arange(N, device=device)

        root_out = self.world_model(batch)
        root_logits = root_out["var_logits"]
        root_probs = root_out["var_probs"]
        root_h_cons = root_out["h_cons"]
        root_plan = root_out["p0_prospectus"]

        tree_bank = TreePagedKVBank.initialize_from_root(
            root_clamped_mask=batch.obs_mask,
            root_clamped_tokens=batch.obs_tokens,
            root_kv=root_out["kv_cache"],
            root_h=root_out["h_var"],
            root_logits=root_logits,
            root_h_cons=root_h_cons,
            root_beta=root_out["beta_trust"],
            root_plan=root_plan,
            max_steps=max(budget, 1),
        )
        # Initialize root intrinsic leaf value
        root_top1 = root_probs.argmax(dim=-1) + 1
        root_cand = torch.where(batch.obs_mask, batch.obs_tokens, root_top1)
        root_chk = env.check_witness(batch, root_cand)
        root_v = self.compute_intrinsic_leaf_value(
            batch=batch,
            child_batch=batch,
            child_logits=root_logits,
            m_ql_child=tree_bank.m_ql_bank[:, 0],
            chk_valid=root_chk,
            depth=tree_bank.depth[:, 0],
            step_var=torch.zeros(N, dtype=torch.long, device=device),
            step_val=torch.zeros(N, dtype=torch.long, device=device),
        )
        tree_bank.q_tree_bank[:, 0] = root_v
        tree_bank.leaf_value_bank[:, 0] = root_v
        tree_bank.subtree_value_sum[:, 0] = root_v

        step_traces: List[Dict[str, Any]] = []
        selected_history: List[torch.Tensor] = []
        ell_curr = root_logits.clone()
        h_cons_curr = root_h_cons.clone()

        for step_b in range(budget):
            b_active = tree_bank.num_active
            cur_trace = self.compute_targets_from_bank(tree_bank, batch=batch)
            j_sel = cur_trace.target_node_select.argmax(dim=-1)

            # Optional depth enforcement when building deep test trees (e.g. d in {2, 4, 8, 16})
            if force_min_depth is not None:
                cur_max_d = int(tree_bank.depth[:, :b_active].max().item())
                if cur_max_d < force_min_depth:
                    exp_mask = tree_bank.get_expandable_node_mask()
                    deepest_scores = tree_bank.depth[:, :b_active].float().masked_fill(~exp_mask, -1e9)
                    if exp_mask.any():
                        j_sel = deepest_scores.argmax(dim=-1)

            selected_history.append(j_sel)
            if record_step_traces:
                step_traces.append(
                    {
                        "step_idx": step_b,
                        "num_active": b_active,
                        "node_features": cur_trace.node_features.detach().clone(),
                        "target_subtree_N": cur_trace.target_subtree_N.detach().clone(),
                        "target_subtree_Q": cur_trace.target_subtree_Q.detach().clone(),
                        "target_node_select": cur_trace.target_node_select.detach().clone(),
                        "selected_node": j_sel.detach().clone(),
                    }
                )

            pa_h = tree_bank.h_bank[b_arange, j_sel]
            pa_logits = tree_bank.logits_bank[b_arange, j_sel]
            pa_clamped_mask = tree_bank.clamped_mask[b_arange, j_sel]
            pa_clamped_tokens = tree_bank.clamped_tokens[b_arange, j_sel]
            pa_plan = tree_bank.plan_bank[b_arange, j_sel]
            pa_edge_delta = tree_bank.edge_delta_amp_bank[b_arange, j_sel]

            is_cont = (j_sel == (b_active - 1)) & (b_active > 1)
            keys_done = tree_bank.edge_keys_bank[:, 1:b_active]
            beta_done = tree_bank.beta_trust_bank[:, 1:b_active] * tree_bank.m_ql_bank[:, 1:b_active]
            active_plan, _, _ = self.plan_head.transport_or_sample_plan(
                is_continuation=is_cont,
                prev_plan=pa_plan,
                realized_shift=pa_edge_delta,
                node_h=pa_h,
                node_logits=pa_logits,
                node_clamped=pa_clamped_mask,
                keys_done=keys_done,
                beta_done=beta_done,
                root_plan_seed=root_plan,
            )

            # Choose (v_sel, z_sel) from the teacher's action prior at j_sel
            prior_vk = self.compute_step_action_prior_at_node(tree_bank, j_sel, active_plan)  # [N, V, K]
            open_mask = tree_bank.get_open_var_val_mask(j_sel)
            any_open = open_mask.any(dim=(-1, -2), keepdim=True)
            safe_open = open_mask | (~any_open)
            masked_prior = prior_vk.masked_fill(~safe_open, -1.0)
            flat_idx = masked_prior.reshape(N, V * K).argmax(dim=-1)
            v_sel = flat_idx // K
            z_sel = flat_idx % K

            pa_probs = F.softmax(pa_logits, dim=-1)
            step_prob = pa_probs[b_arange, v_sel, z_sel].clamp(min=1e-4, max=1.0)

            child_batch = batch.clone()
            child_batch.obs_mask = pa_clamped_mask.clone()
            child_batch.obs_tokens = pa_clamped_tokens.clone()
            child_batch = env.step_unmask(child_batch, v_sel, z_sel + 1)

            child_depth = tree_bank.depth[b_arange, j_sel] + 1
            child_out = self.world_model(
                child_batch,
                h_cons=h_cons_curr,
                depth=child_depth,
                root_clamped_mask=batch.obs_mask,
            )
            child_logits = child_out["var_logits"]
            child_probs = child_out["var_probs"]

            pred_top1 = child_probs.argmax(dim=-1) + 1
            cand_board = torch.where(child_batch.obs_mask, child_batch.obs_tokens, pred_top1)
            chk_valid = env.check_witness(child_batch, cand_board)

            m_ql_child = self.world_model.trust_head.compute_leaf_self_consistency(
                node_logits=child_logits,
                node_clamped_mask=child_batch.obs_mask,
                node_clamped_tokens=child_batch.obs_tokens,
                root_clamped_mask=batch.obs_mask,
                check_valid=chk_valid if not batch.solvable.all() else None,
            )
            if not batch.solvable.all():
                m_ql_child = m_ql_child * chk_valid.to(m_ql_child.dtype)

            leaf_v = self.compute_intrinsic_leaf_value(
                batch=batch,
                child_batch=child_batch,
                child_logits=child_logits,
                m_ql_child=m_ql_child,
                chk_valid=chk_valid,
                depth=child_depth,
                step_var=v_sel,
                step_val=z_sel,
            )

            tree_bank.append_node(
                selected_parent=j_sel,
                var_idx=v_sel,
                val_idx=z_sel,
                new_kv=child_out["kv_cache"],
                new_h=child_out["h_var"],
                new_logits=child_logits,
                new_m_ql=m_ql_child,
                new_beta_trust=child_out["beta_trust"],
                new_valid=chk_valid | batch.solvable,
                active_plan=active_plan,
                aux_emitter=self.world_model.aux_emitter,
                step_prob=step_prob,
                q_tree_val=leaf_v,
            )

            ell_curr, h_cons_curr, _ = self.tree_clearer.clear_tree_at_step(
                tree_bank=tree_bank,
                ell_prev=ell_curr,
                h_cons_prev=h_cons_curr,
            )

        final_trace = self.compute_targets_from_bank(tree_bank, batch=batch)
        final_trace.tree_bank = tree_bank
        final_trace.step_traces = step_traces
        if selected_history:
            final_trace.selected_nodes = torch.stack(selected_history, dim=1)
        else:
            final_trace.selected_nodes = torch.zeros((N, 0), dtype=torch.long, device=device)

        if batch is not None:
            final_trace.query_probs = self.world_model.query_head.predict_query_probs(
                batch, final_trace.target_root_belief, h_cons_curr
            )
            _, act_probs = self.world_model.compute_action_policy(
                batch=batch,
                h_var_detached=root_out["h_var"].detach(),
                var_probs_detached=final_trace.target_root_belief.detach(),
            )
            final_trace.action_probs = act_probs

        return final_trace

    def compute_step_action_prior_at_node(
        self,
        tree_bank: TreePagedKVBank,
        selected_node: torch.Tensor,
        active_plan: Optional[torch.Tensor] = None,
    ) -> torch.Tensor:
        """Compute `[N, V, K]` variable-value prior at `selected_node`."""
        return self.compute_default_action_prior(tree_bank, selected_node)


