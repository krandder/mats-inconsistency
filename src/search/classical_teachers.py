# Teacher 3: CDCLBackjumpTeacher (Unit Prop + 1-UIP Backjump + Global Nogood Broadcast)
# ==============================================================================


class CDCLBackjumpTeacher(BaseClassicalSearchTeacher):
    """Teacher 3: Conflict-Driven Clause Learning (`CDCL-Global-Nogood`).

    Solves Expressivity Barrier 5:
    1. Unit Propagation: selects variables with minimum open entropy (MRV / forced unit clauses).
    2. Conflict-Clause Detection & Non-Chronological 1-UIP Backjump: when a node `k` hits a conflict
       (`~is_valid[k]` or `m_ql(C_k) < tau_conflict`), identifies the highest asserting ancestor
       `j* in Anc(k)` and backjumps non-chronologically over intermediate unrelated decision levels.
    3. Global Conflict-Clause / Nogood Broadcast: broadcasts learned conflict clauses from ALL
       conflicting nodes `k` in the tree globally to ALL nodes `j` (including cousins in disjoint
       subtrees!) whose clamped assignment `O_j` shares the conflicting literal pair.
    """

    teacher_name = "CDCL-Global-Nogood"

    def __init__(
        self,
        world_model: GLCAOMWorldModel,
        tau_conflict: float = 0.25,
        **kwargs: Any,
    ):
        super().__init__(world_model, **kwargs)
        self.tau_conflict = float(tau_conflict)

    def compute_step_action_prior_at_node(
        self,
        tree_bank: TreePagedKVBank,
        selected_node: torch.Tensor,
        active_plan: Optional[torch.Tensor] = None,
    ) -> torch.Tensor:
        """Unit-propagation (MRV / minimum open entropy) variable-value selection."""
        N = tree_bank.batch_size
        V = tree_bank.num_vars
        K = tree_bank.num_vals
        device = tree_bank.logits_bank.device
        b_arange = torch.arange(N, device=device)

        node_logits = tree_bank.logits_bank[b_arange, selected_node]        # [N, V, K]
        open_mask = tree_bank.get_open_var_val_mask(selected_node)          # [N, V, K]
        probs = F.softmax(node_logits, dim=-1)
        ent = -torch.sum(probs * torch.log(probs.clamp_min(1e-7)), dim=-1)  # [N, V]

        # Prioritize minimum entropy (unit clause / forced single) open variable
        unit_score = (-4.0 * ent).unsqueeze(-1) + node_logits
        any_open = open_mask.any(dim=(-1, -2), keepdim=True)
        safe_open = open_mask | (~any_open)
        masked = unit_score.masked_fill(~safe_open, -1e9)
        return F.softmax(masked.reshape(N, V * K), dim=-1).view(N, V, K)

    def compute_targets_from_bank(
        self,
        tree_bank: TreePagedKVBank,
        batch: Optional[EnvBatch] = None,
    ) -> SearchTreeTrace:
        b = tree_bank.num_active
        N = tree_bank.batch_size
        V = tree_bank.num_vars
        K = tree_bank.num_vals
        device = tree_bank.logits_bank.device
        dtype = tree_bank.logits_bank.dtype

        node_feats = extract_local_node_features(tree_bank)
        topo = extract_tree_topology(tree_bank)

        m_ql = tree_bank.m_ql_bank[:, :b]                                   # [N, b]
        is_conflict = (~topo["is_valid"]) | (m_ql < self.tau_conflict)      # [N, b] bool
        is_conflict[:, 0] = False                                           # Root 0 is decision level 0
        conflict_f = is_conflict.to(dtype)
        valid_f = 1.0 - conflict_f

        anc_f = topo["anc_mask"].to(dtype)                                  # [N, b, b]
        n_valid_desc = torch.bmm(anc_f, valid_f.unsqueeze(-1)).squeeze(-1)  # [N, b]
        n_conf_desc = torch.bmm(anc_f, conflict_f.unsqueeze(-1)).squeeze(-1)  # [N, b]
        total_desc = (n_valid_desc + n_conf_desc).clamp(min=1.0)

        # Global Conflict-Clause / Nogood Broadcast across ALL nodes (including disjoint cousins!)
        # Extract the branch-clamped literal vectors (O_k \ O_0) at conflicting nodes k
        branch_clamped = tree_bank.clamped_mask[:, :b] & (~tree_bank.clamped_mask[:, 0:1])  # [N, b, V]
        tok_oh = F.one_hot(
            (tree_bank.clamped_tokens[:, :b].clamp(1, K) - 1).long(), num_classes=K
        ).to(dtype) * branch_clamped.unsqueeze(-1).to(dtype)                # [N, b, V, K]
        flat_lits = tok_oh.reshape(N, b, V * K)                             # [N, b, V*K]

        # Pairwise literal overlap between node j and conflicting node k (anywhere in the tree!)
        lit_overlap = torch.bmm(flat_lits, flat_lits.transpose(1, 2))       # [N, b, b]
        global_nogood_hit = torch.bmm(
            lit_overlap, (conflict_f * (1.0 - m_ql)).unsqueeze(-1)
        ).squeeze(-1)                                                       # [N, b]

        target_N = (n_valid_desc + 1.0).clamp(min=1.0)
        target_Q = (
            m_ql * (n_valid_desc / total_desc)
            - 0.65 * (n_conf_desc / total_desc)
            - 0.55 * torch.tanh(global_nogood_hit)
        ).clamp(-1.0, 1.0)

        # Non-chronological 1-UIP backjump target when tip (b-1) is in conflict, else unit-propagation tip
        depths = topo["depth"].to(dtype)
        expandable = topo["expandable_mask"]
        tip_conflict = is_conflict[:, -1:]                                  # [N, 1] bool
        tip_anc = topo["desc_mask"][:, -1, :]                               # [N, b] ancestors of tip b-1

        # Asserting ancestor: shallowest non-root ancestor along tip's spine with highest edge jump, or root 0
        edge_shift_norm = node_feats[:, :, 14]                              # [N, b]
        asserting_score = (
            2.0 * tip_anc.to(dtype)
            + 1.5 * edge_shift_norm
            - 0.35 * depths
            - 1.2 * torch.tanh(global_nogood_hit)
        )
        continue_score = (
            1.5 * target_Q
            + 0.45 * depths
            + 0.8 * node_feats[:, :, 10]                                    # open stiffness (unit prop)
            - 1.2 * torch.tanh(global_nogood_hit)
        )
        raw_select = torch.where(tip_conflict, asserting_score, continue_score)

        is_root = torch.arange(b, device=device).unsqueeze(0) == 0
        safe_exp = expandable | ((~expandable.any(dim=-1, keepdim=True)) & is_root)
        target_node_select = raw_select.masked_fill(~safe_exp, -1e9)

        j_star = target_node_select.argmax(dim=-1)
        target_action_prior = self.compute_step_action_prior_at_node(tree_bank, j_star)

        # Cleared root belief: combine TwoStageTreeClearer with global conflict nogood refutation
        root_logits = tree_bank.logits_bank[:, 0]
        ell_cleared, _, _ = self.tree_clearer.clear_tree_at_step(
            tree_bank=tree_bank,
            ell_prev=root_logits,
            h_cons_prev=tree_bank.edge_delta_amp_bank[:, 0],
        )
        if is_conflict.any():
            # Penalize root variable-value assignments that directly triggered conflict clauses
            step_v_oh = F.one_hot(topo["step_var"].clamp(0, V - 1), num_classes=V).to(dtype)
            step_z_oh = F.one_hot(topo["step_val"].clamp(0, K - 1), num_classes=K).to(dtype)
            step_lit = step_v_oh.unsqueeze(-1) * step_z_oh.unsqueeze(-2)    # [N, b, V, K]
            nogood_pen = torch.einsum("nb,nbvk->nvk", conflict_f * (1.0 - m_ql), step_lit)
            ell_cleared = ell_cleared - 3.0 * nogood_pen
        target_root_belief = F.softmax(ell_cleared, dim=-1)

        return SearchTreeTrace(
            node_features=node_feats,
            tree_topology=topo,
            target_subtree_N=target_N,
            target_subtree_Q=target_Q,
            target_node_select=target_node_select,
            target_action_prior=target_action_prior,
            target_root_belief=target_root_belief,
            teacher_name=self.teacher_name,
            tree_bank=tree_bank,
            extra_targets={
                "target_log_N": torch.log(target_N.clamp(min=1.0)),
                "global_nogood_hit": global_nogood_hit,
                "is_conflict": conflict_f,
            },
        )


