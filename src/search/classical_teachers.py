# Teacher 2: MinimaxAlphaBetaTeacher (Alternating Max/Min + Proof-Number Search)
# ==============================================================================


class MinimaxAlphaBetaTeacher(BaseClassicalSearchTeacher):
    """Teacher 2: Exact Alternating `max / min` Ply Value Backup + Proof-Number Search (`PNS`)
    + Alpha-Beta Window `[alpha(j), beta(j)]` Principal-Variation Selection.

    Solves Expressivity Barrier 1:
    - Even depths `d(j) % 2 == 0` are MAX / OR nodes:
        `V^{MM}(j) = max_{c in Ch(j)} V^{MM}(c)`
        `pn(j) = min_{c in Ch(j)} pn(c)`, `dn(j) = sum_{c in Ch(j)} dn(c)`
    - Odd depths `d(j) % 2 == 1` are MIN / AND nodes:
        `V^{MM}(j) = min_{c in Ch(j)} V^{MM}(c)`
        `pn(j) = sum_{c in Ch(j)} pn(c)`, `dn(j) = min_{c in Ch(j)} dn(c)`
    """

    teacher_name = "Minimax-AlphaBeta-PNS"

    def compute_targets_from_bank(
        self,
        tree_bank: TreePagedKVBank,
        batch: Optional[EnvBatch] = None,
    ) -> SearchTreeTrace:
        b = tree_bank.num_active
        N = tree_bank.batch_size
        device = tree_bank.logits_bank.device
        dtype = tree_bank.logits_bank.dtype

        node_feats = extract_local_node_features(tree_bank)
        topo = extract_tree_topology(tree_bank)

        leaf_vals = tree_bank.leaf_value_bank[:, :b].clone()                # [N, b]
        depths = topo["depth"]                                              # [N, b]
        child_mask = topo["child_mask"]                                     # [N, b, b] bool
        has_children = child_mask.any(dim=-1)                               # [N, b] bool
        is_max_ply = (depths % 2) == 0                                      # [N, b] bool

        # Initialize V_mm(j) = v(C_j), proof number pn(j), and disproof number dn(j) at leaves
        v_mm = leaf_vals.clone()
        p_win = torch.sigmoid(2.0 * leaf_vals).clamp(0.05, 0.95)
        pn = (1.0 - p_win) * 2.0                                            # [N, b]
        dn = p_win * 2.0                                                    # [N, b]

        max_d = int(depths.max().item()) if b > 0 else 0
        # Exact bottom-up sweep from deepest ply max_d - 1 down to root 0
        for d_cur in range(max_d - 1, -1, -1):
            at_d = (depths == d_cur) & has_children                         # [N, b]
            if not at_d.any():
                continue
            # Children values [N, b, b]
            ch_v_max = v_mm.unsqueeze(1).expand(N, b, b).masked_fill(~child_mask, -1e9).max(dim=-1).values
            ch_v_min = v_mm.unsqueeze(1).expand(N, b, b).masked_fill(~child_mask, 1e9).min(dim=-1).values
            backed_v = torch.where(is_max_ply, ch_v_max, ch_v_min)
            v_mm = torch.where(at_d, backed_v, v_mm)

            # PNS OR/AND backup
            ch_pn_min = pn.unsqueeze(1).expand(N, b, b).masked_fill(~child_mask, 1e9).min(dim=-1).values
            ch_pn_sum = (pn.unsqueeze(1) * child_mask.to(dtype)).sum(dim=-1)
            ch_dn_min = dn.unsqueeze(1).expand(N, b, b).masked_fill(~child_mask, 1e9).min(dim=-1).values
            ch_dn_sum = (dn.unsqueeze(1) * child_mask.to(dtype)).sum(dim=-1)

            pn = torch.where(at_d, torch.where(is_max_ply, ch_pn_min, ch_pn_sum), pn)
            dn = torch.where(at_d, torch.where(is_max_ply, ch_dn_sum, ch_dn_min), dn)

        # Top-down Alpha-Beta window [alpha(j), beta(j)] and Principal-Variation distance
        alpha = torch.full((N, b), -1.0, dtype=dtype, device=device)
        beta = torch.full((N, b), 1.0, dtype=dtype, device=device)
        sib_mask = topo["sibling_mask"]                                     # [N, b, b]
        has_sib = sib_mask.any(dim=-1)                                      # [N, b]
        pa_idx = topo["parent_idx"]                                         # [N, b]
        pa_is_max = ((depths - 1) % 2) == 0

        sib_v_max = v_mm.unsqueeze(1).expand(N, b, b).masked_fill(~sib_mask, -1.0).max(dim=-1).values
        sib_v_min = v_mm.unsqueeze(1).expand(N, b, b).masked_fill(~sib_mask, 1.0).min(dim=-1).values

        for d_cur in range(1, max_d + 1):
            at_d = depths == d_cur
            if not at_d.any():
                continue
            pa_alpha = alpha.gather(1, pa_idx)
            pa_beta = beta.gather(1, pa_idx)
            new_alpha = torch.where(pa_is_max & has_sib, torch.maximum(pa_alpha, sib_v_max), pa_alpha)
            new_beta = torch.where((~pa_is_max) & has_sib, torch.minimum(pa_beta, sib_v_min), pa_beta)
            alpha = torch.where(at_d, new_alpha, alpha)
            beta = torch.where(at_d, new_beta, beta)

        unpruned = (beta >= alpha - 1e-4).to(dtype)                         # [N, b]
        anc_f = topo["anc_mask"].to(dtype)
        # Subtree effective count: unpruned descendants weighted by PNS proving potential
        pns_weight = 1.0 / (0.5 * (pn + dn) + 0.5)
        target_N = torch.bmm(anc_f, (unpruned * (1.0 + pns_weight)).unsqueeze(-1)).squeeze(-1).clamp(min=1.0)
        target_Q = v_mm

        # Principal-Variation + Most-Proving-Node selection score
        pv_gap = (v_mm - v_mm[:, 0:1]).abs()
        window_width = (beta - alpha).clamp(min=0.0)
        ply_signed_v = torch.where(is_max_ply, v_mm, -v_mm)
        raw_select = -2.5 * pv_gap + 0.8 * window_width + 0.6 * ply_signed_v - 0.4 * torch.log1p(pn + dn)

        expandable = topo["expandable_mask"]
        is_root = torch.arange(b, device=device).unsqueeze(0) == 0
        safe_exp = expandable | ((~expandable.any(dim=-1, keepdim=True)) & is_root)
        target_node_select = raw_select.masked_fill(~safe_exp, -1e9)

        j_star = target_node_select.argmax(dim=-1)
        target_action_prior = self.compute_default_action_prior(tree_bank, j_star)

        # Principal-variation weighted root belief clearing
        root_logits = tree_bank.logits_bank[:, 0]
        if b <= 1:
            target_root_belief = F.softmax(root_logits, dim=-1)
        else:
            deltas = tree_bank.logits_bank[:, 1:b] - root_logits.unsqueeze(1)
            pv_w = F.softmax(-3.0 * pv_gap[:, 1:b] + torch.log(unpruned[:, 1:b].clamp(min=1e-3)), dim=-1)
            ell_mm = root_logits + torch.einsum("nb,nbvk->nvk", pv_w, deltas)
            target_root_belief = F.softmax(ell_mm, dim=-1)

        return SearchTreeTrace(
            node_features=node_feats,
            tree_topology=topo,
            target_subtree_N=target_N,
            target_subtree_Q=target_Q,
            target_node_select=target_node_select,
            target_action_prior=target_action_prior,
            target_root_belief=target_root_belief,
            teacher_name=self.teacher_name,
            tree_bank=tree_bank,
            extra_targets={
                "target_log_N": torch.log(target_N.clamp(min=1.0)),
                "proof_number": pn,
                "disproof_number": dn,
                "alpha_bound": alpha,
                "beta_bound": beta,
            },
        )


MinimaxAlphaBetaPNSTeacher = MinimaxAlphaBetaTeacher


