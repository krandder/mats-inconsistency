# Teacher 1: MCTSPUCTTeacher & MCGSTranspositionTeacher
# ==============================================================================


class MCTSPUCTTeacher(BaseClassicalSearchTeacher):
    """Teacher 1: Exact Monte-Carlo Tree Search (`MCTS-PUCT`) with Full Descendant-to-Ancestor Backup.

    For every node `j in {0..b}`:
      `N(j) = sum_{k in Desc(j)} 1 = sum_k anc_mask[j, k]`
      `Q^{MCTS}(j) = (1 / N(j)) sum_{k in Desc(j)} v(C_k)`
    When `use_transposition_dag=True` (`MCGS`), uses `dag_anc_mask = AncMask * E_trans * AncMask`
    so commuted move sequences reaching identical states share descendant visits and values.
    """

    teacher_name = "MCTS-PUCT"

    def __init__(
        self,
        world_model: GLCAOMWorldModel,
        c_puct: float = 1.5,
        use_transposition_dag: bool = False,
        **kwargs: Any,
    ):
        super().__init__(world_model, c_puct=c_puct, **kwargs)
        self.use_transposition_dag = bool(use_transposition_dag)
        if self.use_transposition_dag:
            self.teacher_name = "MCGS-Transposition-DAG"

    def compute_targets_from_bank(
        self,
        tree_bank: TreePagedKVBank,
        batch: Optional[EnvBatch] = None,
    ) -> SearchTreeTrace:
        b = tree_bank.num_active
        N = tree_bank.batch_size
        device = tree_bank.logits_bank.device
        dtype = tree_bank.logits_bank.dtype
        b_arange = torch.arange(N, device=device)

        node_feats = extract_local_node_features(tree_bank)
        topo = extract_tree_topology(tree_bank)

        reach_mask = topo["dag_anc_mask"].to(dtype) if self.use_transposition_dag else topo["anc_mask"].to(dtype)
        leaf_vals = tree_bank.leaf_value_bank[:, :b]                        # [N, b]

        # Exact descendant visit count N(j) and mean value Q^{MCTS}(j)
        target_N = reach_mask.sum(dim=-1).clamp(min=1.0)                    # [N, b]
        val_sum = torch.bmm(reach_mask, leaf_vals.unsqueeze(-1)).squeeze(-1)  # [N, b]
        target_Q = val_sum / target_N                                       # [N, b]

        # Parent visit count N(pa(j)) for PUCT exploration term
        pa_idx = topo["parent_idx"]                                         # [N, b]
        parent_N = target_N.gather(1, pa_idx)                               # [N, b]
        parent_N[:, 0] = target_N[:, 0]

        # Prior P(j | pa(j)) and open-action potential at j
        phi = self.r12_puct.compute_potential_phi(tree_bank)                # [N, b]
        step_prior = tree_bank.step_prob_bank[:, :b]                        # [N, b]
        p_prior = 0.5 * step_prior + 0.5 * (phi / (phi.max(dim=-1, keepdim=True).values + self.eps))

        # Top-down path-PUCT + expandable leaf PUCT score
        puct_bonus = self.c_puct * p_prior * torch.sqrt(parent_N) / (1.0 + target_N - 0.5)
        raw_select_scores = target_Q + puct_bonus

        expandable = topo["expandable_mask"]
        is_root = torch.arange(b, device=device).unsqueeze(0) == 0
        safe_exp = expandable | ((~expandable.any(dim=-1, keepdim=True)) & is_root)
        target_node_select = raw_select_scores.masked_fill(~safe_exp, -1e9)

        j_star = target_node_select.argmax(dim=-1)
        target_action_prior = self.compute_default_action_prior(tree_bank, j_star)

        # MCTS visit-weighted + consistency-gated root belief clearing
        root_logits = tree_bank.logits_bank[:, 0]
        if b <= 1:
            target_root_belief = F.softmax(root_logits, dim=-1)
        else:
            node_logits = tree_bank.logits_bank[:, 1:b]
            deltas = node_logits - root_logits.unsqueeze(1)
            w_visit = target_N[:, 1:b] * tree_bank.m_ql_bank[:, 1:b].clamp(min=0.05)
            w_visit = w_visit / (w_visit.sum(dim=-1, keepdim=True) + self.eps)
            ell_mcts = root_logits + torch.einsum("nb,nbvk->nvk", w_visit, deltas)
            target_root_belief = F.softmax(ell_mcts, dim=-1)

        return SearchTreeTrace(
            node_features=node_feats,
            tree_topology=topo,
            target_subtree_N=target_N,
            target_subtree_Q=target_Q,
            target_node_select=target_node_select,
            target_action_prior=target_action_prior,
            target_root_belief=target_root_belief,
            teacher_name=self.teacher_name,
            tree_bank=tree_bank,
            extra_targets={
                "target_log_N": torch.log(target_N.clamp(min=1.0)),
                "puct_bonus": puct_bonus,
            },
        )


class MCGSTranspositionTeacher(MCTSPUCTTeacher):
    """Monte-Carlo Graph Search (`MCGS`) Teacher with Transposition-DAG backup."""

    teacher_name = "MCGS-Transposition-DAG"

    def __init__(self, world_model: GLCAOMWorldModel, c_puct: float = 1.5, **kwargs: Any):
        super().__init__(world_model, c_puct=c_puct, use_transposition_dag=True, **kwargs)


