# Teacher 6: GumbelSequentialHalvingTeacher (Gumbel MuZero SH & Sibling Rank)
# ==============================================================================


class GumbelSequentialHalvingTeacher(BaseClassicalSearchTeacher):
    """Teacher 6: Gumbel MuZero Sequential Halving (`Gumbel-Sequential-Halving`).

    Solves Expressivity Barrier 4:
    1. Computes completed Q-values `sigma(Q_hat(j)) = (c_visit + max_{s in Sib(j)} N(s)) * c_scale * Q_hat(j)`.
    2. Scores each candidate by `G(j) = log p(j | pa(j)) + sigma(Q_hat(j))`.
    3. Computes Sibling Dominance Rank `rank_sib(j) = sum_{s in Sib(j)} 1[G(s) > G(j)]`
       and eliminates the bottom half of siblings (`rank_sib(j) >= ceil(|Sib(j)| / 2)`),
       allocating next visits to the least-visited surviving top-half candidate.
    """

    teacher_name = "Gumbel-Sequential-Halving"

    def __init__(
        self,
        world_model: GLCAOMWorldModel,
        c_visit: float = 50.0,
        c_scale: float = 0.1,
        **kwargs: Any,
    ):
        super().__init__(world_model, **kwargs)
        self.c_visit = float(c_visit)
        self.c_scale = float(c_scale)

    def compute_targets_from_bank(
        self,
        tree_bank: TreePagedKVBank,
        batch: Optional[EnvBatch] = None,
    ) -> SearchTreeTrace:
        b = tree_bank.num_active
        N = tree_bank.batch_size
        device = tree_bank.logits_bank.device
        dtype = tree_bank.logits_bank.dtype

        node_feats = extract_local_node_features(tree_bank)
        topo = extract_tree_topology(tree_bank)

        anc_f = topo["anc_mask"].to(dtype)                                  # [N, b, b]
        leaf_vals = tree_bank.leaf_value_bank[:, :b]                        # [N, b]
        target_N = anc_f.sum(dim=-1).clamp(min=1.0)                         # [N, b]
        q_mean = torch.bmm(anc_f, leaf_vals.unsqueeze(-1)).squeeze(-1) / target_N

        # Sibling max visit count max_{s in Sib(j) U {j}} N(s)
        sib_or_self = topo["sibling_mask"] | topo["self_mask"]              # [N, b, b] bool
        max_sib_N = target_N.unsqueeze(1).expand(N, b, b).masked_fill(~sib_or_self, 1.0).max(dim=-1).values

        # Gumbel MuZero completed Q transformation sigma(q_hat)
        sigma_q = (self.c_visit + max_sib_N) * self.c_scale * q_mean        # [N, b]
        log_prior = torch.log(tree_bank.step_prob_bank[:, :b].clamp(min=1e-4))
        gumbel_score = log_prior + sigma_q                                  # [N, b]

        # Sibling dominance rank: rank_sib(j) = sum_{s in Sib(j)} 1[G(s) > G(j)]
        g_diff = gumbel_score.unsqueeze(1) - gumbel_score.unsqueeze(2)      # [N, j, s]: G(s) - G(j)
        better_sib = (g_diff > 1e-6) & topo["sibling_mask"]
        rank_sib = better_sib.to(dtype).sum(dim=-1)                         # [N, b]
        num_sib_group = sib_or_self.to(dtype).sum(dim=-1).clamp(min=1.0)    # [N, b]

        # Sequential Halving survival threshold K_r = ceil(num_sib_group / 2)
        k_survive = torch.ceil(0.5 * num_sib_group)
        survived_halving = (rank_sib < k_survive).to(dtype)                 # [N, b]

        target_Q = torch.tanh(0.5 * gumbel_score)
        # Allocate budget to surviving top-half siblings with lowest visit count N(j)
        raw_select = (
            2.5 * survived_halving
            + 0.8 * target_Q
            - 0.6 * (rank_sib / num_sib_group)
            + 1.0 / (target_N + 0.5)
        )

        expandable = topo["expandable_mask"]
        is_root = torch.arange(b, device=device).unsqueeze(0) == 0
        safe_exp = expandable | ((~expandable.any(dim=-1, keepdim=True)) & is_root)
        target_node_select = raw_select.masked_fill(~safe_exp, -1e9)

        j_star = target_node_select.argmax(dim=-1)
        target_action_prior = self.compute_default_action_prior(tree_bank, j_star)

        root_logits = tree_bank.logits_bank[:, 0]
        if b <= 1:
            target_root_belief = F.softmax(root_logits, dim=-1)
        else:
            deltas = tree_bank.logits_bank[:, 1:b] - root_logits.unsqueeze(1)
            sh_w = F.softmax(gumbel_score[:, 1:b] + 2.0 * survived_halving[:, 1:b], dim=-1)
            ell_sh = root_logits + torch.einsum("nb,nbvk->nvk", sh_w, deltas)
            target_root_belief = F.softmax(ell_sh, dim=-1)

        return SearchTreeTrace(
            node_features=node_feats,
            tree_topology=topo,
            target_subtree_N=target_N,
            target_subtree_Q=target_Q,
            target_node_select=target_node_select,
            target_action_prior=target_action_prior,
            target_root_belief=target_root_belief,
            teacher_name=self.teacher_name,
            tree_bank=tree_bank,
            extra_targets={
                "target_log_N": torch.log(target_N.clamp(min=1.0)),
                "sibling_rank": rank_sib,
                "survived_halving": survived_halving,
                "gumbel_score": gumbel_score,
            },
        )


